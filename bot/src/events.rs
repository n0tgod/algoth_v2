//! События журнала — единственное, что ядро запоминает.
//!
//! Состояние (позиции, счёт, выключатель) ВЫВОДИТСЯ из этих событий, а
//! не хранится отдельно: снимок состояния однажды разошёлся бы с
//! историей, и никто бы этого не заметил (урок `build.py` из A2).
//!
//! Правило записи — write-ahead: сначала событие в журнал с fsync,
//! потом действие. Тогда оборванная последняя строка означает «действие
//! не совершалось», и её можно отбросить, ничего не потеряв.

use serde::{Deserialize, Serialize};

/// Сторона позиции. Строки в журнале — те же слова, что в Python-счёте
/// (`long`/`short`): сверка E2 сравнивает записи двух реализаций, и
/// разные имена одного и того же превратили бы её в перевод.
#[derive(Serialize, Deserialize, Clone, Copy, PartialEq, Eq,
         PartialOrd, Ord, Debug)]
#[serde(rename_all = "snake_case")]
pub enum Side {
    Long,
    Short,
}

/// Событие. Метка `ev` в строке журнала различает виды.
///
/// Деньги — f64, как в Python-счёте: сверка идёт до цента, и одинаковая
/// арифметика IEEE754 по обе стороны делает расхождение формул видимым,
/// а расхождение округлений — отсутствующим.
#[derive(Serialize, Deserialize, Clone, PartialEq, Debug)]
#[serde(tag = "ev", rename_all = "snake_case")]
pub enum Event {
    /// Решение модели принято к рассмотрению. Само по себе ничего не
    /// меняет — вход случится (или нет) отдельными событиями.
    Decision {
        arm: String,
        hour: String,
        sym: String,
        side: Side,
        /// Цена закрытия часа сигнала — от неё меряется подарок входа.
        px: Option<f64>,
        /// Версия модели штампуется в сделку (урок RULES_VERSION).
        ver: Option<u32>,
        /// Секунда события ИСТОЧНИКА (живой вход сканера) — у живого
        /// исполнителя она отличается от `at_ms`: журнал режется на
        /// сутки по `at_ms`, и метка события в нём перемешивала бы
        /// номера строк между суточными файлами (первый сухой прогон
        /// X2 сломал так собственный журнал). `at_ms` — момент
        /// записи, событие — здесь.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        src_ts: Option<f64>,
        at_ms: i64,
    },
    /// Риск-слой отверг намерение. Причина — словами: молчаливый отказ
    /// неотличим от тишины, а это главный класс дефектов проекта.
    Reject {
        sym: String,
        side: Side,
        reason: String,
        at_ms: i64,
    },
    /// Позиция открыта (исполнение уже случилось; размер — фактически
    /// исполненный нотионал, а не запрошенный).
    Open {
        /// Ключ позиции, у нынешней книги — «рука:час:имя:сторона».
        pos: String,
        sym: String,
        side: Side,
        notional_usd: f64,
        /// Пустая — у входа без записанной книги и без цены сигнала:
        /// ноль был бы утверждением, а не пропуском.
        entry_px: Option<f64>,
        fee_usd: f64,
        /// Заявка не влезла в книгу целиком. Помечается честно, а не
        /// досчитывается по последнему уровню (спека 09 §4).
        partial: bool,
        ver: Option<u32>,
        at_ms: i64,
    },
    /// Позиция закрыта. `pnl_usd` — нетто, издержки уже вычтены; brutто
    /// восстанавливается из цен и комиссий, лежащих рядом.
    Close {
        pos: String,
        exit_px: Option<f64>,
        fee_usd: f64,
        pnl_usd: f64,
        reason: String,
        at_ms: i64,
    },
    /// Аварийный выключатель повёрнут (спека 01 §10).
    Kill { on: bool, reason: String, at_ms: i64 },
}

impl Event {
    /// Момент события — по нему журнал режется на сутки.
    pub fn at_ms(&self) -> i64 {
        match self {
            Event::Decision { at_ms, .. }
            | Event::Reject { at_ms, .. }
            | Event::Open { at_ms, .. }
            | Event::Close { at_ms, .. }
            | Event::Kill { at_ms, .. } => *at_ms,
        }
    }
}

/// Строка журнала: сквозной номер + событие.
///
/// Номер строго растёт и написан в самой строке — по нему читатель
/// снимает дубли (сутки, лежащие и простыми, и сжатыми после обрыва
/// между переименованием и удалением) и ловит противоречия: два разных
/// события под одним номером — порча, а не данные.
#[derive(Serialize, Deserialize, Clone, PartialEq, Debug)]
pub struct Record {
    pub seq: u64,
    #[serde(flatten)]
    pub event: Event,
}
