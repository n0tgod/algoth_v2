#!/usr/bin/env bash
# Вернуть МОДЕЛЬ из архива книги — разовая починка после дефекта,
# который остановил живой контур 11 августа.
#
# Что случилось
# -------------
#
# «Отставить книгу в архив» делалось переименованием каталога. У
# боковых книг каталог содержит только книгу, и это работало; у ГЛАВНОЙ
# книги каталог — это каталог МОДЕЛИ, и вместе с выборами туда же
# уехали веса, сохранённые векторы, мысли и история IC. Следующий цикл
# упал на `preds.jsonl` в несуществующем каталоге, а наружу это
# выглядело как «цикл упал».
#
# Сам дефект исправлен в коде (переезжают файлы книги, а не каталог).
# Этот скрипт разбирает последствия уже случившегося: возвращает модель
# на место, оставляя книгу в архиве — там ей и место, порядок сечения
# сменился и старые сделки в новый счёт не идут.
#
#   tools/repair_model_dir.sh [каталог out]
#
# Ничего не перезаписывает: файл, уже лежащий в живом каталоге, новее
# архивного (его написал упавший цикл), и затирать его нечем.
set -u

cd "$(dirname "$0")/.." || exit 1
OUT="${1:-research/s8_loop/out}"
LIVE="$OUT/model"

if [ ! -d "$OUT" ]; then
    echo "ОШИБКА: нет каталога $OUT"
    exit 1
fi

# Архив выбирается не по имени, а по СОДЕРЖИМОМУ: чинить надо тот, в
# который уехала модель. Архив без весов — обычная отставленная книга,
# трогать его нельзя.
SRC=""
for d in "$OUT"/model.rank-* "$OUT"/model.was-*; do
    [ -d "$d" ] || continue
    if [ -f "$d/preds.jsonl" ] || ls "$d"/*.pkl >/dev/null 2>&1; then
        SRC="$d"
    fi
done

if [ -z "$SRC" ]; then
    echo "чинить нечего: архива с моделью нет"
    exit 0
fi

echo "== модель нашлась в $SRC =="
mkdir -p "$LIVE" || exit 1

moved=0
kept=0
skipped=0
for p in "$SRC"/* "$SRC"/.[!.]*; do
    [ -e "$p" ] || continue
    f="$(basename "$p")"
    case "$f" in
        picks.jsonl|review.jsonl|account_*.json|manifest.json)
            # Книга остаётся в архиве. Манифест тоже: он описывает ту
            # книгу, а живой цикл напишет свой в первую же минуту.
            kept=$((kept + 1))
            continue
            ;;
    esac
    if [ -e "$LIVE/$f" ]; then
        echo "  уже на месте, не трогаю: $f"
        skipped=$((skipped + 1))
        continue
    fi
    mv "$p" "$LIVE/$f" && moved=$((moved + 1))
done

echo "== вернул файлов: $moved, оставил книге: $kept, пропустил: $skipped =="
echo "Дальше сторож поднимет цикл сам, либо перезапустите:"
echo "  tools/restart_book.sh"
