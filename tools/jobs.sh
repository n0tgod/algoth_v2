#!/usr/bin/env bash
# Очередь заданий: сессия кладёт задание в git, сервер его выполняет.
#
# Зачем
# -----
# Прямого доступа к серверу у ассистента нет и не будет: из песочницы
# наружу открыты только 80 и 443, порт 22 режет политика, а на 443
# стоит терминирующий TLS-прокси (это измерено, а не предположено).
# Владелец при этом устал копировать команды руками.
#
# Открывать исполнение по HTTP на машине, где лежат ключи биржи, —
# плохой обмен. Поэтому канал другой: заданием служит ФАЙЛ В GIT.
# Ассистент коммитит его, сторож на сервере подтягивает и выполняет,
# результат публикуется обратно в git. Аутентификация — доступ к
# репозиторию, аудит — сама история, произвольных команд нет.
#
# Что можно выполнить
# -------------------
# Только питон-файл, лежащий В РЕПОЗИТОРИИ, и только из объявленного
# набора действий. Никакого `eval`, никакой сборки строки: аргументы
# идут массивом и проверяются посимвольно. Код попадает в репозиторий
# коммитом — то есть проходит ровно тот же путь, что и сегодня, когда
# владелец запускает команды руками.
#
# Формат задания: `jobs/<имя>.job`, одна строка:
#     run research/probe_turn/turn.py --tag 1m
#     restart-book
#     agents-run <роль>
#     status
#
# Выполненное задание помечается `jobs/done/<имя>.done` и больше не
# запускается никогда — маркер в git, поэтому переживает перезапуск и
# не зависит от памяти сторожа.
#
#     tools/jobs.sh            # зовётся сторожем каждые 5 минут
set -u

cd "$(dirname "$0")/.." || exit 1
JOBS=jobs
DONE=$JOBS/done
mkdir -p "$DONE"
now() { date -u +"%Y-%m-%dT%H:%M:%SZ"; }

# --- замок на весь проход --------------------------------------------
# `run`-задание уходит в фон, и маркер `.done` пишется через секунды
# после ЗАПУСКА — но между запуском и маркером есть щель, и поке,
# совпавший с пятиминуткой сторожа, запускает два прохода разом:
# гонка на этой щели даёт двойной запуск того же задания. Замок
# закрывает её целиком. (Записано после ложного диагноза 2026-08-30:
# «сторож размножает идущее задание» — неверно, задание отвязано и
# помечено сразу; OOM зонда каскада делали соседи по памяти, не
# дубли.) Занятый замок — не тревога: в queue-state не пишется.
# Отвязанным заданиям fd замка НЕ передаётся (`9>&-` на их запуске):
# унаследованный fd держит flock, пока жив ЛЮБОЙ держатель, — и
# многочасовой прогон замораживал бы очередь на всю свою длину.
# Ровно так первый прогон liqsplit держал её ~4 часа (2026-08-31,
# второй урок того же замка за сутки).
exec 9>"$JOBS/.lock"
if ! flock -n 9; then
    echo "[$(now)] задания: проход уже идёт — выхожу"
    exit 0
fi

# --- подтянуть задания ------------------------------------------------
# Только перемотка вперёд: расхождение означает, что на сервере есть
# незапушенная работа, и молча перематывать её нельзя.
# Ненормальный исход очереди обязан ОСТАТЬСЯ, а не только напечататься:
# `jobs.sh` пишет в stdout сторожа и в `jobs/poke.log`, а до сессии
# доезжает только то, что попало в git. Файл уедет с ближайшей удачной
# публикацией — и первым же делом объяснит, почему очередь молчала.
role_busy() {
    # Держит ли кто-то замок запускалки. Отвечать «занято» на любую
    # беду нельзя: не открылся файл — это не занятость, а отсутствие
    # каталога, и первый же тест поймал, что при таком ответе роли не
    # запускались бы ВООБЩЕ. Не смогли проверить — считаем свободным
    # и отдаём решение самой запускалке: она откажет честно.
    local lk="research/factory/out/agents.lock"
    mkdir -p "$(dirname "$lk")" 2>/dev/null || true
    # Замок проверяется ПОДОБОЛОЧКОЙ: `exec 8>>файл 2>/dev/null`
    # глушит stderr всего скрипта навсегда — своя же проверка поймала
    # это тем, что дальше очередь работала молча.
    : >>"$lk" 2>/dev/null || return 1
    ( flock -n 8 ) 8>>"$lk" 2>/dev/null && return 1
    return 0
}

note() {
    echo "[$(now)] задания: $1"
    # Дописываем, а не перезаписываем: за один проход ненормальных
    # исходов бывает два (не получен origin, потом не свелось дерево), и
    # последний затирал бы первый — а причина обычно в первом. Хвост
    # держится коротким: файл уезжает в git, и история отказов очереди
    # там не нужна.
    printf '%s · %s\n' "$(now)" "$1" >> "$JOBS/queue-state.md"
    tail -n 20 "$JOBS/queue-state.md" > "$JOBS/queue-state.tmp" \
        && mv "$JOBS/queue-state.tmp" "$JOBS/queue-state.md"
}

if [ "${JOBS_NO_FETCH:-0}" != "1" ]; then
    # Отказ `fetch` НЕ выглядит отказом: `merge --ff-only` пройдёт по
    # старой ссылке `origin/main`, очередь честно не найдёт новых
    # заданий и промолчит. Отказ, неотличимый от тишины, — поэтому он
    # называется словами.
    if ! git fetch -q origin main 2>/dev/null; then
        note "origin/main не получен (сеть или доступ) — задания могут быть не видны"
    fi
    if ! git merge -q --ff-only origin/main 2>/dev/null; then
        # Расхождение означает коммит, который на сервере есть, а в
        # origin нет: так кончается публикация, у которой не прошёл
        # push, — а `git pull --rebase` у неё падает на растущем логе
        # ИДУЩЕГО задания. Молча перематывать чужую работу нельзя, но
        # и замирать навсегда нельзя: очередь пробует ОПУБЛИКОВАТЬ
        # застрявшее (ровно то, что сделала бы `publish.sh`), и только
        # не сумев — сдаётся.
        if git pull -q --rebase --autostash origin main 2>/dev/null \
           && git push -q origin main 2>/dev/null; then
            note "дерево расходилось с origin/main: застрявший коммит опубликован"
        else
            git rebase --abort 2>/dev/null || true
            note "дерево разошлось с origin/main и свести не вышло — не трогаю"
            exit 0
        fi
    fi
fi

shopt -s nullglob
found=0
for job in "$JOBS"/*.job; do
    name=$(basename "$job" .job)
    [ -f "$DONE/$name.done" ] && continue
    found=1
    log="$DONE/$name.log"
    line=$(head -n 1 "$job" | tr -d '\r')
    # Разбор в массив БЕЗ eval: слова разделяются пробелами, и каждое
    # проверяется отдельно. Строка задания никогда не попадает в шелл
    # как команда.
    read -r -a parts <<< "$line"
    action="${parts[0]:-}"
    bad=""
    for a in "${parts[@]}"; do
        case "$a" in
            *[!A-Za-z0-9._/=-]*) bad="$a"; break;; esac
    done

    {
        echo "== задание $name =="
        echo "строка: $line"
        echo "начало: $(now)"
    } > "$log"

    if [ -n "$bad" ]; then
        echo "ОТКАЗ: недопустимый символ в аргументе: $bad" >> "$log"
        echo "[$(now)] задание $name отвергнуто (аргумент: $bad)"
    else
        case "$action" in
        run)
            script="${parts[1]:-}"
            case "$script" in
                research/*.py|tools/*.py) ;;
                *) script="";;
            esac
            if [ -z "$script" ] || [ ! -f "$script" ]; then
                echo "ОТКАЗ: скрипт вне репозитория или не найден:" \
                     "${parts[1]:-—}" >> "$log"
            else
                echo "запускаю: .venv/bin/python $script ${parts[*]:2}" \
                    >> "$log"
                # Фоном и с пониженным приоритетом: прогон может
                # считать час, а сборщик и живой цикл важнее. Сторож
                # не ждёт — по завершении задание публикует себя само.
                setsid nohup nice -n 15 bash -c '
                    log="$1"; shift
                    .venv/bin/python "$@" >> "$log" 2>&1
                    rc=$?
                    echo "конец: $(date -u +%FT%TZ), код $rc" >> "$log"
                    # В git уходит ХВОСТ: зонд печатает прогресс
                    # тысячами строк, и целиком он там не нужен.
                    tail -n 400 "$log" > "$log.t" && mv "$log.t" "$log"
                    tools/publish.sh "job: $(basename "$log" .log)" \
                        >> "$log" 2>&1
                ' _ "$log" "$script" "${parts[@]:2}" 9>&- &
                echo "[$(now)] задание $name запущено: $script"
            fi
            ;;
        agents-run)
            # Роль автономной системы. Аргумент один и проверяется
            # ОТДЕЛЬНО от общего белого списка символов: имя роли —
            # это имя файла промпта, и всё, кроме букв и подчёркивания,
            # здесь означает попытку, а не опечатку.
            role="${parts[1]:-}"
            case "$role" in
                *[!a-z_]*|"") role="";; esac
            if [ -z "$role" ] \
               || [ ! -f "research/factory/agents/$role.md" ]; then
                echo "ОТКАЗ: роли нет: ${parts[1]:-—}" >> "$log"
            elif role_busy; then
                # Прогон роли отцеплен, поэтому развёртка идёт дальше и
                # доходит до следующего задания роли, пока первое ещё
                # работает: второе получало честный отказ по замку и
                # СЧИТАЛОСЬ выполненным. Задание остаётся в очереди —
                # следующая развёртка через пять минут возьмёт его.
                # Отметку `.done` не ставим: невыполненное задание,
                # помеченное выполненным, есть потеря работы.
                note "роль занята, задание $name ждёт следующей развёртки"
                continue
            else
                echo "запускаю роль: $role ${parts[*]:2}" >> "$log"
                # Фоном: прогон роли идёт минуты. Публикует себя сам —
                # и запускалка публикует свой артефакт, и очередь свой
                # лог, поэтому «прогона не было» и «прогон был, но
                # молча» различимы.
                setsid nohup nice -n 15 bash -c '
                    log="$1"; shift
                    tools/agents_run.sh "$@" >> "$log" 2>&1
                    rc=$?
                    echo "конец: $(date -u +%FT%TZ), код $rc" >> "$log"
                    tail -n 400 "$log" > "$log.t" && mv "$log.t" "$log"
                    tools/publish.sh "job: $(basename "$log" .log)" \
                        >> "$log" 2>&1
                ' _ "$log" "$role" "${parts[@]:2}" 9>&- &
                echo "[$(now)] задание $name: роль $role"
            fi
            ;;
        restart-book)
            echo "перезапуск сборщика и циклов" >> "$log"
            setsid nohup bash -c "tools/restart_book.sh >> '$log' 2>&1
                tools/publish.sh 'job: $name' >> '$log' 2>&1" 9>&- &
            echo "[$(now)] задание $name: перезапуск сборщика"
            ;;
        cli-update)
            # Обновление самого CLI, которым работают роли. Команда
            # фиксированная и без аргументов: в белом списке она
            # существует ровно потому, что модель, объявленная
            # владельцем, может требовать более свежий CLI, чем стоит
            # на машине, — и первый прогон роли падает на этом
            # громко, а лечится одной командой.
            {
                echo "версия до: $(claude --version 2>&1 | head -1)"
                claude update 2>&1 | tail -20
                echo "версия после: $(claude --version 2>&1 | head -1)"
                echo "конец: $(now)"
            } >> "$log" 2>&1
            tools/publish.sh "job: $name" >> "$log" 2>&1
            echo "[$(now)] задание $name: CLI обновлён"
            ;;
        status)
            {
                echo "--- диск ---"; df -h / /mnt/HC_Volume_* 2>/dev/null
                echo "--- процессы ---"
                pgrep -af "b1_book/collect.py|s8_loop/train.py|bot live" \
                    2>/dev/null || echo "нет"
                # Идущие прогоны отдельной строкой. Без них `status`
                # показывает исправный сервер и молчит о том, считает ли
                # что-нибудь прямо сейчас: длинное задание снаружи
                # неотличимо от повисшего, и это уже стоило ложного
                # диагноза. Список постоянных процессов выше не трогаем —
                # он отвечает на другой вопрос.
                echo "--- идущие прогоны ---"
                pgrep -af "python .*research/.*\.py" 2>/dev/null \
                    | grep -v "b1_book/collect.py\|s8_loop/train.py" \
                    || echo "нет"
                echo "--- статус сбора ---"
                head -c 700 research/b1_book/out/status.json 2>/dev/null
                echo; echo "--- живой исполнитель ---"
                head -c 700 bot/out/live/live_status.json 2>/dev/null
                echo; echo "конец: $(now)"
            } >> "$log" 2>&1
            tools/publish.sh "job: $name" >> "$log" 2>&1
            echo "[$(now)] задание $name: состояние снято"
            ;;
        *)
            echo "ОТКАЗ: неизвестное действие: $action" >> "$log"
            echo "[$(now)] задание $name отвергнуто (действие: $action)"
            ;;
        esac
    fi
    # Маркер ставится ВСЕГДА, даже на отказе: задание, отвергнутое
    # один раз, будет отвергнуто и в следующий раз, а сторож ходит
    # каждые пять минут — иначе журнал заполнится одним и тем же.
    date -u +"%FT%TZ" > "$DONE/$name.done"
done

[ "$found" = 1 ] || exit 0
exit 0
