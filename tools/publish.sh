#!/usr/bin/env bash
# Опубликовать артефакты прогона: отчёты и сводки — в git.
#
# Правило проекта: прогон идёт на сервере, а обсуждается в другом
# месте. Пересказывать консоль скриншотами значит терять числа и время,
# поэтому каждый этап пишет отчёт файлом, а эта команда его публикует.
#
# Что уходит и что нет, решают правила `.gitignore` этапов: отчёты и
# манифесты идут, ряды и журналы — нет. Здесь никакой отдельной логики
# отбора: два места, решающих одно и то же, однажды разойдутся.
#
#     tools/publish.sh "L2: проверка площадки исполнения"

set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
msg="${1:-артефакты прогона}"
branch="$(git rev-parse --abbrev-ref HEAD)"

# --ignore-removal, а не -A: команда публикации не вправе записывать
# удаления. Машина, где артефактов этапа нет на диске, иначе стирает их
# из репозитория, а следующий `git pull` стирает их и на сервере. В
# проекте это случалось дважды: с артефактами F1 и с манифестом L2.
# Отказ `git add` НЕ глотается. Раньше он уходил в /dev/null, и
# «нечего публиковать» звучало одинаково для трёх разных случаев:
# файлов нет, файлы гасит .gitignore, add сломался на пути. Отчёт
# прогона при этом лежал на диске, а в ветке было пусто.
if ! add_err="$(git add --ignore-removal research/*/out docs 2>&1)"; then
    echo "git add отказал: $add_err"
fi
[ -n "${add_err:-}" ] && echo "git add сказал: $add_err"
# Журналы прогонов не публикуются никогда, даже если попали под учёт
# раньше: они меняются каждым запуском, и на сервере это оборачивается
# «cannot pull with rebase: You have unstaged changes» — сведение веток
# встаёт, а прогон при этом уходит на старом коде. Так и вышло с
# research/t4_structure/out/run.log.
git reset -q -- 'research/*/out/*.log' 2>/dev/null || true

# Конфликт на артефакте разрешается в пользу того, что лежит на диске
# ЗДЕСЬ, то есть в пользу прогона. Так уже вышло однажды: в удалённой
# ветке имя отчёта было удалено из индекса, на сервере тот же файл
# записал настоящий прогон, и git отказался решать сам — а публикация
# оборвала сведение и оставила владельца разбираться вручную с телефона.
# Артефакт прогона авторитетнее любого состояния индекса: прогон
# случился, файл существует, его и оставляем. На конфликте вне `out`
# скрипт по-прежнему останавливается — код руками, всегда.
finish_rebase() {
  local i p unmerged bad
  for i in 1 2 3 4 5; do
    unmerged="$(git diff --name-only --diff-filter=U)"
    if [ -n "$unmerged" ]; then
      bad=0
      while IFS= read -r p; do
        [ -z "$p" ] && continue
        case "$p" in
          research/*/out/*)
            # Берём версию ПРОГОНА, а не то, что лежит на диске: при
            # конфликте git уже переписал файл своей склейкой с
            # маркерами `<<<<<<<`, и `git add` отправлял в историю
            # именно её. Так и вышло с отчётом перебора: в ветке
            # оказался отчёт, где обе колонки чисел стоят рядом с
            # маркерами, и читать его нельзя.
            #
            # Во время rebase стороны ПЕРЕВЁРНУТЫ: `--ours` это ветка,
            # НА которую переносят (удалённая), а `--theirs` — тот
            # коммит, который переносят, то есть наш прогон.
            if [ -e "$p" ]; then
              git checkout --theirs -- "$p" 2>/dev/null || true
              git add -- "$p"
            else
              git rm -q -- "$p"
            fi
            echo "  конфликт разрешён в пользу прогона: $p"
            ;;
          *)
            echo "  конфликт не в артефактах, разбирать руками: $p"
            bad=1
            ;;
        esac
      done <<< "$unmerged"
      [ "$bad" = 1 ] && return 1
    fi
    if [ -z "$(git diff --name-only --diff-filter=U)" ] \
       && git diff --cached --quiet; then
      # Замещать нечем: коммит целиком повторяет удалённое состояние.
      GIT_EDITOR=true git rebase --skip && return 0
    fi
    GIT_EDITOR=true git rebase --continue && return 0
  done
  return 1
}

# «Нечего коммитить» и «нечего публиковать» — разные вещи. Коммит мог
# быть сделан руками, а до удалённой ветки не дойти: именно так отчёт
# зонда ленты остался лежать на сервере, а я читал пустоту.
ahead="$(git rev-list --count "origin/$branch..HEAD" 2>/dev/null || echo 0)"
if git diff --cached --quiet && [ "$ahead" = "0" ]; then
  echo "нечего публиковать: в индекс не попало ни одного файла."
  echo "что git видит в артефактах (?? не отслеживается, !! погашен"
  echo ".gitignore, пусто — файла нет вовсе):"
  git status --porcelain --ignored -- research/*/out docs 2>/dev/null \
      | head -30 || true
  echo "нет строк выше — прогон писал не в этот каталог;"
  echo "строки с !! — правило .gitignore этапа гасит отчёт."
  exit 0
fi
if git diff --cached --quiet; then
  echo "новых артефактов нет, но $ahead коммит(ов) не опубликовано — толкаю"
  msg=""
fi

# Последняя защита: в артефакт не должны уезжать маркеры конфликта.
# Проверка дешёвая, а пропущенный маркер делает отчёт нечитаемым и
# живёт в истории — этот случай уже был.
marks="$(git diff --cached -U0 | grep -c '^+\(<<<<<<<\|=======$\|>>>>>>>\)' || true)"
if [ "${marks:-0}" != "0" ]; then
  echo "ОТКАЗ: в публикуемых файлах остались маркеры конфликта ($marks)."
  echo "Разберите руками: git diff --cached | grep -n '<<<<<<<'"
  exit 1
fi

echo "публикуется в ветку $branch:"
git diff --cached --stat

if [ -n "$msg" ]; then
  git commit -q -m "$msg"
fi

# Отказ бывает двух родов, и лечатся они по-разному. Сетевой сбой лечится
# повтором; отвергнутая не-перемотка — только подтягиванием чужих
# коммитов, и повторять push без этого бессмысленно. Первая версия
# скрипта повторяла четыре раза подряд одно и то же и сдавалась.
for attempt in 1 2 3 4; do
  if git push -u origin "$branch"; then
    echo "опубликовано"
    exit 0
  fi
  echo "push не прошёл, подтягиваю ветку и пробую снова "
  echo "(попытка $attempt из 4)"
  if ! git pull --rebase origin "$branch"; then
    if ! finish_rebase; then
      git rebase --abort 2>/dev/null || true
      echo "ветка разошлась и свести автоматически не вышло."
      echo "коммит на месте; разобрать вручную: git pull --rebase origin $branch"
      exit 1
    fi
  fi
  sleep $((2 ** attempt))
done

echo "push не прошёл после четырёх попыток — коммит на месте,"
echo "повторить можно командой: git push -u origin $branch"
exit 1
