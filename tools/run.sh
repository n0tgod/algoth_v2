#!/usr/bin/env bash
# Прогнать этап и опубликовать результат одной командой.
#
#     tools/run.sh "T1: поглощение с перевесом" \
#       research/t1_tape/probe.py --symbols BTCUSDT,ETHUSDT --start 2025-03-03
#
# Публикация перестала быть отдельным шагом намеренно. Прогон идёт часы,
# обсуждается в другом месте, и человек, вернувшийся к серверу через
# сутки, обязан застать результат уже в git, а не вспоминать вторую
# команду. Забытая публикация в этом проекте уже стоила круга: отчёт
# лежал на сервере, а читалась пустота.
#
# Три вещи, которые скрипт делает молча и которые важны:
#
# 1. Отвязывается от ssh (`setsid`), поэтому обрыв связи прогон не
#    убивает и `nohup` писать не нужно.
# 2. Публикует ТОЛЬКО при успехе. Упавший прогон оставляет за собой
#    недописанный артефакт, и опубликовать его значит предъявить обрывок
#    как результат.
# 3. Зовёт python из `.venv`, а не системный. Системный не имеет ни
#    numpy, ни duckdb, и прогон R1 однажды упал на сервере именно так.

set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

if [ $# -lt 2 ]; then
  echo "нужно: tools/run.sh \"сообщение для git\" путь/к/скрипту.py [аргументы]"
  exit 2
fi

msg="$1"
shift
script="$1"

py=".venv/bin/python"
if [ ! -x "$py" ]; then
  echo "нет $py — зависимости этапов живут в .venv, системный python их не имеет"
  exit 2
fi
if [ ! -f "$script" ]; then
  echo "нет файла $script"
  exit 2
fi

stage="$(dirname "$script")"
name="$(basename "$script" .py)"
log="$stage/out/$name.log"
mkdir -p "$stage/out"

# Второй заход — уже отвязанный от терминала: здесь и идёт работа.
if [ "${ALGOTH_RUN_CHILD:-}" = "1" ]; then
  echo "=== $(date -u +%Y-%m-%dT%H:%M:%SZ) прогон: $*"
  if "$py" "$@"; then
    echo "=== прогон кончился, публикую"
    # Своей строки об успехе здесь нет намеренно: `publish.sh` сам
    # говорит, опубликовал он что-то или публиковать было нечего, и
    # второй голос поверх первого однажды соврёт.
    if ! tools/publish.sh "$msg"; then
      echo "=== публикация не прошла; повторить: tools/publish.sh \"$msg\""
    fi
  else
    code=$?
    echo "=== прогон упал (код $code), публикации не будет"
  fi
  exit 0
fi

: > "$log"
ALGOTH_RUN_CHILD=1 setsid nohup "$0" "$msg" "$@" >> "$log" 2>&1 < /dev/null &
sleep 1
echo "запущено. журнал:"
echo "  tail -f $(pwd)/$log"
echo "процесс:"
echo "  pgrep -af $name.py"
