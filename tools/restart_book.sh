#!/usr/bin/env bash
# Перезапуск сборщика стакана — одной командой и без тихих отказов.
#
# Зачем отдельный файл, а не пять строк в чате
# --------------------------------------------
#
# Три перезапуска подряд стоили владельцу лишних кругов, и каждый раз по
# своей причине. Первый: `&` относился ко всей цепочке, поэтому `cd`
# уходил в фон и `tail` искал журнал не там. Второй: пересчёт застыл, а
# страница об этом молчала. Третий: `sleep 3` не хватило старому
# процессу на закрытие часовых файлов, новый упал на занятом порту — и
# на сервере продолжал работать СТАРЫЙ код, отдавая исправную с виду
# страницу.
#
# Общее у всех трёх — отказ был неотличим от успеха. Поэтому здесь
# каждый шаг проверяется, а не предполагается.
#
#   tools/restart_book.sh                # деплой: сборщик, страницы и циклы
#   tools/restart_book.sh --keep-cycle   # только сборщик: перезапуск по памяти
set -u

# `--keep-cycle` — перезапуск сборщика ПО ПАМЯТИ (сторож, потолок RSS),
# а не деплой: циклы обучения не трогаются. Обучение S8 держит 2–3.7 ГБ
# три с половиной часа, и перезапуск, убивающий его ради памяти
# сборщика, лечил бы нехватку памяти нехваткой обучения. Неизвестный
# аргумент — отказ, а не молчаливый деплой.
KEEP_CYCLE=0
for arg in "$@"; do
    case "$arg" in
        --keep-cycle) KEEP_CYCLE=1 ;;
        *) echo "ОШИБКА: неизвестный аргумент: $arg"; exit 2 ;;
    esac
done

cd "$(dirname "$0")/.." || exit 1
PAT='b1_book/collect.py'
LOG=research/b1_book/out/collect.log

echo "== останавливаю прежний =="
pkill -f "$PAT" 2>/dev/null

# Ждём НАСТОЯЩЕГО выхода, а не назначенных секунд: на TERM сборщик
# дожимает часовые файлы, и сколько это займёт, заранее неизвестно.
for i in $(seq 1 60); do
    pgrep -f "$PAT" >/dev/null || break
    [ "$i" = 1 ] && printf 'жду закрытия файлов'
    printf '.'
    sleep 1
done
echo

if pgrep -f "$PAT" >/dev/null; then
    echo "не закрылся за минуту — добиваю"
    pkill -9 -f "$PAT" 2>/dev/null
    sleep 2
fi
if pgrep -f "$PAT" >/dev/null; then
    echo "ОШИБКА: процесс жив даже после KILL, запуск отменён"
    exit 1
fi

echo "== обновляю код =="
# Недоступный git не отменяет запуск: сторож зовёт этот скрипт, чтобы
# поднять упавший сбор, и зависимость подъёма от доступности GitHub
# означала бы «сеть мигнула — сбор лежит до ручного вмешательства».
# `--autostash` обязателен, а не удобен: на сервере прогоны пишут
# отчёты в `out/`, и любой непубликованный отчёт делает дерево грязным.
# Без автостеша `git pull --rebase` отказывается, и обновление кода
# срывается из-за файла, который сам же прогон и создал — ровно это
# случилось 3 августа с отчётом показа. Автостеш ничего не теряет:
# при конфликте изменения остаются в стеше.
# Перезапуск по памяти (`--keep-cycle`) код НЕ подтягивает: это не
# деплой, а подъём того же сборщика с чистой памятью. Подтягивание на
# случайной минуте — это ещё одна встреча веток с автостешем на дереве,
# где лежат непубликованные артефакты; 05.10 23:00 ровно такой pull,
# судя по признакам, оставил на сервере несведённый конфликт карты, и
# публикации с очередью встали на час при исправных страницах. Деплой
# идёт только явным `restart-book`.
if [ "$KEEP_CYCLE" = 1 ]; then
    echo "код не подтягиваю (--keep-cycle: перезапуск по памяти, не деплой)"
else
    git pull --rebase --autostash \
        || echo "ВНИМАНИЕ: git pull не прошёл — запускаю на текущем коде"
fi

echo "== запускаю =="
# MALLOC_ARENA_MAX=2: у glibc каждый поток заводит свою арену памяти,
# а у сборщика их полсотни (двадцать соединений, страницы, сторожа), и
# каждая держит свой пик разбора JSON, не возвращая его системе —
# 06.10 через минуту после подъёма процесс весил 0.7 ГБ при ~0.2 ГБ
# живых объектов. Две арены вместо полусотни — обычная настройка для
# многопоточного Python; числа она не трогает, только память.
( MALLOC_ARENA_MAX=2 nohup .venv/bin/python research/b1_book/collect.py --http 8765 \
    >> "$LOG" 2>&1 & )

# Проверяем, что он ЖИВ, а не что команда вернулась. Упавший на старте
# процесс возвращает ноль так же охотно, как работающий.
sleep 12
if ! pgrep -f "$PAT" >/dev/null; then
    echo "ОШИБКА: сборщик не поднялся. Хвост журнала:"
    tail -20 "$LOG"
    exit 1
fi

echo "== поднялся, хвост журнала =="
tail -8 "$LOG"

# Циклы обучения — тем же скриптом, и это не удобство, а тот же дефект,
# от которого файл и заведён. Скрипт обновлял код и перезапускал
# СБОРЩИК, а `train.py` продолжал работать прежним процессом со старым
# кодом в памяти. Снаружи всё выглядело развёрнутым: pull прошёл,
# сборщик поднялся, страница исправна — а новая правка не работала.
# Ровно это и случилось 5 августа: цикл 07:07 отработал старым кодом и
# не проставил сделкам книгу, хотя коммит уже лежал на диске.
#
# Убиваем и НЕ поднимаем сами: подъём — дело сторожа, и второе место,
# знающее команду запуска, однажды разойдётся с первым.
if [ "$KEEP_CYCLE" = 1 ]; then
    echo "== циклы обучения не трогаю (--keep-cycle: перезапуск по памяти, не деплой) =="
    exit 0
fi
echo "== перезапускаю циклы обучения =="
# Предпросмотр снят (2026-08-07): его строка осталась в списке, чтобы
# ПОГАСИТЬ уже работающий на сервере цикл — сторож его больше не
# поднимет, и после первого такого деплоя строка находит пустоту.
# Боевой цикл запускается БЕЗ аргументов, поэтому шаблон якорится
# концом строки. Тот же шаблон стоит у сторожа; разойтись им нельзя.
for P in "s8_loop/train.py --pretest" "s8_loop/train.py$"; do
    pgrep -f "$P" >/dev/null || { echo "  не запущен: $P"; continue; }
    pkill -f "$P" 2>/dev/null
    for i in $(seq 1 20); do
        pgrep -f "$P" >/dev/null || break
        sleep 1
    done
    if pgrep -f "$P" >/dev/null; then
        echo "  ОШИБКА: не остановился: $P"
    elif [ "$P" = "s8_loop/train.py$" ]; then
        echo "  остановлен, сторож поднимет: $P"
    else
        echo "  остановлен НАВСЕГДА (предпросмотр снят): $P"
    fi
done
