#!/usr/bin/env bash
# Сторож сбора: поднимает умершее и перезапускает зависшее.
#
# Ставится в cron и на перезагрузку сервера:
#
#     crontab -e
#     */5 * * * * /root/algoth_v2/tools/watchdog_book.sh >> /root/algoth_v2/research/b1_book/out/watchdog.log 2>&1
#     @reboot sleep 30 && /root/algoth_v2/tools/watchdog_book.sh >> /root/algoth_v2/research/b1_book/out/watchdog.log 2>&1
#
# Три случая, и каждый проверяется отдельно, потому что выглядят они
# по-разному:
#
# 1. Процесс сборщика УМЕР (OOM, kill, перезагрузка сервера) —
#    ловится pgrep.
# 2. Процесс ЖИВ, но ЗАВИС или потерял все соединения — pgrep его не
#    отличает от здорового. Ловится свежестью status.json: сборщик
#    пишет его каждые 5 секунд, и файл старше трёх минут означает, что
#    внутри всё стоит, как бы бодро процесс ни выглядел снаружи.
#    Урок проекта: тишина неотличима от поломки, поэтому мерим данные,
#    а не признаки жизни.
# 3. Цикл обучения умер — он спит сутками, поэтому для него довод
#    только pgrep: свежесть его артефактов сутками старая ПО ДЕЛУ.
#
# Обрывы, которые сторожа НЕ требуют (уже самовосстанавливаются):
# падение API биржи — шарды переподключаются с отступом 1→30 с вечно;
# отказ REST-опроса — счётчик и повтор через 5 минут; битый час на
# диске — дожимается и спасается при следующем старте.

set -u
cd "$(dirname "$0")/.."

STATUS=research/b1_book/out/status.json
STALE_SEC=180
now() { date -u +"%Y-%m-%dT%H:%M:%SZ"; }

# Момент счёта артефакта книги (`computed_at`), секундами; 0 — файла нет
# или метка не читается. Триггер книг — этот момент, а не mtime файла.
computed_ts() {
    local at
    at=$(grep -o '"computed_at": *"[^"]*"' "$1" 2>/dev/null \
         | head -1 | cut -d'"' -f4)
    [ -n "$at" ] && date -u -d "$at UTC" +%s 2>/dev/null || echo 0
}

# Общий счёт считается ПОСЛЕ книг, из которых он читает: его кэши пишут
# прогоны коротких и длинных книг, и свой таймер давал ему читать кэш
# ПРОШЛОГО часа (2026-09-23: короткие книги показали два новых шорта,
# общий счёт — ноль, потому что считался на 16 минут раньше них).
# Должен — когда ОБА артефакта-источника новее его собственного.
#   $1 общий счёт, $2 короткие книги, $3 длинные книги
pair_due() {
    local p s l
    p=$(computed_ts "$1"); s=$(computed_ts "$2"); l=$(computed_ts "$3")
    [ "$s" -gt "$p" ] && [ "$l" -gt "$p" ]
}
# Самоостанов прогона по памяти — не повод перезапускать его следующим
# тактом (13.10: «СТОП: память» каждые 5 минут трое суток держал память
# занятой, и обучение S8 откладывалось). Последняя строка лога — самоостанов,
# и лог моложе часа — ждать. $1 лог, $2 сейчас (сек, для проверок).
stopped_recently() {
    local now=${2:-$(date -u +%s)} m
    [ -f "$1" ] || return 1
    tail -n 3 "$1" | grep -q "СТОП: память" || return 1
    m=$(stat -c %Y "$1" 2>/dev/null || echo 0)
    [ $(( now - m )) -lt 3600 ]
}
# Гейт памяти для прогонов книг (починка 10.10). Обучение S8 теперь
# начинается, когда память позволяет, а не в фиксированный час, и
# пропуск часов 02 и 06 его не защищает: 05:05 UTC ядро убило
# обучение (3.3 ГБ) рядом с часовыми прогонами книг (≈1.2 ГБ каждый).
# Прогон книг переносится на следующий такт, пока доступной памяти
# меньше порога; строка называет числа. Нет меры (/proc не читается)
# — идём без гейта, и это сказано. `MEMINFO` подменяется проверками.
MEMINFO=${MEMINFO:-/proc/meminfo}
BOOK_MEM_MIN_MB=2500
mem_avail_mb() {
    awk '/^MemAvailable:/ {print int($2/1024)}' "$MEMINFO" 2>/dev/null
}
# Второй гейт — ПО ЦИКЛУ, не по свободной памяти (14:56 10.10): RSS
# обучения плавает между 2.5 и 3.7 ГБ, и в 14:55 гейт по MemAvailable
# пропустил прогон книг, а минутой позже ядро убило цикл на пике —
# пятое потерянное обучение за день. Правило то же, что у деплоя
# (`restart_book.sh`): цикл тяжелее `TRAIN_BUSY_MB` — учится, книги
# ждут такта. Цикла нет или `ps` молчит — ноль, гейт по памяти остаётся.
# 15.10, сервер 16 ГБ (CCX23): часовой цикл без обучения сам держит до
# 2.2 ГБ после матрицы, и порог 2000 откладывал книги каждый час; обучение
# (2.5–4.5 ГБ) и книги (до 3.6) теперь помещаются рядом — порог 5000
# ловит только разнос, остальное решает гейт по свободной памяти.
TRAIN_BUSY_MB=${TRAIN_BUSY_MB:-5000}
# Флаг цикла «обучение S8 ждёт памяти или идёт» (15.10, `train.py`
# `wait_train_mem`): файл с pid цикла. Пока процесс жив — книги уступают:
# разовая проверка памяти в :09 раз за разом попадала на соседний прогон
# книг и откладывала обучение на час (веса 29 ч). Флаг без живого
# процесса — мусор упавшего цикла, сносится.
TRAIN_WAIT_FLAG=${TRAIN_WAIT_FLAG:-research/s8_loop/out/train_wait.flag}
train_waiting() {
    local pid
    [ -f "$TRAIN_WAIT_FLAG" ] || return 1
    pid=$(head -c 32 "$TRAIN_WAIT_FLAG" 2>/dev/null | head -n1 | tr -dc '0-9')
    if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
        return 0
    fi
    rm -f "$TRAIN_WAIT_FLAG"
    return 1
}
train_rss_mb() {
    local pids kb
    pids=$(pgrep -d' ' -f "s8_loop/train.py$" 2>/dev/null || true)
    if [ -z "$pids" ]; then
        echo 0
        return
    fi
    kb=$(ps -o rss= -p "$(echo "$pids" | tr ' ' ',')" 2>/dev/null | sort -n | tail -1 | tr -d ' ')
    echo "$(( ${kb:-0} / 1024 ))"
}
# Третий гейт — ОДИН прогон книг за раз (14.10): в 03:10 UTC память
# только что перевалила за порог, и в одном такте стартовали длинные и
# короткие книги — каждая видела 2500 МБ свободными, вдвоём они их
# съели; ядро убило прогон длинных (1.85 ГБ) и цикл S8 (2.36 ГБ, книги
# часа; обучение кончилось за два часа до того). Гейт по памяти мерит
# «сейчас», а не «после старта соседа», поэтому второй прогон ждёт
# такта: идёт любой прогон книг или в этом такте один уже запущен
# (`BOOKS_LAUNCHED` — `pgrep` только что запущенного может не увидеть).
BOOKS_LAUNCHED=""
# Каденция книг (владелец 14.10, спека 17 путь 1): длинные — каждые 5 мин
# (тёплый прогон 47 с), короткие — каждые 15 (145 с), общий счёт — после
# источников (30 с). Так исполнения внутри часа видны в приложении не
# через час, а через минуты. Публикация в git — раз в час (минута < 5):
# артефакты по 1.5 МБ, двенадцать коммитов в час раздули бы историю.
BOOKS_EVERY_S=${BOOKS_EVERY_S:-300}
SHORT_EVERY_S=${SHORT_EVERY_S:-900}
publish_flag() {
    if [ "$(date -u +%M | sed 's/^0//')" -lt 5 ]; then echo ""; else echo "--no-publish"; fi
}
books_running() {
    pgrep -f "dca_paper/run_(paper|short|pair)[.]py" >/dev/null 2>&1
}
books_mem_ok() {
    local a t
    if [ -n "$BOOKS_LAUNCHED" ]; then
        echo "[$(now)] прогон книг отложен: в этом такте уже запущен ${BOOKS_LAUNCHED} — по одному"
        return 1
    fi
    if books_running; then
        echo "[$(now)] прогон книг отложен: идёт другой прогон книг — по одному"
        return 1
    fi
    t=$(train_rss_mb)
    if [ "${t:-0}" -gt "$TRAIN_BUSY_MB" ]; then
        echo "[$(now)] прогон книг отложен: идёт обучение S8 (цикл ${t} МБ > ${TRAIN_BUSY_MB})"
        return 1
    fi
    if train_waiting; then
        echo "[$(now)] прогон книг отложен: обучение S8 ждёт памяти или идёт (флаг ${TRAIN_WAIT_FLAG})"
        return 1
    fi
    a=$(mem_avail_mb)
    if [ -z "$a" ]; then
        echo "[$(now)] память не измерена ($MEMINFO) — прогон книг без гейта по памяти"
        return 0
    fi
    if [ "$a" -ge "$BOOK_MEM_MIN_MB" ]; then
        return 0
    fi
    echo "[$(now)] прогон книг отложен: доступно ${a} МБ при пороге"          "${BOOK_MEM_MIN_MB} — рядом обучение или тяжёлый прогон"
    return 1
}

# --- порт 80 → сборщик -----------------------------------------------
# Страница наблюдения, очередь заданий (`/jobs-poke`) и проверка ACME
# (`/.well-known/acme-challenge/`) живут на 80, а сборщик слушает 8765:
# правило NAT ставилось руками и ПЕРЕЗАГРУЗКУ НЕ ПЕРЕЖИВАЕТ (15.10,
# после rescale: 443 жив, 80 — 503, единственный канал ассистента
# пропал). Сторож проверяет правило каждый такт и ставит, если его нет.
if command -v iptables >/dev/null 2>&1; then
    if ! iptables -t nat -C PREROUTING -p tcp --dport 80 -j REDIRECT --to-port 8765 >/dev/null 2>&1; then
        if iptables -t nat -A PREROUTING -p tcp --dport 80 -j REDIRECT --to-port 8765 2>/dev/null; then
            echo "[$(now)] порт 80: правила NAT не было (перезагрузка?) — поставлено 80 → 8765"
        else
            echo "[$(now)] порт 80: правило NAT поставить не удалось — страница, очередь и ACME на 80 недоступны"
        fi
    fi
fi

# --- сборщик ---------------------------------------------------------
need_restart=""
if ! pgrep -f "b1_book/collect.py" >/dev/null; then
    need_restart="процесс сборщика не найден"
elif [ -f "$STATUS" ]; then
    age=$(( $(date +%s) - $(stat -c %Y "$STATUS") ))
    if [ "$age" -gt "$STALE_SEC" ]; then
        need_restart="status.json не обновлялся ${age} с — сборщик завис"
    else
        # Свежесть status.json пишет ОТДЕЛЬНЫЙ поток, поэтому она
        # остаётся зелёной при мёртвом сборщике снимков — так 2 августа
        # запись книги встала на сутки при полностью исправном виде.
        # Мерить надо ту величину, ради которой всё работает: возраст
        # последнего записанного снимка.
        snap_age=$(sed -n 's/.*"last_snap_age_sec":[ ]*\([0-9.]*\).*/\1/p' \
                   "$STATUS" | cut -d. -f1)
        if [ -z "$snap_age" ]; then
            : # сборщик старого образца поля не пишет — не судим
        elif [ "$snap_age" -gt "$STALE_SEC" ]; then
            need_restart="снимки книги не пишутся ${snap_age} с при живом процессе"
        fi
    fi
else
    need_restart="status.json отсутствует при живом процессе"
fi

if [ -n "$need_restart" ]; then
    echo "[$(now)] ПЕРЕЗАПУСК СБОРЩИКА: $need_restart — цикл обучения не трогаю"
    # Подъём упавшего сборщика — не деплой (деплой — задание restart-book):
    # цикл обучения к нему отношения не имеет. 17.10 08:05–09:35 UTC полный
    # перезапуск на каждом самоостанове сборщика гасил и цикл — каждые
    # 5–10 мин; живой цикл сторож не трогает, мёртвый поднимает ниже.
    tools/restart_book.sh --keep-cycle
else
    : # здоров — молчим, лог не засоряем
fi

# --- память сборщика --------------------------------------------------
# Замер 05.10 22:42 UTC: RSS сборщика 2448 МБ через 25 ч после подъёма
# при ≈ 1.5 ГБ на старте — рост ≈ 0.9 ГБ в сутки; MemAvailable 3300 МБ
# при пороге обучения S8 3072. Ещё час-два такого роста — и обучение
# снова откладывается каждый час, как 30.09 → 04.10 (109 ч без
# обучения), а снаружи всё исправно. Причина роста не найдена; пока она
# ищется, сборщик перезапускается ПО МЕРЕ, а не по часам: по потолку
# RSS, и строка называет число и возраст — каждый перезапуск есть точка
# замера роста (сутки по часам скрыли бы его). Потолок из бюджета
# машины: 7745 МБ минус 3072 гейту обучения, минус ≈ 1.6 ГБ цикла после
# матрицы, минус ≈ 0.5 ГБ прочего — сборщику остаётся ≈ 2.6 ГБ. База
# свежего сборщика — НЕ 1.5 ГБ из памяти проекта: 05.10 23:12 через
# 12 минут после подъёма он держал 2113 МБ (кэши страниц и журналов
# книг поднимаются на старте), потолок 2200 перезапускал бы его
# каждый час. 2500 — между базой и бюджетом; перезапуск по нему и
# есть замер роста. Цикл обучения НЕ трогается (`--keep-cycle`): это
# не деплой. Ниже потолка блок молчит; «не измерено» — отдельная
# строка, а не тишина.
# 17.10: выше жёсткого порога самоограничителя (4400, машина 15.6 ГБ):
# первым действует сам процесс, сторож — страховка.
COLLECT_RSS_MAX_MB=4800
if [ -z "$need_restart" ]; then
    cpids=$(pgrep -d, -f "b1_book/collect.py")
    if [ -n "$cpids" ]; then
        rss_kb=$(ps -o rss= -p "$cpids" 2>/dev/null | sort -n | tail -1 | tr -d ' ')
        if [ -z "$rss_kb" ]; then
            echo "[$(now)] память сборщика не измерена (ps пуст для pid $cpids)"
        elif [ "$(( rss_kb / 1024 ))" -gt "$COLLECT_RSS_MAX_MB" ]; then
            age_s=$(ps -o etimes= -p "$cpids" 2>/dev/null | sort -n | tail -1 | tr -d ' ')
            echo "[$(now)] ПЕРЕЗАПУСК СБОРЩИКА ПО ПАМЯТИ: RSS $(( rss_kb / 1024 )) МБ" \
                 "при потолке ${COLLECT_RSS_MAX_MB}, возраст $(( ${age_s:-0} / 3600 )) ч" \
                 "— цикл обучения не трогаю"
            tools/restart_book.sh --keep-cycle
        fi
    fi
fi

# --- цикл обучения ---------------------------------------------------
# Шаблон якорится концом строки по наследству: раньше рядом жил
# предпросмотр (`train.py --pretest`), и без якоря pgrep находил его и
# считал боевой цикл живым. Предпросмотр снят решением владельца
# (2026-08-07) — сторож его больше не поднимает, а якорь остаётся:
# однажды рядом снова окажется процесс с аргументами.
if ! pgrep -f "s8_loop/train.py$" >/dev/null; then
    echo "[$(now)] цикл обучения не найден — поднимаю"
    setsid nohup .venv/bin/python research/s8_loop/train.py \
        >> research/s8_loop/out/train.log 2>&1 &
fi

# --- обучение S8: стоит ли ---------------------------------------------
# Цикл жив по pgrep и при этом может не учиться неделями: 30.09 → 04.10
# он каждый час честно откладывал обучение по памяти — в лог, который
# никто не читает, — и книги жили на весах пятидневной давности при
# исправных страницах. Правило одно (`s8_loop/stall.py`): веса старше
# 36 ч — тревога; ниже порога блок молчит, выше — строка каждый такт и
# просьба владельцу один раз на эпизод. Не блокирует ничего.
if [ -x .venv/bin/python ] && [ -f tools/train_alarm.py ]; then
    .venv/bin/python tools/train_alarm.py || true
fi

# --- исполнительное ядро (Rust-тень) ---------------------------------
# Секция молчит, пока бинарник не собран: ядро разворачивают отдельным
# решением, и его отсутствие — состояние, а не поломка. У собранного —
# те же два довода, что у сборщика: процесс жив (pgrep) и внутри
# движется (свежесть status.json; ядро пишет его каждый такт, минута).
BOT_BIN=bot/target/release/bot
BOT_STATUS=bot/out/shadow/status.json
# Маркер выключения (пишет tools/run_bot.sh --off) — СОСТОЯНИЕ, не
# поломка: секция молчит целиком, как молчит при несобранном бинарнике.
# Перезапуск при маркере воскрешал бы то, что владелец выключил.
SHADOW_OFF=bot/out/SHADOW_OFF
if [ -x "$BOT_BIN" ] && [ ! -f "$SHADOW_OFF" ]; then
    bot_restart=""
    if ! pgrep -f "bot run --s8" >/dev/null; then
        bot_restart="процесс ядра не найден"
    elif [ ! -f "$BOT_STATUS" ]; then
        bot_restart="status.json ядра отсутствует при живом процессе"
    else
        bot_age=$(( $(date +%s) - $(stat -c %Y "$BOT_STATUS") ))
        if [ "$bot_age" -gt 300 ]; then
            bot_restart="status.json ядра не обновлялся ${bot_age} с — повис"
        fi
    fi
    if [ -n "$bot_restart" ]; then
        echo "[$(now)] ПЕРЕЗАПУСК ЯДРА: $bot_restart"
        tools/run_bot.sh --no-build
    fi
fi

# --- API приложения (спека 15, этап Y0) --------------------------------
# Поднимается только когда на сервере лежит подготовленное состояние
# (`run tools/app_api/init.py`: конверты, токен оператора, TLS): без
# него молчание — состояние, а не поломка. Ключей биржи процесс не
# видит — только конверты; порт 443.
API_OUT=tools/app_api/out
API_STATUS=$API_OUT/status.json
API_OFF=$API_OUT/API_OFF
if [ -f "$API_OUT/master.pub" ] && [ -f "$API_OUT/tls/cert.pem" ] && [ ! -f "$API_OFF" ]; then
    api_restart=""
    API_DEAF=$API_OUT/deaf.since
    if ! pgrep -f "app_api/server.py" >/dev/null; then
        api_restart="процесс API не найден"
    elif ! curl -sk -m 10 -o /dev/null "https://127.0.0.1:${API_PORT:-443}/api/v1/health"; then
        # Живой процесс — не отвечающий (11.10: TLS-рукопожатие в главном
        # потоке, один молчащий клиент держал приём часами). Два такта
        # подряд без ответа — перезапуск; один — может быть перезапуск
        # из очереди в эту же минуту.
        if [ -f "$API_DEAF" ]; then
            api_restart="процесс есть, но не отвечает на health с $(cat "$API_DEAF")"
            pkill -f "app_api/server.py" || true
            sleep 2
            rm -f "$API_DEAF"
        else
            now > "$API_DEAF"
            echo "[$(now)] API не ответил на health — проверю следующим тактом"
        fi
    else
        rm -f "$API_DEAF"
    fi
    if [ -n "$api_restart" ]; then
        echo "[$(now)] ЗАПУСК API ПРИЛОЖЕНИЯ: $api_restart"
        mkdir -p "$API_OUT"
        setsid nohup .venv/bin/python tools/app_api/server.py >> "$API_OUT/server.log" 2>&1 < /dev/null &
    fi
fi

# --- сертификат API: продление Let's Encrypt (спека 16 L2, 14.10) --------
# Сертификат на 90 суток выпущен на ключ API (пин приложения не меняется).
# Раз в сутки в 04 UTC: продление, если осталось < 30 суток; новый
# сертификат записан — API перезапускается. Осталось < 14 суток — строка
# тревоги каждый такт: молчаливое истечение уронит и сайт, и приложение.
ACME_LOG=$API_OUT/acme.log
