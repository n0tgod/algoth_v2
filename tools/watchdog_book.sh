#!/usr/bin/env bash
# Сторож сбора: поднимает умершее и перезапускает зависшее.
#
# Ставится в cron и на перезагрузку сервера:
#
#     crontab -e
#     */5 * * * * /root/algoth_v2/tools/watchdog_book.sh >> /root/algoth_v2/research/b1_book/out/watchdog.log 2>&1
#     @reboot sleep 30 && /root/algoth_v2/tools/watchdog_book.sh >> /root/algoth_v2/research/b1_book/out/watchdog.log 2>&1
#
# Три случая, и каждый проверяется отдельно, потому что выглядят они
# по-разному:
#
# 1. Процесс сборщика УМЕР (OOM, kill, перезагрузка сервера) —
#    ловится pgrep.
# 2. Процесс ЖИВ, но ЗАВИС или потерял все соединения — pgrep его не
#    отличает от здорового. Ловится свежестью status.json: сборщик
#    пишет его каждые 5 секунд, и файл старше трёх минут означает, что
#    внутри всё стоит, как бы бодро процесс ни выглядел снаружи.
#    Урок проекта: тишина неотличима от поломки, поэтому мерим данные,
#    а не признаки жизни.
# 3. Цикл обучения умер — он спит сутками, поэтому для него довод
#    только pgrep: свежесть его артефактов сутками старая ПО ДЕЛУ.
#
# Обрывы, которые сторожа НЕ требуют (уже самовосстанавливаются):
# падение API биржи — шарды переподключаются с отступом 1→30 с вечно;
# отказ REST-опроса — счётчик и повтор через 5 минут; битый час на
# диске — дожимается и спасается при следующем старте.

set -u
cd "$(dirname "$0")/.."

STATUS=research/b1_book/out/status.json
STALE_SEC=180
now() { date -u +"%Y-%m-%dT%H:%M:%SZ"; }

# --- сборщик ---------------------------------------------------------
need_restart=""
if ! pgrep -f "b1_book/collect.py" >/dev/null; then
    need_restart="процесс сборщика не найден"
elif [ -f "$STATUS" ]; then
    age=$(( $(date +%s) - $(stat -c %Y "$STATUS") ))
    if [ "$age" -gt "$STALE_SEC" ]; then
        need_restart="status.json не обновлялся ${age} с — сборщик завис"
    else
        # Свежесть status.json пишет ОТДЕЛЬНЫЙ поток, поэтому она
        # остаётся зелёной при мёртвом сборщике снимков — так 2 августа
        # запись книги встала на сутки при полностью исправном виде.
        # Мерить надо ту величину, ради которой всё работает: возраст
        # последнего записанного снимка.
        snap_age=$(sed -n 's/.*"last_snap_age_sec":[ ]*\([0-9.]*\).*/\1/p' \
                   "$STATUS" | cut -d. -f1)
        if [ -z "$snap_age" ]; then
            : # сборщик старого образца поля не пишет — не судим
        elif [ "$snap_age" -gt "$STALE_SEC" ]; then
            need_restart="снимки книги не пишутся ${snap_age} с при живом процессе"
        fi
    fi
else
    need_restart="status.json отсутствует при живом процессе"
fi

if [ -n "$need_restart" ]; then
    echo "[$(now)] ПЕРЕЗАПУСК СБОРЩИКА: $need_restart"
    tools/restart_book.sh
else
    : # здоров — молчим, лог не засоряем
fi

# --- цикл обучения ---------------------------------------------------
# Шаблон якорится концом строки по наследству: раньше рядом жил
# предпросмотр (`train.py --pretest`), и без якоря pgrep находил его и
# считал боевой цикл живым. Предпросмотр снят решением владельца
# (2026-08-07) — сторож его больше не поднимает, а якорь остаётся:
# однажды рядом снова окажется процесс с аргументами.
if ! pgrep -f "s8_loop/train.py$" >/dev/null; then
    echo "[$(now)] цикл обучения не найден — поднимаю"
    setsid nohup .venv/bin/python research/s8_loop/train.py \
        >> research/s8_loop/out/train.log 2>&1 &
fi

# --- исполнительное ядро (Rust-тень) ---------------------------------
# Секция молчит, пока бинарник не собран: ядро разворачивают отдельным
# решением, и его отсутствие — состояние, а не поломка. У собранного —
# те же два довода, что у сборщика: процесс жив (pgrep) и внутри
# движется (свежесть status.json; ядро пишет его каждый такт, минута).
BOT_BIN=bot/target/release/bot
BOT_STATUS=bot/out/shadow/status.json
# Маркер выключения (пишет tools/run_bot.sh --off) — СОСТОЯНИЕ, не
# поломка: секция молчит целиком, как молчит при несобранном бинарнике.
# Перезапуск при маркере воскрешал бы то, что владелец выключил.
SHADOW_OFF=bot/out/SHADOW_OFF
if [ -x "$BOT_BIN" ] && [ ! -f "$SHADOW_OFF" ]; then
    bot_restart=""
    if ! pgrep -f "bot run --s8" >/dev/null; then
        bot_restart="процесс ядра не найден"
    elif [ ! -f "$BOT_STATUS" ]; then
        bot_restart="status.json ядра отсутствует при живом процессе"
    else
        bot_age=$(( $(date +%s) - $(stat -c %Y "$BOT_STATUS") ))
        if [ "$bot_age" -gt 300 ]; then
            bot_restart="status.json ядра не обновлялся ${bot_age} с — повис"
        fi
    fi
    if [ -n "$bot_restart" ]; then
        echo "[$(now)] ПЕРЕЗАПУСК ЯДРА: $bot_restart"
        tools/run_bot.sh --no-build
    fi
fi

# --- место на диске ---------------------------------------------------
# Запись книги — единственные данные, которых нельзя докачать: архива
# стакана не существует нигде. Заполненный диск не «замедляет», а
# обрывает сбор, и узнать об этом по молчанию нельзя. Сборщик считает
# срок сам (`days_left` в status.json), сторож его читает и КРИЧИТ
# заранее — за неделю, чтобы диск успели расширить.
# Порог берётся по СВОБОДНОМУ МЕСТУ, а не по сроку `days_left`. Срок
# считается по скорости записи за последний час, а она скачет не от
# сбора: раз в час закрываются сотни файлов, очередь сжатия отстаёт, и
# несжатые часы на диске дают всплеск до 1013 МБ/ч вместо 58 — срок
# падает с 40 суток до двух и возвращается назад через десять минут.
# Тревога, кричащая ложно, перестаёт быть сигналом. Свободное место от
# очереди сжатия так не скачет.
FREE_WARN_GB=12
if [ -f "$STATUS" ]; then
    free=$(sed -n 's/.*"free_gb":[ ]*\([0-9.]*\).*/\1/p' "$STATUS" \
           | cut -d. -f1)
    left=$(sed -n 's/.*"days_left":[ ]*\([0-9.]*\).*/\1/p' "$STATUS" \
           | cut -d. -f1)
    if [ -n "$free" ] && [ "$free" -lt "$FREE_WARN_GB" ]; then
        echo "[$(now)] ДИСК: свободно ${free} ГБ (срок по текущей" \
             "скорости ~${left} сут) — расширять"
    fi
fi

# --- суточный круг фабрики агентов -----------------------------------
# Один шаг круга за такт, а не круг целиком: такт сторожа идёт раз в
# пять минут, роль работает минуты, судья — часы. Решает `cycle.py`,
# читая состояние С ДИСКА, поэтому обрыв посреди круга ничего не
# теряет и повторный вызов безвреден.
#
# Предохранители живут в самом `cycle.py` (выключатель, предел
# прогонов ролей за сутки, час начала) — здесь их дублировать нельзя:
# два места, решающих одно, однажды разойдутся.
#
# Вывод уходит в свой лог: круг говорит на каждом такте, и его строки
# не должны тонуть в журнале сторожа.
if [ -x .venv/bin/python ] && [ -f research/factory/cycle.py ]; then
    nice -n 10 .venv/bin/python research/factory/cycle.py \
        >> research/factory/out/cycle.log 2>&1 || true
fi

# --- турнир политик (спека 10) ---------------------------------------
# Раз в сутки, в ночное окно 02:xx UTC: реплей журнала листов по всем
# 72 вариантам и публикация артефактов. Триггер — ВОЗРАСТ артефакта, а
# не память сторожа: сторож без состояния, возраст файла переживает
# перезагрузку. Догоняющий запуск при артефакте старше 48 ч (сервер
# мог проспать своё окно), первый на чистом каталоге — сразу, без
# ожидания ночи. Прогон идёт с пониженным приоритетом: сборщик и
# боевой цикл важнее. Код прогона сторож НЕ обновляет — деплой
# остаётся за git pull владельца.
TOUR=research/s10_policy/out/V1-tournament.json
TOUR_LOG=research/s10_policy/out/tournament.log
if ! pgrep -f "s10_policy/tournament.py" >/dev/null; then
    tour_age=999999999
    if [ -f "$TOUR" ]; then
        tour_age=$(( $(date +%s) - $(stat -c %Y "$TOUR") ))
    fi
    if { [ "$(date -u +%H)" = "02" ] && [ "$tour_age" -gt 43200 ]; } \
       || [ "$tour_age" -gt 172800 ]; then
        echo "[$(now)] турнир политик: артефакту ${tour_age} с — запускаю прогон"
        setsid nohup bash -c "
            nice -n 10 .venv/bin/python research/s10_policy/tournament.py \
                >> $TOUR_LOG 2>&1 \
            && tools/publish.sh 'V1: суточный прогон турнира политик' \
                >> $TOUR_LOG 2>&1" &
    fi
fi

# --- свежие данные и бумажная месячная книга --------------------------
# Раз в сутки, в окно 06:xx UTC: докачка хранилища A2 свежими барами
# Binance, следом — бумажная книга. Порядок именно такой: книга
# считается ПО хранилищу, и без докачки она не запишет ни одного
# настоящего наблюдения — упрётся в край.
#
# Окно 06 часов, а не полночь: суточный архив Binance за день `D`
# выходит ПОСЛЕ конца суток `D`, и к шести утра он опубликован. Это
# та же структурная задержка, из-за которой решение на дату `D`
# нельзя посчитать раньше `D + 1` ни при каком расписании.
#
# Триггер — ВОЗРАСТ артефакта книги, а не память сторожа: сторож без
# состояния, возраст файла переживает перезагрузку. Догоняющий запуск
# при артефакте старше 36 ч (сервер мог проспать окно), первый на
# чистом каталоге — сразу. Пропущенный день не теряется: догон
# досчитает его, но решение станет ВОССТАНОВЛЕННЫМ, а не настоящим —
# ради этого ежедневность и нужна.
#
# Цепочка через `;`, а не `&&`: если докачка не прошла (сеть, архив),
# книга обязана посчитать то, что есть, и сама скажет причину. Записать
# лишнего она не может — решение без бара своей даты не создаётся.
PAPER=research/paper_monthly/out/PAPER-30d.json
PAPER_LOG=research/paper_monthly/out/daily.log
if ! pgrep -f "a2_storage/refresh.py|paper_monthly/book.py" >/dev/null; then
    paper_age=999999999
    if [ -f "$PAPER" ]; then
        paper_age=$(( $(date +%s) - $(stat -c %Y "$PAPER") ))
    fi
    if { [ "$(date -u +%H)" = "06" ] && [ "$paper_age" -gt 43200 ]; } \
       || [ "$paper_age" -gt 129600 ]; then
        echo "[$(now)] книга: артефакту ${paper_age} с — докачка и прогон"
        setsid nohup bash -c "
            nice -n 10 .venv/bin/python research/a2_storage/refresh.py \
                --interval 1m >> $PAPER_LOG 2>&1
            nice -n 10 .venv/bin/python research/paper_monthly/book.py \
                --catchup >> $PAPER_LOG 2>&1" &
    fi
fi

# --- бумажные DCA-книги: живой ход записи ------------------------------
# Владелец 2026-09-04: «запустить книги в live, подтянуть бэктест и
# продолжить его живыми данными, не разделяя». Показ это делает (кривая
# одна, у сделки бэктеста метка), а сам ПРОГОН оставался ручным заданием
# очереди — и книга поэтому стояла: открытые позиции считает только
# счётный прогон, а `--restat` пересобирает сводку из журнала и честно
# пишет «не считали».
#
# Каденция — час: журнал листов пополняется каждый час, значит с этим же
# шагом появляются новые решения, а отметка открытой позиции стареет
# вместе с ценой. Прогон дёшев не по случайности: кэш реплея
# пересчитывает только новые и НЕзакрытые решения — 2026-09-05 тёплый
# прогон посчитал 400 решений из 8689 за 53 с.
#
# Часы 02 и 06 UTC пропускаются ради ХОЛОДНОГО прогона: с пустым кэшем
# (или после смены правил) он стоит 17–19 минут, а в эти окна идут
# ночной турнир и докачка хранилища с месячной книгой — третий тяжёлый
# счёт рядом с записью стакана её прореживает, а докачать её неоткуда.
# Возраст растёт, и в 03 или 07 книга догоняет сама.
#
# Триггер — `computed_at` артефакта, а не его mtime: `--restat`
# переписывает файл, СОХРАНЯЯ эту метку, то есть она отвечает «когда
# считали», а не «когда трогали файл». Метки нет либо она не читается —
# считаем: прогон идемпотентен и стоит минуту, а молчащая книга стоит
# суток наблюдения.
DCAP=research/dca_paper/out/DCA-paper.json
DCAP_LOG=research/dca_paper/out/daily.log
if ! pgrep -f "dca_paper/run_paper.py" >/dev/null; then
    dca_age=999999999
    if [ -f "$DCAP" ]; then
        dca_at=$(grep -o '"computed_at": *"[^"]*"' "$DCAP" \
                 | head -1 | cut -d'"' -f4)
        if [ -n "$dca_at" ]; then
            dca_ts=$(date -u -d "$dca_at UTC" +%s 2>/dev/null || true)
            if [ -n "$dca_ts" ]; then
                dca_age=$(( $(date -u +%s) - dca_ts ))
            fi
        fi
    fi
    dca_hh=$(date -u +%H)
    if [ "$dca_hh" != "02" ] && [ "$dca_hh" != "06" ] \
       && [ "$dca_age" -gt 3600 ]; then
        echo "[$(now)] DCA-книги: последний счёт ${dca_age} с назад — прогон"
        setsid nohup bash -c "
            nice -n 10 .venv/bin/python research/dca_paper/run_paper.py \
                >> $DCAP_LOG 2>&1" &
    fi
fi

# --- очередь заданий (docs/00-INDEX.md) -------------------------------
# Ассистент кладёт задание файлом в git, сервер его выполняет: прямого
# доступа к серверу у ассистента нет (наружу открыты только 80 и 443),
# а открывать исполнение по HTTP рядом с ключами биржи — плохой обмен.
# Что можно выполнить, решает `tools/jobs.sh` белым списком; произвол
# невозможен по построению, аудит — история git.
if [ -x tools/jobs.sh ]; then
    tools/jobs.sh
fi
