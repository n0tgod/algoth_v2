#!/usr/bin/env bash
# Свести конфликт на ГЕНЕРИРУЕМОЙ карте кода — и только на ней.
#
# Зачем. `docs/MAP*.md` пересобирает хук на КАЖДОЙ стороне: и в сессии,
# и на сервере. Две стороны правят один файл автоматически, поэтому
# любая встреча веток даёт конфликт — не смысловой, а механический.
# Публикация с сервера на нём останавливается («конфликт не в
# артефактах, разбирать руками»), коммит остаётся лежать локально, и
# очередь заданий после этого не берётся ни за одно задание: она
# отказывается работать на разошедшемся дереве. Так канал вставал
# трижды за сутки, и каждый раз его разбирал владелец руками с консоли.
#
# Правило: содержимое карты не хранится, а ВЫВОДИТСЯ из исходников,
# поэтому у конфликта здесь нет двух версий-кандидатов — есть одна,
# пересобранная. Берём любую сторону, пересобираем и кладём в индекс.
# Пересборка не удалась (нет питона, чужое дерево) — конфликт всё равно
# снимается: карту перестроит хук на первом же коммите, а замерший
# канал публикации стоит дороже суточной свежести карты.
#
# Смысловые конфликты (код, спеки, журнал) эта команда НЕ трогает:
# она смотрит ровно на три пути.
set -u
cd "$(git rev-parse --show-toplevel 2>/dev/null)" || exit 1
MAPS="docs/MAP.md docs/MAP-symbols.md docs/MAP-tests.md"
# shellcheck disable=SC2086
un="$(git diff --name-only --diff-filter=U -- $MAPS 2>/dev/null)"
[ -z "$un" ] && exit 0
echo "$un" | while IFS= read -r p; do
    [ -z "$p" ] && continue
    git checkout --theirs -- "$p" 2>/dev/null \
        || git checkout --ours -- "$p" 2>/dev/null || true
done
python3 tools/project_map.py >/dev/null 2>&1 || \
    echo "  карта не пересобрана (её перестроит хук на первом коммите)"
# shellcheck disable=SC2086
git add -- $un 2>/dev/null || true
echo "  конфликт на генерируемой карте кода сведён пересборкой:" \
     "$(echo "$un" | tr '\n' ' ')"
