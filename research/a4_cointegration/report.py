HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
sys.path.insert(0, HERE)

import walkforward as W  # noqa: E402


def read(name):
    path = os.path.join(OUT, name)
    if not os.path.exists(path):
        raise SystemExit(f"нет {path} — сначала посчитать прогон")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def pct(x):
    return "—" if x is None or not np.isfinite(x) else f"{100*x:.1f} %"


def num(x, d=1):
    return "—" if x is None or not np.isfinite(x) else f"{x:.{d}f}"


def main():
    wf = read("walkforward_summary.json")
    cmp_ = read("A4-null-comparison.json")
    sweep = read("sweep_2025-06-15.json")
    s = wf["summary"]
    rows = sorted(wf["windows"], key=lambda r: r["date"])
    P = print

    P("# Этап A4 — тест на коинтеграцию по сетке walk-forward")
    P()
    P("Спека 02: §3.2 (Энгл–Грейнджер только на окне отбора), §3.3 "
      "(поправка на множественность и обязательный артефакт «до и "
      "после»), §3.4 (отбраковка по полураспаду), §6 (протокол окон), "
      "§7 (сравнение с нулевой моделью), §8 (критерии).")
    P()
    fa = cmp_["all_windows"]
    fl = cmp_["late_windows"]
    a = s["adjacent"]
    P("## 0. Итог")
    P()
    P(f"Критерий 1 не выполнен: пар после FDR на окно "
      f"**{num(s['fdr_pass_mean'])}** при пороге 50, медиана "
      f"{num(s['fdr_pass_median'], 0)}. Критерий 2 не выполнен: "
      f"выживаемость между соседними окнами **{pct(a['survival'])}** при "
      f"пороге 30 %. Правило немедленной остановки не сработало — окон с "
      f"менее чем 15 парами {s['windows_fdr_below_15']} из {s['windows']} "
      f"при требуемом большинстве.")
    P()
    P(f"**Главное не в этом.** Тот же конвейер на перемешанных метках "
      f"групп даёт те же числа: доля сырых срабатываний "
      f"{pct(fa['real']['raw_pass_share'])} против "
      f"{pct(fa['null']['raw_pass_share'])}, доля прошедших поправку "
      f"{pct(fa['real']['fdr_pass_share'])} против "
      f"{pct(fa['null']['fdr_pass_share'])} — у нуля выше. Выживаемость "
      f"на соседних окнах {pct(fa['real']['adjacent']['survival'])} против "
      f"{pct(fa['null']['adjacent']['survival'])} — у нуля тоже выше. "
      f"Экономическая группировка §3.1 не добавляет ничего измеримого.")
    P()
    P(f"В срезе богатых окон ({fl['real']['windows']} окон, "
      f"{num(fl['real']['candidates_mean'], 0)} кандидатов на окно, ни "
      f"одного окна с нулём пар) на расстоянии трёх шагов, где окна "
      f"отбора не делят ни одного дня данных, обе ветки сидят на "
      f"случайности: превосходство над случайным отбором "
      f"×{num(fl['real']['three_steps']['survival_over_chance'])} у "
      f"прогона и "
      f"×{num(fl['null']['three_steps']['survival_over_chance'])} у нуля.")
    P()
    P("## 1. Что и как считалось")
    P()
    P("| параметр | значение | откуда |")
    P("|---|---|---|")
    P(f"| шаг бара | {wf['step']} | замер, раздел 2 |")
    P(f"| окно отбора | {wf['form_days']} дней | тест видит только "
      f"`[t−{wf['form_days']}, t)` |")
    P(f"| эмбарго | {wf['embargo_days']} дней | §6, больше максимума "
      f"удержания в 5 дней |")
    P(f"| торговое окно и шаг сетки | {wf['trade_days']} дней | §6 |")
    P(f"| уровень FDR | {wf['alpha']} | §3.3 |")
    P(f"| максимальный полураспад | {wf['max_half_life_days']:.0f} дней | "
      f"§3.4 в части, не зависящей от издержек |")
    P()
    P(f"Окон: **{s['windows']}**, с {rows[0]['date']} по {rows[-1]['date']}. "
      f"Проверено **{s['tested_total']}** пар-кандидатов.")
    P()
    P("Все параметры зафиксированы до прогона. Нижней границы полураспада "
      "нет намеренно: «слишком быстрый возврат» отбраковывается не "
      "полураспадом, а сравнением амплитуды σ спреда с издержками, а "
      "посимвольная комиссия и funding — предмет A6.")
    P()

    P("## 2. Шаг бара выбран измерением")
    P()
    P("Спека задаёт 1m как разрешение хранения (§2.2). Разрешение "
      "хранения и разрешение теста — разные вещи, и второго спека не "
      "задаёт. Выбрано на 300 парах в одном окне.")
    P()
    P("| шаг | наблюдений | p<0.05 | после FDR | полураспад медиана | β медиана |")
    P("|---|---|---|---|---|---|")
    for step, v in sweep["steps"].items():
        if v.get("skipped"):
            P(f"| {step} | — | — | — | — | пропущен: {v['skipped']} |")
            continue
        P(f"| {step} | {v['obs_median']} | {v['raw_pass']}/{v['tested']} | "
          f"{v['fdr_pass']} | {num(v['half_life_days_p50'])} дн | "
          f"{num(v['beta_median'], 3)} |")
    P()
    P("Доля прошедших растёт с измельчением бара — это свойство теста, "
      "мощность против сколь угодно слабого возврата растёт с выборкой. "
      "Решает другое: **полураспад тех же пар, измеренный в сутках**, "
      "укорачивается вместе с шагом. Полураспад в единицах времени — "
      "свойство спреда, а не сетки наблюдений, и от шага зависеть не "
      "должен.")
    P()
    P("| шаг | полураспад относительно замера на 4h, медиана | пар |")
    P("|---|---|---|")
    for step, v in sweep["half_life_invariance"].items():
        P(f"| {step} | {num(v['p50'], 2)} | {v['pairs']} |")
    P()
    P("Монотонное сползание к нулю — подпись микроструктурного шума: "
      "отскок между сторонами стакана даёт отрицательную "
      "автокорреляцию, которая на минуте видна, а на часах "
      "усредняется. Взят **1h**: наблюдений на порядок выше порога, "
      "искажение полураспада 6 % против 31 % на 1m, 24 лага ADF "
      "накрывают сутки, и 0.074 с на пару против 2.86 — на сетке из 48 "
      "окон это часы против суток.")
    P()
    e = sweep["epps"]
    P(f"**Открытый пункт A2 закрыт для β уровней.** Эффект Эппса на "
      f"оценку не влияет: β(1m)/β(1h) по {e['pairs']} парам — 25/50/75 % "
      f"равны {num(e['beta_1m_over_1h_p25'], 3)} / "
      f"{num(e['beta_1m_over_1h_p50'], 3)} / "
      f"{num(e['beta_1m_over_1h_p75'], 3)}. Оговорка: Эппс бьёт по "
      f"оценкам на доходностях, и если A5 будет считать что-то по ним, "
      f"проверять придётся заново.")
    P()
    P("**Чего выбор не гарантирует.** Точка отсчёта в таблице "
      "инвариантности — сам замер на 4h, и тренд к ней не "
      "выполаживается: переход 4h → 1h всё ещё даёт −6 %. Значит и на "
      "1h полураспад слегка занижен, то есть пары выглядят быстрее, чем "
      "они есть, — ошибка в сторону оптимизма. Правильная проверка — "
      "окно от 200 дней, где становится возможен шаг 1d; на 90 днях его "
      "поставить не на чем.")
    P()

    P("## 3. Воронка по окнам (обязательный артефакт §3.3)")
    P()
    P("«Прогон» — кандидаты A3. «Нуль» — тот же конвейер на "
      "перемешанных метках групп, раздел 5.")
    P()
    P("| дата | кандидатов | | p<0.05 | | после FDR | |")
    P("|---|---|---|---|---|---|---|")
    P("| | прогон | нуль | прогон | нуль | прогон | нуль |")
    for f in cmp_["funnel"]:
        P(f"| {f['date']} | {f['candidates_real']} | {f['candidates_null']} "
          f"| {f['raw_real']} | {f['raw_null']} | **{f['fdr_real']}** | "
          f"{f['fdr_null']} |")
    P()
    P(f"Разница между «p<0.05» и «после FDR» — прямая мера того, "
      f"сколько мы едва не приняли за находку: в сумме "
      f"{int(s['raw_pass_mean']*s['windows'])} сырых срабатываний "
      f"против {int(s['fdr_pass_mean']*s['windows'])} переживших "
      f"поправку.")
    P()

    P("## 4. Против критериев раздела 8")
    P()
    P("| критерий | порог | получено | |")
    P("|---|---|---|---|")
    P(f"| 1. пар после FDR на окно | ≥ 50 | среднее "
      f"**{num(s['fdr_pass_mean'])}**, медиана "
      f"**{num(s['fdr_pass_median'], 0)}** | "
      f"**{'выполнен' if s['criterion_1_fdr_ge_50'] else 'не выполнен'}** |")
    P(f"| 2. выживание между соседними окнами | ≥ 30 % | "
      f"**{pct(a['survival'])}** | "
      f"**{'выполнен' if s['criterion_2_survival_ge_30pct'] else 'не выполнен'}** |")
    P(f"| правило немедленной остановки | окон с < 15 пар в большинстве | "
      f"**{s['windows_fdr_below_15']} из {s['windows']}** | "
      f"**{'СРАБОТАЛО' if s['stop_rule_triggered'] else 'не сработало'}** |")
    P()
    zero = sum(1 for r in rows if r["fdr_pass"] == 0)
    top4 = sorted(r["fdr_pass"] for r in rows)[-4:]
    total = sum(r["fdr_pass"] for r in rows)
    P(f"Среднее {num(s['fdr_pass_mean'])} при медиане "
      f"{num(s['fdr_pass_median'], 0)} — распределение без середины. В "
      f"**{zero} окнах из {s['windows']}** после поправки не выживает ни "
      f"одной пары, а четыре лучших окна дают "
      f"{100*sum(top4)/total:.0f} % всех отобранных за историю.")
    P()

    P("## 5. Выживаемость пар и нулевая модель")
    P()
    P("### 5.1 Как считается выживаемость")
    P()
    P("Пара исчезает из отбора по двум разным причинам: связь распалась "
      "(пару проверили, и она не прошла) либо её перестали проверять "
      "(нога вышла из кандидатов A3). Вторая причина к устойчивости "
      "отношения отношения не имеет, а в безусловной доле неотличима от "
      "первой. Знаменатель — только отобранные пары, дожившие до "
      "второго окна кандидатами.")
    P()
    P(f"На данных поправка оказалась мала: кандидаты переходят между "
      f"соседними окнами на {pct(a['candidate_carryover'])}, из "
      f"отобранных пар остаются кандидатами "
      f"{pct(a['selected_still_candidate'])}, условная и безусловная "
      f"доли расходятся в третьем знаке "
      f"({pct(a['survival'])} против {pct(a['survival_unconditional'])}). "
      f"Список тестируемого стабилен — распадаются именно связи, и "
      f"объяснить результат выбраковкой в A3 нельзя.")
    P()
    P("### 5.2 Нулевая модель §7")
    P()
    P("Перемешиваются метки групп между активами, фиксированным зерном "
      f"{cmp_['null_seed']}. Сохраняется всё: размеры групп (а значит и "
      "число кандидатов, от которого зависит порог BH), фильтр по "
      "обороту ×10, фильтр ликвидности, преемственность списка между "
      "окнами. Отнимается ровно одно — смысл метки.")
