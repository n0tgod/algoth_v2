#!/usr/bin/env python3
"""
A4 — тест на коинтеграцию и поправка на множественность.

Спека 02, разделы 3.2 и 3.3. Определения спреда и полураспада — спека 01,
раздел 2, и повторяются здесь ровно в том же виде:

    spread_t   = ln(P_A,t) − β · ln(P_B,t)
    Δspread_t  = λ · spread_{t−1} + ε
    half_life  = −ln(2) / λ

Почему корреляция не годится и нужен именно тест на стационарность:
два актива могут ходить вместе с корреляцией 0.9, а разность их
логарифмов уходить в бесконечность. Торгуется возврат спреда, а не
совместность движения.

**Главная ловушка этапа — размер выборки.** Мощность теста растёт с
числом наблюдений, а окно в 90 дней на минутных барах даёт 130 тысяч
точек. При такой выборке единичный корень отвергается у пары, спред
которой возвращается к среднему за сорок дней, — статистически это
коинтеграция, торгово это мусор при удержании 1–5 дней. Поэтому:

1. шаг бара выбирается измерением (`sweep.py`), а не по умолчанию;
2. вместе с p-значением всегда считается период полураспада, и он
   докладывается рядом. Значимость без полураспада — не результат.

Поправка на множественность — Бенджамини–Хохберг: контролируется доля
ложных среди отобранных. Бонферрони при тысячах тестов не оставит
ничего, включая настоящие находки.
"""

import numpy as np
from statsmodels.tsa.stattools import coint

# Направление регрессии фиксируется, иначе β и p-значение зависели бы от
# того, в каком порядке пара пришла из A3. Первой ногой берётся актив с
# бо́льшим оборотом — он же ликвиднее, и остаток регрессии на нём устойчивее.
MIN_OBS = 200          # меньше — оценка β шумнее, чем сам эффект

# Потолок числа лагов ADF. Правило Шверта, которым statsmodels выбирает
# максимум по умолчанию, на 130 тысячах минутных баров даёт 72 лага, и
# каждый лишний лаг — это регрессия на всей выборке: перебор по AIC
# становится дороже самого этапа. Содержательно лаги сверх суток баров
# ничего не добавляют, а перебор идёт по AIC внутри потолка, то есть
# правило выбора остаётся тем же на всех шагах.
LAG_CAP = 24


def log_prices(a, b):
    return np.log(a), np.log(b)


def ols_beta(la, lb):
    """β и свободный член регрессии ln P_A на ln P_B.

    Через нормальные уравнения: матрица 2x2, обусловленность здесь не
    проблема, а зависимость от внешней библиотеки — лишняя.
    """
    n = len(lb)
    sx, sy = lb.sum(), la.sum()
    sxx = float(lb @ lb)
    sxy = float(lb @ la)
    den = n * sxx - sx * sx
    if den == 0:
        return np.nan, np.nan
    beta = (n * sxy - sx * sy) / den
    alpha = (sy - beta * sx) / n
    return beta, alpha


def half_life(spread):
    """Полураспад по модели Орнштейна–Уленбека, спека 01 §2.4.

    Возвращает бесконечность, если λ ≥ 0: спред не возвращается, а
    расходится. Нуль и отрицательные значения полураспада смысла не
    имеют и наружу не выдаются.
    """
    s = np.asarray(spread, dtype=np.float64)
    ds = np.diff(s)
    prev = s[:-1]
    lam, _ = ols_beta(ds, prev)
    if not np.isfinite(lam) or lam >= 0:
        return np.inf
    return float(-np.log(2.0) / lam)


def test_pair(pa, pb):
    """Энгл–Грейнджер по паре цен. Возвращает словарь или None.

    p-значение берётся у statsmodels: критические значения Энгла–
    Грейнджера — это поверхность отклика Маккиннона, и своя реализация
    здесь была бы источником ошибок, которых никто не заметит.
    """
    if len(pa) < MIN_OBS or len(pb) < MIN_OBS:
        return None
    la, lb = log_prices(pa, pb)
    if not (np.all(np.isfinite(la)) and np.all(np.isfinite(lb))):
        return None
    maxlag = min(LAG_CAP, int(12 * (len(la) / 100.0) ** 0.25))
    stat, pvalue, _ = coint(la, lb, trend="c", maxlag=maxlag,
                            autolag="aic")
    beta, alpha = ols_beta(la, lb)
    spread = la - beta * lb - alpha
    return {"stat": float(stat), "p": float(pvalue), "beta": float(beta),
            "half_life": half_life(spread), "n": int(len(la)),
            "spread_sd": float(np.std(spread, ddof=1))}


def benjamini_hochberg(pvalues, alpha=0.10):
    """Индексы отвергнутых гипотез при контроле FDR на уровне alpha.

    Процедура шаговая: p-значения упорядочиваются, ищется наибольшее k,
    при котором p_(k) ≤ k/m · alpha, и отвергается всё до него включительно
    — в том числе те, чьё собственное p порог не проходит. Наивная
    проверка «p_i ≤ i/m·alpha по каждому» даёт другой, меньший набор, и
    это самая частая ошибка в реализациях.
    """
    p = np.asarray(pvalues, dtype=np.float64)
    m = len(p)
    if m == 0:
        return np.array([], dtype=int)
    order = np.argsort(p, kind="mergesort")
    ranked = p[order]
    thresh = (np.arange(1, m + 1) / m) * alpha
    passing = np.nonzero(ranked <= thresh)[0]
    if len(passing) == 0:
        return np.array([], dtype=int)
    kmax = passing[-1]
    return np.sort(order[: kmax + 1])
