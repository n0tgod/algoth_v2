#!/usr/bin/env python3
"""W1 — ядро волнового зонда: форма и зигзаг.

Владелец попросил проверить волновой анализ: «найти в данных
повторяющиеся волны, чтобы на этом строить стратегии». Слово «волна» у
трейдера значит одно, у статистика другое, и зонд обязан мерить обе
прочитки, а не выбирать удобную.

**Прочитка 1 — форма повторяется.** Никаких допущений о том, что такое
волна: берётся путь цены за последние `W` баров, снимается уровень и
масштаб, и ищутся ближайшие по форме куски ИЗ ПРОШЛОГО. Если формы
повторяются со смыслом, будущее соседей предсказывает будущее запроса.

**Прочитка 2 — структура волн (то, что трейдер называет Эллиоттом).**
Цена раскладывается зигзагом на ноги, и меряется распределение
коэффициента отката `|нога n| / |нога n−1|`. Центральное числовое
утверждение волнового анализа — что откаты садятся на уровни Фибоначчи
(0.382, 0.5, 0.618) — проверяемо прямо: случайное блуждание с тем же
распределением приращений даёт СВОЁ распределение откатов, и вопрос
ровно в том, отличается ли настоящее.

Три правила, без которых зонд мерил бы не то
--------------------------------------------

1. **Зигзаг причинный.** Вершина видна не в вершине, а тогда, когда
   цена отошла от неё на порог. `zigzag` возвращает обе метки —
   индекс самой вершины и индекс её ПОДТВЕРЖДЕНИЯ; разница между ними
   и есть цена честности. Разметка, берущая вершину в момент вершины,
   заглядывает в будущее — и именно так волновая разметка обычно и
   рисуется.
2. **Замороженный ряд формой не является.** A2 нашла 84 инструмента,
   у которых архив публикует бар с перенесённой ценой годами после
   смерти. У такого пути σ равна нулю или дрожанию последнего знака, а
   z-нормировка делит на σ — то есть раздувает округление в «форму»,
   идеально повторяющуюся по всему универсуму. Это ловушка S1
   (обратная волатильность без пола) в новом костюме, и `znorm` кладёт
   пропуск, а не единичный вектор.
3. **Разрыв записи рвёт волну.** Ряд дырявый, и путь, склеенный через
   шестичасовую дыру, — не наблюдение. Зигзаг сбрасывает состояние на
   разрыве длиннее `MAX_GAP`, форма с любым пропуском внутри окна не
   строится вовсе.

Ядро ничего не решает о торгуемости: ни стопа, ни цели, ни размера. Оно
даёт формы, соседей и ноги; меряет и судит `probe.py`.
"""

import numpy as np

# Пропусков подряд больше — зигзаг начинается заново. Число объявлено
# до прогона: на часовой сетке шесть часов тишины у ликвидного перпа
# означают не «волну», а дыру записи.
MAX_GAP = 6

# Путь, весь размах которого меньше этого, формой не считается. Пять
# базисных пунктов на сутки часовых баров — это не волна, а шаг цены.
MIN_PATH_SD_BP = 5.0

# Уровни Фибоначчи и полуширина полосы, в которой считается попадание.
# Объявлены ДО прогона: подобрать ширину после того, как виден
# результат, значит найти кластер там, где его нет.
FIB_LEVELS = (0.382, 0.500, 0.618, 0.786, 1.000, 1.618)
FIB_BAND = 0.02


def zigzag(x, theta, max_gap=MAX_GAP):
    """Причинный зигзаг: подтверждённые развороты по порогу `theta`.

    `x` — логарифмическая цена, пропуски — NaN. `theta` — порог
    разворота в тех же единицах (то есть в долях, а не в процентах).

    Возвращает список `(i_pivot, i_confirm, d)`, где `d` — знак ноги,
    ЗАКОНЧИВШЕЙСЯ в `i_pivot` (`+1` — вершина, то есть нога шла вверх;
    `−1` — впадина). `i_confirm` — момент, когда разворот стало видно.

    Почему меток две. В `i_pivot` о вершине не знает никто: цена ещё не
    отошла. Знание появляется в `i_confirm`, и любое правило входа
    обязано пользоваться им, а не самой вершиной. Разница между метками
    неустранима и растёт с порогом — это и есть плата за уверенность в
    развороте.

    Промежуточных баров ниже подтверждающего быть не может: `i_confirm`
    есть ПЕРВЫЙ бар, ушедший за порог, значит все бары между вершиной и
    им лежат выше `экстремум − theta`, а сам он не выше. Поэтому новый
    экстремум начинается ровно с подтверждающего бара, и это не
    приближение.
    """
    n = len(x)
    out = []
    if n == 0 or not np.isfinite(theta) or theta <= 0:
        return out
    fin = np.isfinite(x)
    i0 = int(np.argmax(fin)) if fin.any() else -1
    if i0 < 0:
        return out
    hi = lo = float(x[i0])
    hi_i = lo_i = i0
    d = 0                       # 0 — направление ещё не известно
    last = i0
    for i in range(i0 + 1, n):
        if not fin[i]:
            continue
        if i - last > max_gap:
            # Разрыв записи. Волна через дыру не продолжается: то, что
            # выглядело бы ногой, есть склейка двух кусков.
            hi = lo = float(x[i])
            hi_i = lo_i = i
            d = 0
            last = i
            continue
        last = i
        v = float(x[i])
        if d >= 0 and v > hi:
            hi, hi_i = v, i
        if d <= 0 and v < lo:
            lo, lo_i = v, i
        if d >= 0 and v <= hi - theta:
            out.append((hi_i, i, +1))
            d = -1
            lo, lo_i = v, i
        elif d <= 0 and v >= lo + theta:
            out.append((lo_i, i, -1))
            d = +1
            hi, hi_i = v, i
    return out


def _gap_inside(x, i0, i1, max_gap):
    """Есть ли внутри отрезка разрыв записи длиннее `max_gap` баров."""
    run = 0
    for i in range(i0 + 1, i1):
        if np.isfinite(x[i]):
            run = 0
        else:
            run += 1
            if run > max_gap:
                return True
    return False


def legs(x, piv, max_gap=None):
    """Ноги и коэффициенты отката по подтверждённым разворотам.

    Возвращает список словарей: размер ноги в долях (`size`, всегда
    положителен), её длительность в барах (`bars`), направление (`dir`),
    цены концов (`px_from`, `px_to`), отношение к предыдущей ноге
    (`ratio`, у первой ноги — NaN) и обе метки конца ноги — сама
    вершина и её подтверждение.

    `max_gap` — найденный дефект и его починка: зигзаг после дыры
    записи начинается заново, но плоский список вершин об этом молчит,
    и пара «последняя вершина до дыры → первая после» выглядела обычной
    ногой — склейкой двух кусков под видом движения. Если `max_gap`
    задан, такая пара ногой не считается. Умолчание None сохраняет
    прежний счёт бит в бит: опубликованный отчёт W1 считался без
    фильтра, и молча менять его числа нельзя.

    Отношение и есть предмет проверки Фибоначчи: волновой анализ
    утверждает, что откаты садятся на 0.382 / 0.5 / 0.618.
    """
    out = []
    prev = None
    for k in range(1, len(piv)):
        i0, _, _ = piv[k - 1]
        i1, ic1, d1 = piv[k]
        a, b = float(x[i0]), float(x[i1])
        if not (np.isfinite(a) and np.isfinite(b)):
            prev = None
            continue
        if max_gap is not None and _gap_inside(x, i0, i1, max_gap):
            prev = None
            continue
        size = abs(b - a)
        rec = {"i_from": i0, "i_to": i1, "i_confirm": ic1,
               "dir": d1, "size": size, "bars": i1 - i0,
               "px_from": a, "px_to": b,
               "ratio": (size / prev) if (prev and prev > 0) else np.nan}
        out.append(rec)
        prev = size
    return out


def fib_shares(ratios, levels=FIB_LEVELS, band=FIB_BAND):
    """Доля откатов, попавших в полосу вокруг каждого уровня.

    Мера намеренно простая: трейдер обязан иметь возможность проверить
    её карандашом. Сравнивать её надо не с нулём, а с той же долей у
    суррогата — у зигзага есть собственная геометрия, и она сама по
    себе даёт неровное распределение.
    """
    r = np.asarray([v for v in ratios if np.isfinite(v)], dtype=np.float64)
    out = {"n": int(len(r))}
    for f in levels:
        out[f] = (float(np.mean(np.abs(r - f) <= band)) if len(r)
                  else float("nan"))
    return out


def block_bootstrap(d, block, rng):
    """Суррогат приращений: те же значения, порядок разбит блоками.

    Зачем блоки, а не простая перестановка. Полная перестановка рвёт и
    волны, и кластеризацию волатильности разом — а кластеризация
    волатильности заведомо есть, и разница с ней читалась бы как
    «волны существуют». Блок длиной в сутки сохраняет её внутри блока и
    рвёт всё, что длиннее. Отличие от суррогата и есть структура
    ДЛИННЕЕ блока — то, на что претендует волновой анализ.

    Пропуски остаются на своих местах: суррогат обязан иметь ту же
    дырявость, иначе у него будет больше наблюдений, чем у оригинала.
    """
    d = np.asarray(d, dtype=np.float64)
    fin = np.isfinite(d)
    vals = d[fin]
    m = len(vals)
    if m == 0:
        return np.full(len(d), np.nan)
    nb = int(np.ceil(m / block))
    starts = rng.integers(0, max(m - block, 1), size=nb)
    take = np.concatenate([vals[s:s + block] for s in starts])[:m]
    if len(take) < m:                       # короткий ряд: добираем с начала
        take = np.resize(take, m)
    out = np.full(len(d), np.nan)
    out[fin] = take
    return out


def znorm(X, min_sd_bp=MIN_PATH_SD_BP):
    """Формы: уровень снят, масштаб снят, строки единичной длины.

    После нормировки скалярное произведение двух строк есть в точности
    корреляция их путей — то есть поиск ближайшей формы становится
    умножением матриц, а не перебором.

    Снятие масштаба здесь не удобство, а разделение сигналов. Величина
    хода — это уже измеренный проектом краткосрочный возврат (R2,
    зонд возврата, D1). Поделив на собственный размах, мы оставляем
    ТОЛЬКО форму: если она предсказывает, это второй сигнал, а не тот
    же самый в новом костюме.

    Путь с размахом меньше пола формой не является и возвращается
    строкой пропусков — правило 2 модуля.
    """
    X = np.asarray(X, dtype=np.float32)
    if X.ndim != 2 or X.shape[1] < 2:
        raise ValueError("формы — матрица (строк × длина пути ≥ 2)")
    Z = X - X.mean(axis=1, keepdims=True)
    nrm = np.sqrt((Z.astype(np.float64) ** 2).sum(axis=1))
    sd_bp = nrm / np.sqrt(X.shape[1]) * 1e4
    ok = np.isfinite(nrm) & (nrm > 0) & (sd_bp >= min_sd_bp)
    Z = np.divide(Z, np.where(ok, nrm, np.nan)[:, None],
                  out=np.full_like(Z, np.nan), where=ok[:, None])
    Z[~ok] = np.nan
    return Z, ok


def top_neighbours(Q, POOL, k, block=2048, forbid=None):
    """`k` ближайших по форме из прошлого: индексы и сходство.

    Возвращает `(idx, sim)` — по строке на запрос. Сходство есть
    корреляция путей, потому что строки единичной длины.

    Считается блоками запросов: матрица «все запросы × весь пул» на
    живых размерах не помещается в память, а прогон, убитый ядром по
    памяти, уже стоил проекту суток (D1). Размер блока — параметр, а не
    константа: он не меняет ответа, и это закреплено проверкой.

    `forbid` — необязательная функция `(строки запросов) -> маска
    (запросы × пул)`, которой пул запрещается. Через неё зонд убирает
    соседей из того же времени: у одновременных соседей будущее одно и
    то же — рынок, — и предсказание выродилось бы в подсматривание.
    """
    nq = Q.shape[0]
    k = int(min(k, POOL.shape[0]))
    idx = np.full((nq, k), -1, dtype=np.int64)
    sim = np.full((nq, k), np.nan, dtype=np.float32)
    if k <= 0 or nq == 0:
        return idx, sim
    PT = np.ascontiguousarray(POOL.T)
    for a in range(0, nq, block):
        b = min(a + block, nq)
        q = Q[a:b]
        good = np.isfinite(q).all(axis=1)
        if not good.any():
            continue
        S = q[good] @ PT                       # корреляции: строки единичны
        if forbid is not None:
            S = np.where(forbid(np.arange(a, b)[good]), -np.inf, S)
        part = np.argpartition(-S, kth=k - 1, axis=1)[:, :k]
        vals = np.take_along_axis(S, part, axis=1)
        order = np.argsort(-vals, axis=1)
        rows = np.flatnonzero(good) + a
        idx[rows] = np.take_along_axis(part, order, axis=1)
        sim[rows] = np.take_along_axis(vals, order, axis=1)
    sim[~np.isfinite(sim)] = np.nan
    return idx, sim


def spearman(a, b):
    """Ранговая корреляция по конечным парам. NaN, если пар меньше трёх."""
    a = np.asarray(a, dtype=np.float64)
    b = np.asarray(b, dtype=np.float64)
    ok = np.isfinite(a) & np.isfinite(b)
    if int(ok.sum()) < 3:
        return float("nan")
    x, y = a[ok], b[ok]
    rx = _rank(x)
    ry = _rank(y)
    rx = rx - rx.mean()
    ry = ry - ry.mean()
    den = np.sqrt((rx * rx).sum() * (ry * ry).sum())
    return float((rx * ry).sum() / den) if den > 0 else float("nan")


def _rank(v):
    """Ранги со средним для совпадений: ничья не вправе давать порядок."""
    order = np.argsort(v, kind="mergesort")
    r = np.empty(len(v), dtype=np.float64)
    r[order] = np.arange(len(v), dtype=np.float64)
    s = v[order]
    i = 0
    while i < len(s):
        j = i
        while j + 1 < len(s) and s[j + 1] == s[i]:
            j += 1
        if j > i:
            r[order[i:j + 1]] = (i + j) / 2.0
        i = j + 1
    return r
