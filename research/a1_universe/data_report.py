    for k in ("0.05", "0.25", "0.5", "0.75", "0.95"):
        na = m["naive_abs_diff_pp"].get(k)
        al = m["aligned_abs_diff_pp"].get(k)
        if na is None or al is None:
            continue
        add(f"| {int(float(k)*100)} % | {na:.1f} | {al:.1f} |")
    add(f"| максимум | {m['naive_max_abs_pp']:.1f} | {m['aligned_max_abs_pp']:.1f} |")
    add("")

    add("### 4.2 Что было хвостом\n")
    add("Активы с наибольшим расхождением по сводкам — и они же после")
    add("выравнивания.\n")
    top = sorted((v for v in usable.values() if v["naive_diff_pp"] is not None),
                 key=lambda v: -abs(v["naive_diff_pp"]))[:10]
    add("| Актив | По сводкам, п.п. | На пересечении, п.п. | Окно, дней |")
    add("|---|---:|---:|---:|")
    for v in top:
        add(f"| {v['bybit_symbol']} | {v['naive_diff_pp']:+.1f} | "
            f"{v['diff_pp']:+.1f} | {v['span_days']:.0f} |")
    add("")

    add("### 4.3 Что остаётся после выравнивания\n")
    worst = sorted(usable.values(), key=lambda v: -abs(v["diff_pp"]))[:10]
    add("| Актив | Bybit, годовых | Binance, годовых | Разница, п.п. | Окно, дней |")
    add("|---|---:|---:|---:|---:|")
    for v in worst:
        add(f"| {v['bybit_symbol']} | {v['bybit_ann_pct']:+.1f} % | "
            f"{v['binance_ann_pct']:+.1f} % | {v['diff_pp']:+.1f} | {v['span_days']:.0f} |")
    add("")
    add(f"Знак издержки различается у {m['sign_disagreement']} активов из "
        f"{m['assets_usable']}: на одной площадке позиция получает funding, на")
    add("другой платит. Ставка Bybit выше у "
        f"{m['bybit_higher']} активов — систематического перекоса нет, и это")
    add("важно: расхождение не сводится к постоянной поправке, которую можно")
    add("было бы один раз вычесть.\n")

    # --- 4.4 показательный случай
    ill = max((v for v in A.values() if v["naive_diff_pp"] is not None),
              key=lambda v: abs(v["naive_diff_pp"]))
    add("### 4.4 Чем опасна оценка по сводкам\n")
    add(f"Крайний случай — {ill['bybit_symbol']}. По сводкам за всю историю")
    add(f"расхождение составляет {ill['naive_diff_pp']:+.1f} п.п. годовых, причём")
    add("с разным знаком: выходит, что на одной площадке инструмент дорого")
    add("шортить, а на другой дорого держать в лонг. На пересечении периодов")
    add(f"(окно — {_days(ill['span_days'])}) разница равна {ill['diff_pp']:+.1f} п.п.")
    add("Первая величина не является измерением расхождения площадок — она")
    add("измеряет разницу периодов наблюдения.\n")

    # --- 4.5 в единицах удержания
    diffs = sorted(abs(v["diff_pp"]) for v in usable.values())

    def qq(p):
        return diffs[int(p * (len(diffs) - 1))] if diffs else 0.0

    add("### 4.5 Во что это обходится на горизонте удержания\n")
    add("Раздел 3.2 спеки 01 держит позицию 1–5 дней. Ошибка, которую даёт")
    add("подстановка ставок Binance вместо ставок площадки исполнения, на одну")
    add("ногу, в базисных пунктах от нотионала:\n")
    add("| Горизонт | Медиана | 75 % | 95 % |")
    add("|---|---:|---:|---:|")
    for days, lbl in ((1, "1 день"), (3, "3 дня"), (5, "5 дней")):
        f = lambda x: x * days / 365 * 100  # noqa: E731 — п.п. годовых → б.п. за период
        add(f"| {lbl} | {f(qq(0.5)):.1f} б.п. | {f(qq(0.75)):.1f} б.п. | "
            f"{f(qq(0.95)):.1f} б.п. |")
    add("")
    add("Сравнивать это следует не с нулём, а с комиссией. Парная позиция")
    add("делает четыре сделки на вход и выход.")
    if fs:
        add(f"Модальная ставка тейкера по универсуму — {fs['modal_taker_bp']:.2f} б.п.")
        add(f"(раздел 6), то есть цикл стоит {4*fs['modal_taker_bp']:.0f} б.п.")
        add("Ставка измерена по ключу, как требует раздел 5.1, а не взята по")
        add("памяти.\n")
    else:
        add("Ставка комиссии не собрана — сравнение здесь не приводится,")
        add("чтобы не подставлять число из памяти. Числа в таблице выше от")
        add("этого не зависят: они измерены.\n")
    add("Даже с такой оговоркой вывод устойчив: у хвоста в 5 % активов ошибка")
