#!/usr/bin/env python3
"""
Отчёт M1 из готовой сводки. Стандартная библиотека намеренно: отчёт
обязан собираться на любой машине из самого артефакта, а не из
состояния исходников (урок R1 — отчёт, требовавший numpy, нельзя было
собрать даже из готового JSON).

    python3 research/m1_features/report.py out/m1_summary_1m.json
"""

import json
import sys


def render(s):
    cov = s["coverage"]
    feats = "\n".join(
        f"| `{k}` | {cov[k] * 100:.1f} % |"
        for k in s["features"] + [f"target_{h}" for h in
                                  s["settings"]["horizons"]])
    per_year = " · ".join(f"{y}: {n:,}" for y, n in
                          sorted(s["rows_per_year"].items()))
    b = s["budget"]
    skip = (f"\n**Источники пропущены явно: {', '.join(s['skip'])}** — "
            f"матрица неполная и вердиктов по ней не выносится.\n"
            if s["skip"] else "")
    return f"""# M1 — матрица признаков ({s['interval']}{'' if not s['tag'] else ', ' + s['tag']})

Окно {s['start']} … {s['end']}. Гипотеза 6, спека 07, этап M1.
{skip}
## Размер

| | |
|---|---|
| строк (актив-день в универсуме) | {s['rows']:,} |
| активов | {s['assets']} |
| сечений с ≥ {s['settings']['min_section']} активами | {s['sections']:,} |
| строк без единого пропуска | {s['complete_rows']:,} |

По годам: {per_year}.

## Покрытие признаков

Доля заполненных значений среди строк универсума. Дыры не чинятся и не
заполняются нулями — модель обязана видеть пропуск пропуском.

| признак | заполнено |
|---|---|
{feats}

## Бюджет вычислений

| | |
|---|---|
| этап 1 (дневная сводка из A2) | {b['stage1_sec']} с, месяцев готово заранее {b['stage1_resumed']} |
| этап 2 (признаки и цели) | {b['stage2_sec']} с |
| гребневая регрессия на всей матрице | {b['ridge_fit_sec']} с |
| всего | {b['total_sec']} с |

Гребневая регрессия — нижняя граница цены одного обучения. Бустинг M2
дороже; его цену M2 обязан замерить собственным смоуком ДО полной
сетки, и по тому числу решается вопрос о железе.

## Что дальше

M2: walk-forward по сетке спеки §5 — модель против лучшего одиночного
признака против статической модели. Если модель не бьёт одиночный
признак, гипотеза умирает дёшево (критерий остановки §8).
"""


def main():
    with open(sys.argv[1], encoding="utf-8") as f:
        print(render(json.load(f)))


if __name__ == "__main__":
    main()
