"""Тейкерская ставка по символу — одна на весь проект.

Ставка НЕ одно число. A1 сняла её по ключу на площадке исполнения и
намерила четыре тарифа: 5.50 б.п. у большинства, 2.75 у не-криптоактивов
и части имён, 11.00 у тонких, 10.00 у трёх. Между дешёвым и дорогим
разница вчетверо, поэтому константа в модели издержек ошибается не на
проценты, а в разы — и ошибается систематически, потому что дорогой
тариф стоит на тонких инструментах, куда кросс-секционный отбор как раз
и заходит.

Чего здесь нет намеренно: мейкерской ставки в расчёте сделки. Правило
проекта — не предполагать исполнение лимитной заявки по касанию цены
(ошибка движка v1). Мейкер лежит в таблице и годится как верхняя
граница, но круг сделки считается тейкером.

Символа нет в таблице — возвращается умолчание И признак «не знаем».
Молча подставить модальный тариф значило бы сделать пропуск
неотличимым от измерения; вызывающий обязан уметь сказать, по скольким
именам ставка настоящая.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESEARCH = os.path.dirname(HERE)
FEES_PATH = os.path.join(RESEARCH, "a1_universe", "out", "fees.json")

# Модальный тариф A1: 396 символов универсума из 722. Это умолчание, а
# не оценка — оно применяется только там, где ставки нет вовсе.
DEFAULT_TAKER_BP = 5.5


def load(path=FEES_PATH):
    """`{символ: тейкер в б.п.}` из выгрузки A1.

    Формат выгрузки — список записей площадки, ставки долями единицы
    (`"0.00055"`). Ключ ищется по имени поля, а не по номеру: тот же
    класс дефекта уже стоил проекту тихого нуля в загрузчике funding,
    где ставка бралась как `row[1]`.
    """
    try:
        with open(path, encoding="utf-8") as f:
            raw = json.load(f)
    except (OSError, ValueError):
        return {}
    out = {}
    for r in raw if isinstance(raw, list) else []:
        sym, rate = r.get("symbol"), r.get("takerFeeRate")
        if not sym or rate is None:
            continue
        try:
            out[sym] = round(float(rate) * 1e4, 4)
        except (TypeError, ValueError):
            continue
    return out


def taker_bp(sym, table):
    """`(ставка, известна ли)`. Второе — не украшение, а мера покрытия."""
    v = (table or {}).get(sym)
    if v is None:
        return DEFAULT_TAKER_BP, False
    return v, True
