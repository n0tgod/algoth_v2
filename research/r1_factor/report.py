#!/usr/bin/env python3
"""
R1 — отчёт по проверке посылки §8.1 спеки 03.

Все числа читаются из артефакта прогона. Ни одно не зашито в текст: в A2
расхождение «42 партиции» против 78 появилось ровно потому, что число
попало в текст, а не бралось из состояния.

    python3 report.py > out/R1-report.md

Отчёт намеренно не импортирует `premise.py` и не требует numpy, duckdb и
pyarrow: настройки и пороги прогона лежат в самом артефакте. Поэтому
отчёт собирается из JSON где угодно — в том числе там, где тяжёлых
зависимостей нет вовсе, — и описывает тот прогон, который этот файл
породил, а не текущее состояние исходников.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")


def pct(x, d=1):
    return "—" if x is None else f"{100 * x:.{d}f} %"


def median(v):
    v = sorted(v)
    n = len(v)
    if not n:
        return None
    return v[n // 2] if n % 2 else (v[n // 2 - 1] + v[n // 2]) / 2


def main():
    with open(os.path.join(OUT, "premise_summary.json"), encoding="utf-8") as f:
        doc = json.load(f)
    cfg = doc.get("config")
    if cfg is None:
        raise SystemExit(
            "в артефакте нет раздела config — он собран кодом раннего\n"
            "образца, читавшим пороги из исходников. Подставлять сюда\n"
            "сегодняшние значения нельзя: отчёт обязан описывать тот\n"
            "прогон, который породил файл. Перезапустите premise.py."
        )
    P1_MIN_EXPLAINED = cfg["p1_min_explained"]
    P2_MAX_SPREAD = cfg["p2_max_spread"]
    STEP, COARSER = cfg["step"], cfg["coarser"]
    s, W = doc["summary"], doc["windows"]
    good = [w for w in W if "r2_median" in w]
    ev = s["explained_variance"]
    interval = good[0].get("interval", "?") if good else "?"

    p = print
    p("# R1 — рыночная волна и проверка посылки\n")
    p(f"**Спека:** 03, этап R1, условия §8.1  ")
    p(f"**Окон:** {s['windows']}, измерено {s['windows_measured']}  ")
    p(f"**Шаг теста:** {STEP}, сравнение с {', '.join(COARSER)}  ")
    p(f"**Разрешение хранилища:** {interval}\n")

    ok = "ВЫПОЛНЕНА" if s["premise_pass"] else "НЕ ВЫПОЛНЕНА"
    p(f"## Итог: посылка **{ok}**\n")
    p("| Условие | Порог | Получено | |")
    p("|---|---|---|---|")
    p(f"| П1 — доля дисперсии, объяснённая волной | ≥ {pct(P1_MIN_EXPLAINED, 0)} "
      f"| **{pct(ev['median_over_windows'])}** | {'✓' if s['p1_pass'] else '✗'} |")
    p(f"| П2 — зависимость β от шага бара | ≤ {pct(P2_MAX_SPREAD, 0)} "
      f"| **{pct(s['beta_step_max_deviation'], 2)}** "
      f"| {'✓' if s['p2_pass'] else '✗'} |\n")

    p("## 1. П1 — волна действительно является волной\n")
    p("Мера — доля дисперсии доходностей актива, объяснённая равновзвешенной "
      "волной универсума, медиана по активам внутри окна и медиана по окнам.\n")
    p(f"- медиана по окнам — **{pct(ev['median_over_windows'])}** при пороге "
      f"{pct(P1_MIN_EXPLAINED, 0)}")
    p(f"- разброс по окнам: минимум {pct(ev['min'])}, максимум {pct(ev['max'])}")
    p(f"- квантили по окнам: 5-й {pct(ev['q']['0.05'])}, 25-й {pct(ev['q']['0.25'])}, "
      f"75-й {pct(ev['q']['0.75'])}, 95-й {pct(ev['q']['0.95'])}")
    p(f"- в агрегате (взвешенно по дисперсии) — {pct(ev['aggregate_median_over_windows'])}")
    p(f"- окон ниже порога: **{ev['windows_below_threshold']}** из {s['windows_measured']}\n")
    p("Агрегат ниже медианы закономерно: он взвешен дисперсией, а самые "
      "волатильные активы — это и есть самые «свои», хуже всего объяснимые "
      "общей волной. Обе величины докладываются, чтобы выбор меры не менял вывод.\n")

    lo = [w for w in good if w["r2_median"] < P1_MIN_EXPLAINED]
    if lo:
        p("**Окна, не прошедшие порог поодиночке:**\n")
        p("| Окно | Активов | Доля дисперсии |")
        p("|---|---|---|")
        for w in lo:
            p(f"| {w['date']} | {w['assets_fitted']} | {pct(w['r2_median'])} |")
        p("")

    first = [w["r2_median"] for w in good[:12]]
    last = [w["r2_median"] for w in good[-12:]]
    p(f"**Тренд.** Первые двенадцать окон дают медиану {pct(median(first))}, "
      f"последние двенадцать — {pct(median(last))}. Волна не разрушается, но "
      f"слабеет по мере расширения универсума: в 2022 отбору удовлетворяют "
      f"{good[0]['assets_fitted']} активов, преимущественно мажоры, ходящие "
      f"вместе; к {good[-1]['date']} их {good[-1]['assets_fitted']}, и хвост "
      f"альтов имеет собственную жизнь. Это существенно для R2: хедж об волну "
      f"слабее там, где данных больше всего.\n")

    p("## 2. П2 — эффект Эппса на доходностях\n")
    p("A4 закрыла вопрос для β **на уровнях цен** (β(1m)/β(1h) = 0.999 / 1.000 / "
      "1.001) и оставила оговорку: Эппс бьёт по оценкам на доходностях. Эта "
      "спека считает по доходностям, поэтому проверка сделана заново.\n")
    p(f"| Шаг | β(шаг)/β({STEP}), медиана по окнам | Отклонение от 1 | Окон |")
    p("|---|---|---|---|")
    for c in COARSER:
        r = s["beta_step_ratio"].get(c)
        if r:
            p(f"| {c} | {r['median_over_windows']:.4f} | "
              f"{pct(r['deviation'], 2)} | {r['windows']} |")
    p("")
    p(f"Наибольшее отклонение — {pct(s['beta_step_max_deviation'], 2)} при "
      f"допуске {pct(P2_MAX_SPREAD, 0)}. **Систематического занижения β на "
      f"мелком шаге нет**, то есть хедж на {STEP} не недооценивает экспозицию и "
      f"книга остаётся нейтральной. Оговорка A4 снята и для доходностей.\n")

    p("## 3. Проверки корректности\n")
    p("**Средняя β по сечению обязана выходить около единицы** — каждый актив "
      "входит в волну с весом 1/n, и это следует из построения, а не из "
      "свойств рынка. Отклонение означало бы ошибку расчёта.\n")
    bm = [w["beta_median"] for w in good]
    p(f"- медиана β по окнам: {median(bm):.3f}, диапазон {min(bm):.3f}–{max(bm):.3f}\n")
    oi = s.get("own_inclusion_beta_ratio")
    if oi:
        p("**Актив исключён из собственной волны.** При трёхстах активах "
          "собственный вес 1/300 и роли не играет, но в ранних окнах их "
          "двадцать. Размер смещения измерен, а не объявлен малым:\n")
        p(f"- β с включением себя / β без: медиана по окнам "
          f"{oi['median_over_windows']:.4f}, максимум {oi['max']:.4f}\n")
        p("То есть на живых данных поправка оказалась мелкой. Узнать это можно "
          "было только измерив: на синтетике из двадцати активов актив, не "
          "связанный с рынком, при включении себя получает β больше 0.5.\n")

    p("## 4. Состав окон\n")
    a = s["assets"]
    p(f"- ликвидных активов на окно: медиана {a['liquid_median']:.0f}")
    p(f"- оценено β: медиана {a['fitted_median']:.0f}, минимум {a['min_fitted']}")
    p(f"- из них с меткой сектора A3: медиана {a['labelled_median']:.0f}\n")
    p("Волна строится по **всему** ликвидному универсуму, а не только по "
      "размеченной его части: A4 требовала метку, потому что без неё не из чего "
      "составить пару, а волна есть свойство рынка целиком.\n")

    p("## 5. Что дальше\n")
    if s["premise_pass"]:
        p("Посылка выполнена — переход к R2 (возврат остатка вне выборки, "
          "критерии §8.3 п. 1–3). Открытым в R1 остаётся вопрос, поднятый "
          "самими данными: доля объяснённой дисперсии падает к концу истории, "
          "и последние окна — самые слабые. Если в R2 сигнал окажется "
          "сосредоточен там же, это придётся объяснять, а не списывать.\n")
    else:
        p("Посылка НЕ выполнена. §8.1 требует остановки с пересмотром модели "
          "фактора, а не перехода к R2.\n")

    p("## Приложение: по окнам\n")
    p("| Окно | Активов | Доля дисперсии | β медиана | β 5-й | β 95-й | 4h/1h | 1d/1h |")
    p("|---|---|---|---|---|---|---|---|")
    for w in good:
        r4 = w.get("beta_step_ratio", {}).get("4h", {}).get("median")
        r1 = w.get("beta_step_ratio", {}).get("1d", {}).get("median")
        p(f"| {w['date']} | {w['assets_fitted']} | {pct(w['r2_median'])} | "
          f"{w['beta_median']:.3f} | {w['beta_q']['0.05']:.3f} | "
          f"{w['beta_q']['0.95']:.3f} | "
          f"{'—' if r4 is None else f'{r4:.4f}'} | "
          f"{'—' if r1 is None else f'{r1:.4f}'} |")


if __name__ == "__main__":
    main()
