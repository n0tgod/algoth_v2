#!/usr/bin/env python3
"""
R1 — рыночная волна и остаток. Ядро расчёта.

Спека 03, раздел 3. Здесь только арифметика: цены → доходности → фактор →
β и доля объяснённой дисперсии. Ни обращений к диску, ни к базе — чтобы
всё это проверялось тестами с известным ответом, а не только глазами на
результате прогона.

Три места, где легко ошибиться незаметно, и что с ними сделано.

**Доходность считается только между соседними барами.** Ряды дырявы:
бар без сделок в хранилище отсутствует (A2 требует считать `trades = 0`
пропуском, а не наблюдением). Если брать `diff` по имеющимся барам
подряд, доходность через шестичасовую дыру попадёт в ряд как часовая.
Дисперсия такого ряда завышена, а β вместе с ней. Поэтому цены сначала
кладутся на регулярную сетку с пропусками в виде NaN, и `diff` через
пропуск даёт NaN сам собой.

**Актив исключается из собственного фактора.** Волна — среднее по
универсуму, и актив входит в неё сам. При 300 активах собственный вес
1/300 и роли не играет, но в июле 2022 условиям отбора удовлетворяют
20 активов (A3), собственный вес 5 %, и регрессия актива на среднее,
куда он сам входит, завышает и β, и R². Считается версия «все, кроме
меня»:

    F_i(t) = (сумма доходностей в момент t − r_i(t)) / (число − 1)

Обе версии возвращаются, чтобы размер смещения был виден числом, а не
предполагался малым.

**R² — доля дисперсии, а не корреляция.** Критерий П1 спеки 03 (§8.1)
сформулирован как доля дисперсии доходностей, объяснённая волной, и
порог 40 % относится именно к ней.
"""

import numpy as np

STEP_MS = {"1m": 60_000, "5m": 300_000, "15m": 900_000, "1h": 3_600_000,
           "4h": 14_400_000, "1d": 86_400_000}

MIN_ASSETS_IN_BAR = 5     # меньше — «рынок» из горстки имён, среднее бессмысленно
MIN_COVERAGE = 0.5        # доля сетки, ниже которой актив не оценивается


def price_grid(series, step, t0_ms, t1_ms):
    """Цены на регулярной сетке шага `step`; пропуск — NaN.

    Регулярная сетка, а не объединение наблюдённых меток: только на ней
    «соседний бар» определён однозначно, а именно от этого зависит,
    не попадёт ли доходность через дыру в ряд как одношаговая.
    """
    ms = STEP_MS[step]
    start = (t0_ms // ms) * ms
    grid = np.arange(start, t1_ms, ms, dtype=np.int64)
    symbols = sorted(series)
    P = np.full((len(grid), len(symbols)), np.nan)
    if len(grid) == 0:
        return grid, symbols, P
    for j, s in enumerate(symbols):
        t, c = series[s]
        if len(t) == 0:
            continue
        pos = np.searchsorted(grid, t)
        pos = np.clip(pos, 0, len(grid) - 1)
        ok = grid[pos] == t
        P[pos[ok], j] = c[ok]
    return grid, symbols, P


def log_returns(P):
    """Логарифмические доходности по сетке.

    NaN через пропуск возникает сам: `log(NaN)` заражает разность с
    обеих сторон, то есть бар без сделок гасит и вход в него, и выход.
    Это и требуется — наблюдения через дыру в ряду нет.
    """
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.diff(np.log(P), axis=0)


def market_factor(R, min_assets=MIN_ASSETS_IN_BAR):
    """Равновзвешенная волна и версия «все, кроме меня».

    Взвешивание по размеру не используется намеренно (спека 03 §3.1):
    универсум идёт от 20 активов в 2022 до 318 в 2026, и взвешивание по
    капитализации превратило бы волну в «BTC плюс шум».
    """
    ok = ~np.isnan(R)
    n = ok.sum(axis=1)
    s = np.where(ok, R, 0.0).sum(axis=1)

    thin = n < min_assets
    with np.errstate(invalid="ignore", divide="ignore"):
        F = np.where(thin, np.nan, s / np.maximum(n, 1))
        # «Все, кроме меня»: из суммы вычитается собственная доходность,
        # из числа — единица. Там, где актива в баре нет, вычитать
        # нечего и знаменатель прежний.
        own = np.where(ok, R, 0.0)
        cnt = n[:, None] - ok.astype(np.int64)
        F_loo = (s[:, None] - own) / np.maximum(cnt, 1)
        F_loo[cnt < min_assets] = np.nan
        F_loo[thin, :] = np.nan
    return F, F_loo, n


def regress(y, x):
    """МНК `y = a + b·x` по общим наблюдениям. Возвращает b, R², n.

    Свободный член нужен: без него снос актива за окно уехал бы в
    наклон. На окне формирования остаток получает нулевое среднее по
    построению, и это правильно — торгуется отклонение, а не уровень.
    """
    m = ~(np.isnan(y) | np.isnan(x))
    n = int(m.sum())
    if n < 2:
        return None
    yy, xx = y[m], x[m]
    xm, ym = xx.mean(), yy.mean()
    dx, dy = xx - xm, yy - ym
    sxx = float(dx @ dx)
    syy = float(dy @ dy)
    if sxx <= 0 or syy <= 0:
        return None
    b = float(dx @ dy) / sxx
    resid = dy - b * dx
    r2 = 1.0 - float(resid @ resid) / syy
    return b, r2, n


def betas(R, F_loo, min_coverage=MIN_COVERAGE):
    """β и R² каждого актива против собственной волны «все, кроме меня».

    Возвращает список `(индекс, β, R², n)`; активы с покрытием ниже
    порога пропускаются — на огрызке ряда β не оценивается, а
    выдумывается.
    """
    out = []
    need = int(min_coverage * R.shape[0])
    for j in range(R.shape[1]):
        r = regress(R[:, j], F_loo[:, j])
        if r is None or r[2] < need:
            continue
        out.append((j, r[0], r[1], r[2]))
    return out


def residuals(R, F_loo, fitted):
    """Остатки `r − a − β·F` по оценкам окна формирования.

    Коэффициенты передаются снаружи и на торговом окне не
    пересчитываются — прямой запрет CLAUDE.md и §3.2 спеки 03.
    """
    out = np.full(R.shape, np.nan)
    for j, b, _, _ in fitted:
        y, x = R[:, j], F_loo[:, j]
        m = ~(np.isnan(y) | np.isnan(x))
        if not m.any():
            continue
        a = y[m].mean() - b * x[m].mean()
        out[m, j] = y[m] - a - b * x[m]
    return out


def quantiles(vals, ps=(0.05, 0.25, 0.5, 0.75, 0.95)):
    v = sorted(float(x) for x in vals if x == x)
    if not v:
        return {}
    return {str(p): v[int(p * (len(v) - 1))] for p in ps}
