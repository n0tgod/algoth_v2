# Ступени 2 и 3 лестницы §3.3 спеки 03. Добавлены итерацией 1 (§12.3).
#
# Все три ступени — одна конструкция: фактор есть взвешенное среднее
# доходностей по сечению, а версия «все, кроме меня» получается вычитанием
# собственного вклада. Рынок — частный случай с весами 1/n, сектор — с
# весами 1/|группа| на её членах, главная компонента — с весами из
# собственного вектора. Поэтому ниже нет трёх реализаций, есть одна.
# ---------------------------------------------------------------------------


def sector_factor(R, members, min_members=5):
    """Секторный фактор группы и его версия «все, кроме меня».

    `members` — индексы столбцов `R`, входящих в группу. Группы меньше
    `min_members` фактора не дают вовсе: среднее по трём именам есть шум,
    а не фактор, и вычитание такого «фактора» добавило бы в остаток
    чужую случайность вместо того, чтобы убрать общую.

    Возвращает `(F, F_loo)`, где `F_loo` имеет столбец на каждого члена
    группы в порядке `members`. `None`, если группа мала.
    """
    if len(members) < min_members:
        return None
    sub = R[:, members]
    ok = ~np.isnan(sub)
    n = ok.sum(axis=1)
    s = np.where(ok, sub, 0.0).sum(axis=1)
    with np.errstate(invalid="ignore", divide="ignore"):
        F = np.where(n >= min_members, s / np.maximum(n, 1), np.nan)
        cnt = n[:, None] - ok.astype(np.int64)
        F_loo = (s[:, None] - np.where(ok, sub, 0.0)) / np.maximum(cnt, 1)
        F_loo[cnt < min_members - 1] = np.nan
        F_loo[n < min_members, :] = np.nan
    return F, F_loo


def pairwise_cov(R, min_overlap=100):
    """Ковариация по попарно доступным наблюдениям.

    Заполнять пропуски нулями перед разложением нельзя: ноль есть
    утверждение «доходность была нулевой», то есть то самое молчание,
    выданное за данные, которым в A2 отличались замороженные ряды.
    Пары с пересечением короче `min_overlap` считаются неизвестными и
    получают ноль ковариации — это смещает разложение к недооценке
    связи, то есть в консервативную сторону.
    """
    n = R.shape[1]
    C = np.zeros((n, n))
    ok = ~np.isnan(R)
    X = np.where(ok, R, 0.0)
    cnt = ok.astype(np.float64)
    # Суммы произведений и счётчики — матричным умножением, а не циклом
    # по парам: при 300 активах пар 45 тысяч.
    S = X.T @ X
    N = cnt.T @ cnt
    Sx = X.T @ cnt
    with np.errstate(invalid="ignore", divide="ignore"):
        C = (S - Sx * Sx.T / np.maximum(N, 1)) / np.maximum(N - 1, 1)
    C[N < min_overlap] = 0.0
    C = 0.5 * (C + C.T)                      # симметрия после округлений
    return C


def top_components(C, m):
    """Веса первых `m` главных компонент, столбцами.

    Отрицательные собственные значения, возникающие из-за попарной
    оценки ковариации, обнуляются: они означают, что матрица не является
    положительно полуопределённой из-за разных пересечений, а не что у
    направления отрицательная дисперсия.

    Знак каждой компоненты фиксируется так, чтобы сумма весов была
    неотрицательна. Собственный вектор определён с точностью до знака, и
    без фиксации первая компонента произвольно меняла бы направление от
    окна к окну, а вместе с ней и знак β.
    """
    vals, vecs = np.linalg.eigh(C)
    order = np.argsort(vals)[::-1][:m]
    W = vecs[:, order]
    for j in range(W.shape[1]):
        if W[:, j].sum() < 0:
            W[:, j] = -W[:, j]
    return W, np.maximum(vals[order], 0.0)


def weighted_factor(R, W):
    """Факторы `R·W` и их версии «все, кроме меня».

    Возвращает `(F, contrib)`: `F` формы (T, m) — сами факторы, `contrib`
    формы (T, N, m) — вклад каждого актива в каждый фактор. Версия «все,
    кроме меня» для актива i есть `F − contrib[:, i, :]`.

    Отсутствующий актив вносит ноль — то есть фактор в этот момент чуть
    ослаблен. Величина ослабления равна доле недостающего веса и при
    покрытии выше 99 % (замер A2) пренебрежима; главное, что вычитание
    собственного вклада остаётся точным.
    """
    X = np.where(np.isnan(R), 0.0, R)
    F = X @ W
    contrib = X[:, :, None] * W[None, :, :]
    return F, contrib


def regress_multi(y, X):
    """МНК `y = a + Σ b_j x_j` по общим наблюдениям.

    Возвращает `(b, R², n)`. Свободный член оценивается, но не
    возвращается: он нужен, чтобы снос актива не уехал в наклоны, а сам
    по себе в остаток не входит — остаток торгуется как отклонение.
    """
    m = ~(np.isnan(y) | np.isnan(X).any(axis=1))
    n = int(m.sum())
    if n < X.shape[1] + 2:
        return None
    yy, XX = y[m], X[m]
    A = np.column_stack([np.ones(n), XX])
    syy = float(((yy - yy.mean()) ** 2).sum())
    if syy <= 0:
        return None
    try:
        coef, *_ = np.linalg.lstsq(A, yy, rcond=None)
    except np.linalg.LinAlgError:
        return None
    resid = yy - A @ coef
    r2 = 1.0 - float(resid @ resid) / syy
    return coef[1:], r2, n
