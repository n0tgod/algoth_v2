"""Правило кандидата → ЖИВАЯ бумажная книга.

Решение владельца (2026-09-02): «именно живая книга должна заводиться
для отобранных кандидатов, иначе смысл тогда искать стратегии». До
этого объявленный кандидат судился ТОЛЬКО реплеем по журналу листов —
пересчётом, а не торговлей: без живого сканера, кассы и слотов. Реплей
отвечает на вопрос «что бы вышло», живая книга — «что выходит», и
второе и есть предмет поиска.

Что этот модуль делает: превращает реестр испытаний (`ledger.jsonl`) в
записи `books_extra.json`, то есть в книги, которые ведёт цикл. Что он
НЕ делает: не решает, кого объявлять (это потолок и `declare.py`), не
считает денег (это касса) и не трогает ядро книг — реестр ядра живёт
кодом и решением владельца.

Три правила, каждое из уроков проекта:

* **Живая книга заводится ОБЕИМ полосам — и отобранной, и случайной.**
  Владелец назвал отобранных, но случайная рука и есть та мера, против
  которой отобранных судят; заведи живую книгу одной полосе и реплей
  другой — сравнивались бы две системы измерения, а не две полосы.
  Знаменатель испытаний важнее экономии слотов.
* **Правило приходит из РЕЕСТРА, а применённое пишет манифест книги.**
  Это не две копии одного: реестр есть инструкция (что объявлено и
  переписать нечем), манифест — запись о том, чем книга торговала на
  самом деле. Расхождение между ними обязано быть видно.
* **Ось, которую живая машинерия сегодня не умеет, НЕ становится
  книгой молча.** Причина называется словами и печатается числом
  («столько кандидатов без живой книги, потому что …»): «книги нет» и
  «книга невозможна» снаружи неотличимы, а нам нужно знать, какую
  часть пула мы судим вживую.

Модуль на стандартной библиотеке: его читают и цикл обучения, и
суточный прогон фабрики. Единственный импорт сверх неё — `space`,
модуль объявленного пространства, тоже без зависимостей: геометрия
сделки обязана приходить ОТТУДА ЖЕ, откуда её берёт реплей, иначе
живая книга торговала бы не то правило, которое её судит.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import space as SP                                          # noqa: E402

# Каталог книги кандидата: `model_c_<ключ>`. Префикс `model_`
# обязателен (правило `books.MAIN_DIR`) — в демо-прогоне каталог модели
# подменяется целиком, и книга вне правила не переехала бы с ним, а
# выглядела бы заведённой. Отдельная буква `c` отделяет кандидатов от
# ядра: имя ядра занять нельзя, и проверка это ловит.
DIR_PREFIX = "model_c_"

# Ситуационная книга держит места ПО СТОРОНАМ (реплей `simulate`
# считает `width` на сторону), поэтому мест у книги вдвое больше.
SLOTS_PER_WIDTH = 2

# Ось «размер» реестра → имя правила кассы (`trades.account`).
SIZING = {"equal": None, "risk": "fixed_risk", "inv_sigma": "inv_risk2"}

# Ось «полоса отношения» → пара (пол, потолок) для гейта сканера.
RR_BAND = {"none": (0.0, None), "lo": (0.0, 1.5), "hi": (2.0, None)}


def rule_gap(rule):
    """Чем живая машинерия сегодня не умеет это правило, или None.

    Причина — ПОЛНОЙ фразой: она уезжает в отчёт и на страницу, и
    «не поддержано» без имени оси лечить нечем.
    """
    if not isinstance(rule, dict):
        return "правило не объект"
    if rule.get("target") != "fwd_4h":
        return (f"цель {rule.get('target')}: лист сечения несёт только "
                "горизонт сигнала, и живой сканер судит по нему")
    if rule.get("basket") == "whole":
        return ("корзина целиком: живая корзинная книга закрывается по "
                "общему нереализованному результату, а это эхо "
                "источника, а не своя книга")
    if rule.get("sizing") not in SIZING:
        return f"размер {rule.get('sizing')}: правила кассы с таким нет"
    if rule.get("rr_band") not in RR_BAND:
        return f"полоса отношения {rule.get('rr_band')}: гейта с такой нет"
    return None


def book_of(cid, rec, describe=None):
    """Запись книги для `books_extra.json` или (None, причина).

    `rec` — запись реестра испытаний: правило, полоса, момент
    объявления и момент вылета.
    """
    rule = rec.get("rule") or {}
    gap = rule_gap(rule)
    if gap:
        return None, gap
    if not cid or not set(str(cid)) <= set(
            "abcdefghijklmnopqrstuvwxyz0123456789_"):
        return None, f"ключ {cid!r} негоден для адреса и пути"
    lo, hi = RR_BAND[rule["rr_band"]]
    # Возраст позиции и наличие уровней — из геометрии реплея, ОДНИМ
    # источником: вторая таблица «геометрия → предел» разошлась бы, и
    # живая книга жила бы дольше той, которую судит реплей. Ось
    # `timer` — «выход по времени»: стопа и цели у неё нет вовсе, и
    # это обязан знать 5-секундный сторож, иначе он закроет позицию
    # по уровню, которого правилу не объявляли.
    _st, _tk, age_h = SP.GEOMETRY[rule["geom"]]
    no_levels = _st == "no" and not _tk
    lane = rec.get("lane")
    # Подпись — ОПИСАНИЕ правила простыми словами плюс полоса, а не
    # ключ: ключ вида `h4_z_f30_w5_gl_rrlo_se_b0_a0` на странице не
    # объясняет ничего (тот же урок, что лист турнира из 72 ключей).
    label = f"кандидат {cid}"
    if describe:
        label = f"{describe(rule)} · {lane or '—'}"
    return {
        "key": cid,
        "dir": DIR_PREFIX + cid,
        "label": label,
        # Ситуационная: курок у живой цены, выход по уровням. Это
        # единственная семья, которую сегодня ведёт живой сканер, и
        # `rule_gap` уже отсеял остальные.
        "family": "situational",
        "horizon_h": None,
        "traded": True,
        "echo": False,
        "agree": False,
        "in_menu": False,
        # Кандидатов может быть до сотни, и ряд из ста кнопок показом
        # не является: своя страница у них — «построено системой».
        "rule": dict(rule),
        "lane": lane,
        "declared_at": rec.get("declared_at"),
        "retired_at": rec.get("retired_at"),
        "gate": {
            "min_rr": lo,
            "max_rr": hi,
            "slots": int(rule["width"]) * SLOTS_PER_WIDTH,
            "per_side": int(rule["width"]),
            "floor_bp": float(rule["floor_bp"]),
            "rank": rule["rank"],
            "agree": rule["agree"] == "yes",
            "age_h": age_h,
            "no_levels": no_levels,
        },
        "sizing": SIZING[rule["sizing"]],
    }, None


def build(state, describe=None):
    """Реестр испытаний → (книги, пропущенные с причинами).

    Вылетевший кандидат книгу СОХРАНЯЕТ: его запись — накопленный
    форвард, и убрать её значило бы стереть наблюдение. Новых входов
    он не берёт (`retired_at` стоит в записи, гейт его не пускает).
    """
    books, skipped = [], []
    for cid in sorted(state):
        b, why = book_of(cid, state[cid], describe=describe)
        if b is None:
            skipped.append({"id": cid, "why": why})
        else:
            books.append(b)
    return books, skipped


def write(path, books, log=None):
    """Атомарно записать `books_extra.json`.

    Пишется ВСЕГДА состоянием целиком, а не дельтой: список книг есть
    функция реестра, и дописывание однажды оставило бы книгу, которой
    в реестре уже нет (тот же дефект, что сводка сборки в A2).
    """
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(books, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)
    if log:
        log(f"книг кандидатов: {len(books)} → {path}")
    return len(books)
