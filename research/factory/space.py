"""Пространство кандидатов фабрики — объявлено ДО первого прогона.

Оси и значения — дословно раздел 4 спеки 13. Менять их можно, но это
СОБЫТИЕ: всё, добавленное после того как поверхность увидена, судится
только на данных, собранных после объявления (§10). Поэтому список
живёт кодом рядом с проверкой, которая держит его число испытаний
литералом: молчаливое расширение пространства обесценило бы все
прошлые числа фабрики разом.

Каждый кандидат — СТРОКА ПАРАМЕТРОВ того, что движок уже умеет, а не
новый модуль. Оси, которых движок не умеет (новый признак, другой
источник данных, другой горизонт данных), фабрике недоступны: их
пишет ассистент отдельной задачей.

Модуль без импортов сверх стандартной библиотеки: его читают цикл,
страницы и суточный прогон фабрики.
"""

import hashlib

# Порядок осей = порядок полей в ключе кандидата. Менять порядок значит
# менять ключи всех уже объявленных кандидатов — то есть рвать реестр.
AXES = (
    # Цель ранжирования. Какие цели лист сечения несёт СЕЙЧАС, решает
    # его содержимое (`horizon.sheet_caps`), а не эта таблица: цель,
    # которой в листе нет, кандидатом не становится и не реплеится
    # полями соседнего горизонта (см. `unavailable`).
    ("target", ("fwd_4h", "fwd_24h")),
    # Порядок сечения: сырой прогноз против прогноза в единицах σ
    # монеты. Ровно та пара, которую проект уже сравнивал книгами
    # h24 и z, — здесь она становится осью, а не отдельной книгой.
    ("rank", ("raw", "sigma")),
    # Пол входа в СЫРЫХ б.п.: порог выведен из круга издержек, и в
    # единицах σ у него якоря нет (то же решение, что у гейта
    # ситуационной книги). 0 — пола нет.
    ("floor_bp", (0, 22, 30, 44)),
    # Ширина книги на сторону. Замер `V1-width` намерил ступеньку:
    # места 1–5 дают +86 б.п. на ногу, места 6–30 — ноль; поэтому
    # крайние значения взяты по обе стороны от неё.
    ("width", (3, 5, 10)),
    # Геометрия сделки: по времени (книга со сроком), стоп и тейк по
    # обещаниям пути, только уровни (без отмены по времени).
    ("geom", ("timer", "stop_take", "levels")),
    # Полоса обещанного отношения. Замер по наблюдательной записи и
    # S11 намерили градиент в пользу НИЗКОГО RR — обе стороны в оси.
    ("rr_band", ("none", "lo", "hi")),
    # Размер позиции. Обратная σ измерена и проигрывала на записи с
    # одним разгоном; ось нужна, чтобы перемерить на календаре.
    ("sizing", ("equal", "risk", "inv_sigma")),
    # Корзина: отдельные выходы против закрытия целиком ±5 %.
    ("basket", ("no", "whole")),
    # Согласие рук: обе руки выбрали одно имя и сторону.
    ("agree", ("no", "yes")),
)

# Геометрия сделки одной таблицей: (стоп, тейк, предел возраста).
# Живёт ЗДЕСЬ, в модуле пространства, а не рядом с реплеем, потому что
# читателей у неё двое — реплей кандидата (`candidate.geometry`) и
# заводчик живой книги (`live_books`). Вторая такая таблица разошлась
# бы с первой, и живая книга торговала бы не то правило, которое судит
# её собственный реплей: у `timer` нет ни стопа, ни цели вовсе, и
# 5-секундный сторож обязан знать об этом.
GEOMETRY = {
    "timer": ("no", False, 24),
    "stop_take": ("q", True, 24),
    "levels": ("q", True, 72),
}


AXIS_NAMES = tuple(a for a, _ in AXES)
VALUES = dict(AXES)

# Полный перебор. Число закреплено ЛИТЕРАЛОМ в проверке: оно и есть
# знаменатель испытаний фабрики, и молчаливое его изменение — то же
# самое, что молчаливая правка порога.
TOTAL = 1
for _n, _vals in AXES:
    TOTAL *= len(_vals)

# Короткие ярлыки для ключа кандидата: ключ уезжает в имя каталога и в
# адрес страницы, поэтому только латиница, цифры и подчёркивание.
_SHORT = {
    "target": {"fwd_4h": "h4", "fwd_24h": "h24"},
    "rank": {"raw": "r", "sigma": "z"},
    "width": {3: "w3", 5: "w5", 10: "w10"},
    "geom": {"timer": "gt", "stop_take": "gs", "levels": "gl"},
    "rr_band": {"none": "rr0", "lo": "rrlo", "hi": "rrhi"},
    "sizing": {"equal": "se", "risk": "sr", "inv_sigma": "sv"},
    "basket": {"no": "b0", "whole": "b1"},
    "agree": {"no": "a0", "yes": "a1"},
}


def validate(rule):
    """Строка параметров годна? Возвращает причину отказа или None.

    Проверяются ОБЕ стороны: нет лишней оси и нет пропущенной. Кандидат
    с пропущенной осью получил бы значение по умолчанию где-то в
    исполнении, и правило, исчезающее при забытом поле, есть отказ,
    неотличимый от тишины.
    """
    if not isinstance(rule, dict):
        return "правило не объект"
    extra = set(rule) - set(AXIS_NAMES)
    if extra:
        return f"лишние оси: {sorted(extra)}"
    for name in AXIS_NAMES:
        if name not in rule:
            return f"нет оси {name}"
        if rule[name] not in VALUES[name]:
            return f"ось {name}: значение {rule[name]!r} не объявлено"
    return None


def key(rule):
    """Ключ кандидата — из САМОГО правила, а не из счётчика.

    Два одинаковых правила дают один ключ, то есть дубль в реестре
    невозможно завести незаметно; и по ключу книги видно, чем она
    отличается от соседней, без обращения к реестру.
    """
    bad = validate(rule)
    if bad:
        raise ValueError(bad)
    parts = [_SHORT["target"][rule["target"]],
             _SHORT["rank"][rule["rank"]],
             f"f{rule['floor_bp']}",
             _SHORT["width"][rule["width"]],
             _SHORT["geom"][rule["geom"]],
             _SHORT["rr_band"][rule["rr_band"]],
             _SHORT["sizing"][rule["sizing"]],
             _SHORT["basket"][rule["basket"]],
             _SHORT["agree"][rule["agree"]]]
    return "_".join(parts)


def describe(rule, lang="ru"):
    """Объяснение книги ИЗ ПАРАМЕТРОВ — страница обязана его печатать.

    Без него пул зарастает неподписанными книгами, и владелец видит сто
    ключей вида `h4_z_f30_w5...`, про которые нельзя сказать, чем они
    различаются (§8 спеки).
    """
    hz = "4 ч" if rule["target"] == "fwd_4h" else "24 ч"
    rank = ("по сырому прогнозу" if rule["rank"] == "raw"
            else "по прогнозу в единицах σ монеты")
    floor = ("без пола входа" if not rule["floor_bp"]
             else f"вход от {rule['floor_bp']} б.п.")
    geom = {"timer": "выход по времени",
            "stop_take": "стоп и тейк по обещаниям пути",
            "levels": "только уровни, без отмены по времени"}[rule["geom"]]
    rr = {"none": "любое отношение",
          "lo": "отношение не выше 1.5",
          "hi": "отношение не ниже 2"}[rule["rr_band"]]
    sz = {"equal": "равный доллар",
          "risk": "равный риск",
          "inv_sigma": "обратно волатильности"}[rule["sizing"]]
    bk = ("выходы у каждой ноги свои" if rule["basket"] == "no"
          else "корзина закрывается целиком ±5 %")
    ag = ("обе руки" if rule["agree"] == "no"
          else "только там, где руки согласны")
    if lang == "en":
        return (f"horizon {hz}, ranked {rule['rank']}, floor "
                f"{rule['floor_bp']} bp, width {rule['width']}+"
                f"{rule['width']}, {rule['geom']}, rr {rule['rr_band']}, "
                f"size {rule['sizing']}, basket {rule['basket']}, "
                f"agree {rule['agree']}")
    return (f"горизонт {hz}, сечение {rank}, {floor}, "
            f"ширина {rule['width']}+{rule['width']}, {geom}, {rr}, "
            f"размер {sz}, {bk}, {ag}")


def _rand(seed, i):
    """Зерно выводится ЧИСЛОМ, а не `hash()`: хеш строки в Python
    солится на каждый процесс, и нуль, который нельзя повторить, не
    является проверяемым (урок R3 — там это стоило двух разных нулей
    на одних данных)."""
    h = hashlib.sha256(f"{int(seed)}:{int(i)}".encode()).digest()
    return int.from_bytes(h[:8], "big")


def index_to_rule(idx):
    """Номер сочетания → правило. Порядок осей объявлен, значит номер
    и правило переводятся друг в друга однозначно."""
    rule = {}
    for name, vals in reversed(AXES):
        idx, r = divmod(idx, len(vals))
        rule[name] = vals[r]
    return rule


def draw(seed, n, exclude=(), available_only=True, caps=None):
    """`n` РАЗЛИЧНЫХ правил равномерно случайно из пространства.

    Это контрольная рука §3: её кандидатов не выбирает ни ассистент, ни
    селектор, ни ретро-замер. Зерно закреплено числом и лежит в
    реестре — иначе «случайная» рука не воспроизводима, а значит и не
    проверяема.

    `caps` — тот же разбор листа, что у `unavailable`: жребий обязан
    тянуть из того же множества исполнимого, из которого объявляются
    отобранные. Разойдись они, полосы сравнивались бы на разных
    пространствах, и разница читалась бы как качество отбора.
    """
    taken = set(exclude)
    out = []
    i = 0
    guard = 0
    while len(out) < n and guard < 100000:
        guard += 1
        rule = index_to_rule(_rand(seed, i) % TOTAL)
        i += 1
        if available_only and unavailable(rule, caps):
            continue
        k = key(rule)
        if k in taken:
            continue
        taken.add(k)
        out.append(rule)
    return out


# --- что из пространства сегодня исполнимо ---------------------------
#
# Пространство объявлено целиком и не сжимается, но часть его сегодня
# НЕ ИСПОЛНИМА: лист сечения несёт не всякую цель, и кандидата на цель,
# которой в листе нет, реплеить не по чему. Это надо говорить числом,
# а не тихо не заводить такие книги: «кандидатов нет» и «кандидаты
# невозможны» снаружи неотличимы.
#
# Решает СОДЕРЖИМОЕ листа, а не эта константа (механика 12cc2578):
# `horizon.sheet_caps` читает последние листы журнала и отвечает, какие
# цели там лежат и с чем — с порядком в σ, с квантильными концами пути.
# Константа осталась ОБЪЯВЛЕННЫМ ОБРАЗЦОМ и служит ответом ровно там,
# где содержимое не читали; отказ в этом случае так и говорит. Иначе
# образец однажды разошёлся бы с тем, что цикл пишет на самом деле, и
# разойтись мог бы молча — в обе стороны.
DECLARED_SHEET = {"targets": {"fwd_4h": {"z": True, "q": True}}}
SHEET_TARGETS = tuple(DECLARED_SHEET["targets"])


def unavailable(rule, caps=None):
    """Причина, по которой правило сегодня не исполнимо, или None.

    `caps` — разбор СОДЕРЖИМОГО листа сечения (`horizon.sheet_caps`):
    словарь с полем `targets` вида `{цель: {"z": …, "q": …}}`. Не
    подан — судим по объявленному образцу и говорим об этом словами.

    Причин пять, и все снимаются кодом, а не ожиданием:

    * листа не несёт цель правила — кандидату не из чего собрать ногу;
    * порядок в σ требует поля прогноза в единицах σ у ЭТОЙ цели;
    * размер обратно волатильности выводится из `fwd / fwd_z`, то есть
      требует того же поля;
    * геометрия со стопом и тейком требует квантильных концов пути; на
      24-часовой цели их нет (цикл их не учит), и подставить сюда
      4-часовые — значит судить другую книгу, чем объявлена;
    * равный риск считается от ИСПОЛНЯЕМОГО стопа, то есть от тех же
      квантильных концов;
    * корзина закрывается по ОБЩЕМУ нереализованному результату, то
      есть требует отметки открытых ног по ходу удержания; исход ноги
      в реплее — одно число, пути в нём нет.

    Все названы словами и все считаются числом (`available_total`):
    «кандидатов нет» и «кандидаты невозможны» снаружи неотличимы.
    """
    read = isinstance(caps, dict) and bool(caps.get("targets"))
    src = caps if read else DECLARED_SHEET
    have = (src.get("targets") or {}).get(rule.get("target"))
    if not have:
        lying = ", ".join(sorted(src.get("targets") or {})) or "ни одной цели"
        return (f"лист сечения не несёт {rule.get('target')}: в нём "
                f"{lying}"
                + ("" if read else " (по объявленному образцу — "
                                   "содержимое листа не читалось)"))
    if rule.get("rank") == "sigma" and not have.get("z"):
        return (f"порядок в σ требует прогноза в единицах σ, а цель "
                f"{rule.get('target')} лежит в листе без него")
    if rule.get("sizing") == "inv_sigma" and not have.get("z"):
        return (f"размер обратно σ выводится из fwd/fwd_z, а цель "
                f"{rule.get('target')} лежит в листе без прогноза в σ")
    if rule.get("geom") != "timer" and not have.get("q"):
        return (f"квантильных концов пути у цели {rule.get('target')} в "
                f"листе нет: стоп и тейк реплеить нечем, а 4-часовые "
                f"подставлять — значит судить другую книгу")
    if rule.get("sizing") == "risk" and not have.get("q"):
        return (f"равный риск считается от исполняемого стопа, а у цели "
                f"{rule.get('target')} квантильных концов в листе нет")
    if rule.get("basket") == "whole":
        return ("корзина целиком требует отметки открытых ног по ходу "
                "удержания, а исход ноги в реплее — одно число")
    return None


def available_total(caps=None):
    """Сколько сочетаний исполнимо сегодня — знаменатель, который
    печатается рядом с числом потраченных испытаний.

    Считается по тому же `unavailable` и по тому же разбору листа:
    знаменатель, посчитанный другой мерой, чем отказ, врал бы ровно на
    ту разницу, которой между ними нет только в замысле.
    """
    n = 0
    for i in range(TOTAL):
        if not unavailable(index_to_rule(i), caps):
            n += 1
    return n
