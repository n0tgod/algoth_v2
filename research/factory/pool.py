"""Пул кандидатов: сколько объявлять и кого отставлять.

Два правила владельца, и оба здесь чистыми функциями, потому что судить
их придётся числами, а не чтением кода.

**Доля контрольной руки.** Спека 13 §3: из ста слотов двадцать пять
отдаются жребию. Держится доля ПУЛА, а не партии: партии приходят
разного размера, и «четверть каждой партии» дала бы у пула долю,
зависящую от того, как их нарезали. Контроль объявляется В ТОТ ЖЕ
момент, что отобранные, — объявленный месяцем позже сравнивался бы с
ними по другому календарю, а календарь здесь и есть предмет.

**Вылет.** Правило владельца — «ниже своего нуля десять суток подряд»,
но по СУММЕ окна, а не по буквальной серии: у мёртвой книги серия из
десяти красных дней случается с вероятностью 1/1024, за месяц это 2 %,
и сто слотов заросли бы зомби за двадцать суток. Замер и довод — §6
спеки; то же самое уже находилось в спеке 10 у правила kill-10.

Молчание тоже вылет: слот, занятый книгой без сделок, ничем не лучше
занятого сливающей.
"""

CAP = 100                 # предел живых бумажных слотов (владелец)
CONTROL_SHARE = 0.25      # доля контрольной руки в пуле (§3)
PER_DAY = 5               # предел объявлений в сутки (владелец)
WINDOW_D = 10             # окно вылета в сутках (владелец)
IDLE_D = 30               # простой, после которого слот освобождается
DAY = 86400.0


def plan_batch(n_active, n_control_active, want, cap=CAP,
               share=CONTROL_SHARE, per_day=PER_DAY):
    """Сколько отобранных и сколько случайных объявить сейчас.

    Возвращает (отобранных, случайных, причина усечения или None).
    Контроль добирается ДО доли пула: если он отстал, партия отдаёт ему
    места раньше, чем отобранным, — иначе доля 25 % существует только на
    бумаге спеки.
    """
    want = max(0, int(want))
    free = max(0, cap - n_active)
    limit = min(want, per_day, free)
    why = None
    if limit < want:
        why = ("предел суток" if per_day <= free else "пул заполнен")
    total_after = n_active + limit
    need_ctl = int(round(share * total_after)) - n_control_active
    need_ctl = max(0, min(need_ctl, limit))
    return limit - need_ctl, need_ctl, why


def window_net(daily, now, window_d=WINDOW_D, day=DAY):
    """Сумма нетто за последние `window_d` СУТОК и число дней с записью.

    Окно календарное, а не «последние десять записей»: книга, торговавшая
    три дня из десяти, обязана считаться по этим трём, а не тянуть в окно
    сделки месячной давности.
    """
    lo = now - window_d * day
    days = [t for t in daily if lo <= t <= now]
    return sum(daily[t] for t in days), len(days)


def split_forward(daily, declared_at, day=DAY):
    """Дневной ряд книги → (форвард, реплей по прошлому).

    Кандидат реплеится по ВСЕМУ журналу листов, то есть его ряд несёт
    и дни ДО объявления. Это разные вещи, и складывать их нельзя:
    после объявления книга торгует вперёд и переписать её нечем, а до
    объявления это пересчёт по прошлому, которое ассистент видел,
    когда предлагал. Смешав их, кривая читалась бы треком, будучи
    наполовину бэктестом, — ровно то различие, ради которого месячная
    бумажная книга носит `written_at` в каждой записи.

    Возвращает два словаря «день → нетто». День объявления идёт в
    форвард целиком: книга объявлена внутри суток, и делить сутки
    пополам нечем — сделки в ряду стоят по дню ВЫХОДА, а не по часу.
    Это в пользу строгости к нам ровно наполовину и названо словами,
    а не спрятано.
    """
    d0 = int((declared_at or 0.0) // day)
    fwd = {d: v for d, v in daily.items() if int(d) >= d0}
    pre = {d: v for d, v in daily.items() if int(d) < d0}
    return fwd, pre


def should_retire(daily, now, null_median, declared_at,
                  window_d=WINDOW_D, idle_d=IDLE_D, day=DAY):
    """Причина вылета кандидата или None.

    `daily` — момент суток (epoch) → нетто книги за эти сутки.
    `null_median` — медиана нуля за то же окно: сравнение идёт со СВОИМ
    нулём, а не с нулём в долларах, иначе правило било бы по книгам,
    которые просто крупнее.
    """
    age_d = (now - declared_at) / day
    if age_d < window_d:
        # Окна ещё не существует: судить кандидата по трём дням значило
        # бы отставлять по шуму быстрее, чем он успевает торговать.
        return None
    net, n_days = window_net(daily, now, window_d, day)
    if n_days == 0:
        if age_d >= idle_d:
            return (f"простой {age_d:.0f} суток при пределе {idle_d}: "
                    f"слот занят молчанием")
        return None
    if net < null_median:
        return (f"нетто за {window_d} суток {net:+.2f} ниже медианы "
                f"нуля {null_median:+.2f}")
    return None


def sweep(state, daily_by_id, now, null_median, **kw):
    """Кого отставить сейчас — по всем живым кандидатам разом.

    Контрольная рука судится ТЕМ ЖЕ правилом: иначе сравнивали бы
    живучих отобранных с любыми случайными, и разница читалась бы как
    качество отбора, будучи разницей правил вылета.
    """
    out = []
    for cid, rec in state.items():
        if rec.get("retired_at") is not None:
            continue
        why = should_retire(daily_by_id.get(cid) or {}, now, null_median,
                            rec.get("declared_at") or 0.0, **kw)
        if why:
            out.append((cid, why))
    return out
