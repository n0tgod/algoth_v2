"""Пул кандидатов: сколько объявлять и кого отставлять.

Три правила владельца, и все здесь чистыми функциями, потому что судить
их придётся числами, а не чтением кода.

**Доля контрольной руки.** Спека 13 §3: из ста слотов двадцать пять
отдаются жребию. Держится доля ПУЛА, а не партии: партии приходят
разного размера, и «четверть каждой партии» дала бы у пула долю,
зависящую от того, как их нарезали. Контроль объявляется В ТОТ ЖЕ
момент, что отобранные, — объявленный месяцем позже сравнивался бы с
ними по другому календарю, а календарь здесь и есть предмет.

**Вылет по деньгам.** Правило владельца — «ниже своего нуля десять
суток подряд», но по СУММЕ окна, а не по буквальной серии: у мёртвой
книги серия из десяти красных дней случается с вероятностью 1/1024, за
месяц это 2 %, и сто слотов заросли бы зомби за двадцать суток. Замер и
довод — §6 спеки; то же самое уже находилось в спеке 10 у правила
kill-10.

Молчание тоже вылет: слот, занятый книгой без сделок, ничем не лучше
занятого сливающей.

**Вылет по ФОРМЕ (решение владельца 2026-09-02).** «Важнее стабильность
стратегии: интересны те, что приносят немного, но стабильно, и не
забирают за один день всю прибыль за неделю или месяц.» Прежнее правило
судило только СУММУ окна, то есть деньги, а не форму, и книга, отдающая
недельную прибыль одним днём, проходила его, пока сумма оставалась выше
нуля. Мера формы одна на весь проект — `stability.stats`; здесь живёт
только правило, которое по ней выносит вердикт.

Пороги объявлены ЗДЕСЬ и до первого прогона правила; менять их после
того, как станет видно, кого они отставили, запрещено — это перебор без
поправки.

**Единица ключа дневного ряда — НОМЕР СУТОК** (`candidate.daily_net`
кладёт `exit // DAY`), и это не мелочь: до 2026-09-02 окно вылета
сравнивало номера суток с моментом в СЕКУНДАХ, поэтому в окно не
попадало ни одних суток на живых данных. Следствий было два, и оба
молчаливые: за деньги не отставлялся никто вовсе, а на тридцатые сутки
после объявления любой кандидат — хоть с полусотней сделок в сутки —
попал бы под «простой». Дефект прожил в живом пуле потому, что фикстура
правила была написана в секундах, то есть не выглядела как живой
артефакт. Ряд не в тех единицах теперь ОТВЕРГАЕТСЯ громко.
"""

CAP = 100                 # предел живых бумажных слотов (владелец)
CONTROL_SHARE = 0.25      # доля контрольной руки в пуле (§3)
PER_DAY = 5               # предел объявлений в сутки (владелец)
WINDOW_D = 10             # окно вылета в сутках (владелец)
IDLE_D = 30               # простой, после которого слот освобождается
DAY = 86400.0

# --- пороги формы -----------------------------------------------------
#
# Обычный день не вправе быть отрицательным. «Приносит немного, но
# стабильно» есть утверждение о МЕДИАНЕ суток, а не о сумме: книга с
# отрицательной медианой теряет не редким срывом, а каждый день, и
# сумму ей поднимает хвост — ровно та форма, от которой владелец
# отказался.
MIN_MED_DAY = 0.0

# Худший день не глубже десяти обычных прибыльных. Число не выдумано и
# не подобрано: критерий 8 спеки 04 объявил отношение худшего периода к
# медианному — 10 терпимо, 40 означает «год работы отдаётся за неделю».
# Слова владельца задают вилку с другой стороны: неделя обычных
# прибыльных дней это примерно 5, месяц — примерно 20. Десять есть
# собственное уже объявленное число проекта внутри этой вилки.
MAX_BITE = 10.0

# Ключ дневного ряда — номер суток от эпохи. Больше этого — секунды, а
# не сутки (сто тысяч суток от эпохи это 2243 год).
MAX_DAY_NO = 100000


def plan_batch(n_active, n_control_active, want, cap=CAP,
               share=CONTROL_SHARE, per_day=PER_DAY):
    """Сколько отобранных и сколько случайных объявить сейчас.

    Возвращает (отобранных, случайных, причина усечения или None).
    Контроль добирается ДО доли пула: если он отстал, партия отдаёт ему
    места раньше, чем отобранным, — иначе доля 25 % существует только на
    бумаге спеки.
    """
    want = max(0, int(want))
    free = max(0, cap - n_active)
    limit = min(want, per_day, free)
    why = None
    if limit < want:
        why = ("предел суток" if per_day <= free else "пул заполнен")
    total_after = n_active + limit
    need_ctl = int(round(share * total_after)) - n_control_active
    need_ctl = max(0, min(need_ctl, limit))
    return limit - need_ctl, need_ctl, why


def day_no(t, day=DAY):
    """Момент в СЕКУНДАХ → номер суток, то есть ключ дневного ряда."""
    return int(t // day)


def days_of(daily):
    """Ключи дневного ряда — и громкий отказ, если это не сутки.

    Единицу задаёт писатель ряда (`candidate.daily_net`), и она —
    номер суток. Ряд в секундах не пересекается ни с одним окном, и
    правило молча перестаёт судить (см. шапку модуля). Молчание здесь
    дороже падения: отказ виден в тот же прогон, а неотставленный
    кандидат — через месяц и не тем признаком.
    """
    out = []
    for d in daily:
        try:
            n = int(d)
        except (TypeError, ValueError):
            raise ValueError(f"ключ дневного ряда не число: {d!r}")
        if abs(n) > MAX_DAY_NO:
            raise ValueError(
                f"ключ дневного ряда {n} — это не номер суток, а, судя "
                f"по величине, секунды: правило вылета сравнивает его с "
                f"номером суток и не увидело бы ни одних")
        out.append(n)
    return out


def window_net(daily, now, window_d=WINDOW_D, day=DAY):
    """Сумма нетто за последние `window_d` СУТОК и число дней с записью.

    Окно календарное, а не «последние десять записей»: книга, торговавшая
    три дня из десяти, обязана считаться по этим трём, а не тянуть в окно
    сделки месячной давности.

    `now` приходит в секундах (так его знает вызывающий), ключи ряда —
    номера суток; перевод делается ЗДЕСЬ, в одном месте.
    """
    hi = day_no(now, day)
    lo = hi - window_d
    days = [d for d in days_of(daily) if lo <= d <= hi]
    return sum(daily[d] for d in days), len(days)


def split_forward(daily, declared_at, day=DAY):
    """Дневной ряд книги → (форвард, реплей по прошлому).

    Кандидат реплеится по ВСЕМУ журналу листов, то есть его ряд несёт
    и дни ДО объявления. Это разные вещи, и складывать их нельзя:
    после объявления книга торгует вперёд и переписать её нечем, а до
    объявления это пересчёт по прошлому, которое ассистент видел,
    когда предлагал. Смешав их, кривая читалась бы треком, будучи
    наполовину бэктестом, — ровно то различие, ради которого месячная
    бумажная книга носит `written_at` в каждой записи.

    Возвращает два словаря «день → нетто». День объявления идёт в
    форвард целиком: книга объявлена внутри суток, и делить сутки
    пополам нечем — сделки в ряду стоят по дню ВЫХОДА, а не по часу.
    Это в пользу строгости к нам ровно наполовину и названо словами,
    а не спрятано.
    """
    d0 = day_no(declared_at or 0.0, day)
    fwd = {d: v for d, v in daily.items() if int(d) >= d0}
    pre = {d: v for d, v in daily.items() if int(d) < d0}
    return fwd, pre


def shape_why(daily, declared_at, min_med=MIN_MED_DAY, max_bite=MAX_BITE,
              day=DAY):
    """Причина вылета ПО ФОРМЕ или None.

    Судится ФОРВАРД — дни со дня объявления: до объявления это пересчёт
    по прошлому, которое ассистент видел, когда предлагал, и отставлять
    по нему значило бы судить кандидата бэктестом.

    Судится он ЦЕЛИКОМ, а не последним окном, и это решение: хвост есть
    свойство правила, а не последних десяти суток. Забыв однажды
    случившийся срыв, пул переоткрывал бы его каждый месяц.

    Меньше `stability.MIN_DAYS` суток — вердикта нет вовсе: не измерено
    не есть провал. Мера — `stability.stats`, одна на весь проект;
    ввозится она внутри функции намеренно, потому что `pool` читает и
    сборщик (единственный процесс, который нельзя ронять), а
    `stability` тянет за собой правку `sys.path` — и незачем платить
    этим за модуль, которым сборщик пользуется ради двух чистых
    функций.
    """
    import stability as SB

    fwd, _pre = split_forward(daily, declared_at, day)
    s = SB.stats(fwd)
    if not s or s["thin"]:
        return None
    if s["med"] < min_med:
        return (f"обычный день отрицателен: медиана {s['med']:+.2f} по "
                f"{s['days']} суткам форварда, прибыльных суток "
                f"{s['green']:.2f} — книга теряет не редким срывом, а "
                f"каждый день")
    if s["bite"] is not None and s["bite"] > max_bite:
        return (f"один плохой день съедает {s['bite']:.1f} обычных "
                f"прибыльных при пределе {max_bite:.0f}: худший "
                f"{s['worst']:+.2f} против медианы прибыльного дня "
                f"{s['med_green']:+.2f} по {s['days']} суткам форварда")
    return None


def should_retire(daily, now, null_median, declared_at,
                  window_d=WINDOW_D, idle_d=IDLE_D, day=DAY,
                  min_med=MIN_MED_DAY, max_bite=MAX_BITE):
    """Причина вылета кандидата или None.

    `daily` — НОМЕР СУТОК → нетто книги за эти сутки.
    `null_median` — медиана нуля за то же окно: сравнение идёт со СВОИМ
    нулём, а не с нулём в долларах, иначе правило било бы по книгам,
    которые просто крупнее.

    Форма судится ПЕРВОЙ: с 2026-09-02 она главный критерий владельца, и
    когда верны обе причины, читать он обязан ту, из-за которой книга
    ему неинтересна, а не ту, которую правило проверило раньше.
    """
    age_d = (now - declared_at) / day
    if age_d < window_d:
        # Окна ещё не существует: судить кандидата по трём дням значило
        # бы отставлять по шуму быстрее, чем он успевает торговать.
        return None
    net, n_days = window_net(daily, now, window_d, day)
    if n_days == 0:
        if age_d >= idle_d:
            return (f"простой {age_d:.0f} суток при пределе {idle_d}: "
                    f"слот занят молчанием")
        return None
    why = shape_why(daily, declared_at, min_med, max_bite, day)
    if why:
        return why
    if net < null_median:
        return (f"нетто за {window_d} суток {net:+.2f} ниже медианы "
                f"нуля {null_median:+.2f}")
    return None


def sweep(state, daily_by_id, now, null_median, **kw):
    """Кого отставить сейчас — по всем живым кандидатам разом.

    Контрольная рука судится ТЕМ ЖЕ правилом: иначе сравнивали бы
    живучих отобранных с любыми случайными, и разница читалась бы как
    качество отбора, будучи разницей правил вылета. Это верно и для
    правила формы: полоса жребия обязана умирать от той же медианы дня
    и того же укуса.
    """
    out = []
    for cid, rec in state.items():
        if rec.get("retired_at") is not None:
            continue
        why = should_retire(daily_by_id.get(cid) or {}, now, null_median,
                            rec.get("declared_at") or 0.0, **kw)
        if why:
            out.append((cid, why))
    return out
