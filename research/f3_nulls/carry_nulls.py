#!/usr/bin/env python3
"""
F3 — нулевые модели раздела 7 спеки 04. Ядро расчёта.

Три нуля, и один из них оказался не тем, чем объявлялся
-------------------------------------------------------

Спека §7 объявила:

- **нуль 1** — перестановка оценок между активами внутри сечения;
- **нуль 2** — сдвиг сечения во времени: оценка даты `t` против форварда
  даты `t + сдвиг`;
- **нуль 3** — случайная книга той же ширины, «для сравнения хвостов».

При реализации выяснилось, что **нуль 1 и нуль 3 суть одна и та же
конструкция**. Отбор в книгу — ранговый: берутся верхняя и нижняя доли
сечения. Перестановка оценок между активами даёт равномерно случайное
подмножество заданного размера в каждой ноге. Назначение активам свежих
случайных оценок даёт ровно то же равномерно случайное подмножество.
Распределение книг совпадает, а не близко.

Это не отменяет нуль 3 и не повод его тихо переопределить: объявленное
до прогона считается как объявлено. Но читать его как **независимое**
свидетельство нельзя, и в отчёте это сказано прямо. Полезен он в другом
качестве: два нуля, обязанные совпасть по построению, служат проверкой
самой реализации. Разойдутся заметно — значит в одном из них ошибка.

Чего спека НЕ объявила и потому здесь не считается: нуль, сопоставленный
по волатильности. Настоящая книга набирается из активов с экстремальной
ставкой, а это разогнанные или разваливающиеся имена с высокой
волатильностью; равномерно случайная книга берёт средние. Поэтому
сравнение хвостов «настоящая против случайной» смешивает две вещи —
качество отбора и попадание в волатильный хвост. Правильный нуль для
этого вопроса сопоставляется по волатильности ног, и он записан в
`IDEAS.md`, а не введён задним числом.
"""

import numpy as np

# Имя файла — `carry_nulls`, а не `nulls`, намеренно. Модуль с именем
# `nulls.py` в проекте уже есть (`r2_residual/nulls.py`, нули гипотезы
# 2), и при одинаковых именах импорт подхватывал чужой: пути обоих
# этапов лежат в `sys.path` одного процесса. Прогон падал на
# `AttributeError`, но мог бы и не упасть — совпади имена функций,
# считались бы чужие нули без единого признака подмены.


def permuted(score, rng):
    """Нуль 1: оценки перемешаны между активами внутри сечения.

    Переставляются и NaN вместе со значениями. Иначе актив без оценки
    получил бы чужую, число участников сечения изменилось бы, и нуль
    отличался бы от прогона не только разрывом связи.
    """
    return score[rng.permutation(len(score))]


def random_scores(score, rng):
    """Нуль 3: случайная книга той же ширины.

    Свежие случайные оценки тем активам, у которых оценка есть. Ширина
    ног и состав участников сохраняются; разрушается всё остальное.
    """
    out = np.full(len(score), np.nan)
    m = np.isfinite(score)
    out[m] = rng.random(int(m.sum()))
    return out


def align_by_name(names_to, names_from, values):
    """Значения `values`, разложенные по именам `names_to`.

    Нужно нулю 2: сечение даты `t` и сечение даты `t + сдвиг` состоят из
    разных активов, и сопоставлять их по позиции нельзя — совпадение
    длин ничего не гарантирует. Актив, которого во втором сечении нет,
    получает NaN и выбывает.
    """
    pos = {n: i for i, n in enumerate(names_from)}
    out = np.full(len(names_to), np.nan)
    for i, n in enumerate(names_to):
        j = pos.get(n)
        if j is not None:
            out[i] = values[j]
    return out


def percentile(values, q):
    v = sorted(float(x) for x in values if x is not None and x == x)
    if not v:
        return None
    if len(v) == 1:
        return v[0]
    pos = q / 100.0 * (len(v) - 1)
    lo = int(np.floor(pos))
    hi = min(lo + 1, len(v) - 1)
    return v[lo] + (v[hi] - v[lo]) * (pos - lo)


def sigmas_from(value, samples):
    """Расстояние от среднего распределения зёрен, в его сигмах.

    Устойчивая мера силы результата. Вердикт §8.2 выносится по 95-му
    процентилю (порог менять нельзя), но при десяти зёрнах 95-й
    процентиль есть попросту максимум десяти, а максимум десяти —
    шумная величина: в R3 отношение «прогон / процентиль» выходило
    ×8.6, ×10.7 и ×19.3 при неизменном прогоне.
    """
    v = np.asarray([x for x in samples if x is not None and x == x],
                   dtype=np.float64)
    if len(v) < 2:
        return None
    sd = float(v.std(ddof=1))
    if sd <= 0:
        return None
    return (float(value) - float(v.mean())) / sd
