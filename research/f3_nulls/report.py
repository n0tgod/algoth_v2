#!/usr/bin/env python3
"""
F3 — отчёт по артефакту прогона. Зависимостей не имеет намеренно.

    python3 report.py --interval 1m > out/F3-report-1m.md
"""

import argparse
import json
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")


def bp(x, d=1):
    return "—" if x is None else f"{x * 10000:.{d}f}"


def pct(x, d=1):
    return "—" if x is None else f"{x * 100:.{d}f} %"


def f(x, d=1):
    return "—" if x is None else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--interval", default="1m")
    ap.add_argument("--funding-venue", default="bybit")
    a = ap.parse_args()
    path = os.path.join(OUT, f"f3_{a.interval}_{a.funding_venue}.json")
    if not os.path.exists(path):
        raise SystemExit(f"нет {path} — сначала run.py")
    with open(path, encoding="utf-8") as fh:
        d = json.load(fh)
    cfg, cells, grid, stop = (d["config"], d["cells"], d["grid"],
                              d["stop_criterion"])
    p = print
    n = grid["cells"]

    p("# F3 — нулевые модели\n")
    p("**Спека:** 04, раздел 7 и критерий немедленной остановки §8.2  ")
    p(f"**Разрешение хранилища:** {cfg['interval']}, ставки "
      f"{cfg['funding_venue']}  ")
    p(f"**Зёрен на нуль:** {cfg['seeds']}, сдвигов: {len(cfg['shifts'])}  ")
    p(f"**Сечений:** {cfg['sections']}\n")
    if cfg["funding_venue"] != "bybit":
        p("> **Ставки взяты НЕ с площадки исполнения** — проверка "
          "конвейера, не вердикт.\n")

    p("## Оговорка, которую надо прочесть до чисел\n")
    p("Спека объявила три нуля. При реализации выяснилось, что **нуль 1 и "
      "нуль 3 суть одна конструкция**: отбор в книгу ранговый, поэтому и "
      "перестановка оценок между активами, и назначение свежих случайных "
      "оценок дают равномерно случайное подмножество заданного размера в "
      "каждой ноге. Совпадают распределения книг, а не близки — это "
      "закреплено тестом.\n")
    p("Объявленное до прогона считается как объявлено, поэтому оба нуля "
      "здесь есть. Но читать нуль 3 как **независимое** свидетельство "
      "нельзя. Полезен он в другом качестве: два нуля, обязанные совпасть "
      "по построению, проверяют саму реализацию — заметное расхождение "
      "означало бы ошибку в одном из них.\n")
    p("Нуль, который был бы для сравнения хвостов правильным, "
      "**сопоставляется по волатильности**: настоящая книга набирается из "
      "активов с экстремальной ставкой, то есть из разогнанных и "
      "разваливающихся имён, а равномерно случайная берёт средние. Спека "
      "такого нуля не объявила, и вводить его задним числом нельзя — "
      "записан в `IDEAS.md`.\n")

    p("## 1. Результат против нулей\n")
    p("| Ячейка | Прогон, б.п. | Нуль 1: среднее | 95-й проц. | σ "
      "| Нуль 2: среднее | максимум | σ | Нуль 3: среднее |")
    p("|---|---|---|---|---|---|---|---|---|")
    for name in sorted(cells):
        c = cells[name]
        p(f"| {name} | **{bp(c['real'])}** | {bp(c['null1_mean'])} "
          f"| {bp(c['null1_p95'])} | {f(c['null1_sigmas'])} "
          f"| {bp(c['null2_mean'])} | {bp(c['null2_max'])} "
          f"| {f(c['null2_sigmas'])} | {bp(c['null3_mean'])} |")
    p("")
    p(f"Выше 95-го процентиля нуля 1: **{grid['above_null1_p95']} из {n}**. "
      f"Выше максимума нуля 2: **{grid['above_null2_max']} из {n}**.\n")
    p(f"Расстояние от среднего распределения зёрен: медиана "
      f"**{f(grid['sigmas_null1_median'])} σ** от нуля 1 и "
      f"**{f(grid['sigmas_null2_median'])} σ** от нуля 2.\n")
    p("Силу результата читать по сигмам, а не по отношению к процентилю. "
      "При десяти зёрнах 95-й процентиль есть попросту максимум десяти, а "
      "максимум десяти — шумная величина: в R3 отношение «прогон / "
      "процентиль» выходило ×8.6, ×10.7 и ×19.3 при неизменном прогоне. "
      "Вердикт §8.2 выносится по процентилю (порог менять нельзя), "
      "устойчивая мера — сигмы.\n")

    p("## 2. Хвост: просадка против случайной книги\n")
    p("| Ячейка | Просадка прогона | Просадка нуля 3, медиана | Хуже? |")
    p("|---|---|---|---|")
    for name in sorted(cells):
        c = cells[name]
        p(f"| {name} | {pct(c['drawdown'])} "
          f"| {pct(c['drawdown_null3_median'])} "
          f"| {'да' if c['drawdown_worse_than_null3'] else 'нет'} |")
    p("")
    p(f"Просадка хуже, чем у случайной книги: "
      f"**{grid['drawdown_worse_than_null3']} из {n}**.\n")
    p("Это брутто: издержек в просадке нет, они предмет F4.\n")

    p("## 3. Критерий немедленной остановки §8.2\n")
    p("| Условие | Порог | Получено | |")
    p("|---|---|---|---|")
    p(f"| Медианный результат выше 95-го процентиля нуля 1 | во всех "
      f"ячейках | {grid['above_null1_p95']} из {n} "
      f"| {'✗ СРАБОТАЛ' if stop['not_above_null1'] else '✓'} |")
    p(f"| Просадка хуже, чем у нуля 3 | менее чем в 5 ячейках "
      f"| {grid['drawdown_worse_than_null3']} из {n} "
      f"| {'✗ СРАБОТАЛ' if stop['drawdown_worse_in_5plus'] else '✓'} |")
    p("")
    p("Два других условия §8.2 измерены на F1 и не сработали: медиана "
      "брутто по сетке положительна, цена съедает начисления в 0 ячейках "
      "из 8.\n")

    p("## Вердикт\n")
    if any(stop.values()):
        p("**Критерий немедленной остановки §8.2 сработал.** Гипотеза "
          "закрывается до бэктеста. По решению §11.3 спеки права на "
          "итерацию нет.\n")
    else:
        p("Критерий немедленной остановки не сработал ни по одному "
          "условию. Переход к **F4** — издержки, бэктест, все критерии "
          "§8.3 целиком. Напоминание §11.3: исход «выполнены частично» "
          "для этой гипотезы отменён, любой невыполненный критерий "
          "закрывает её.\n")


if __name__ == "__main__":
    main()
