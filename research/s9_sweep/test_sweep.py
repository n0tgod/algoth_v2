#!/usr/bin/env python3
"""Проверки перебора правил: геометрия сделки и отбор ног.

Считается тут одно — чем кончилась сделка, — и ошибка здесь была бы
невидимой: числа получились бы, а описывали бы другую сделку. Поэтому
каждый исход проверяется на баре, построенном руками, и рядом стоит
случай ничьей, который обязан решаться ПРОТИВ нас.

    python3 research/s9_sweep/test_sweep.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import sweep as S                                            # noqa: E402

FAIL = []


def check(name, ok, extra=""):
    print(("  ok   " if ok else "  ПАДЕНИЕ ") + name
          + ("" if ok else f": {extra}"))
    if not ok:
        FAIL.append(name)


def bar(t, o, h, l, c):
    return [t, o, h, l, c, 1.0]


def test_bracket():
    t0 = 1_786_000_000
    # Лонг: вход 100, обещания −20 / +40 б.п. → стоп 99.8, цель 100.4.
    up = [bar(t0, 100.0, 100.05, 99.95, 100.0),
          bar(t0 + 60, 100.0, 100.45, 99.99, 100.4)]
    got = S.bracket(up, t0, 100.0, "long", -20.0, 40.0)
    check("лонг: цель взята вторым баром",
          got and got[0] == "цель" and round(got[1]) == 40, str(got))

    down = [bar(t0, 100.0, 100.05, 99.75, 99.8)]
    got = S.bracket(down, t0, 100.0, "long", -20.0, 40.0)
    check("лонг: стоп взят первым баром",
          got and got[0] == "стоп" and round(got[1]) == -20, str(got))

    # Ничья внутри бара: задеты оба уровня. Решается против нас.
    both = [bar(t0, 100.0, 100.50, 99.70, 100.2)]
    got = S.bracket(both, t0, 100.0, "long", -20.0, 40.0)
    check("оба уровня в одном баре — считается стоп",
          got and got[0] == "стоп", str(got))

    # Без цели уровень в пользу не закрывает — только стоп и срок.
    got = S.bracket(up, t0, 100.0, "long", -20.0, 40.0, take=False)
    check("без цели сделка доживает до срока",
          got and got[0] == "срок", str(got))

    # Шорт зеркален: стоп сверху, цель снизу.
    sh = [bar(t0, 100.0, 100.05, 99.55, 99.6)]
    got = S.bracket(sh, t0, 100.0, "short", 20.0, -40.0)
    check("шорт: цель снизу",
          got and got[0] == "цель" and round(got[1]) == -40, str(got))
    sh2 = [bar(t0, 100.0, 100.25, 99.95, 100.2)]
    got = S.bracket(sh2, t0, 100.0, "short", 20.0, -40.0)
    check("шорт: стоп сверху",
          got and got[0] == "стоп" and round(got[1]) == 20, str(got))

    # Записи нет — нога не считается вовсе, а не считается нулём.
    check("без баров ноги нет", S.bracket([], t0, 100.0, "long",
                                          -20.0, 40.0) is None)
    # Бары есть, но все ДО входа — то же самое.
    old = [bar(t0 - 600, 100.0, 100.4, 99.6, 100.0)]
    check("бары до входа не считаются",
          S.bracket(old, t0, 100.0, "long", -20.0, 40.0) is None)

    # Срок: цена никуда не дошла, берётся закрытие последнего бара.
    flat = [bar(t0, 100.0, 100.05, 99.95, 100.05)]
    got = S.bracket(flat, t0, 100.0, "long", -20.0, 40.0)
    check("срок: исход по закрытию последнего бара",
          got and got[0] == "срок" and round(got[1]) == 5, str(got))


def test_net_and_rr():
    # Лонг: ход +40, круг 11 → нетто +29; риск = |−20| + 11 = 31.
    n, r = S.net_bp("long", 40.0, -20.0)
    check("нетто лонга — ход минус круг издержек",
          round(n, 1) == 29.0 and round(r, 2) == 0.94, f"{n} {r}")
    # Шорт: ход цены −40 означает +40 позиции.
    n, r = S.net_bp("short", -40.0, 20.0)
    check("нетто шорта — знак перевёрнут",
          round(n, 1) == 29.0, f"{n} {r}")
    # Риск считается ВМЕСТЕ с издержками: иначе R завышается ровно на
    # круг, и «1 к 2» на бумаге оказывается 1 к 1.8 в деньгах.
    check("издержки входят в риск, а не только в результат",
          round(S.net_bp("long", 0.0, -20.0)[1], 3) == round(
              -11.0 / 31.0, 3))

    leg = {"mae": -20.0, "mfe": 60.0}
    check("RR считается по обещаниям пути", S.rr_of(leg) == 3.0)
    check("без обещания против RR не существует",
          S.rr_of({"mae": 0.0, "mfe": 60.0}) is None)


def test_stop_walk():
    """Пробой обещанной линии и возврат к цели — арифметика руками.

    Замечание владельца: стоп стоит РОВНО там, куда модель предсказала
    ход против, то есть заявка ставится в точку, куда цена по нашему же
    прогнозу придёт. Замер обязан отвечать двумя числами — как часто
    линию касаются и на сколько её пробивают, — и оба считаются здесь
    по барам, построенным руками.
    """
    import stops as ST

    t0 = 1_786_000_000
    # Лонг, вход 100, обещания −20 / +40 б.п.: линия против 99.8.
    # Цена уходит до 99.7 (пробой 10 б.п. = половина длины линии) и
    # возвращается к цели 100.4.
    bars = [bar(t0, 100.0, 100.05, 99.70, 99.9),
            bar(t0 + 60, 99.9, 100.45, 99.85, 100.4)]
    w = ST.walk(bars, t0, 100.0, "long", -20.0, 40.0)
    check("касание линии замечено", w and w["touched"], str(w))
    check("пробой измерен в б.п. и в долях линии",
          w and round(w["over_bp"]) == 10 and abs(w["over_x"] - 0.5)
          < 1e-6, str(w))
    check("возврат к цели после касания засчитан",
          w and w["recovered"], str(w))

    # Не коснулась вовсе — ни пробоя, ни возврата.
    calm = [bar(t0, 100.0, 100.10, 99.90, 100.05)]
    w = ST.walk(calm, t0, 100.0, "long", -20.0, 40.0)
    check("без касания пробоя нет",
          w and not w["touched"] and w["over_bp"] == 0.0, str(w))

    # Коснулась и НЕ вернулась: цель не достигнута.
    down = [bar(t0, 100.0, 100.05, 99.50, 99.6),
            bar(t0 + 60, 99.6, 99.80, 99.40, 99.5)]
    w = ST.walk(down, t0, 100.0, "long", -20.0, 40.0)
    check("коснулась и не вернулась — возврата нет",
          w and w["touched"] and not w["recovered"], str(w))

    # Шорт зеркален: линия против сверху.
    up = [bar(t0, 100.0, 100.30, 99.95, 100.2),
          bar(t0 + 60, 100.2, 100.25, 99.55, 99.6)]
    w = ST.walk(up, t0, 100.0, "short", 20.0, -40.0)
    check("шорт: пробой считается вверх",
          w and w["touched"] and round(w["over_bp"]) == 10
          and w["recovered"], str(w))

    # Буфер отодвигает стоп ровно на свою долю: та же нога с буфером
    # 0.5 доживает до цели, без него закрывается стопом.
    leg = {"sym": "A", "side": "long", "px": 100.0, "mae": -20.0,
           "mfe": 40.0, "at": t0, "bars": bars}
    m0 = ST.measure_buffer([leg], 0.0)
    m_eq = ST.measure_buffer([leg], 0.5)   # буфер РАВЕН пробою
    m1 = ST.measure_buffer([leg], 0.6)
    check("без буфера — стоп", m0["stop"] == 1, str(m0))
    # Граница честная: буфер РОВНО в пробой не спасает — касание
    # уровня считается срабатыванием, как и у живого сторожа. Спасает
    # буфер БОЛЬШЕ пробоя.
    check("буфер ровно в пробой не спасает", m_eq["stop"] == 1,
          str(m_eq))
    check("буфер больше пробоя доводит до цели", m1["target"] == 1,
          str(m1))


def main():
    test_bracket()
    test_stop_walk()
    test_net_and_rr()
    print()
    if FAIL:
        print(f"ПАДЕНИЙ: {len(FAIL)} — " + ", ".join(FAIL))
        raise SystemExit(1)
    print("все проверки прошли")


if __name__ == "__main__":
    main()
