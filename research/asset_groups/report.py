#!/usr/bin/env python3
"""Формирует отчёт A3 в markdown из groups.yaml и candidates_*.json.

Числа не вписываются в текст руками: при следующем прогоне отчёт
разошёлся бы с данными и стал бы хуже, чем его отсутствие.

    python3 report.py --interval 1m
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")

sys.path.insert(0, HERE)
import pairs as P                                    # noqa: E402
from check_coverage import GROUPS, eligible, parse_groups  # noqa: E402

SHOW_WINDOWS = ("2022-12-28", "2023-06-26", "2024-06-20", "2025-06-15",
                "2026-03-12")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--interval", default="1m")
    args = ap.parse_args()

    with open(os.path.join(OUT, f"candidates_{args.interval}.json"),
              encoding="utf-8") as f:
        cand = json.load(f)
    sections = parse_groups(GROUPS)
    meta = {k: sections.pop(k, []) for k in P.META_SECTIONS}
    working, cutoff = eligible()
    excluded = set(sections.get("excluded_special", []))
    tradable = {g: v for g, v in sections.items() if g != "excluded_special"}
    assigned = {a for v in sections.values() for a in v}

    L, add = [], None
    L = []
    add = L.append

    add("# Отчёт A3 — экономическая группировка\n")
    add("Сгенерирован `research/asset_groups/report.py`.")
    add("Спецификация 02, раздел 3.1.\n")
    add("Перебор всех пар универсума — методологическая ошибка: при "
        "тысячах")
    add("тестов часть пар пройдёт тест на коинтеграцию случайностью, и "
        "поправка")
    add("на множественность съест вместе с ними настоящие находки. "
        "Задача этапа —")
    add("сократить пространство поиска по признакам, **не выведенным из "
        "цен**.\n")
    add("---\n")

    # 1
    add("## 1. Охват\n")
    add("| | |")
    add("|---|---:|")
    add(f"| Подлежит группировке (листинг до {cutoff}) | {len(working)} |")
    add(f"| Размечено по секторам | {len(assigned & working)} |")
    add(f"| Из них особые случаи (не для парной торговли) | "
        f"{len(excluded & working)} |")
    add(f"| Без метки | {len(set(meta['unlabeled']) & working)} |")
    add(f"| Метка ненадёжна | {len(meta['low_confidence'])} |")
    add(f"| Покрытие | {100*len(assigned & working)/len(working):.1f} % |")
    add("")
    add("Знаменатель — не «торгуемые сегодня» и не когорты с длинной")
    add("историей, а всё, что может попасть хотя бы в одно окно")
    add("walk-forward: криптоактив с историей Binance, листингованный не")
    add("позже чем за 365 дней до конца данных. Черновик этапа считал")
    add("покрытие от 269 активов с историей 3+ года — это описывало бы")
    add("только ранние окна.\n")
    add("**Без метки активы кандидатов не порождают.** Пустая метка хуже")
    add("отсутствующей: она создаёт пары, у которых нет причины быть")
    add("парой, и они пойдут прямо в квоту ложных открытий раздела 3.3.\n")

    # 2
    add("## 2. Группы\n")
    add("| Группа | Активов | Пар |")
    add("|---|---:|---:|")
    for g, v in sorted(tradable.items(), key=lambda kv: -len(kv[1])):
        n = len({a for a in v if a in working})
        add(f"| `{g}` | {n} | {n*(n-1)//2} |")
    add("")
    add("DeFi разделён **по функции**, а не по размеру: у биржи и у")
    add("кредитного протокола разные драйверы — объём торгов и ставка.")
    add("Группа `smart_contract_l1` намеренно оставлена крупной: деление")
    add("«майоры против остальных» есть деление по сегодняшнему обороту,")
    add("то есть заглядывание вперёд. Размер учитывается в разделе 4 —")
    add("на момент окна.\n")

    # 3
    add("## 3. Одинаковые активы под двумя тикерами\n")
    add("Найдено при разметке: часть тикеров универсума — это один и тот")
    add("же актив после ребрендинга с миграцией 1:1.\n")
    for p in meta["duplicate_listings"]:
        add(f"- `{p.replace('/', '` / `')}`")
    add("")
    add("Спред между такими тикерами постоянен по построению. Тест на")
    add("коинтеграцию нашёл бы здесь **сильнейшую «связь» в универсуме**,")
    add("и она попала бы в отчёт как лучшая находка этапа. Пары")
    add("исключаются целиком.\n")
    add("Отдельно — механически связанные: разные активы, но связь задана")
    add("протоколом, а не нарративом.\n")
    for p in meta["mechanically_linked"]:
        add(f"- `{p.replace('/', '` / `')}`")
    add("")
    add("Такие пары входят в отбор независимо от разницы в обороте:")
    add("газовый токен всегда меньше своей сети.\n")

    # 4
    add("## 4. Кандидаты на момент окна\n")
    add(f"Оценка ликвидности — {cand['form_days']} дней, "
        f"**закончившихся до** даты отбора.")
    add(f"Требование к истории — {cand['min_history_days']} дней. "
        f"Порог свежести цены —")
    add(f"доля минут со сделками не ниже {100*cand['min_share_traded']:.0f} %."
        f" Порог по размеру —")
    add(f"оборот ног различается не больше чем в "
        f"{cand['max_turnover_ratio']:.0f} раз.\n")
    add("| Дата отбора | Активов | Кандидатов | Возможных пар | Отсечено |")
    add("|---|---:|---:|---:|---:|")
    for w in cand["windows"]:
        if w["date"] not in SHOW_WINDOWS:
            continue
        cut = 100 * (1 - w["pairs"] / max(1, w["all_pairs"]))
        add(f"| {w['date']} | {w['assets']} | {w['pairs']} | "
            f"{w['all_pairs']} | {cut:.1f} % |")
    add("")
    first, last = cand["windows"][0], cand["windows"][-1]
    add(f"**Универсум окна мал в начале истории.** На {first['date']} "
        f"условиям")
    add(f"отбора удовлетворяют {first['assets']} активов, на "
        f"{last['date']} — {last['assets']}.")
    add("Требование 365 дней истории на площадке исполнения плюс сама")
    add("история листингов делают ранние окна тонкими: статистика по ним")
    add("будет слабее, и это надо помнить при чтении walk-forward, а не")
    add("объяснять потом.\n")

    add("### Чувствительность к порогу размера\n")
    add("| Дата | ×3 | ×10 | ×30 | без порога |")
    add("|---|---:|---:|---:|---:|")
    for w in cand["windows"]:
        if w["date"] not in SHOW_WINDOWS:
            continue
        r = w["pairs_by_ratio"]
        add(f"| {w['date']} | {r['3.0']} | {r['10.0']} | {r['30.0']} | "
            f"{r['1000000000.0']} |")
    add("")
    add("Порог ×10 выбран не по красоте числа: позиция берётся равным")
    add("нотионалом на обе ноги, поэтому при десятикратной разнице")
    add("оборотов доля от рынка у меньшей ноги вдесятеро хуже, и")
    add("проскальзывание считается по ней. Порог — правило на паре, а не")
    add("разбиение на корзины: разбиение развело бы активы с оборотом")
    add("9.9 и 10.1 млн, не различающиеся ничем.\n")

    add("## 5. Что этот этап НЕ даёт\n")
    add("- **Группа не есть доказательство связи.** Это способ не")
    add("  проверять заведомо бессмысленное. Пара внутри группы всё равно")
    add("  обязана пройти коинтеграцию, поправку на множественность и")
    add("  фильтр по полураспаду;")
    add("- **метки секторов — суждение, а не измерение.** У четверти")
    add("  размеченных активов метка помечена ненадёжной. Если находка")
    add("  придётся на такую пару, первым делом проверяется метка;")
    add("- **ликвидность измерена по Binance**, потому что там история.")
    add("  Исполнение идёт на Bybit, и там обороты другие. Для отсева")
    add("  заведомо мёртвых ног этого достаточно, для модели издержек A6 —")
    add("  нет.\n")

    path = os.path.join(OUT, "A3-groups-report.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("записан", path)


if __name__ == "__main__":
    main()
