#!/usr/bin/env python3
"""
Z2 — признаки СОБСТВЕННОЙ записи стакана, сведённые по минутам.

Здесь только разбор и арифметика над одним символо-часом: ни чтения
каталогов, ни матриц, ни статистики. Разделение то же, что у M1, и по
той же причине — заглядывание в будущее проверяется лишь на функциях,
которым можно подать выдуманные данные.

Что даёт эта запись и чего не дают ни свечи, ни принты
------------------------------------------------------

Четыре замера ленты (T1–T4) видели, СКОЛЬКО агрессии прошло через
уровень, и не видели, подставляли ли уровень заново. Знаменателя не
было. Здесь он появляется: глубина полосы стоит в каждом снимке, и
разность соседних снимков плюс прошедшая между ними агрессия дают
чистое ДОБАВЛЕНИЕ или СНЯТИЕ ликвидности.

Сверх того запись даёт величины, невыразимые на сделках вовсе: ход
середины БЕЗ единой сделки (котировка ушла, потому что сняли заявки),
число обновлений книги в секунду, растяжение лесенки, время жизни
лучшей цены при текущем потоке.

Два времени снимка, и это не мелочь
-----------------------------------

В строке лежат ДВА времени: наша метка `t` и биржевая `ts` последнего
применённого обновления. Метку `t` сборщик ставит ОДИН РАЗ на весь
проход по символам (`now` фиксируется до цикла), а проход занимает от
0.18 до 2.5 секунды — значит у символов, до которых очередь дошла
позже, содержимое снимка новее собственной метки. Это заглядывание в
будущее ровно того размера, который решает на секундных горизонтах.

Поэтому моментом наблюдения считается `max(t, ts)`: биржевая метка
говорит, каким было состояние книги, когда его прочитали, и не бывает
в будущем относительно чтения. У неактивного символа `ts` старая — это
не мешает: состояние с тех пор не менялось.

Минута как единица
------------------

Снимок раз в секунду по 725 именам — 2.5 ГБ в сутки в памяти, если
держать посекундные матрицы. Всё, что нужно замеру, сводится по
минутам прямо при чтении: путь середины, доля пути без сделок, медианы
спреда и глубины, суммы агрессии по сторонам. Секундная подробность
входит внутрь этих величин и не хранится.
"""

import json

# Полоса глубины, по которой считается выедание. Узкая (±0.05 %) у
# плотных имён вырождается — у BTCUSDT все полсотни уровней помещались
# внутрь неё, — а широкая у тонких выходит за охват книги. Полоса
# ±0.25 % выбрана как единственная, где обе крайности живы; охват
# (`reach`) едет рядом числом, чтобы вырождение было видно.
BAND = "0.0025"


def _num(line, key, start=0):
    """Число по ключу в кавычках. Быстрее json.loads в разы.

    Ключ ищется вместе с кавычками и двоеточием: `"bid":` не совпадает
    с `"bid_sz":`, а `,"t":` — с `"ts":`. Разбор закреплён тестом на
    совпадение с `json.loads` дословно: быстрый путь, разошедшийся с
    медленным, — это другая мера, а не ускорение.
    """
    i = line.find(key, start)
    if i < 0:
        raise ValueError(f"нет {key}")
    i += len(key)
    j = i
    while j < len(line) and line[j] not in ",}":
        j += 1
    return float(line[i:j]), j


def snap_line(line):
    """Снимок: момент наблюдения и скаляры книги.

    Возвращает кортеж
    `(known_at, mid, spread_bp, bid_sz, ask_sz, upd, reach, bq, aq)`.
    Лесенка не разбирается вовсе — она втрое тяжелее всего остального,
    а величины уровней нужны отдельному замеру.
    """
    bid, j = _num(line, '"bid":')
    ask, j = _num(line, '"ask":', j)
    bsz, j = _num(line, '"bid_sz":', j)
    asz, j = _num(line, '"ask_sz":', j)
    ts, _ = _num(line, '"ts":')
    upd, _ = _num(line, '"upd":')
    rb, _ = _num(line, '"reach_b":')
    ra, _ = _num(line, '"reach_a":')
    bq, _ = _num(line, f'"bq{BAND}":')
    aq, _ = _num(line, f'"aq{BAND}":')
    t, _ = _num(line, ',"t":')
    mid = (bid + ask) / 2.0
    if mid <= 0:
        raise ValueError("нулевая середина")
    # Момент наблюдения — позднее из двух времён (см. шапку).
    known = max(t, ts / 1000.0)
    return (known, mid, (ask - bid) / mid * 1e4, bsz, asz, upd,
            min(rb, ra), bq, aq)


def trade_line(line):
    """Принт: момент, сторона агрессора, нотионал."""
    ts, _ = _num(line, '"ts":')
    side, _ = _num(line, '"side":')
    p, _ = _num(line, '"p":')
    v, _ = _num(line, '"v":')
    return ts / 1000.0, int(side), p * v


def minute_of(t, t0):
    return int((t - t0) // 60)


def fold(snaps, trades, t0, n_min):
    """Свести символо-час к минутам. Обе последовательности — по времени.

    Возвращает словарь массивов длины `n_min`. Пустая минута остаётся
    пропуском (`None`), а не наблюдением с нулями: минута без снимков —
    это отсутствие данных, и ноль в глубине читался бы как «книга
    пуста» (урок A2 про бар без сделок).

    Считается в два прохода: сперва по снимкам, потом по минутам —
    потому что «снятие ликвидности» есть изменение глубины МИНУС то,
    что объяснено сделками, а суммы сделок известны только после
    второго прохода. Считать их в одном значило бы вычитать нули.
    """
    keys = ("mid_open", "mid_close", "mid_hi", "mid_lo", "spread",
            "depth_b", "depth_a", "imb", "reach", "upd", "path",
            "path_quiet", "buy", "sell", "trades", "snaps",
            "pull_bid", "pull_ask")
    out = {k: [None] * n_min for k in keys}
    tr_sec = {}
    for ts, side, notional in trades:
        a = tr_sec.setdefault(int(ts), [0.0, 0.0])
        a[0 if side > 0 else 1] += notional
    per = {}
    prev = None
    for known, mid, spread, bsz, asz, upd, reach, bq, aq in snaps:
        m = minute_of(known, t0)
        if m < 0 or m >= n_min:
            prev = None
            continue
        a = per.get(m)
        if a is None:
            a = per[m] = {"n": 0, "spread": [], "bq": [], "aq": [],
                          "reach": [], "upd": 0.0, "path": 0.0,
                          "quiet": 0.0, "first_mid": mid,
                          "last_mid": mid, "hi": mid, "lo": mid,
                          "first_bq": bq, "first_aq": aq,
                          "last_bq": bq, "last_aq": aq}
            prev = None            # путь не сшивается через границу
        a["n"] += 1
        a["spread"].append(spread)
        a["bq"].append(bq)
        a["aq"].append(aq)
        a["reach"].append(reach)
        a["upd"] += upd
        a["last_mid"] = mid
        a["last_bq"], a["last_aq"] = bq, aq
        a["hi"] = max(a["hi"], mid)
        a["lo"] = min(a["lo"], mid)
        if prev is not None:
            step = abs(mid - prev[1]) / prev[1] * 1e4
            a["path"] += step
            # Была ли сделка МЕЖДУ снимками. Полуинтервал (prev, now]:
            # сделка ровно на метке прошлого снимка уже учтена там.
            traded = any(sec in tr_sec
                         for sec in range(int(prev[0]), int(known) + 1))
            if not traded:
                a["quiet"] += step
        prev = (known, mid)
    for m, a in per.items():
        b = s_ = 0.0
        n_tr = 0
        for sec in range(int(t0) + m * 60, int(t0) + (m + 1) * 60):
            got = tr_sec.get(sec)
            if got:
                b += got[0]
                s_ += got[1]
                n_tr += 1
        db, da = _med(a["bq"]), _med(a["aq"])
        tot = (db or 0.0) + (da or 0.0)
        out["snaps"][m] = a["n"]
        out["mid_open"][m] = a["first_mid"]
        out["mid_close"][m] = a["last_mid"]
        out["mid_hi"][m], out["mid_lo"][m] = a["hi"], a["lo"]
        out["spread"][m] = _med(a["spread"])
        out["depth_b"][m], out["depth_a"][m] = db, da
        out["imb"][m] = (((db or 0.0) - (da or 0.0)) / tot
                         if tot > 0 else None)
        out["reach"][m] = _med(a["reach"])
        out["upd"][m] = a["upd"]
        out["path"][m] = a["path"]
        out["path_quiet"][m] = a["quiet"]
        out["buy"][m], out["sell"][m] = b, s_
        out["trades"][m] = n_tr
        # Снятие ликвидности: глубина изменилась на Δ, сделками
        # объяснено `eat`, остальное — заявки. Плюс означает уход
        # ликвидности БЕЗ сделок, минус — приход. Это и есть
        # знаменатель, которого не было у четырёх замеров ленты: они
        # видели `eat` и не видели, подставили ли уровень заново.
        out["pull_bid"][m] = -((a["last_bq"] - a["first_bq"]) + s_)
        out["pull_ask"][m] = -((a["last_aq"] - a["first_aq"]) + b)
    return out


def _med(v):
    if not v:
        return None
    s = sorted(v)
    n = len(s)
    m = n // 2
    return s[m] if n % 2 else (s[m - 1] + s[m]) / 2.0
