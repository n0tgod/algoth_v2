#!/usr/bin/env python3
"""Z3: потоки по ЦЕНОВЫМ УРОВНЯМ — ядро меры.

Зачем это отдельно от Z2. Z2 меряет снятие заявок по ПОЛОСЕ ±0.25 %,
привязанной к середине, а середина движется: часть «снятия» на резком
ходе есть смещение полосы, а не уход заявок. Отчёт Z2 назвал это своей
главной оговоркой, и починить её полосой нельзя — нужна привязка к
самой цене уровня. Это и есть недостающий знаменатель четырёх замеров
ленты T1–T4: они видели, сколько агрессии прошло через уровень, и не
видели, подставляли ли уровень заново.

## Что меряется (объявлено ДО прогона)

Между двумя соседними снимками одного символа, по каждой цене `p`:

* `Δ = размер(p, сейчас) − размер(p, прежде)`;
* `съедено(p) = min(убыль, объём сделок НА ЭТОЙ ЦЕНЕ)` — уровень выели;
* `снято(p) = убыль − съедено(p)` — уровень убрали, сделок не было;
* `добавлено(p) = прирост` — уровень подставили.

Сведённые к минуте поля (нотионал = цена × размер):

| поле | что это |
|---|---|
| `vis_b/a` | видимый нотионал пересечения — знаменатель всего |
| `eat_b/a` | съедено сделками на своих ценах |
| `cancel_b/a` | снято БЕЗ сделки на этой цене |
| `add_b/a` | добавлено |
| `dead_b/a` | нотионал уровней, ушедших в ноль без единой сделки |
| `refill_b/a` | добавлено на ценах, где в ту же минуту была сделка |
| `sweep` | съедено на базисный пункт хода середины |
| `pairs` | пар снимков в минуте; ноль — ПРОПУСК, а не нулевое наблюдение |

## Три правила, без которых мера считала бы не то

1. **Цена, ушедшая за край видимой лесенки, — не снятие.** Лесенка
   обрезана (50 уровней у альтов, 200 у BTC и ETH), и при ходе цены
   дальние уровни выпадают из видимости, не будучи отменёнными. Поэтому
   считается только ПЕРЕСЕЧЕНИЕ видимых цен двух снимков. Ровно эта
   ошибка и загрязняет полосовую меру Z2.
2. **Убыль, объяснённая сделкой на этой же цене, — не снятие.** Иначе
   «снятие» окажется переодетой агрессией, и знаменатель T1–T4 снова не
   построится.
3. **Разрыв в записи не даёт наблюдения.** Пара снимков дальше
   `MAX_DT` секунд друг от друга пропускается: иначе пятиминутная дыра
   станет гигантским «снятием». Тот же класс дефекта, что окно по
   номеру точки в L2 и зашитый шаг в загрузчике цен.

## Чего ядро НЕ делает

Не решает, торгуемо ли это: у меры нет ни стопа, ни цели, ни размера.
Скрин по этим полям — следующий шаг, и его условия объявляются там же,
где объявлялись условия Z1 и Z2.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
for p in (os.path.join(ROOT, "research", "z2_book"),
          os.path.join(ROOT, "research", "b1_book")):
    if p not in sys.path:
        sys.path.insert(0, p)

MAX_DT = 3.0        # секунд между снимками; дальше — разрыв, не наблюдение
MIN_PAIRS = 20      # пар в минуте, ниже которых минута — пропуск

FIELDS = ("vis_b", "vis_a", "eat_b", "eat_a", "cancel_b", "cancel_a",
          "add_b", "add_a", "dead_b", "dead_a", "refill_b", "refill_a",
          "sweep", "pairs")


def side_flows_slow(prev, cur, traded):
    """Потоки одной стороны через словари — образцовая реализация.

    Медленная и очевидная: быстрый путь ниже обязан совпадать с ней бит
    в бит, и это закреплено проверкой на случайных лесенках. Ускорение,
    меняющее числа, есть другая мера.
    """
    # Обход идёт в порядке САМОЙ лесенки, а не по множеству ключей:
    # множество перебирается в произвольном порядке, и сумма чисел с
    # плавающей точкой от порядка зависит в последних битах. Тогда
    # строгое равенство с быстрым путём недостижимо в принципе, и
    # проверка «бит в бит» выродилась бы в проверку с допуском.
    b = {float(p): float(s) for p, s in cur}
    vis = eat = cancel = add = dead = refill = 0.0
    for p0, s0 in prev:
        p = float(p0)
        if p not in b:
            continue
        sa, sb = float(s0), b[p]
        d = sb - sa
        vis += p * sa
        t = traded.get(p, 0.0)
        if d < 0:
            gone = -d
            e = min(gone, t)
            eat += p * e
            cancel += p * (gone - e)
            if sb == 0.0 and t == 0.0:
                dead += p * sa
        elif d > 0:
            add += p * d
            if t > 0.0:
                refill += p * d
    return {"vis": vis, "eat": eat, "cancel": cancel, "add": add,
            "dead": dead, "refill": refill}


def _monotone(levels):
    """Направление лесенки: 1 — по возрастанию, −1 — по убыванию, 0 — не
    монотонна.

    Проверяется по краям, то есть за одно сравнение: этого хватает, чтобы
    решить, годится ли слияние, и не хватает, чтобы прозевать
    перемешанную лесенку молча — при 0 считает образцовый путь. Молчаливый
    ноль здесь был бы худшим исходом: непересёкшиеся цены выглядят как
    «уровни ушли за край», то есть мера обнулилась бы, не сломавшись.
    """
    if len(levels) < 2:
        return 1
    return 1 if levels[0][0] < levels[-1][0] else -1


def side_flows(prev, cur, traded):
    """Потоки одной стороны между двумя снимками.

    `prev`, `cur` — списки `[цена, размер]`; `traded` — словарь
    «цена → объём сделок на ней за интервал». Возвращает нотионалы:
    видимое, съеденное, снятое, добавленное, умершее, подставленное.

    Считается ТОЛЬКО по пересечению видимых цен: цена, которой в одном
    из снимков не видно, могла уйти за край лесенки, а не быть снятой.

    Лесенка приходит отсортированной (биды по убыванию, аски по
    возрастанию), поэтому пересечение берётся СЛИЯНИЕМ, без хеширования:
    замер дал 10.0 мкс против 32.2 у словарей, а на проходе по всей
    записи это часы. Порядок проверяется по краям, и при непонятном
    порядке считает образцовый путь.
    """
    if not prev or not cur:
        return {"vis": 0.0, "eat": 0.0, "cancel": 0.0, "add": 0.0,
                "dead": 0.0, "refill": 0.0}
    da, db = _monotone(prev), _monotone(cur)
    if da != db or da == 0:
        return side_flows_slow(prev, cur, traded)
    i = j = 0
    n, m = len(prev), len(cur)
    vis = eat = cancel = add = dead = refill = 0.0
    while i < n and j < m:
        pa, sa = prev[i]
        pb, sb = cur[j]
        if pa == pb:
            d = sb - sa
            vis += pa * sa
            t = traded.get(pa, 0.0) if traded else 0.0
            if d < 0:
                gone = -d
                e = t if t < gone else gone
                eat += pa * e
                cancel += pa * (gone - e)
                if sb == 0.0 and t == 0.0:
                    dead += pa * sa
            elif d > 0:
                add += pa * d
                if t > 0.0:
                    refill += pa * d
            i += 1
            j += 1
        elif (pa < pb) == (da > 0):
            i += 1
        else:
            j += 1
    return {"vis": vis, "eat": eat, "cancel": cancel, "add": add,
            "dead": dead, "refill": refill}


def pair_flows(prev, cur, trades):
    """Потоки обеих сторон плюс ход середины между двумя снимками.

    `trades` — список `(цена, сторона, объём)`, сторона `+1` — агрессор
    покупал (ест аски), `-1` — продавал (ест биды). Пара с разрывом
    больше `MAX_DT` наблюдением не является и даёт `None`: пропуск, а
    не ноль.
    """
    dt = cur["t"] - prev["t"]
    if not (0 < dt <= MAX_DT):
        return None
    tb, ta = {}, {}
    for px, side, sz in trades:
        d = ta if side > 0 else tb
        d[float(px)] = d.get(float(px), 0.0) + float(sz)
    fb = side_flows(prev["b"], cur["b"], tb)
    fa = side_flows(prev["a"], cur["a"], ta)
    m0 = (prev["bid"] + prev["ask"]) / 2.0
    m1 = (cur["bid"] + cur["ask"]) / 2.0
    move_bp = abs(m1 - m0) / m0 * 1e4 if m0 > 0 else 0.0
    return {"b": fb, "a": fa, "move_bp": move_bp}


def minute_accum():
    """Пустой накопитель минуты. Ноль пар означает ПРОПУСК."""
    return {k: 0.0 for k in FIELDS}


def add_pair(acc, fl):
    """Добавить пару снимков в накопитель минуты."""
    if fl is None:
        return acc
    for side, key in (("b", "_b"), ("a", "_a")):
        f = fl[side]
        acc["vis" + key] += f["vis"]
        acc["eat" + key] += f["eat"]
        acc["cancel" + key] += f["cancel"]
        acc["add" + key] += f["add"]
        acc["dead" + key] += f["dead"]
        acc["refill" + key] += f["refill"]
    acc["sweep"] += fl["b"]["eat"] + fl["a"]["eat"]
    acc["_move"] = acc.get("_move", 0.0) + fl["move_bp"]
    acc["pairs"] += 1
    return acc


def close_minute(acc):
    """Итог минуты: пропуск, если пар меньше `MIN_PAIRS`.

    Минута, собранная из трёх снимков вместо шестидесяти, описывает не
    ту же величину, и засчитать её наблюдением значило бы разбавить
    выборку. Урок склада Z2: порог тонкой минуты — порог ЗАМЕРА.
    """
    if acc["pairs"] < MIN_PAIRS:
        return None
    out = {k: acc[k] for k in FIELDS}
    mv = acc.get("_move", 0.0)
    out["sweep"] = acc["sweep"] / mv if mv > 0 else float("nan")
    return out
