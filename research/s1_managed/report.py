#!/usr/bin/env python3
"""
S1 — отчёт по артефакту прогона. Зависимостей не имеет намеренно.

    python3 report.py --interval 1m > out/S1-report-1m.md
"""

import argparse
import json
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")
ARMS = (("base", "равные веса, без выходов"),
        ("sized", "правило 1: обратная волатильность"),
        ("managed", "правила 1 и 2 вместе"))


def bp(x, d=1):
    return "—" if x is None else f"{x * 10000:.{d}f}"


def pct(x, d=1):
    return "—" if x is None else f"{x * 100:.{d}f} %"


def f(x, d=2):
    return "—" if x is None else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--interval", default="1m")
    ap.add_argument("--funding-venue", default="bybit")
    a = ap.parse_args()
    path = os.path.join(OUT, f"s1_{a.interval}_{a.funding_venue}.json")
    if not os.path.exists(path):
        raise SystemExit(f"нет {path} — сначала run.py")
    with open(path, encoding="utf-8") as fh:
        d = json.load(fh)
    cfg, grid, cells = d["config"], d["grid"], d["cells"]
    p = print
    n = grid["cells"]

    p("# S1 — книга carry с управлением риском\n")
    p("**Спека:** 05, этап S1, критерий немедленной остановки §8.1  ")
    p(f"**Разрешение хранилища:** {cfg['interval']}, ставки "
      f"{cfg['funding_venue']}  ")
    p(f"**Сечений:** {cfg['sections']}, ячеек {n}, объявленных испытаний "
      f"{cfg['declared_trials']}  ")
    p(f"**Уровень выхода:** {cfg['declared_stop']} по горизонту, объявлен "
      f"до прогона\n")
    if cfg["funding_venue"] != "bybit":
        p("> **Ставки взяты НЕ с площадки исполнения** — проверка "
          "конвейера, не вердикт.\n")

    p("## Три руки и зачем их три\n")
    p("- **base** — равные веса, без выходов. Та же книга, что в F1, но на "
      "универсуме, где волатильность измерима: без этой руки эффект "
      "сужения универсума приписался бы правилам;\n"
      "- **sized** — правило 1 в одиночку;\n"
      "- **managed** — правила 1 и 2 вместе. **Вердикт выносится по ней.**\n")
    p("Разложение по правилам — диагностика. Выбрать по нему лучшую руку "
      "значило бы превратить одно объявленное семейство испытаний в три.\n")

    p("## Итог по сетке\n")
    p("| Рука | Брутто, б.п. | Просадка, медиана | Худшая просадка |")
    p("|---|---|---|---|")
    for arm, title in ARMS:
        g = grid[arm]
        p(f"| {title} | {bp(g['gross_median'])} "
          f"| {pct(g['drawdown_median'])} | {pct(g['drawdown_worst'])} |")
    p("")
    p(f"Просадка улучшилась в **{grid['drawdown_improved']} ячейках из "
      f"{n}**, брутто упало в **{grid['gross_worse']}**.\n")

    p("## По ячейкам\n")
    p("| Ячейка | Брутто base | Брутто managed | Просадка base "
      "| Просадка managed | Доля + | Хвост | Худшая нога |")
    p("|---|---|---|---|---|---|---|---|")
    for name in sorted(cells):
        c = cells[name]
        b, m = c["base"], c["managed"]
        p(f"| {name} | {bp(b['gross'])} | **{bp(m['gross'])}** "
          f"| {pct(b['drawdown'])} | **{pct(m['drawdown'])}** "
          f"| {f(m['positive_share'])} | {f(m['tail_ratio'], 1)} "
          f"| {pct(m['worst_leg'], 0)} |")
    p("")

    p("## Что делают выходы\n")
    p("| Ячейка | Уровень | Доля гросса, вышедшая | Перекос без пары "
      "| Доп. оборот |")
    p("|---|---|---|---|---|")
    for name in sorted(cells):
        c = cells[name]
        p(f"| {name} | {pct(-c['stop_level'], 0)} "
          f"| {f(c['exit_share'], 3)} | {f(c['unpaired'], 3)} "
          f"| {f(c['exit_turnover'], 3)} |")
    p("")
    p("«Перекос без пары» — §5.3 спеки: выбив ногу, книга перестаёт быть "
      "равной по деньгам с обеих сторон, и освободившиеся деньги НЕ "
      "перераспределяются. Доп. оборот идёт в издержки на этапе S4.\n")

    p("## Критерий 13 — исполнимость\n")
    p("> Ни одна нога не теряет больше 100 % позиции.\n")
    blown = grid["cells_with_blown_leg"]
    p(f"Ячеек, где нога всё же теряет больше 100 %: **{blown} из {n}**.\n")
    if blown:
        p("**Это не сбой стопа, а его предел.** Выход исполняется по "
          "закрытию бара, на котором уровень пробит; если цена прошла "
          "уровень разрывом внутри одного часа, закрытие уже хуже уровня. "
          "Ровно так ведёт себя сквиз, ради защиты от которого стоп и "
          "ставится, — и это тот самый довод §3.2 спеки, что стоп "
          "наименее надёжен там, где создаётся весь хвост.\n")

    p("## Критерий немедленной остановки §8.1\n")
    p("| Условие | Порог | Получено | |")
    p("|---|---|---|---|")
    worse_gross = grid["gross_median_worse"] = (
        grid["managed"]["gross_median"] < grid["base"]["gross_median"])
    dd_ok = grid["drawdown_improved"] > n / 2
    p(f"| Медиана брутто после правил против книги без них | не ниже "
      f"| {bp(grid['managed']['gross_median'])} против "
      f"{bp(grid['base']['gross_median'])} "
      f"| {'✗ СРАБОТАЛ' if worse_gross else '✓'} |")
    p(f"| Просадка улучшилась в большинстве ячеек | > {n // 2} "
      f"| {grid['drawdown_improved']} "
      f"| {'✓' if dd_ok else '✗ СРАБОТАЛ'} |")
    p("| Просадка против нуля 4 (случайные выходы) | лучше в большинстве "
      "| считается на S3 | — |")
    p("")

    p("## Вердикт\n")
    if worse_gross or not dd_ok:
        p("**Критерий немедленной остановки §8.1 сработал.** Гипотеза "
          "закрывается до бэктеста; по §8.3 спеки права на итерацию "
          "нет.\n")
        p("Читать это следует буквально: правила не улучшили того, ради "
          "чего вводились. Если брутто упало, а просадка не улучшилась, "
          "то управление риском здесь не управляет риском, а просто "
          "сокращает экспозицию — того же можно добиться меньшим плечом, "
          "без всякой конструкции.\n")
    else:
        p("Критерий немедленной остановки не сработал. Переход к **S2** — "
          "ловушки §5: перекос после выходов, оборот ног, критерий 13, "
          "оценка сверху по делистингу.\n")


if __name__ == "__main__":
    main()
