#!/usr/bin/env python3
"""
S1 — книга carry с управлением риском. Ядро расчёта.

Спека 05, раздел 3. Здесь только арифметика: веса по обратной
волатильности, применение выходов, разложение PnL. Ни диска, ни базы.

Порядок правил обратный интуитивному, и это результат замера, а не вкус
-----------------------------------------------------------------------

Хвост книги carry — шорт-сквизы: 35 ног из 35, теряющих больше 100 %
позиции, оказались короткими, на 25 активах и 30 датах. В сквизе цена
идёт разрывом, ликвидность на нашей стороне исчезает, и заявка
исполняется не на уровне, а много хуже. То есть **стоп наименее
надёжен ровно там, где создаётся весь хвост**.

Поэтому первым идёт размер позиции (правило 1), вторым — выход
(правило 2). Размер работает на разрывах, выход нет.
"""

import numpy as np


VOL_FLOOR_PCT = 10          # пол волатильности, процентиль сечения


def floored_vol(vol, ok, pct=VOL_FLOOR_PCT):
    """Волатильность с полом по процентилю сечения.

    Без пола правило 1 вырождается в ловушку замороженных рядов, и это
    не рассуждение, а замер: медиана σ часовых доходностей равна 0.008,
    а 0.1-й процентиль — 0.000057, то есть в 140 раз меньше. Вес обратен
    σ, поэтому такой актив забирал **до 92.7 % своей половины книги**
    (медиана доли одного имени 17.2 % против 5.6 % при равных весах).
    Смоук поймал это обвалом брутто с +40.7 до +0.3 б.п.

    Пол берётся из САМОГО сечения, а не константой: волатильность
    универсума меняется с режимом рынка, и фиксированное число
    связывало бы то слишком сильно, то никак. Верхний хвост не
    подрезается намеренно — подавлять волатильные имена и есть смысл
    правила.
    """
    if not ok.any():
        return vol
    floor = float(np.percentile(vol[ok], pct))
    return np.maximum(vol, floor)


def inverse_vol_weights(score, vol, width, min_vol=1e-6):
    """Веса книги: ноги по рангу оценки, доли внутри ноги ∝ 1/σ.

    Ноги остаются равными **по деньгам** — половина гросса на каждую, —
    меняется распределение внутри ноги. Смысл: актив, который ходит в
    разы, получает меньшую долю ещё до того, как что-либо произошло.

    Свободного параметра здесь нет вовсе: множитель не подбирается,
    правило либо применено, либо нет.

    Актив без измеримой волатильности в книгу не входит. Это не
    придирка: у замороженного ряда (A2) волатильность равна нулю, и
    обратная величина дала бы ему бесконечный вес — дефект данных стал
    бы всей книгой.
    """
    ok = np.isfinite(score) & np.isfinite(vol) & (vol > min_vol)
    w = np.zeros(len(score))
    n = int(ok.sum())
    k = int(n * width)
    if k < 1:
        return w, 0
    orig = np.flatnonzero(ok)
    idx = np.argsort(score[ok], kind="mergesort")
    v = floored_vol(vol, ok)
    for side, sel in ((+1, idx[-k:]), (-1, idx[:k])):
        pos = orig[sel]
        inv = 1.0 / v[pos]
        w[pos] = side * 0.5 * inv / inv.sum()
    return w, k


def equal_weights(score, vol, width, min_vol=1e-6):
    """Равные веса на том же универсуме — контрольная рука.

    Нужна по той же причине, по которой R4 строил `resid_r`: правило 1
    выбрасывает активы без измеримой волатильности, и сравнив книгу с
    правилом против книги на ПОЛНОМ универсуме, мы приписали бы правилу
    эффект сужения. Здесь универсум тот же, отличается только
    распределение весов внутри ноги.
    """
    ok = np.isfinite(score) & np.isfinite(vol) & (vol > min_vol)
    w = np.zeros(len(score))
    n = int(ok.sum())
    k = int(n * width)
    if k < 1:
        return w, 0
    orig = np.flatnonzero(ok)
    idx = np.argsort(score[ok], kind="mergesort")
    w[orig[idx[-k:]]] = +0.5 / k
    w[orig[idx[:k]]] = -0.5 / k
    return w, k


def apply_exits(w, pos_ret, exit_ret, exit_frac, fund):
    """Доходность каждой ноги с учётом выхода по уровню.

    `pos_ret` — доходность позиции за полный период (уже в единицах
    позиции, знак учтён). `exit_ret` — доходность в момент первого
    пробоя уровня либо NaN, если уровень не пробит. `exit_frac` — какая
    доля периода пройдена к моменту выхода.

    **Начисления прорезаются пропорционально времени в позиции.**
    Выбитая нога перестаёт их получать, и оставлять их целиком значило
    бы дарить книге доход, которого не было; в замере потолка F2 такая
    поблажка делалась намеренно, здесь она недопустима.

    Возвращает `(доходность_ноги, признак_выхода)`.
    """
    hit = np.isfinite(exit_ret)
    ret = np.where(hit, exit_ret, pos_ret)
    frac = np.where(hit, exit_frac, 1.0)
    # Знак начислений противоположен знаку веса: положительная ставка
    # означает, что лонги платят.
    accr = -np.sign(w) * fund * frac
    return ret + accr, hit


def book_pnl(w, leg_ret):
    """PnL книги и по ногам из доходностей позиций."""
    contrib = np.abs(w) * leg_ret
    lo, sh = w > 0, w < 0
    return {
        "gross": float(contrib.sum()),
        "long": float(contrib[lo].sum()),
        "short": float(contrib[sh].sum()),
        "worst_leg": (float(leg_ret[w != 0].min())
                      if np.any(w != 0) else None),
        "legs": int((w != 0).sum()),
    }


def unpaired_share(w, hit):
    """Доля гросса, оставшаяся без пары после выходов. §5.3 спеки.

    Выбив ногу, книга перестаёт быть равной по деньгам с обеих сторон.
    Освободившиеся деньги НЕ перераспределяются: доливка пошла бы в
    позиции, которые в этот момент, скорее всего, тоже под давлением.
    Возникающий перекос надо мерить, а не прятать.
    """
    live = (w != 0) & ~hit
    lo = float(np.abs(w[live & (w > 0)]).sum())
    sh = float(np.abs(w[live & (w < 0)]).sum())
    tot = lo + sh
    return abs(lo - sh) / tot if tot > 0 else 0.0


def turnover_from_exits(w, hit):
    """Дополнительный оборот от сработавших выходов, в долях гросса.

    Выход — это внеплановое закрытие позиции: комиссия за него платится
    сверх плановой перекладки. Умножать на два не нужно — открытие уже
    оплачено при ребалансе, а повторный вход произойдёт на следующем и
    будет учтён там.
    """
    return float(np.abs(w[hit]).sum())
