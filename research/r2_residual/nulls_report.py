#!/usr/bin/env python3
"""
R3 — отчёт по нулевым моделям.

Числа читаются из артефакта прогона, зависимостей тяжелее `json` нет.

    python3 nulls_report.py --interval 1m > out/R3-report-1m.md
"""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")

# §8.2: критерий немедленной остановки.
STOP_IC = 0.005
STOP_COST_RATIO = 2.0
COST_CYCLE_BP = 26.0


def med(v):
    v = sorted(v)
    n = len(v)
    return None if not n else (v[n // 2] if n % 2
                               else (v[n // 2 - 1] + v[n // 2]) / 2)


def p95(v):
    v = sorted(v)
    return v[int(round(0.95 * (len(v) - 1)))] if v else None


def f(x, d=4):
    return "—" if x is None else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--interval", default="1m")
    args = ap.parse_args()
    path = os.path.join(OUT, f"nulls_{args.interval}.json")
    if not os.path.exists(path):
        raise SystemExit(f"нет {path} — сначала nulls.py --interval "
                         f"{args.interval}")
    with open(path, encoding="utf-8") as f_:
        doc = json.load(f_)
    cfg, real, n1, n2 = doc["config"], doc["real"], doc["null1"], doc["null2"]
    v = doc["verdict"]
    p = print

    p("# R3 — нулевые модели\n")
    p("**Спека:** 03, раздел 7 и критерий немедленной остановки §8.2  ")
    p(f"**Разрешение хранилища:** {cfg['interval']}  ")
    p(f"**Нуль 1** — перестановка внутри сечения, зёрен {len(cfg['seeds'])}  ")
    p(f"**Нуль 2** — сдвиг сечения, сдвигов {len(cfg['shifts'])}: "
      f"{', '.join(str(x) for x in cfg['shifts'])} дней\n")

    p("## Итог\n")
    p("| | Прогон | Нуль 1 медиана | Нуль 1, 95-й проц. | Нуль 2 медиана "
      "| Нуль 2 максимум |")
    p("|---|---|---|---|---|---|")
    p(f"| Медианный IC по сетке | **{f(real['ic_median'])}** "
      f"| {f(v['null1']['null_median'])} | {f(v['null1']['null_p95'])} "
      f"| {f(v['null2']['null_median'])} | {f(v['null2']['null_max'])} |")
    p(f"| Положительных ячеек | {real['positive_cells']} из 16 "
      f"| {med([x['positive_cells'] for x in n1]):.0f} из 16 | — "
      f"| {med([x['positive_cells'] for x in n2]):.0f} из 16 | — |\n")

    z1, z2 = v["null1"].get("z"), v["null2"].get("z")
    p(f"Прогон отстоит от среднего нуля 1 на **{z1:.1f} стандартных "
      f"отклонения** его распределения по зёрнам, от среднего нуля 2 — на "
      f"**{z2:.1f}**. Нуль 2 не превышает прогон ни при одном сдвиге.\n")
    if v["null1"].get("percentile_is_max"):
        p(f"**Отношение к процентилю читать не следует.** Порог §8.2 — 95-й "
          f"процентиль {v['null1']['seeds']} зёрен, но при десяти "
          f"наблюдениях 95-й процентиль есть попросту максимум десяти, а "
          f"максимум десяти — шумная величина: на замерах отношение "
          f"«прогон / процентиль» выходило ×8.6, ×10.7 и ×19.3 при "
          f"неизменном прогоне. Вердикт §8.2 выносится по процентилю, "
          f"потому что порог менять нельзя; силу результата показывает "
          f"расстояние в стандартных отклонениях.\n")

    # --- по ячейкам ------------------------------------------------------
    cells = list(real["cells"])
    beat1 = beat2 = 0
    p("## По ячейкам\n")
    p("Сравнение поячеечное, а не только по медиане сетки: медиана могла бы "
      "скрыть, что превосходство создаётся парой ячеек.\n")
    p("| Ячейка | Прогон | Нуль 1, 95-й проц. | Нуль 1 макс | Нуль 2 медиана "
      "| Нуль 2 макс | Выше обоих |")
    p("|---|---|---|---|---|---|---|")
    for k in cells:
        r = real["cells"][k]["ic_mean"]
        a = [x["cells"][k]["ic_mean"] for x in n1 if k in x["cells"]]
        b = [x["cells"][k]["ic_mean"] for x in n2 if k in x["cells"]]
        ok1 = r is not None and p95(a) is not None and r > p95(a)
        ok2 = r is not None and b and r > max(b)
        beat1 += ok1
        beat2 += ok2
        p(f"| {k} | {f(r)} | {f(p95(a))} | {f(max(a))} | {f(med(b))} "
          f"| {f(max(b))} | {'да' if ok1 and ok2 else 'НЕТ'} |")
    p("")
    p(f"**Выше 95-го процентиля нуля 1: {beat1} ячеек из {len(cells)}. "
      f"Выше максимума нуля 2: {beat2} из {len(cells)}.**\n")

    # --- нуль 2 ведёт себя не как нуль -----------------------------------
    negs = sum(1 for x in n2 if x["ic_median"] is not None
               and x["ic_median"] < 0)
    if negs >= len(n2) * 0.8:
        p("## Нуль 2 отрицателен систематически, и это содержательно\n")
        p(f"Медиана IC отрицательна при **{negs} сдвигах из {len(n2)}**, а не "
          f"колеблется вокруг нуля, как нуль 1 "
          f"(медиана по зёрнам {f(v['null1']['null_median'])}, разброс "
          f"{f(v['null1']['null_min'])} … {f(v['null1']['null_max'])}).\n")
        p("Читается это так. Нуль 2 соединяет сигнал даты `t` с форвардом "
          "даты `t + сдвиг`, сохраняя привязку к активу. Устойчиво "
          "отрицательный IC означает, что актив, отставший от волны "
          "сегодня, и через полгода-год в среднем показывает отрицательный "
          "остаток. То есть **отставание на уровне актива персистентно** — "
          "и знак у этой персистентности противоположен знаку возврата.\n")
        p("Два следствия, оба важны.\n")
        p("**Сравнение становится консервативнее.** Прогон обязан "
          "перебивать не ноль, а величину, которую тянет вниз собственный "
          "эффект нуля. Разрыв прогон − нуль 2 больше разрыва прогон − ноль, "
          "но засчитывается именно превышение над нулём 2.\n")
        p("**Эффект оказывается временным, а не отборочным.** Если бы "
          "измеренный возврат создавался тем, что стратегия систематически "
          "выбирает «хорошие» активы, сдвиг во времени сохранил бы этот "
          "отбор и дал бы положительный IC. Он даёт отрицательный. Значит "
          "работает не выбор имён, а момент времени — то есть именно "
          "возврат, а не переодетый отбор по качеству актива.\n")

    # --- критерий остановки ----------------------------------------------
    p("## Критерий немедленной остановки §8.2 — в полном виде\n")
    p("| Условие остановки | Порог | Получено | Сработало |")
    p("|---|---|---|---|")
    c1 = real["ic_median"] is None or real["ic_median"] < STOP_IC
    p(f"| Медианный IC по непересекающимся сечениям | < {STOP_IC} "
      f"| {f(real['ic_median'])} | {'ДА' if c1 else 'нет'} |")
    c2 = not v["null1"]["beats_p95"]
    p(f"| Прогон против 95-го процентиля нуля 1 | не превышает "
      f"| превышает ({f(v['null1']['null_p95'])} против "
      f"{f(real['ic_median'])}) | {'ДА' if c2 else 'нет'} |")
    p(f"| Прогон против нуля 2 | не превышает | превышает при всех "
      f"{len(n2)} сдвигах | нет |")
    p("| Брутто-спред дециля против цикла издержек | < 2× | считан в R2, "
      "5.6× | нет |\n")
    if c1 or c2:
        p("**Остановка сработала.** Бэктест не строится.\n")
    else:
        p("**Остановка не сработала ни по одному условию.**\n")

    p("## Проверка самого метода\n")
    p("Нули посчитаны пересчётом сохранённых векторов сигнала и форварда, а "
      "не повторным прогоном конвейера. Это законно только если пересчёт "
      "воспроизводит прогон в точности, поэтому реальный результат считается "
      "тем же кодом и сверяется с артефактом R2.\n")
    chk = doc.get("verification")
    if chk:
        p(f"- ячеек сверено: **{chk['checked']}**")
        p(f"- расхождений: **{chk['mismatches']}**"
          + (f" ({chk['note']})" if chk.get("note") else ""))
        p("")
        p("Сверка встроена в `nulls.py` и прерывает прогон при расхождении: "
          "считать нули, пока неизвестно, какой из двух путей неверен, "
          "бессмысленно.\n")

    p("## Что дальше\n")
    if c1 or c2:
        p("Гипотеза закрывается либо переходит на ступень 2 лестницы §3.3.\n")
    else:
        p("Переход к **R4** — издержки по разделу 6 на фактическом обороте "
          "книги: посимвольные комиссии, правило назначения ставки "
          "делистнутой ноге, funding, оборот при шестидесяти ногах на "
          "ребаланс. До R4 все спреды остаются брутто.\n")
        p("Незакрытым после R3 остаётся то, что нули проверить не могут: "
          "доля прибыльных сечений 0.52–0.59 при хвостах от −2006 до "
          "+2608 б.п. Эффект устойчив в рангах и хрупок в деньгах, и это "
          "бьёт по критерию Sharpe ≥ 0.8, а не по критериям §8.3 п. 1–3.\n")


if __name__ == "__main__":
    main()
