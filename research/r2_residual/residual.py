#!/usr/bin/env python3
"""
R2 — возврат остатка. Ядро расчёта.

Спека 03, разделы 4 и 8.3. Здесь только арифметика сечения: сигнал,
форвардная доходность, ранговая корреляция, спред корзины. Ни диска, ни
базы — чтобы проверялось тестами с известным ответом.

Что именно измеряется
---------------------

На каждую дату ребаланса `t`:

    сигнал_i    = − Σ остаток_i по барам за последние k дней до t
    форвард_i   =   Σ остаток_i по барам за [t, t+h)
    IC          = ранговая корреляция(сигнал, форвард) по сечению

Знак сигнала перевёрнут намеренно: **положительный сигнал означает
«отстал от волны», то есть ожидание роста.** Тогда работающий возврат
даёт положительный IC, и во всех отчётах «больше — лучше». Без этого
соглашения знак пришлось бы держать в голове при каждом чтении таблицы.

Остаток накапливается **по барам, а не по концам периода**:

    остаток_i(бар) = r_i(бар) − β_i · F_i(бар)

Сумма берётся только по тем барам, где у актива есть доходность. Это
важнее, чем кажется: если актив перестал торговаться на середине
форвардного окна, разность цен «конец минус начало» приписала бы ему
движение волны за всё окно, хотя половину этого времени его цена не
существовала. Побарная сумма исключает волну ровно за те бары, что
актив прожил.

Чего здесь намеренно нет
------------------------

Издержек. §8.2 требует сравнить брутто-спред дециля с циклом издержек,
но сам расчёт издержек — предмет R4. Здесь считается брутто, и это
записано в отчёте явно, чтобы брутто нельзя было прочитать как нетто.
"""

import numpy as np


def accumulate(R, F, beta, i0, i1):
    """Сумма остатков по барам `[i0, i1)` для каждого актива.

    Возвращает `(остаток, число_баров)`. Актив без единого бара получает
    NaN, а не ноль: ноль означал бы «не отклонился», то есть наблюдение,
    которого не было. Это тот же класс ошибки, что замороженный ряд из
    §5.1 спеки — молчание, выданное за данные.
    """
    r = R[i0:i1]
    f = F[i0:i1]
    e = r - beta[None, :] * f
    m = ~np.isnan(e)
    n = m.sum(axis=0)
    s = np.where(m, e, 0.0).sum(axis=0)
    out = np.where(n > 0, s, np.nan)
    return out, n


def ranks(x):
    """Средние ранги с корректной обработкой связок.

    Связки обрабатываются средним рангом, а не порядком появления. В A1
    небрежность со связками стоила ложного вывода: пары с побитово
    одинаковым funding шли в знаменатель как согласие, и плацебо на
    перемешанных метках давало 0.520 вместо 0.500 — читалось бы как
    слабая, но связь.
    """
    n = len(x)
    order = np.argsort(x, kind="mergesort")
    r = np.empty(n, dtype=np.float64)
    r[order] = np.arange(n, dtype=np.float64)
    xs = x[order]
    i = 0
    while i < n:
        j = i + 1
        while j < n and xs[j] == xs[i]:
            j += 1
        if j - i > 1:
            r[order[i:j]] = (i + j - 1) / 2.0
        i = j
    return r


def spearman(a, b):
    """Ранговая корреляция сечения по общим наблюдениям."""
    m = ~(np.isnan(a) | np.isnan(b))
    n = int(m.sum())
    if n < 3:
        return None, n
    ra, rb = ranks(a[m]), ranks(b[m])
    ra -= ra.mean()
    rb -= rb.mean()
    da, db = float(ra @ ra), float(rb @ rb)
    if da <= 0 or db <= 0:
        return None, n
    return float(ra @ rb) / np.sqrt(da * db), n


def basket_spread(score, fwd, width):
    """Спред длинно-короткой корзины: верхняя доля минус нижняя.

    `width` — доля универсума в каждой ноге (0.1 — дециль). Деньги с
    обеих сторон равны, поэтому спред есть разность средних, а не
    взвешенная сумма.

    Индексы ног возвращаются **в исходной нумерации активов**, а не в
    нумерации отфильтрованного массива. Разница незаметна, пока их не
    начнут использовать: диагностика состава §5.2 сопоставляет индекс с
    именем актива, и сдвиг нумерации назвал бы в дециле совсем другие
    инструменты, ничем себя не выдав.
    """
    m = ~(np.isnan(score) | np.isnan(fwd))
    n = int(m.sum())
    k = int(n * width)
    if k < 1:
        return None
    orig = np.flatnonzero(m)
    s, f = score[m], fwd[m]
    idx = np.argsort(s, kind="mergesort")
    lo, hi = idx[:k], idx[-k:]
    return {"spread": float(f[hi].mean() - f[lo].mean()),
            "long": float(f[hi].mean()), "short": float(f[lo].mean()),
            "n": n, "per_leg": k,
            "long_idx": orig[hi].tolist(), "short_idx": orig[lo].tolist()}


def tstat(vals):
    """t-статистика среднего. Возвращает (среднее, t, n)."""
    v = np.asarray([x for x in vals if x is not None and x == x],
                   dtype=np.float64)
    n = len(v)
    if n < 2:
        return (float(v.mean()) if n else None), None, n
    sd = float(v.std(ddof=1))
    mean = float(v.mean())
    if sd <= 0:
        return mean, None, n
    return mean, mean / (sd / np.sqrt(n)), n


def quantiles(vals, ps=(0.05, 0.25, 0.5, 0.75, 0.95)):
    v = sorted(float(x) for x in vals if x is not None and x == x)
    if not v:
        return {}
    return {str(p): v[int(p * (len(v) - 1))] for p in ps}


def window_bounds(i_form, i_t, n_returns, k, h, bars_per_day):
    """Границы трёх окон в индексах ряда доходностей.

    Вынесено отдельной функцией ради теста: ошибка на один бар здесь
    ничем себя не выдаёт. Сигнал и форвард в любом случае не
    пересекаются, поэтому проверка «нет общих баров» дефект НЕ ловит.
    Ловит его только явное требование, что форвард начинается ровно с
    `i_t`: бар `i_t − 1` есть доходность периода, ЗАКОНЧИВШЕГОСЯ в
    момент ребаланса, то есть уже известного. Включив его в форвард,
    стенд зарабатывал бы на прошлом и показал бы отскок после падения
    как эдж.

    Возвращает `(формирование, сигнал, форвард)`, полуинтервалы.
    """
    form = (i_form, i_t)
    sig = (max(i_form, i_t - k * bars_per_day), i_t)
    fwd = (i_t, min(n_returns, i_t + h * bars_per_day))
    return form, sig, fwd
