#!/usr/bin/env python3
"""Формирует отчёт A2 о гигиене данных в markdown из hygiene_*.json."""

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")


def a1_duplicates(interval):
    """Сколько дублей насчитала инвентаризация A1 по сырым архивам."""
    path = os.path.join(os.path.dirname(HERE), "a1_universe", "out",
                        f"klines_inventory_{interval}.json")
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        assets = json.load(f)["assets"]
    return sum(v.get("duplicate_bars", 0) for v in assets.values())


def q(vals, p):
    s = sorted(v for v in vals if v is not None)
    return s[min(len(s) - 1, int(p * (len(s) - 1)))] if s else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--interval", default="15m")
    args = ap.parse_args()

    with open(os.path.join(OUT, f"hygiene_{args.interval}.json"),
              encoding="utf-8") as f:
        d = json.load(f)
    with open(os.path.join(OUT, f"build_{args.interval}.json"),
              encoding="utf-8") as f:
        b = json.load(f)

    S, m = d["symbols"], d["meta"]
    lines, add = [], None
    lines = []
    add = lines.append

    add("# Отчёт A2 — гигиена данных\n")
    add("Сгенерирован `research/a2_storage/report.py`.")
    add("Спецификация 02, раздел 2.4. Без этого отчёта последующие числа не")
    add("подлежат интерпретации — поэтому он предшествует любому отбору.\n")
    add(f"Таймфрейм **{m['interval']}**, срез универсума {m['universe_as_of']}.\n")
    add("---\n")

    # 1
    add("## 1. Хранилище\n")
    add("| | |")
    add("|---|---:|")
    add(f"| Символов | {m['symbols']} |")
    add("| Баров | " + f"{m['bars']:,}".replace(",", " ") + " |")
    add(f"| Партиций (месяцев) | {b['months']} |")
    add(f"| Объём Parquet | {b['bytes']/1024**3:.2f} ГБ |")
    unknown = b.get("duplicates_unknown_months", 0)
    add(f"| Снято дублей при сборке | {b['duplicates']}"
        + (f" (+ {unknown} партиций без записи)" if unknown else "") + " |")
    add("")
    add("Партиция — календарный месяц со всеми символами внутри, каждый")
    add("символ отдельной row group. Кросс-секционный запрос «весь универсум")
    add("на дату» читается одним проходом: именно этого не умела схема v1 с")
    add("таблицей на инструмент, где такой запрос превращался в джойн на")
    add("250 таблиц.\n")
    add(f"Дубли ({b['duplicates']}) — пересечение месячных архивов с суточными,")
    add("которыми на этапе A1 дозакрывались обрывы месячных файлов Binance.")
    add("Снимаются по ключу `(symbol, open_time)`.\n")
    if unknown:
        add(f"**Число дублей неполно:** у {unknown} партиций из {b['months']}")
        add("оно не записано (собраны ранним кодом). Дочитывается прогоном")
        add("`build.py --restat`, партиции при этом не переписываются.\n")
    # Сверка с A1 делается здесь, а не утверждается текстом: инвентаризация
    # считает дубли по сырым архивам, сборка — по факту снятия, и совпадение
    # двух независимых путей есть содержательная проверка. Разойдись они —
    # это увидит отчёт, а не читатель.
    a1 = a1_duplicates(m["interval"])
    if a1 is not None and not unknown:
        if a1 == b["duplicates"]:
            add(f"Инвентаризация A1 по сырым архивам даёт то же число ({a1}),")
            add("посчитанное независимым путём, — как и общее число баров.\n")
        else:
            add(f"**Расхождение с A1:** инвентаризация сырых архивов даёт {a1},")
            add(f"сборка сняла {b['duplicates']}. Одно из двух измерений")
            add("неверно, числа ниже интерпретации не подлежат.\n")

    # 2
    miss = sum(v["missing"] for v in S.values())
    exp = sum(v["expected"] for v in S.values())
    holed = [s for s, v in S.items() if v["missing"] > 0]
    add("## 2. Пропуски баров\n")
    add(f"Пропущено **{miss}** баров из " + f"{exp:,}".replace(",", " ")
        + f" ожидаемых ({100*miss/exp:.4f} %), у {len(holed)} символов.\n")
    add("Ожидание считается по наблюдаемому диапазону каждого символа, а не")
    add("по календарю: месяц листинга и месяц делистинга неполны по")
    add("построению. Пропуски не заполняются интерполяцией — остановка")
    add("торгов реальное событие, на котором срабатывает стоп.\n")
    if holed:
        if len(holed) > 8:
            add(f"Восемь крупнейших из {len(holed)}:\n")
        add("| Символ | Пропущено | Доля |")
        add("|---|---:|---:|")
        for s in sorted(holed, key=lambda x: -S[x]["missing"])[:8]:
            add(f"| {s} | {S[s]['missing']} | {S[s]['missing_pct']:.3f} % |")
        add("")

    # 3 — главное
    frozen = d.get("frozen_tails", [])
    add("## 3. Замороженные ряды — главная находка этапа\n")
    add("Архив Binance не прекращает публиковать бары после того, как")
    add("инструмент там перестал торговаться. Бар выходит каждые")
    add(f"{m['interval']} с перенесённой ценой, годами.\n")
    if frozen:
        total = sum(f["frozen_days"] for f in frozen)
        add(f"**{len(frozen)} символов из {m['symbols']}** имеют такой хвост")
        add("длиной не меньше недели, суммарно "
            + f"{total:,}".replace(",", " ") + " дней.\n")
        add("| Символ | Заморожен, дней | Последняя сделка | Бары идут до |")
        add("|---|---:|---|---|")
        for f in frozen[:12]:
            add(f"| {f['symbol']} | {f['frozen_days']} | {f['last_traded'][:10]} "
                f"| {f['last_bar'][:10]} |")
        add("")
    add("Почему это опаснее обычного пропуска:\n")
    add("- проверка «есть ли бар» проходит на 100 %, то есть штатная гигиена")
    add("  такой ряд не ловит вовсе;")
    add("- доходности равны нулю, поэтому волатильность выглядит крошечной,")
    add("  а σ спреда — заниженной. Сайзинг раздела 4 спеки 01 берёт размер")
    add("  позиции обратно пропорционально σ, то есть по замороженной ноге")
    add("  он выдаст **завышенный** размер;")
    add("- на площадке исполнения инструмент в это время торговался. У ORBS")
    add("  последняя сделка на Binance 2024-12-09, а на Bybit он жил до")
    add("  2026-06-11. То есть ряд для оценки отношения фиктивен ровно там,")
    add("  где торговое окно настоящее.\n")
    add("**Требование к A3 и далее:** концом ряда Binance считается последний")
    add("бар со сделкой, а не последний опубликованный. Бар с `trades = 0` —")
    add("пропуск, а не наблюдение.\n")

    # 4
    nt = [v["no_trade_pct"] for v in S.values()]
    add("## 4. Бары без сделок\n")
    add("Тот же дефект в непрерывном виде: бар есть, сделок в нём нет, цена")
    add("перенесена с предыдущего.\n")
    add("| Квантиль по символам | Доля баров без сделок |")
    add("|---|---:|")
    for p in (0.5, 0.75, 0.9, 0.95, 0.99, 1.0):
        add(f"| {int(p*100)} % | {q(nt, p):.2f} % |")
    add("")
    add(f"Хотя бы один такой бар есть у {sum(1 for x in nt if x > 0)} символов")
    add(f"из {len(nt)}. Медиана безобидна, но хвост тяжёлый: у верхнего")
    add("процента больше половины баров пустые.\n")
    worst = sorted(S.items(), key=lambda kv: -kv[1]["no_trade_pct"])[:6]
    add("| Символ | Баров без сделок |")
    add("|---|---:|")
    for s, v in worst:
        add(f"| {s} | {v['no_trade_pct']:.1f} % |")
    add("")
    add("**Это и есть фильтр ликвидности в измеримом виде.** Оборот в")
    add("долларах отвечает на вопрос «много ли торгуют», а доля баров со")
    add("сделками — на вопрос «свежая ли цена в момент, когда мы считаем")
    add("спред». Для парной торговли важен второй.\n")

    # 5
    P = d["pair_alignment"]
    if P:
        common = [x["share_common"] for x in P]
        traded = [x["share_both_traded"] for x in P]
        bad90 = sum(1 for x in traded if x < 0.9)
        bad50 = sum(1 for x in traded if x < 0.5)
        add("## 5. Согласованность двух ног по времени\n")
        add(f"Измерено на {len(P)} парах, на пересечении сроков жизни.\n")
        add("| Квантиль | Общий бар есть | Обе ноги торговались |")
        add("|---|---:|---:|")
        for p in (0.05, 0.25, 0.5, 0.75, 0.95):
            add(f"| {int(p*100)} % | {100*q(common, p):.1f} % "
                f"| {100*q(traded, p):.1f} % |")
        add("")
        add("**Наивная проверка бесполезна.** Общий бар есть в 100 % случаев")
        add("на всех квантилях: сетка Binance выровнена идеально, бар")
        add("публикуется всегда. Вопрос «имеют ли обе ноги бар в одну минуту»")
        add("проходит стопроцентно и не сообщает ничего.\n")
        add(f"Содержательный ответ даёт вторая колонка: у {bad90} пар из")
        add(f"{len(P)} ({100*bad90/len(P):.0f} %) обе ноги торговались реже чем")
        add(f"в 90 % общих баров, у {bad50} — реже чем в половине.\n")

        # Два разных дефекта нельзя показывать одним числом. Хвост этого
        # распределения не про несинхронную торговлю: он целиком про
        # замороженные ряды раздела 3, где одна нога на Binance давно
        # мертва, а бары продолжают выходить. Если их не отделить, читатель
        # заключит «некоторые пары никогда не торгуются одновременно»,
        # тогда как верное утверждение — «одна нога умерла».
        frozen = {x["symbol"] for x in d.get("frozen_tails", [])}
        zero = [x for x in P if x["share_both_traded"] == 0]
        zero_frozen = [x for x in zero
                       if x["a"] in frozen or x["b"] in frozen]
        clean = [x for x in P if x["a"] not in frozen and x["b"] not in frozen]

        if zero:
            add(f"Пар, где совпадений нет вовсе: {len(zero)}. Из них "
                f"{len(zero_frozen)} содержат замороженную ногу — то есть это")
            add("не рассогласование торговли, а дефект раздела 3: инструмент")
            add("на Binance мёртв, бары продолжают публиковаться. Пример — "
                f"`{zero[0]['a']}` / `{zero[0]['b']}`, общее окно "
                f"{zero[0]['overlap_days']:.0f} дней.\n")

        if clean:
            ct = [x["share_both_traded"] for x in clean]
            below = sum(1 for x in ct if x < 0.99)
            add("**Без замороженных ног картина другая, и она и есть мера")
            add(f"несинхронной торговли.** На {len(clean)} парах доля общих")
            add("баров, где торговались обе ноги:\n")
            add("| Квантиль | 5 % | 25 % | 50 % | 90 % |")
            add("|---|---:|---:|---:|---:|")
            add("| Обе ноги торговались | "
                + " | ".join(f"{100*q(ct, p):.1f} %"
                             for p in (0.05, 0.25, 0.5, 0.90)) + " |")
            add("")
            add(f"Медиана {100*q(ct, 0.5):.1f} %, то есть примерно в "
                f"{100-100*q(ct, 0.5):.1f} % общих баров одна из ног стоит.")
            add(f"Реже чем в 99 % баров торгуются обе у {below} пар из "
                f"{len(clean)} ({100*below/len(clean):.0f} %).")
            add("Потеря небольшая по величине, но систематическая, и бьёт она")
            add("именно по оценке отношения: β и корреляция на несинхронных")
            add("рядах занижаются (эффект Эппса). Спека 02 §5.5 задаёт")
            add("двухэтапность как раз поэтому — грубо по универсуму, точно")
            add("по выжившим парам.\n")

    # 6
    add("## 6. Начало и конец жизни\n")
    add("Спека требует карантин после листинга, но не задаёт его длину.")
    add("Профиль ниже — во сколько раз движение в k-й день жизни превышает")
    add("обычное **для того же инструмента**; нормировка на сам инструмент")
    add("нужна, иначе профиль опишет состав выборки, а не поведение.\n")
    ls = d["life_start"]
    add("| День после листинга | Движение против обычного |")
    add("|---:|---:|")
    for r in ls:
        if r["day"] in (0, 1, 2, 3, 5, 7, 10, 14, 21, 30):
            add(f"| {r['day']} | ×{r['ratio']:.2f} |")
    add("")
    # Числа берутся из данных, а не из прозы. Прежде здесь стояли значения,
    # снятые на 15m, и при первом же прогоне на 1m таблица и текст под ней
    # разошлись: таблица показывала ×2.89, текст — ×3.1.
    prof = {r["day"]: r["ratio"] for r in ls}
    if prof:
        d0 = prof.get(0)
        d7 = prof.get(7)
        d30 = prof.get(30)
        add(f"Резкий участок — первые пять-семь дней (×{d0:.2f} → ×{d7:.2f}),")
        add(f"дальше спад медленный и к тридцатому дню не заканчивается "
            f"(×{d30:.2f}).\n")
    add("**Практически карантин избыточен.** Универсум требует 365 дней")
    add("истории, поэтому любой инструмент в отборе давно старше месяца.")
    add("Параметр остаётся значимым только для коротких окон вроде анализа")
    add("funding и как страховка, если требование к истории ослабят.\n")
    le = d["life_end"]
    if le:
        vals = [r["ratio"] for r in le]
        add("С другого края картина иная: за тридцать дней до последнего бара")
        add(f"движение остаётся обычным (медиана ×{q(vals, 0.5):.2f}, разброс")
        add(f"×{min(vals):.2f}…×{max(vals):.2f}). Всплеска волатильности перед")
        add("делистингом в данных нет — деградация конца жизни проявляется не")
        add("в цене, а в исчезновении сделок, то есть в разделах 3 и 4.\n")

    # 7
    out = [v["outlier_pct"] for v in S.values()]
    add("## 7. Выбросы\n")
    add("Помечено " + f"{sum(v['outliers'] for v in S.values()):,}".replace(",", " ")
        + " баров")
    add(f" — движение больше {m['outlier_mad_threshold']:.0f} медианных")
    add("абсолютных отклонений доходности **того же символа**.\n")
    add("| Квантиль по символам | Доля помеченных баров |")
    add("|---|---:|")
    for p in (0.5, 0.75, 0.95, 1.0):
        add(f"| {int(p*100)} % | {q(out, p):.2f} % |")
    add("")
    add("Порог берётся от самого символа, потому что общего порога не")
    add("существует: у альта дневное движение в 20 % норма, у BTC — событие.")
    add("Медиана робастна к выбросам, стандартное отклонение раздувается")
    add("ровно теми значениями, которые мы ищем.\n")
    add("**Выбросы помечаются, но не удаляются.** Для нас это реальные")
    add("события, на которых срабатывают стопы: удалив их, мы получили бы")
    add("бэктест, в котором стопы не срабатывают никогда.\n")

    path = os.path.join(OUT, f"A2-hygiene-report.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"записан {path}")


if __name__ == "__main__":
    main()
