#!/usr/bin/env python3
"""
F2 — отчёт по артефакту прогона. Зависимостей не имеет намеренно.

    python3 report.py --interval 1m > out/F2-report-1m.md
"""

import argparse
import json
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")


def bp(x, d=1):
    return "—" if x is None else f"{x * 10000:.{d}f}"


def f(x, d=3):
    return "—" if x is None else f"{x:.{d}f}"


def money(x):
    return "—" if x is None else f"${x:,.0f}".replace(",", " ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--interval", default="1m")
    ap.add_argument("--funding-venue", default="bybit")
    a = ap.parse_args()
    path = os.path.join(OUT, f"f2_{a.interval}_{a.funding_venue}.json")
    if not os.path.exists(path):
        raise SystemExit(f"нет {path} — сначала run.py")
    with open(path, encoding="utf-8") as fh:
        d = json.load(fh)
    cfg, cells, grid = d["config"], d["cells"], d["grid"]
    p = print

    p("# F2 — ловушки раздела 5\n")
    p("**Спека:** 04, этап F2  ")
    p(f"**Разрешение хранилища:** {cfg['interval']}, ставки "
      f"{cfg['funding_venue']}  ")
    p(f"**Сечений:** {cfg['sections']}\n")
    if cfg["funding_venue"] != "bybit":
        p("> **Ставки взяты НЕ с площадки исполнения** — проверка "
          "конвейера, не вердикт.\n")

    p("Все меры считаются **пересчётом векторов F1**, а не вторым проходом "
      "по хранилищу: ловушки суть функции того, что F1 уже сохранил. "
      "Ценовой борт книги, пересчитанный из тех же векторов, обязан "
      "совпасть с артефактом F1 — сверка встроена в прогон и прерывает "
      "его при расхождении.\n")

    p("## 1. Бета книги — §5.2, критерий 10\n")
    p("После F1 это решающий замер, а не гигиена. Обе ноги книги в F1 "
      "ехали вниз (средняя доходность активов длинной ноги −181 б.п. за "
      "десять дней, короткой −113), и надо показать, что положительное "
      "брутто не является ставкой против рынка альтов, отработавшей в "
      "этом конкретном периоде.\n")
    p("β считается регрессией **ценового борта книги** на доходность "
      "равновзвешенной волны за те же периоды. Не взвешенной суммой β "
      "активов: та несла бы ошибки оценки каждой и предполагала бы "
      "постоянство β на окне удержания.\n")
    p("| Ячейка | β | R² | β скольз., медиана | мин | макс |")
    p("|---|---|---|---|---|---|")
    for n in sorted(cells):
        c = cells[n]
        p(f"| {n} | **{f(c['beta'])}** | {f(c['beta_r2'], 2)} "
          f"| {f(c['beta_rolling_median'])} | {f(c['beta_rolling_min'])} "
          f"| {f(c['beta_rolling_max'])} |")
    p("")
    p(f"Медиана \\|β\\| по сетке **{f(grid['abs_beta_median'])}**, максимум "
      f"{f(grid['abs_beta_max'])} при пороге 0.2 — критерий 10 "
      f"**{'✓' if grid['criterion_10_pass'] else '✗'}**.\n")
    p("Скользящая β приводится потому, что одно число скрывает смену "
      "режима: книга с β +0.5 полгода и −0.5 полгода в среднем даст ноль "
      "и покажется нейтральной.\n")

    p("## 2. Делистинги — §5.3\n")
    p("У инструмента перед снятием с торгов базис разъезжается и ставка "
      "становится экстремальной, то есть в дециль он попадает почти "
      "наверняка, а выйти придётся по цене расчёта. Исключить такие "
      "активы из универсума нельзя — это был бы отбор «по сегодняшнему "
      "списку». Их можно только измерить.\n")
    p(f"| Ячейка | Доля гросса, медиана | Максимум | Брутто | "
      f"Брутто без них | Разница |")
    p("|---|---|---|---|---|---|")
    for n in sorted(cells):
        c = cells[n]
        g, gc = c["gross"], c["gross_no_delist"]
        diff = None if (g is None or gc is None) else gc - g
        p(f"| {n} | {f(c['delist_share'])} | {f(c['delist_share_max'])} "
          f"| {bp(g)} | {bp(gc)} | {bp(diff)} |")
    p("")
    p("Разница в последней колонке — это `брутто без них` минус `брутто`, "
      "то есть **что происходит, когда активы, идущие к делистингу, из "
      "книги убраны**. Отрицательная величина означает, что без них книга "
      "зарабатывает меньше, — то есть часть результата держалась именно на "
      "ловушке.\n")
    lean = [(n, (cells[n]["gross_no_delist"] - cells[n]["gross"]),
             cells[n]["gross"]) for n in cells
            if cells[n]["gross"] and cells[n]["gross_no_delist"]]
    worse = [x for x in lean if x[1] < 0]
    if worse:
        w = min(worse, key=lambda x: x[1])
        p(f"Получено: без таких активов брутто **падает в "
          f"{len(worse)} ячейках из {len(lean)}**. Худший случай — "
          f"`{w[0]}`: {bp(w[2])} → {bp(w[2] + w[1])} б.п., то есть "
          f"**{abs(w[1]) / abs(w[2]) * 100:.0f} % результата** ячейки "
          f"приходило с активов, снимаемых с торгов в ближайшие "
          f"{cfg['delist_horizon_days']} дней.\n")
        p("Это не подделка результата, но **известная неточность модели**: "
          "цены берутся из архива Binance, а снимает инструмент с торгов "
          "Bybit, и цену закрытия позиции при расчёте мы не моделируем "
          "вовсе. Медианная доля таких активов нулевая — эффект "
          "сосредоточен в немногих периодах, — но в F4 их вклад обязан "
          "быть показан отдельной строкой, а не растворён в итоге.\n")
    else:
        p("Получено: удаление таких активов брутто не улучшает ни в одной "
          "ячейке — книга на этой ловушке не держится.\n")

    p("## 3. Ликвидность и ёмкость — §5.5\n")
    p("| Ячейка | Оборот лонга | Оборот шорта | Оборот универсума "
      "| Доля баров со сделками | Худшая доля оборота | Предельный капитал |")
    p("|---|---|---|---|---|---|---|")
    for n in sorted(cells):
        c = cells[n]
        m = lambda x: "—" if x is None else f"${x / 1e6:.1f} млн"
        p(f"| {n} | {m(c['turn_long'])} | {m(c['turn_short'])} "
          f"| {m(c['turn_universe'])} | {f(c['share_traded_book'], 4)} "
          f"| {f(c['capacity_worst_share'], 4)} "
          f"| {money(c['capital_limit'])} |")
    p("")
    p(f"«Худшая доля оборота» — какую часть суточного оборота актива "
      f"занимает самая крупная позиция при капитале {money(cfg['capital'])}. "
      f"«Предельный капитал» — при каком размере книги эта доля упирается "
      f"в {cfg['max_turnover_share'] * 100:.0f} %. Порогом при капитале фаз "
      f"C–D это не является, но знать величину надо до фазы E.\n")

    p("## 4. Смена режима начисления — §5.6\n")
    p("Bybit переводит инструмент на часовые начисления в периоды высокого "
      "базиса и возвращает обратно (318 символов из 722). Ставка, "
      "оценённая на четырёхчасовом режиме и полученная на часовом, стоит "
      "вчетверо дороже. Оценка §3.2 считает суточную величину именно "
      "поэтому; здесь проверяется, насколько часто режим вообще менялся "
      "между окном оценки и окном удержания.\n")
    p("| Ячейка | Доля гросса со сменой режима |")
    p("|---|---|")
    for n in sorted(cells):
        p(f"| {n} | {f(cells[n]['regime_share'])} |")
    p("")

    p("## Вердикт\n")
    if grid["criterion_10_pass"]:
        p("Критерий 10 выполнен: книга не является переодетой ставкой "
          "против рынка. Переход к **F3** — три нулевые модели и критерий "
          "немедленной остановки §8.2.\n")
    else:
        p("**Критерий 10 не выполнен: книга есть ставка против рынка, а не "
          "carry.** По решению §11.3 спеки любой невыполненный критерий "
          "§8.3 закрывает гипотезу — права на итерацию нет.\n")


if __name__ == "__main__":
    main()
