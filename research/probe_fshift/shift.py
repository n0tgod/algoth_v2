#!/usr/bin/env python3
"""
Смена интервала начисления funding как датированное событие.

Что здесь лежит
---------------

Ядро механики «Смена интервала начисления funding как принудительный
поток»: извлечение СОБЫТИЙ из рядов funding площадки исполнения и
арифметика сделки вокруг них. Прохода по хранилищу здесь нет вовсе —
цены подаёт `run_ceiling.py`, а этот модуль работает на рядах и потому
проверяется целиком без духдб и без парккета.

Утверждение механики: площадка переводит перп на более короткий
интервал начисления (8/4/2 ч → 1 ч), когда ставка упирается в свой
предел, и так же возвращает его обратно. В момент первого начисления по
укороченному интервалу суточная стоимость удержания ПЛАТЯЩЕЙ стороны
умножается в 2–8 раз скачком. Это принудительный поток, датированный
самой площадкой, а не наш вывод о толпе из цены.

Три решения, каждое из которых меняет числа
-------------------------------------------

**1. Событие ищется СТРОГО ПО ПРОШЛОМУ.** Соблазн определить смену
интервала как «режим до длинный, режим после короткий» велик и был бы
дефектом: режим ПОСЛЕ метки в момент метки неизвестен. Здесь событие
опознаётся по двум величинам, обе известны в `t[i]`: режим по окну
шагов, кончающемуся на `t[i-1]`, и сам шаг `t[i] − t[i-1]`. Никакой
записи после `t[i]` детектор не касается, и это закреплено тестом
(`test_no_lookahead_in_events`) с негативным контролем.

**2. Окно и кратность взяты у проекта, а не назначены.** Окно режима —
`WINDOW = 25` шагов, значение по умолчанию `funding.gap_report`, где та
же задача (оценить локальный режим ряда, у которого режим меняется по
ходу истории) уже решалась. Кратность `RATIO = 2.0` — не порог
чувствительности, а арифметика площадки: интервалы бывают 1, 2, 4 и 8
часов, значит любая настоящая смена есть изменение не меньше чем вдвое.
Требование `MIN_BEFORE_STEPS = 5` отсекает не порог, а бессмыслицу:
режим, оценённый по одному-двум шагам, режимом не является, и свежий
листинг иначе давал бы событие на третьем начислении.

**3. Порог «упёрлась в предел» не задаётся числом вовсе.** Величину
предела площадка меняет молча, поэтому событием служит ФАКТ смены
интервала, а близость ставки к пределу считается отдельно
(`rate_extremity`) как проверка посылки, а не как условие входа.

Знак ставки
-----------

Соглашение загрузчика (`research/common/funding_series.py`):
**положительная ставка означает, что лонги платят шортам.** Отсюда
сторона ячейки вердикта: ставка < 0 — платят шорты, выталкивает их, и
позиция ЛОНГ. Знак закреплён тестом ЧИСЛОМ (`test_side_sign_by_number`):
перевёрнутый развернул бы сторону молча, и весь замер описывал бы
другую сделку.

Только numpy и stdlib.
"""

import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RESEARCH = os.path.dirname(HERE)
for _p in (os.path.join(RESEARCH, "common"),):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import funding as FU                                        # noqa: E402

MS_H = 3_600_000
MS_D = 86_400_000

WINDOW = 25                 # шагов в окне режима — умолчание gap_report
RATIO = 2.0                 # интервалы площадки 1/2/4/8 ч: смена ≥ ×2
MIN_BEFORE_STEPS = 5        # режим по паре шагов режимом не является
MAX_HOLD_MS = 24 * MS_H     # предел удержания ячейки вердикта

# Ячейка вердикта: ставка < 0 (платят шорты) — позиция ЛОНГ.
# Сторона выбрана до всякого счёта по критерию владельца: у лонга худший
# день ограничен падением имени за сутки, у шорта у верхнего предела
# хвост не ограничен ничем (в F-серии ноги теряли до −589 % позиции).
VERDICT_SIGN = -1           # знак ставки в ячейке вердикта


def side_of_rate(rate):
    """Сторона позиции по знаку ставки. Плюс — лонг, минус — шорт.

    Положительная ставка = лонги платят шортам, значит выталкивает
    ЛОНГОВ, и встать надо против них — в шорт. Отрицательная ставка
    выталкивает шортов, и позиция длинная. Ноль стороны не задаёт:
    платить некому, и `None` здесь честнее любого из двух знаков.
    """
    if not np.isfinite(rate) or rate == 0.0:
        return None
    return +1 if rate < 0 else -1


def regime_before(t_ms, i, window=WINDOW, min_steps=MIN_BEFORE_STEPS):
    """Режим ряда по шагам, кончающимся на `t[i-1]`. Строго прошлое.

    Считается ТЕМ ЖЕ кодом, которым проект меряет режим ряда
    (`funding.modal_step_hours`): второй реализации не заводится — у
    загрузчика funding две копии уже расходились, и расхождение не
    падало, а меняло вердикт.

    `None` означает «режим не измерен» — это НЕ то же самое, что
    «режим равен нулю»: у события без измеренного режима сравнивать
    шаг не с чем, и оно не событие, а пропуск.
    """
    lo = max(0, i - 1 - window)
    chunk = t_ms[lo:i]                      # метки до t[i-1] включительно
    if len(chunk) - 1 < min_steps:
        return None
    return FU.modal_step_hours(list(chunk))


def shift_events(t_ms, rates, window=WINDOW, ratio=RATIO,
                 min_steps=MIN_BEFORE_STEPS):
    """Первые начисления по УКОРОЧЕННОМУ интервалу.

    Возвращает список словарей: индекс, метка, ставка этого начисления,
    шаг в часах, прежний режим и сторона позиции по знаку ставки.

    Детектор смотрит только назад: и режим, и шаг известны в `t[i]`.
    """
    t = np.asarray(t_ms, dtype=np.int64)
    r = np.asarray(rates, dtype=np.float64)
    if len(t) != len(r):
        raise ValueError("метки и ставки разной длины")
    out = []
    for i in range(2, len(t)):
        step_h = (int(t[i]) - int(t[i - 1])) / MS_H
        prev_h = (int(t[i - 1]) - int(t[i - 2])) / MS_H
        if step_h <= 0 or prev_h <= 0:
            continue
        # ПЕРВОЕ начисление по укороченному интервалу, а не всякое.
        # Без этого условия переход 8ч→1ч даёт событие на каждом из
        # первых двадцати пяти часовых начислений: окно режима ещё
        # состоит в основном из восьмичасовых шагов, и «режим до»
        # остаётся длинным. Ровно так `gap_report` получала 112 ложных
        # пропусков у BLURUSDT. Предыдущий шаг известен в `t[i]`, так
        # что условие остаётся причинным.
        #
        # Условие стоит ПЕРЕД оценкой режима намеренно: оба входят в
        # событие через «и», а режим стоит окна в двадцать пять шагов
        # на каждое начисление — по 2.4 млн начислений универсума это
        # разница в минуты. Порядок дешёвой и дорогой проверок чисел не
        # меняет (`test_only_first_short_accrual_is_event` держит их
        # обе), а ускорение, меняющее числа, было бы другой мерой.
        if prev_h < step_h * ratio:
            continue
        before = regime_before(t, i, window, min_steps)
        if before is None or before < step_h * ratio:
            continue
        out.append({"i": i, "ts": int(t[i]), "rate": float(r[i]),
                    "step_h": round(step_h, 4),
                    "before_h": round(float(before), 4),
                    "side": side_of_rate(float(r[i]))})
    return out


def reverse_ts(t_ms, i, short_h, ratio=RATIO):
    """Метка первого начисления по ВОЗВРАЩЁННОМУ длинному интервалу.

    Это выход, а не вход, и потому смотреть вперёд здесь законно: факт
    возврата виден в `t[j]` — в момент, когда начисление пришло позже
    короткого шага. Знать о возврате РАНЬШЕ можно (ожидаемое часовое
    начисление не пришло), но такой выход требует «ожидали и не
    дождались», а мы берём консервативный поздний вариант: удержание
    длиннее, а не короче, и потолок от этого не растёт.

    `None` — возврата в ряду нет (ряд кончился раньше).
    """
    t = np.asarray(t_ms, dtype=np.int64)
    for j in range(i + 1, len(t)):
        if (int(t[j]) - int(t[j - 1])) / MS_H >= short_h * ratio:
            return int(t[j])
    return None


def holding(t_ms, ev, max_hold_ms=MAX_HOLD_MS):
    """Окно удержания `(вход_мс, выход_мс, причина)`.

    До первого начисления по возвращённому длинному интервалу либо
    `max_hold_ms`, что раньше, — как объявлено ячейкой вердикта.
    """
    entry = int(ev["ts"])
    cap = entry + int(max_hold_ms)
    back = reverse_ts(t_ms, ev["i"], ev["step_h"])
    if back is not None and back <= cap:
        return entry, back, "интервал вернулся"
    return entry, cap, "предел удержания"


def dedup_by_name(events, min_gap_ms=MAX_HOLD_MS):
    """Одна позиция на имя: событие внутри чужого удержания пропускается.

    Без этого один эпизод флаппинга интервала дал бы несколько
    перекрывающихся позиций по одному инструменту, а бюджет
    доказательства раздулся бы числом, которого нет. Тот же приём, что
    `dedup_rows` в Z1, только гранулярность — имя и удержание.
    """
    keep, last = [], None
    for e in sorted(events, key=lambda x: x["ts"]):
        if last is not None and e["ts"] - last < min_gap_ms:
            continue
        keep.append(e)
        last = e["ts"]
    return keep


def rate_extremity(t_ms, rates, i, min_hist=20):
    """Насколько ставка события крайняя в СОБСТВЕННОМ прошлом ряда.

    Возвращает `(ранг, доля_от_максимума)` по |ставке| среди всех
    начислений строго ДО события. Это проверка посылки механики
    («интервал укорачивают, когда ставка упёрлась в предел»), а не
    условие входа: величину предела площадка меняет молча, и зашивать
    её числом нельзя.

    `(None, None)` при слишком короткой истории — «не измерено», а не
    «ноль»: нулевой ранг читался бы как «ставка была обычной».
    """
    r = np.abs(np.asarray(rates, dtype=np.float64)[:i])
    r = r[np.isfinite(r)]
    if len(r) < min_hist:
        return None, None
    v = abs(float(rates[i]))
    rank = float(np.searchsorted(np.sort(r), v, side="left") / len(r))
    top = float(r.max())
    return rank, (v / top if top > 0 else None)


# --- плотность событий (число «а» потолка) ---------------------------

def day_of(ts_ms):
    return int(ts_ms) // MS_D


def active_share(event_ts, first_day=None, last_day=None, window_d=30):
    """Доля суток хотя бы с одним событием, по скользящим окнам.

    Возвращает `(общая_доля, медиана_по_окнам, минимум, максимум,
    число_окон)`. Общая доля отвечает «часто ли вообще», окна — «нет ли
    длинных провалов»: правило вылета судит форму по СУТКАМ, и
    кандидат, у которого события сбиты в несколько недель, по форме
    неизмерим, сколько бы событий он ни дал в те недели.

    Пустой вход — `None` во всех полях, а не нули: доля, которой нет,
    не равна нулю.
    """
    if not len(event_ts):
        return {"share": None, "med": None, "lo": None, "hi": None,
                "windows": 0, "days": 0, "active_days": 0}
    days = sorted({day_of(t) for t in event_ts})
    d0 = first_day if first_day is not None else days[0]
    d1 = last_day if last_day is not None else days[-1]
    span = int(d1) - int(d0) + 1
    have = np.zeros(max(span, 1), dtype=bool)
    for d in days:
        k = int(d) - int(d0)
        if 0 <= k < span:
            have[k] = True
    shares = []
    if span >= window_d:
        c = np.concatenate([[0], np.cumsum(have.astype(np.int64))])
        for a in range(span - window_d + 1):
            shares.append(float(c[a + window_d] - c[a]) / window_d)
    return {"share": float(have.mean()),
            "med": float(np.median(shares)) if shares else None,
            "lo": float(np.min(shares)) if shares else None,
            "hi": float(np.max(shares)) if shares else None,
            "windows": len(shares), "days": span,
            "active_days": int(have.sum())}


# --- арифметика сделки -----------------------------------------------

def excess_bp(own_ret, cross_ret, side):
    """Превышение над одновременной кросс-секцией, в базисных пунктах.

    Одно место на весь замер: и событие, и контроль 2, и нуль считаются
    этой функцией. Вторая формула знака стороны однажды разошлась бы, и
    таблица сравнивала бы лонг с шортом.
    """
    if not (np.isfinite(own_ret) and np.isfinite(cross_ret)):
        return np.nan
    return float(side) * (float(own_ret) - float(cross_ret)) * 1e4


def funding_bp(sum_rates, side):
    """Начисления, ПОЛУЧЕННЫЕ позицией за удержание, в базисных пунктах.

    Издержка позиции есть `сторона · сумма_ставок` (лонг с плюсом
    платит), значит доход — она же со знаком минус. У лонга при
    отрицательной ставке величина положительна: нам платят.
    """
    if sum_rates is None or not np.isfinite(sum_rates):
        return np.nan
    return -float(side) * float(sum_rates) * 1e4
