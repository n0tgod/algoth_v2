HOLD_H = 4                        # горизонт выбора — цель fwd_4h
# Максимальный нотионал, до которого лесенка стамповывается в запись.
# Фазы C–D — капитал $1–20 тыс., то есть позиция до ~$830 при двадцати
# четырёх слотах; запас впятеро. Заявка крупнее стамповки честно
# помечается «не влезло», а не досчитывается по последней цене: цена
# уровня, которого мы не видели, есть выдумка.
LADDER_CAP_USD = 5000.0
# Круг издержек живёт ЗДЕСЬ, а не в цикле обучения: его читают и цикл
# (при разборе), и сборщик (при переоценке открытых сделок). Две копии
# одного числа однажды разойдутся, и таблица покажет одну цену круга, а
# счёт другую. Модуль на стандартной библиотеке нарочно — его импорт не
# должен требовать numpy.
ROUND_COST_BP = 11.0


# Выходы, которые ставили МЫ САМИ: стоп и цель. Причины выхода живут
# строками в разборе, и список обязан быть один на весь проект —
# страница, сводка и отчёт не вправе решать это каждый по-своему.
#
# Различие содержательное, а не оформительское. «Угадал знак» отвечает
# на вопрос, сработала ли ГЕОМЕТРИЯ сделки: цена дошла до нашей цели
# или до нашего стопа. Сделка, закрытая разворотом прогноза или
# пределом возраста, до уровня не дошла ни разу — её исход есть та
# цена, на которой мы её застали, и знак у неё случаен. Замечание
# владельца: доля «знак угадан» стояла выше 70 % при отрицательном
# счёте, потому что мелкие плюсы отменённых сигналов считались
# победами наравне с дошедшими до цели.
LEVEL_EXITS = ("цена прошла обещанный ход против",
               "цена дошла до обещанной цели")


def by_level(t):
    """Сделка закрыта нашим же уровнем (стоп или цель)."""
    return t.get("exit_reason") in LEVEL_EXITS


def _ts(hour):
    """`2026-08-03-17` → epoch-секунды начала часа."""
    try:
        return datetime.strptime(hour, "%Y-%m-%d-%H").replace(
            tzinfo=timezone.utc).timestamp()
    except (ValueError, TypeError):
        return None


def _hour_of(ts):
    return datetime.fromtimestamp(ts, timezone.utc).strftime(
        "%Y-%m-%d-%H")


def hour_end(hour):
    """Когда час кончился. Нужно тем, кто решает, ждать ли сводку."""
    ts = _ts(hour)
    return None if ts is None else ts + 3600


def position_path(side, mae_v, mfe_v, h=4):
    """Ход ПРОТИВ и В ПОЛЬЗУ позиции из целей, считанных по цене.

    `mae_{h}h` — минимум цены за горизонт, `mfe_{h}h` — максимум, обе
    по ЦЕНЕ, а не по позиции: у лонга против идёт `mae`, в пользу
    `mfe`; у шорта наоборот. Правило живёт ЗДЕСЬ, в общем модуле:
    его читают цикл обучения (выбор монет) и сборщик (живой сторож
    ситуационной книги), а вторая копия однажды переставила бы
    стороны молча — эта ошибка в проекте уже случалась.

    Возвращает `(против, в пользу, имя цели против, имя цели в
    пользу)`. Неоценённая сторона остаётся `None`, а не нулём.
    """
    if side == "long":
        return mae_v, mfe_v, f"mae_{h}h", f"mfe_{h}h"
    return mfe_v, mae_v, f"mfe_{h}h", f"mae_{h}h"


def rr_of(t):
    """Отношение обещанной прибыли к обещанному риску у ЭТОЙ сделки.

    Одна формула на всех: гейт входа ситуационной книги пускает по
    `|mfe| / |mae|`, и фильтр показа обязан считать ровно то же —
    иначе таблица отбирала бы по одной величине, а книга входила по
    другой, и обе назывались бы «RR». Поля записи уже размечены
    сторонами (`path_fields`), применять `position_path` повторно
    нельзя.

    `None` — когда обещания против нет или оно нулевое: отношение к
    нулю не существует, и придумывать ему число значило бы пускать
    такую сделку в любой порог.
    """
    adv, fav = t.get("mae_bp"), t.get("mfe_bp")
    if adv is None:
        adv, fav = t.get("mae"), t.get("mfe")
    try:
        adv, fav = abs(float(adv)), abs(float(fav))
    except (TypeError, ValueError):
        return None
    return (fav / adv) if adv else None


def by_rr(trades, rr_min):
    """Сделки, чьё обещанное отношение не ниже порога.

    Сделка без отношения (нет обещания против) НЕ проходит ни один
    порог: неизмеримое не есть удовлетворяющее. Возвращает
    `(отобранные, сколько отброшено, сколько без отношения)` — числа
    нужны показу, потому что «стало меньше сделок» и «часть сделок
    нечем судить» это разные сообщения.
    """
    if not rr_min:
        return list(trades), 0, 0
    keep, cut, unknown = [], 0, 0
    for t in trades:
        r = rr_of(t)
        if r is None:
            unknown += 1
            cut += 1
            continue
        if r + 1e-9 < rr_min:
            cut += 1
            continue
        keep.append(t)
    return keep, cut, unknown


def wider_stop(mean_adv, q_adv):
    """Дальний из двух уровней стопа — квантильный либо средний.

    Квантильная модель обучается отдельно от средней, и порядок между
    ними ничем не гарантирован: на части строк предсказанный квантиль
    выходит БЛИЖЕ среднего (пересечение квантилей — известное свойство
    независимых подгонок), а изредка и с другим знаком. Ни то, ни
    другое не является сведением о рынке, поэтому правило одно:
    берётся дальний уровень ТОЙ ЖЕ стороны. Отсюда инвариант, который
    и закреплён тестом: новый стоп не бывает ТЕСНЕЕ прежнего — правка
    может только отодвинуть заявку, но не придвинуть.
    """
    if q_adv is None:
        return mean_adv
    if mean_adv is None:
        return q_adv
    if (q_adv > 0) != (mean_adv > 0):
        return mean_adv                 # сторона перевернулась — артефакт
    return q_adv if abs(q_adv) > abs(mean_adv) else mean_adv


def path_fields(side, mae_v, mfe_v, h=4, mae_q=None, mfe_q=None):
    """Оба конца пути готовыми полями записи выбора.

    В записи поле `mae` — всегда ход ПРОТИВ ЭТОЙ позиции, `mfe` —
    в пользу, какой бы ни была сторона. Читателю записи применять
    `position_path` повторно НЕЛЬЗЯ: двойное применение переставляет
    стороны у шорта обратно — этот дефект был найден в выходах
    ситуационной книги и закрыт тестом с шортом, который не должен
    закрываться.

    `mae_q`/`mfe_q` — квантильные концы пути (низкий квантиль минимума
    цены и высокий квантиль максимума). Когда они есть, ходом ПРОТИВ
    становится квантильный уровень, а среднее остаётся полем `mae_m`.
    Смысл замены — замечание владельца: стоп стоял ровно там, куда
    модель сама предсказывала цену, то есть на уровне, который по
    построению перекрывается примерно в половине случаев (замер
    `s9_sweep/stops.py`: касаются 52 %, и 37 % касаний возвращаются к
    цели — их стоп убивает зря). Ход В ПОЛЬЗУ остаётся средним: цель
    — это то, чего ждут, а не то, за что заходят редко.
    """
    adv, fav, a_of, f_of = position_path(side, mae_v, mfe_v, h)
    out = {"mae": adv, "adverse_of": a_of,
           "mfe": fav, "favourable_of": f_of}
    if mae_q is None and mfe_q is None:
        return out
    q_adv, _, _, _ = position_path(side, mae_q, mfe_q, h)
    stop = wider_stop(adv, q_adv)
    if stop is None or stop == adv:
        return out
    out["mae"] = stop
    out["mae_m"] = adv                  # линия среднего, для показа
    out["adverse_of"] = (f"maeq_{h}h" if side == "long"
                         else f"mfeq_{h}h")
    return out


_FEES = None


def fee_table():
    """Таблица ставок, читаемая один раз на процесс.

    Ленивая, а не при импорте: модуль читает страница сборщика, и
    падение на отсутствующем файле выгрузки A1 стоило бы ей показа —
    при том что без ставок она обойдётся умолчанием и скажет об этом
    числом покрытия.
    """
    global _FEES
    if _FEES is None:
        _FEES = FEES.load()
    return _FEES


def cum_ladder(levels, cap_usd=LADDER_CAP_USD):
    """Лесенка → `[[цена, накопленный нотионал], …]` до потолка.

    Сжатие записи, а не расчёт: снимок несёт до двухсот уровней, а
    сделке нужны первые несколько. Накопленный нотионал считается
    сразу, потому что заявка исполняется в деньгах, а не в единицах
    базового актива, и переводить их на каждом чтении значило бы
    повторять одно деление во всех вызовах.
    """
    out, cum = [], 0.0
    for lvl in levels or []:
        try:
            p, q = float(lvl[0]), float(lvl[1])
        except (TypeError, ValueError, IndexError):
            continue
        if p <= 0 or q <= 0:
            continue
        cum += p * q
        out.append([p, round(cum, 2)])
        if cum >= cap_usd:
            break
    return out


def walk(cum, notional):
    """Средняя цена рыночной заявки на `notional` долларов.

    Возвращает `(цена, влезло ли целиком)`. Не влезло — цена всё равно
    считается по тому, что видели, но признак ставится `False`: молча
    выдать частичное исполнение за полное значило бы занизить издержки
    ровно там, где инструмент тонкий.
    """
    if not cum or not notional or notional <= 0:
        return None, False
    prev, qty, left = 0.0, 0.0, notional
    for p, c in cum:
        take = min(left, c - prev)
        if take <= 0:
            prev = c
            continue
        qty += take / p
        left -= take
        prev = c
        if left <= 1e-9:
            break
    if qty <= 0:
        return None, False
    return (notional - left) / qty, left <= 1e-9


def exec_cost(t, size, table=None):
    """Полный круг издержек ЭТОЙ сделки: комиссия + проскальзывание.

    Считается по записанной книге в момент входа и в момент выхода, а
    не константой. Замер на живом стакане показал, почему константа не
    годится: круг проскальзывания заявкой в $42 идёт от 1.5 б.п.
    (AVAX) до 18.0 (SSPC) — разброс вдвенадцатеро, и он систематически
    больше как раз у тонких имён, куда отбор и заходит.

    Обе ноги круга берутся по СВОЕЙ стороне книги: лонг входит в аск и
    выходит в бид, шорт наоборот. Взять середину обеих значило бы
    подарить полспреда дважды.

    Возвращает `None`, если хоть одна лесенка не записана: посчитать
    неизвестную издержку нулём — тот же класс ошибки, что бар без
    сделок вместо пропуска (урок A2).
    """
    cin, cout = t.get("cum_in"), t.get("cum_out")
    if not cin or not cout or not size:
        return None
    if table is None:
        table = fee_table()
    long_ = t.get("side") == "long"
    # Вход: лонг покупает в аске, шорт продаёт в биде.
    px_in, ok_in = walk(cin["a" if long_ else "b"], size)
    px_out, ok_out = walk(cout["b" if long_ else "a"], size)
    mid_in, mid_out = cin.get("mid"), cout.get("mid")
    if not px_in or not px_out or not mid_in or not mid_out:
        return None
    fee, known = FEES.taker_bp(t.get("sym"), table)
    slip_in = (px_in / mid_in - 1.0) * (1e4 if long_ else -1e4)
    slip_out = (px_out / mid_out - 1.0) * (-1e4 if long_ else 1e4)
    # Движение цены считается по ФАКТИЧЕСКИМ ценам исполнения, а не по
    # серединам минус поправка: у сделки два конца, и складывать их из
    # разных источников значило бы завести второе определение цены.
    move = (px_out / px_in - 1.0) * (1e4 if long_ else -1e4)
    return {"fee_bp": round(fee * 2, 2), "fee_known": known,
            "slip_in_bp": round(slip_in, 2),
            "slip_out_bp": round(slip_out, 2),
            "exec_bp": round(fee * 2 + slip_in + slip_out, 2),
            "fill_in": px_in, "fill_out": px_out,
            "move_bp": round(move, 1),
            "net_bp": round(move - fee * 2, 1),
            "filled": bool(ok_in and ok_out)}


def _gift(px, px_live, side):
    """Насколько вход по цене сигнала выгоднее доступного в решении.

    Положительное — записанная сделка вошла ЛУЧШЕ, чем вошла бы вживую:
    цена успела уйти в нашу сторону, пока цикл считал. Знак берётся по
    позиции, а не по цене, — иначе у шорта подарок читался бы наоборот.
    """
    if not px or not px_live:
        return None
    move = (px_live / px - 1.0) * 1e4
    return round(move if side == "long" else -move, 1)


def load_books(path):
    """Дописанные задним числом книги: `{(рука, час, символ): {in, out}}`.

    Отдельный приписной файл, а не правка `picks.jsonl` на месте. Цикл
    дописывает те же файлы и поднимается сторожем, поэтому переписать их
    целиком значит однажды потерять час выборов — молча, потому что
    файл при этом остаётся исправным на вид. Приписывать безопасно, а
    отменить пересчёт можно удалением одного файла.
    """
    out = {}
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                k = (r.get("arm"), r.get("hour"), r.get("sym"))
                if all(k):
                    out[k] = r
    except OSError:
        pass
    return out


def build(picks, reviews, now=None, hold_h=HOLD_H, px_at=None, books=None):
    """Сделки из выборов и разборов, свежие сверху.

    `picks` и `reviews` — строки соответствующих `.jsonl`.

    `hold_h=None` — книга БЕЗ срока (ситуационная): позиция закрывается
    не по времени, а разбором, и строка разбора несёт `exit_hour`.
    Открытая позиция такой книги не имеет ни срока, ни обратного
    отсчёта — и никогда не переходит в «ждёт разбора»/«без исхода» по
    таймеру: судьи-времени у неё нет.

    Про время входа
    ---------------

    `hour` — час, на ЗАКРЫТИИ которого модель приняла решение. Значит
    войти можно не раньше конца этого часа: признаки считаются по всему
    часу, и в 20:00 их ещё нет. Цель `fwd_4h` определена так же —
    движение от закрытия часа `t` до закрытия часа `t+4`.

    Первая версия ставила вход на НАЧАЛО часа и закрытие на «начало
    плюс четыре». Обе метки уезжали на час назад: обратный отсчёт врал,
    метка на графике стояла до того, как сигнал вообще существовал, а
    состояние «без исхода» наступало на час раньше срока.
    """
    now = now if now is not None else time.time()
    done = {}
    for rv in reviews or []:
        for r in rv.get("rows") or []:
            done[(rv.get("arm") or "gbm", rv.get("hour"), r.get("sym"),
                  r.get("side"))] = (r, rv)
    # Самый поздний РАЗОБРАННЫЙ час по каждой руке. Он и различает два
    # разных случая, которые прежде звались одним словом «без исхода»:
    # выбор, до которого разбор ещё не дошёл, и выбор, который разбор
    # рассмотрел и ничего не смог посчитать. Первое — ожидание, второе —
    # дефект данных, и путать их нельзя.
    last_rev = {}
    for rv in reviews or []:
        a = rv.get("arm") or "gbm"
        h = rv.get("hour") or ""
        if h > last_rev.get(a, ""):
            last_rev[a] = h
    out = []
    made = set()
    for pk in picks or []:
        arm = pk.get("arm") or "gbm"
        hour = pk.get("hour")
        h0 = _ts(hour)
        # Вход — на ЗАКРЫТИИ часа решения, а не на его начале.
        t0 = (h0 + 3600) if h0 is not None else None
        # Когда решение было принято на самом деле: цикл просыпается
        # через несколько минут после закрытия часа, и это задержка
        # входа, которую нельзя выдавать за ноль. Пишется циклом; у
        # старых записей её нет, и тогда поле остаётся пустым.
        decided = pk.get("at_ts")
        for side in ("long", "short"):
            for p in pk.get(side) or []:
                key = (arm, hour, p.get("sym"), side)
                # Дубли снимаются НА СТРОКЕ, а не на (руке, часе):
                # перезапуск пишет тот же час целиком — его строки
                # совпадут и уйдут; живой вход дописывает к часу
                # ВТОРУЮ запись с новыми именами — они остаются.
                if key in made:
                    continue
                made.add(key)
                got, rv = done.get(key, (None, None))
                t_close = (t0 + hold_h * 3600) \
                    if (t0 is not None and hold_h) else None
                # Книга входа: своя у выбора либо дописанная пересчётом.
                cin = (p.get("cum") or (books or {}).get(
                    (arm, hour, p.get("sym")), {}).get("in"))
                # Живой вход (сканер ситуаций): решение и вход — в
                # момент пересечения гейта, а не на закрытии часа.
                row_ts = p.get("at_ts")
                tr = {
                    "arm": arm, "hour": hour, "sym": p.get("sym"),
                    "side": side,
                    "opened_at": row_ts or t0, "closes_at": t_close,
                    "decided_at": row_ts or decided,
                    "lag_sec": (round(decided - t0)
                                if decided and t0 and not row_ts
                                else None),
                    "close_hour": (_hour_of(t_close) if t_close
                                   else None),
                    "expected_bp": p.get("fwd"),
                    # Цена закрытия часа сигнала — она же цена входа.
                    # Если выбор её не несёт (записан до того, как поле
                    # появилось), берётся из сводки того же часа —
                    # величина та же самая, а не приблизительная.
                    "entry_px": (p.get("px")
                                 or (px_at or {}).get(
                                     (p.get("sym"), hour))),
                    # Цена, доступная в МОМЕНТ РЕШЕНИЯ, и подарок,
                    # который даёт вход по цене сигнала. Считается, а не
                    # применяется: исход сделки разбор меряет от того же
                    # закрытия часа, и подменить один конец, оставив
                    # другой, значило бы завести дефект хуже чинимого.
                    # Сперва число, потом перенос всей цепочки.
                    # Середина в момент решения берётся из книги, если
                    # своего поля у выбора нет: у сделок, пересчитанных
                    # задним числом, история не правится вовсе, и
                    # величина живёт только в дописанной книге. Без
                    # этого подарок у них не считался бы — при том что
                    # данные для него есть.
                    "px_live": p.get("px_live") or (cin or {}).get("mid"),
                    "gift_bp": _gift(p.get("px"),
                                     p.get("px_live")
                                     or (cin or {}).get("mid"), side),
                    # Книга в момент входа. Сама сделка её не считает —
                    # цена исполнения зависит от размера, а размер знает
                    # только счёт.
                    "cum_in": cin,
                    # Ожидаемый ход ПРОТИВ позиции — то, что модель
                    # обещает пережить. Без него ожидание читается как
                    # обещание пути, а это разные вещи.
                    "mae_bp": p.get("mae"),
                    # Линия, куда модель ЖДЁТ цену, — рядом со стопом,
                    # но не вместо него: стоп стоит за ней. Пустая у
                    # сделок прежних правил, и это правильный ответ —
                    # у них стоп и был на самой линии.
                    "mae_m_bp": p.get("mae_m"),
                    "stop_of": p.get("adverse_of"),
                    # Ожидаемый ход в ПОЛЬЗУ позиции. У старых записей
                    # его нет, и тогда поле пустое, а не ноль: ноль
                    # означал бы «модель не ждёт движения», то есть
                    # утверждение вместо отсутствия данных.
                    "mfe_bp": p.get("mfe"),
                    "odd": p.get("odd"),
                    "ver": pk.get("ver"),
                    # Просьба владельца: сделка несёт, КАКИМ обучением
                    # открыта и ПОЧЕМУ. Номер обучения у ситуационной
                    # строки свой (лист, породивший вход), у часовой —
                    # общий на запись выбора; `why` — вклад признаков
                    # в прогноз, `rank`/`of` — место в сечении, и есть
                    # ответ «почему эта монета» у часовой книги;
                    # `fwd0_bp` — что обещал лист до того, как цена
                    # отдала скидку.
                    "train_seq": (p.get("train_seq")
                                  or pk.get("train_seq")),
                    "why": p.get("why"),
                    # Вид ситуации: верхние семейства признаков этого
                    # прогноза с долями — «на чём стоит сделка».
                    "setup": p.get("setup"),
                    "rank": p.get("rank"), "of": p.get("of"),
                    "fwd0_bp": p.get("fwd0"),
                }
                if got is not None:
                    tr["cum_out"] = (got.get("cum")
                                     or (books or {}).get(
                                         (arm, hour, p.get("sym")),
                                         {}).get("out"))
                    # Ситуационная книга: срок закрытия задаёт РАЗБОР.
                    # У живого выхода это СЕКУНДА пересечения, которую
                    # сторож записал событием, а не конец часа: позиции
                    # в 18:19 уже нет, и держать её деньги до 19:00
                    # значило бы морить голодом входы того же вечера
                    # (на живой книге так и вышло — сделки 18:31 и 18:46
                    # получили нулевой размер, а тень бота, знавшая о
                    # закрытии, их профинансировала: сверка кричала).
                    if got.get("exit_hour"):
                        tr["closes_at"] = (got.get("exit_ts")
                                           or hour_end(got["exit_hour"]))
                        tr["close_hour"] = got["exit_hour"]
                        tr["exit_reason"] = got.get("reason")
                        tr["exit_ts"] = got.get("exit_ts")
                    tr.update(state="закрыта", got_bp=got.get("got"),
                              net_bp=got.get("net"), pnl=got.get("pnl"),
                              pos=got.get("pos"),
                              cost_bp=(rv or {}).get("cost_bp"),
                              # Когда разбор был ЗАПИСАН. Кассе счёта
                              # нельзя узнавать исход раньше этого
                              # момента; у старых записей поля нет — там
                              # остаётся плановое время закрытия.
                              review_at=(rv or {}).get("at_ts"),
                              hit=(got.get("got") or 0) > 0
                              if side == "long"
                              else (got.get("got") or 0) < 0)
                elif t_close is not None and now >= t_close:
                    # Срок вышел, а разбора нет. Ни в каком случае это
                    # НЕ «закрыта в ноль»: посчитать неизвестный исход
                    # нулём значило бы разбавить статистику выдумкой
                    # (урок оборванных бумажных сделок; урок A2, где
                    # бар без сделок — пропуск, а не нулевая доходность).
                    #
                    # Но случая два. Если разбор уже дошёл до БОЛЕЕ
                    # ПОЗДНЕГО часа этой руки, значит и этот он
                    # рассмотрел — выборы разбираются по возрастанию
                    # часа — и цель посчитать не смог: в удержании была
                    # дыра записи, монета выпала из универсума, беты не
                    # хватило. Это окончательно, и это дефект данных.
                    #
                    # Если позднее ничего не разобрано, разбор до него
                    # просто не дошёл: цикл идёт раз в час, и сделка
                    # ждёт своего прохода. Это ожидание, а не потеря.
                    tr.update(state=("без исхода"
                                     if last_rev.get(arm, "") > hour
                                     else "ждёт разбора"))
                else:
                    tr.update(state="открыта",
                              closes_in_sec=(t_close - now
                                             if t_close else None))
                out.append(tr)
    out.sort(key=lambda t: (t["opened_at"] or 0), reverse=True)
    net_positions(out)
    return out


def net_positions(trades):
    """Одно имя — одна позиция: долив своей стороны, схлопывание чужой.

    Решение владельца (2026-08-09) и требование ПЛОЩАДКИ, а не удобство:
    на одном аккаунте нельзя держать несколько отдельных лонгов по одной
    паре. Можно долить в позицию, держать хедж либо открыть вторую после
    закрытия первой. Четырёхчасовые книги входят каждый час и держали до
    ЧЕТЫРЁХ лотов на имени — то есть моделировали то, чего площадка не
    умеет.

    Долив денег не меняет и здесь не требует ничего: PnL линеен, и
    четыре лота, купленные по разным ценам и закрытые в разное время,
    дают ту же сумму, что одна позиция со средней ценой и частичными
    выходами. Слитая позиция — предмет показа и маржи, а не счёта.

    Схлопывание меняет: вход противоположной стороны в одностороннем
    режиме не открывает вторую позицию, а ЗАКРЫВАЕТ существующую.
    Закрывается самый старый открытый лот (FIFO, как у площадки), по
    цене входа схлопнувшего сигнала: обе сделки на одном имени в один
    момент, и это ровно та цена, по которой площадка исполнила бы
    встречный ордер. Издержки закрытого лота остаются его собственные —
    величина того же порядка, и второй расчёт завёл бы второе
    определение круга.

    Схлопнувший сигнал позицию НЕ открывает и молча не исчезает: он
    остаётся в записи состоянием «схлопнула позицию». Решение, не
    ставшее сделкой, обязано быть видно — иначе книга теряет выбор
    модели, ничем себя не выдав.

    Замерено ДО правки (`one_name.py`): схлопывание не просто
    бесплатно, а лучше в обеих книгах (+140.82 → +177.99 у книги 4 ч,
    +118.59 → +124.97 у книги в единицах σ) — оно закрывает лот
    досрочно ровно тогда, когда прогноз развернулся.
    """
    live = {}
    for t in sorted(trades, key=lambda q: (q.get("opened_at") or 0,
                                           q.get("sym") or "")):
        key = (t.get("arm"), t.get("sym"))
        now = t.get("opened_at") or 0
        keep = [q for q in live.get(key, [])
                if (q.get("exit_ts") or q.get("closes_at") or 0) > now]
        live[key] = keep
        clash = [q for q in keep if q.get("side") != t.get("side")]
        if not clash:
            keep.append(t)                 # своя сторона — долив
            continue
        victim = min(clash, key=lambda q: q.get("opened_at") or 0)
        # Выход схлопнутого лота — это КНИГА В МОМЕНТ ВСТРЕЧНОГО ВХОДА,
        # то есть лесенка того сигнала, который его закрыл. Без этой
        # подстановки касса пересчитывала круг по лесенке ПРЕЖНЕГО
        # разбора (`exec_cost` перекрывает `net_bp`, когда обе лесенки
        # на месте), и деньги схлопывания молча возвращались к тому
        # выходу, которого больше нет: `build` давал +189.0, а счёт
        # писал −35.2. Нашлось сверкой с Rust — тот считал по своим
        # ценам и не совпадал.
        if t.get("cum_in") is not None:
            victim["cum_out"] = t["cum_in"]
        else:
            # Лесенки нет — пересчитывать нечем, и старая лесенка
            # выхода обязана уйти: иначе она перебьёт наш нетто.
            victim.pop("cum_out", None)
        px0, px1 = victim.get("entry_px"), t.get("entry_px")
        if px0 and px1:
            sign = 1.0 if victim.get("side") == "long" else -1.0
            move = sign * (px1 / px0 - 1.0) * 1e4
            cost = victim.get("exec_bp")
            if cost is None:
                cost = ROUND_COST_BP
            victim["got_bp"] = round(move, 1)
            victim["net_bp"] = round(move - cost, 1)
            victim["closes_at"] = now
            victim["exit_ts"] = now
            victim["state"] = "закрыта"
            victim["exit_reason"] = "встречный сигнал закрыл позицию"
        keep.remove(victim)
        t["state"] = "схлопнула позицию"
        t["netted_with"] = victim.get("hour")
        # Позиции у неё нет — значит нет ни входа, ни денег: касса
        # берёт только сделки с моментом открытия.
        t["opened_at"] = None
    return trades


START_BALANCE = 1000.0

# Версия ПРАВИЛА КАССЫ. Счёт Python — чистая функция от файлов и
# лечится пересчётом сам; журнал тени на Rust дописывается и хранит
# размеры, посчитанные тем правилом, которое действовало в момент
# записи. Поэтому правка правила делает старые записи несравнимыми
# навсегда, и сверка краснеет вечно, ничего при этом не сообщая:
# у ORDERUSDT бот держал 164.68387740645395 — дословно прежнее
# значение Python, — а исправленный счёт давал 165.50642363913860.
# Красное, которое всегда красное, перестаёт быть сигналом.
#
# Версия печатается в маркер журнала: сменилась — журнал уходит в
# архив и тень начинает чистую запись, ровно как при смене источника
# книги. Семь чистых суток E3 считаются с этого момента заново.
#
# 1 — до 2026-08-08; 2 — своя сделка не закрывается раньше своего же
# входа (сделка нулевой длительности больше не течёт деньгами);
# 3 — одно имя одна позиция: долив своей стороны, схлопывание чужой
# (двух отдельных лонгов по одной паре площадка не даёт);
# 4 — потолок экспозиции на имя (забор владельца, 2026-08-09).
CASH_RULES_VERSION = 4

# Потолок суммарной экспозиции на ОДНО имя, в долях текущего капитала
# книги (cash + busy — тот же знаменатель, что у плеча). Число назначил
# владелец ДО прогона, по замеру: пик по имени доходил до 19.4 %
# депозита (TUT), а у книг с шестью слотами одна позиция составляла
# 16.7 % просто сайзингом. Это ЗАБОР, а не настройка: он не учится и
# не подбирается по результатам — модель, учащаяся «не сливать» на
# выборке без сливов, выучила бы, что сливов не бывает.
NAME_CAP_SHARE = 0.10


def account(trades, arm, start=START_BALANCE, hold_h=HOLD_H, table=None,
            slots=None, sizing=None, name_cap=None):
    """Счёт ОДНОГО капитала: экспозиция не превышает его.

    Прежняя модель считала каждый час независимо — весь баланс делился
    на шесть позиций часа. При горизонте в четыре часа таких наборов
    одновременно открыто четыре, то есть экспозиция выходила
    ЧЕТЫРЁХКРАТНОЙ, а счёт показывал её как торговлю на тысячу. Плечо
    брать можно, но не молча и не задним числом.

    Здесь капитал один. Размер позиции при входе — доля свободных денег
    на число одновременных слотов: позиций в своём часе, умноженное на
    горизонт в часах. При шести именах и четырёх часах это двадцать
    четыре слота, то есть гросс равен капиталу — плечо ровно единица,
    как и требует фаза C.

    Свободные деньги считаются по КАССЕ: занятое возвращается только при
    закрытии позиции. Размер, посчитанный от нереализованной прибыли,
    наращивал бы плечо на растущем рынке — ровно та ошибка, которой этот
    пересчёт и посвящён.

    Функция ЧИСТАЯ и полная: она пересчитывает счёт с начала по списку
    сделок. Поэтому повторный прогон цикла не может провести те же
    сделки дважды — состояние не накапливается, а выводится.

    `slots` — фиксированное число слотов кассы: у ситуационной книги
    одновременных позиций не больше объявленного числа, и делить
    капитал на «имена × горизонт» там не на что — горизонта нет.

    Возвращает `(история, баланс)` и проставляет каждой сделке `size` —
    сумму, которая в ней стоит.
    """
    # Проверка на `is not None`, а не на истинность: метка времени
    # может быть нулём, и тогда сделка молча выпадала бы из счёта —
    # тот же род ошибки, что «честный ноль не есть отсутствие
    # измерения» в замере диска.
    rows = [t for t in trades
            if t["arm"] == arm and t.get("opened_at") is not None]
    if not rows:
        return [], start
    per_hour = {}
    for t in rows:
        per_hour.setdefault(t["hour"], []).append(t)
    # В один и тот же момент ЗАКРЫТИЕ идёт раньше открытия: деньги
    # возвращаются в кассу до того, как их снова размещают. Порядок был
    # обратным, и на живых данных это дало `size = 0` у всей свежей
    # руки: при горизонте в четыре часа выход часа H совпадает со
    # входом часа H+4, и открытие пыталось занять деньги, которые ещё
    # не вернулись. Ошибка тихая — счёт при этом не падал, просто
    # переставал торговать.
    ev = []
    for t in rows:
        if t["state"] == "закрыта" \
                and (t.get("closes_at") or t.get("review_at")):
            # Деньги возвращаются не раньше, чем исход стал ИЗВЕСТЕН.
            # Прежде выход вставал по плановому времени, даже когда
            # разбор опоздал на часы, — и касса задним числом
            # финансировала входы, которые исполнительное ядро в тот
            # момент честно отвергло за пустотой кассы. Сверка ловила
            # это как «есть у Python, нет у бота». Знание из будущего
            # в кассе — тот же класс дефекта, что отбор универсума по
            # сегодняшнему списку. У записей без метки прихода разбора
            # остаётся плановое время — их история уже сведена.
            # Живой выход — исключение, и оно того же правила, а не
            # против него: факт записан СТОРОЖЕМ в секунду пересечения,
            # то есть исход стал известен тогда. Цикл его лишь
            # переписывает часом позже, и ждать переписи значило бы
            # держать деньги в позиции, которой уже нет.
            back = t.get("exit_ts") or max(t.get("closes_at") or 0,
                                           t.get("review_at") or 0)
            # Правило «выход раньше входа» — про ЧУЖИЕ сделки: деньги
            # возвращаются в кассу до того, как их снова размещают.
            # Своя сделка закрыться раньше, чем открылась, не может, а
            # сканер закрывает позицию по пути цены и попадает в ту же
            # СЕКУНДУ, что вход (живой случай: CATIUSDT 18:08:35 —
            # открыта и закрыта одной секундой). При общем правиле её
            # выход шёл первым: размер ещё не проставлен, поэтому pnl
            # считался от нуля, а занятые входом деньги не возвращались
            # уже никому — касса беднела, и следующим входам доставался
            # размер 0. Сверка с ядром показала это тремя строками
            # разом (деньги −0.04 против −0.0, размер 165.47 против
            # 0.0, баланс на пять копеек).
            own = int(max(t["opened_at"], t.get("decided_at") or 0))
            ev.append((back, 2 if int(back) <= own else 0, t))
        # Вход занимает деньги В МОМЕНТ РЕШЕНИЯ, а не на номинальной
        # границе часа. Правило «касса не знает будущего» обязано быть
        # симметричным: сдвинув выходы к моменту записи разбора и
        # оставив входы на границе, мы морили голодом каждую книгу на
        # полном обороте — вход 19:00 просил деньги, которые разбор
        # возвращал в 19:16, и вся рука получала размер 0 (владелец
        # увидел это на часовой книге как pnl 0.00 при живом нетто).
        # Разбор в цикле пишется РАНЬШЕ выбора, так что касса успевает.
        # Цена входа остаётся ценой закрытия часа сигнала — сдвигается
        # только денежное событие; задержка решения и так записана
        # полем lag.
        ev.append((max(t["opened_at"], t.get("decided_at") or 0),
                   1, t))                          # 1 — потом вход
        # Порядок внутри секунды: 0 — чужие выходы, 1 — входы, 2 —
        # выход сделки, закрывшейся в секунду своего же входа.
    # Порядок — по ЦЕЛОЙ секунде, и внутри неё выход раньше входа.
    # Ниже секунды сравнивать нечего: разбор штампуется миллисекундами
    # (`round(t, 3)`), а выбор — целой секундой, и одно мгновение такта
    # выходит у них разным числом. На живой часовой книге разбор часа H
    # получал 1786125836.339, а выбор часа H+1, записанный ПОСЛЕ него,
    # — 1786125836: вход вставал перед выходом, деньги ещё не
    # вернулись, и вся рука получала размер 0 через час на третий.
    # Сравнение секунд не зависит от того, как какой писатель округлил.
    ev.sort(key=lambda x: (int(x[0]), x[1]))
    # Веса внутри часа для руки 1/σ²: риском служит предсказанный ход
    # ПРОТИВ позиции (|mae|) — его межимённый ранг и есть ранг
    # волатильности (замерено: внутри имени величина прогноза пуста,
    # между именами Спирмен до +0.57). Урок S1 переносится дословно:
    # риск снизу ограничен 10-м процентилем СВОЕГО сечения — обратная
    # величина без пола есть ловушка замороженных рядов, и нога с
    # крошечным |mae| забрала бы всю корзину часа. Нога без |mae|
    # получает медианный риск сечения: неизмеренное не есть безопасное.
    w_map = {}
    if sizing == "inv_risk2":
        for hour, legs in per_hour.items():
            rs = [abs(q.get("mae_bp")) for q in legs
                  if q.get("mae_bp")]
            if not rs:
                continue
            rs_sorted = sorted(rs)
            med = rs_sorted[len(rs_sorted) // 2]
            # Пол риска: P10 сечения, но не ниже ПОЛОВИНЫ медианы. На
            # сечении из шести ног P10 равен минимуму и не держит
            # ничего — первый прогон теста это показал: нога с |mae|
            # 0.001 забирала 90 % корзины часа. Вторая скоба — вес не
            # выше ДВУХ равных долей: ограничение структурное и не
            # зависит от того, насколько сечение мало. Недобранный
            # бюджет остаётся в кассе — консервативно, а не размазано.
            p10 = rs_sorted[max(0, int(0.1 * (len(rs_sorted) - 1)))]
            floor = max(p10, 0.5 * med, 1.0)
            inv = []
            for q in legs:
                r = abs(q.get("mae_bp")) if q.get("mae_bp") else med
                inv.append(1.0 / max(r, floor) ** 2)
            tot = sum(inv) or 1.0
            n = len(legs)
            for q, v in zip(legs, inv):
                w_map[id(q)] = min(v / tot, 2.0 / n) * n
    cash, busy, hist = start, 0.0, []
    name_busy = {}
    for _, kind, t in ev:
        if kind == 1:
            n_slots = slots or max(1, len(per_hour[t["hour"]])
                                   * max(1, hold_h or 1))
            want = (cash + busy) / n_slots * w_map.get(id(t), 1.0)
            # Забор: суммарная позиция по имени не выше потолка. Срез
            # виден полем — молчаливое уменьшение читалось бы как
            # пропажа денег, урок «0.25× выглядит поломкой».
            # `name_cap` переопределяется ТОЛЬКО тестами тайминга кассы:
            # их предмет — очередь денег во времени, и потолок, отменяя
            # голодание кассы в их маленьких фикстурах, прятал бы ровно
            # то, что они проверяют. Боевые вызовы аргумент не передают.
            room = ((NAME_CAP_SHARE if name_cap is None else name_cap)
                    * (cash + busy) - name_busy.get(t["sym"], 0.0))
            if want > room + 1e-9:
                t["name_capped"] = True
            want = min(want, max(0.0, room))
            # Больше свободных денег в позицию не положить. Настоящий
            # счёт ведёт себя так же, и молчать об этом нельзя: урезание
            # видно полем `size`.
            size = max(0.0, min(want, cash))
            # Округлять размер НЕЛЬЗЯ: касса уменьшается на настоящую
            # величину, и округлённая копия перестала бы сходиться с
            # ней — двадцать четыре позиции по 41.67 дают 1000.08, то
            # есть гросс выше капитала. Округляет показ.
            t["size"] = size
            cash -= size
            busy += size
            name_busy[t["sym"]] = name_busy.get(t["sym"], 0.0) + size
        else:
            size = t.get("size") or 0.0
            # Издержки считаются ЗДЕСЬ и только здесь, потому что здесь
            # известен размер позиции, а цена исполнения от него
            # зависит. Разбор пишет ФАКТ (движение цены и лесенки), а
            # деньги выводит счёт: иначе завелось бы второе определение
            # размера — ровно то, чего этот модуль избегает.
            ec = exec_cost(t, size, table)
            if ec:
                t.update({k: ec[k] for k in
                          ("fee_bp", "fee_known", "slip_in_bp",
                           "slip_out_bp", "exec_bp", "fill_in",
                           "fill_out", "filled")})
                t["net_bp"] = ec["net_bp"]
                t["cost_basis"] = "книга"
            elif t.get("net_bp") is not None:
                # Старые сделки: плоский круг, записанный разбором.
                # Помечены явно — смешать две основы в одной колонке
                # значило бы сравнивать несравнимое молча.
                t.setdefault("cost_basis", "плоский 11")
            pnl = size * (t.get("net_bp") or 0.0) / 1e4
            t["pnl"] = round(pnl, 2)
            cash += size + pnl
            busy -= size
            name_busy[t["sym"]] = max(
                0.0, name_busy.get(t["sym"], 0.0) - size)
            hist.append({"hour": t["hour"], "sym": t["sym"],
                         "pnl": round(pnl, 2),
                         "balance": round(cash + busy, 2)})
    return hist, round(cash + busy, 2)


def dd_money(trades, deposit=START_BALANCE):
    """Просадку — в деньгах и в долях ДЕПОЗИТА, а не позиции.

    Решение владельца, и причина видна на живом числе: шорт HFT показал
    −47.67 %, что читается как «потеряли половину», тогда как позиция
    составляет 1/24 счёта и в деньгах это −19.90 $, то есть 2 % депозита.
    Процент от позиции — факт о ЦЕНЕ, процент от депозита — факт о
    СЧЁТЕ, и решения принимаются по второму.

    Знаменателем взят стартовый депозит, а не текущий баланс: одна и та
    же прошлая сделка не должна менять свою просадку оттого, что счёт с
    тех пор вырос. Числитель — размер позиции, проставленный счётом;
    своей арифметики размера здесь нет.

    Сделка без размера остаётся без денежной просадки: ноль вместо
    неизвестного был бы наблюдением, которого не было.
    """
    n = 0
    for t in trades:
        dd, size = t.get("dd_bp"), t.get("size")
        if dd is None or not size or not deposit:
            continue
        t["dd_usd"] = round(size * dd / 1e4, 2)
        # В б.п. депозита — той же единице, в которой страница показывает
        # всё прочее, поэтому показ не заводит второго преобразования.
        t["dd_cap_bp"] = round(dd * size / deposit, 1)
        n += 1
    return n


def summary(trades, arm=None, capital=None, start=None):
    """Сводка: закрытые — фактом, открытые — переоценкой.

    Закрытые и открытые считаются РАЗДЕЛЬНО и никогда не смешиваются в
    одну цифру. У закрытой исход известен, у открытой это лишь текущая
    отметка, которая до срока может стать любой; сложить их значило бы
    выдать незавершённое за результат.

    Размер позиции для нереализованных денег берётся так же, как его
    берёт разбор: баланс делится на число позиций ТОГО ЖЕ часа. Иначе
    получилось бы второе определение размера позиции, и деньги на
    странице разошлись бы с деньгами в счёте.
    """
    rows = [t for t in trades
            if (arm is None or t["arm"] == arm)]
    closed = [t for t in rows if t["state"] == "закрыта"]
    op = [t for t in rows if t["state"] == "открыта"]
    lost = [t for t in rows if t["state"] == "без исхода"]
    wait = [t for t in rows if t["state"] == "ждёт разбора"]
    # Живой выход, ещё не разобранный циклом: состояние существует с
    # тех пор, как сторож стал закрывать позиции секундами, а в сводке
    # его не было — счётчики не сходились с числом сделок, и владелец
    # честно прочёл это как «показывает не все». Считать его закрытым
    # нельзя: денег у него пока нет.
    exiting = [t for t in rows if t["state"] == "вышла, ждёт разбора"]
    out = {"closed": len(closed), "open": len(op),
           "no_outcome": len(lost), "awaiting": len(wait),
           "exiting": len(exiting),
           # Сколько сделок всего у этой руки — чтобы столбики можно
           # было сложить и получить именно его, а не гадать.
           "trades": len(rows)}
    _unreal(rows, out, capital)
    _dd(rows, out)
    # Подарок входа считается по ВСЕМ сделкам, а не только закрытым:
    # он известен в момент открытия и от исхода не зависит вовсе.
    # Издержки — разложением, а не одним числом. Комиссию задаёт тариф
    # символа, проскальзывание — толщина книги, и лечатся они разным:
    # первое выбором инструментов, второе размером и частотой.
    ex = [t for t in closed if t.get("exec_bp") is not None]
    if ex:
        ex.sort(key=lambda t: t["exec_bp"])
        mid_t = ex[len(ex) // 2]
        out["exec_n"] = len(ex)
        out["exec_med_bp"] = mid_t["exec_bp"]
        out["exec_avg_bp"] = round(
            sum(t["exec_bp"] for t in ex) / len(ex), 2)
        out["fee_med_bp"] = mid_t["fee_bp"]
        out["slip_med_bp"] = round(mid_t["slip_in_bp"]
                                   + mid_t["slip_out_bp"], 2)
        # Сколько сделок посчитано по НАСТОЯЩЕЙ ставке, а не по
        # умолчанию, и у скольких заявка не влезла в записанную книгу.
        out["fee_known"] = sum(1 for t in ex if t.get("fee_known"))
        out["exec_partial"] = sum(1 for t in ex if not t.get("filled"))
        out["cost_flat"] = sum(1 for t in closed
                               if t.get("cost_basis") == "плоский 11")
    have = [t for t in rows if t.get("gift_bp") is not None]
    if have:
        gifts = sorted(t["gift_bp"] for t in have)
        out["gift_n"] = len(gifts)
        out["gift_med_bp"] = gifts[len(gifts) // 2]
        out["gift_avg_bp"] = round(sum(gifts) / len(gifts), 1)
        lags = sorted(t["lag_sec"] for t in have
                      if t.get("lag_sec") is not None)
        out["gift_lag_med"] = lags[len(lags) // 2] if lags else None
    if not closed:
        return out
    # Знаменатель «знака» — сделки, дошедшие до уровня. У книг со
    # сроком (1/4/24 ч) уровней в выходе нет вовсе, там причина пуста и
    # знаменателем остаются все закрытые: смысл меры там другой —
    # «куда ушла цена за горизонт».
    lvl = [t for t in closed if by_level(t)]
    base = lvl if lvl else closed
    out["hit_basis"] = "levels" if lvl else "all"
    out["hit_n"] = len(base)
    # Прежнее число (по всем закрытым) остаётся рядом: разница между
    # ними и есть цена отменённых сигналов, и прятать её значило бы
    # заменить одну неполную правду другой.
    if lvl:
        out["hit_rate_all"] = round(
            sum(1 for t in closed if t.get("hit")) / len(closed), 3)
    # Сколько сделок каким выходом закрылось — числом, а не догадкой по
    # доле: без этой раскладки «знак угадан у 55 %» не говорит, о
    # скольких сделках речь.
    ex_by = {}
    for t in closed:
        ex_by[t.get("exit_reason") or "срок"] = 1 + ex_by.get(
            t.get("exit_reason") or "срок", 0)
    out["exits"] = ex_by
    hits = sum(1 for t in base if t.get("hit"))
    nets = [t.get("net_bp") for t in closed if t.get("net_bp") is not None]
    pnls = [t.get("pnl") for t in closed if t.get("pnl") is not None]
    exps = [t.get("expected_bp") for t in closed
            if t.get("expected_bp") is not None]
    gots = [t.get("got_bp") for t in closed if t.get("got_bp") is not None]
    out.update(
        hit_rate=round(hits / len(base), 3),
        net_bp_avg=round(sum(nets) / len(nets), 1) if nets else None,
        pnl=round(sum(pnls), 2) if pnls else None,
        expected_avg=round(sum(exps) / len(exps), 1) if exps else None,
        got_avg=round(sum(gots) / len(gots), 1) if gots else None)
    # Раздельно по сторонам. Общий итог молчит о том, какая нога
    # зарабатывает, а это не деталь: книга нейтральна по ЧИСЛУ ног и не
    # нейтральна по бете, и если весь доход приносит одна сторона —
    # перед нами ставка на направление рынка, а не кросс-секция.
    # Проект уже дважды читал такое неверно: в F1 всю книгу вытягивала
    # короткая нога при убыточной длинной, и увидеть это в сумме было
    # нельзя.
    #
    # `start` — знаменатель процента, депозит НА СТАРТЕ. Считать долю
    # от текущего капитала значило бы делить прибыль на неё же саму.
    for side in ("long", "short"):
        s = [t for t in closed if t.get("side") == side]
        p = [t.get("pnl") for t in s if t.get("pnl") is not None]
        n = [t.get("net_bp") for t in s if t.get("net_bp") is not None]
        out[f"n_{side}"] = len(s)
        out[f"pnl_{side}"] = round(sum(p), 2) if p else None
        out[f"pnl_{side}_pct"] = (
            round(100 * sum(p) / start, 2) if p and start else None)
        out[f"net_bp_{side}"] = round(sum(n) / len(n), 1) if n else None
        # Знак по стороне — на том же знаменателе, что общий: иначе
        # стороны считались бы по одной выборке, а итог по другой.
        sb = [t for t in s if by_level(t)] if lvl else s
        out[f"hit_{side}"] = (
            round(sum(1 for t in sb if t.get("hit")) / len(sb), 3)
            if sb else None)
    return out


def _dd(rows, out):
    """Просадка по сделкам: худшая, медианная и сколько их измерено.

    Ведущая единица — доли ДЕПОЗИТА (`*_cap_bp`) и деньги, потому что
    решения принимаются по ним. Процент от позиции остаётся рядом, но
    вторым: −47.67 % от позиции и −1.99 % от депозита — одно и то же
    событие, и путать их нельзя.

    Худшая отвечает на «какую просадку мы держали в моменте», медианная
    — на «а обычно сколько». Разница между ними и есть форма риска: у
    carry она была огромной, и именно это, а не среднее, убило гипотезу.

    Знаменателем служит число ИЗМЕРЕННЫХ сделок, а не всех: у сделки без
    цены входа или без сводок за часы удержания просадки нет, и считать
    её нулём значило бы разбавить статистику выдумкой.
    """
    got = sorted(t["dd_bp"] for t in rows if t.get("dd_bp") is not None)
    out["dd_measured"] = len(got)
    if not got:
        return
    out["dd_worst_bp"] = round(got[0], 1)
    out["dd_med_bp"] = round(got[len(got) // 2], 1)
    # В долях депозита сортировать надо ЗАНОВО: худшая по цене и худшая
    # по деньгам — разные сделки, если размеры позиций различаются.
    cap = sorted((t["dd_cap_bp"], t.get("dd_usd"))
                 for t in rows if t.get("dd_cap_bp") is not None)
    if cap:
        out["dd_worst_cap_bp"] = round(cap[0][0], 1)
        out["dd_worst_usd"] = cap[0][1]
        out["dd_med_cap_bp"] = round(cap[len(cap) // 2][0], 1)
        out["dd_sized"] = len(cap)
    # Открытые отдельно: у них просадка ещё может углубиться, и мешать
    # их с завершёнными значило бы выдавать незаконченное за результат —
    # та же причина, по которой не смешиваются деньги.
    live = sorted(t["dd_cap_bp"] for t in rows
                  if t["state"] == "открыта"
                  and t.get("dd_cap_bp") is not None)
    if live:
        out["dd_open_worst_cap_bp"] = round(live[0], 1)


def _unreal(rows, out, capital):
    """Переоценка открытых — отдельными полями, не смешивая с фактом."""
    op = [t for t in rows if t["state"] == "открыта"]
    # Экспозиция — по ВСЕМ открытым, а не только по переоценённым.
    # Позиция без текущей цены (книга молчит) экспозицию всё равно
    # несёт, и считать её нулём значило бы занижать плечо ровно там,
    # где с инструментом что-то не так.
    exp = sum(t["size"] for t in op if t.get("size"))
    if exp:
        out["exposure"] = round(exp, 2)
        # Сколько часовых наборов книги стоит сейчас. Книга набирается
        # `hold_h` часов, и свежая заполнена на четверть — плечо выходит
        # 0.25 не потому, что что-то сломалось. Без этого числа неполная
        # экспозиция читается как пропавшие деньги: владелец прочитал
        # «500 $» как «депозит стал 500».
        out["fill_hours"] = len({t["hour"] for t in op if t.get("size")})
        out["fill_of"] = HOLD_H
        if capital:
            out["capital"] = round(capital, 2)
            # Плечо — то, ради чего экспозицию и показывают. В долларах
            # она читается неверно, если капиталов несколько: у двух
            # рук по тысяче, и 1504 $ на вкладке «обе» — это 0.75, а
            # вовсе не полтора плеча.
            out["leverage"] = round(exp / capital, 2)
    marked = [t for t in op if t.get("unreal_net_bp") is not None]
    out["marked"] = len(marked)
    if not marked:
        return
    nets = [t["unreal_net_bp"] for t in marked]
    out["unreal_net_avg_bp"] = round(sum(nets) / len(nets), 1)
    out["unreal_win"] = round(
        sum(1 for v in nets if v > 0) / len(nets), 3)
    # Деньги — по тому же размеру позиции, что проставил счёт. Своя
    # арифметика здесь была бы вторым определением размера, и сумма на
    # странице разошлась бы с суммой в счёте.
    sized = [t for t in marked if t.get("size")]
    if sized:
        out["unreal_pnl"] = round(
            sum(t["size"] * t["unreal_net_bp"] / 1e4 for t in sized), 2)


def hour_rows(sum_dir, pairs):
    """Цена часа из почасовых сводок: `{(символ, час): {c, hi, lo}}`.

    Один загрузчик на всё, что берётся из сводок: и цена входа, и путь
    внутри удержания. Второй обход тех же файлов был бы вторым
    определением «цены часа» — ровно то, чего в проекте не заводят.

    `hi` и `lo` — крайние значения середины стакана за час, снятые из
    посекундных снимков. Значит просадка по ним есть **нижняя** оценка:
    ход внутри секунды в снимок не попал.

    Читаются только нужные символо-дни, а не весь каталог: сделок
    десятки, и обходить сводки целиком ради них незачем.
    """
    want = {}
    for sym, hour in pairs:
        if not sym or not hour:
            continue
        want.setdefault((sym, hour[:10]), set()).add(hour)
    out = {}
    for (sym, day), hours in want.items():
        path = os.path.join(sum_dir, sym, day + ".jsonl")
        try:
            with open(path, encoding="utf-8") as f:
                for line in f:
                    try:
                        r = json.loads(line)
                    except ValueError:
                        continue
                    h = r.get("hour")
                    if h in hours and r.get("mid_close"):
                        c = float(r["mid_close"])
                        # Поздняя строка часа побеждает — тот же порядок,
                        # что при сборке матриц.
                        out[(sym, h)] = {
                            "c": c,
                            "hi": float(r.get("mid_high") or c),
                            "lo": float(r.get("mid_low") or c)}
        except OSError:
            continue
    return out


def entry_prices(sum_dir, pairs):
    """Цены входа: `{(символ, час): цена}` — закрытие часа сигнала.

    Цена входа уже лежит в сводке полем `mid_close`. Значит записывать
    её в выбор было удобством, а не необходимостью: у выборов, сделанных
    до того, как поле появилось, цена НЕ потеряна — её надо прочитать.
    """
    return {k: v["c"] for k, v in hour_rows(sum_dir, pairs).items()}


def live_hours(t, hold_h=HOLD_H, now=None):
    """Часы, которые позиция прожила: от `час+1` до часа закрытия.

    Вход — на закрытии часа сигнала, то есть позиция живёт со следующего
    часа. У открытой сделки берутся только ЗАКРЫВШИЕСЯ часы: текущий час
    ещё пишется, и его крайние значения будут другими через минуту.
    """
    h0 = _ts(t.get("hour"))
    if h0 is None:
        return []
    now = now if now is not None else time.time()
    last_done = (now // 3600) * 3600            # начало текущего часа
    # Конец жизни: своё закрытие, если оно известно, иначе полный
    # горизонт. У сделки, закрытой раньше срока (ситуационная книга),
    # часы после выхода — не её часы: мерить по ним просадку значило
    # бы приписать позиции путь, которого она не держала.
    end = t.get("closes_at") or (h0 + (max(1, hold_h or 1) + 1) * 3600)
    out = []
    i = 1
    while True:
        ts = h0 + i * 3600
        if ts + 3600 > end or ts >= last_done:  # час не в жизни сделки
            break
        out.append(_hour_of(ts))
        i += 1
    return out


def excursion(trades, rows, hold_h=HOLD_H, now=None):
    """Худший ход ПРОТИВ позиции за время удержания, в б.п.

    Отвечает на вопрос «какую просадку мы держим в моменте»: итог сделки
    говорит, чем всё кончилось, и ничего не говорит о том, сколько
    позиция была в минусе по дороге. У лонга это минимум середины, у
    шорта максимум — стороны считаются раздельно, иначе у шорта
    благоприятный ход был бы записан как просадка (эта ошибка в проекте
    уже случалась с колонкой `mae`).

    Величина ВСЕГДА ≤ 0 и берётся брутто: издержки платятся один раз на
    круг, а просадка — это то, что видно на позиции по дороге.

    Час без сводки не считается нулём — он просто не входит в замер, и
    число покрытых часов пишется рядом полем `dd_hours`. Ноль вместо
    пропуска был бы наблюдением, которого не было.
    """
    n = 0
    for t in trades:
        px0 = t.get("entry_px")
        if not px0:
            continue
        worst, at = None, None
        seen = 0
        for h in live_hours(t, hold_h, now):
            r = rows.get((t.get("sym"), h))
            if not r:
                continue
            seen += 1
            px = r["lo"] if t.get("side") == "long" else r["hi"]
            move = (px / px0 - 1.0) * 1e4
            adv = move if t.get("side") == "long" else -move
            if worst is None or adv < worst:
                worst, at = adv, h
        t["dd_hours"] = seen
        if worst is None:
            continue
        # Позиция, ни разу не уходившая в минус, имеет просадку ноль, а
        # не положительную величину: «просадка» есть ход против, и вверх
        # она не бывает.
        t["dd_bp"] = round(min(0.0, worst), 1)
        t["dd_at"] = at
        n += 1
    return n


def equity(trades, arm, rows, start=START_BALANCE, hold_h=HOLD_H,
           cost_bp=ROUND_COST_BP, now=None):
    """Почасовая кривая счёта С УЧЁТОМ открытых позиций.

    Кривая по одним закрытиям систематически льстит: позиция, уходившая
    в минус на 40 % и вернувшаяся, входит в неё мелким убытком, и
    просадка счёта выходит меньше пережитой. Здесь каждый час все живые
    позиции переоцениваются по закрытию этого часа — это и есть «сколько
    мы держали в моменте».

    Переоценка НЕТТО, как и у открытых сделок на странице: реализованный
    результат уже за вычетом круга, и брутто-отметка давала бы скачок
    вниз ровно в момент закрытия — разрыв кривой на ровном месте.

    Час, в котором хоть одну живую позицию переоценить нечем, помечается
    `full = False`: считать пропущенную ногу нулём значило бы занизить
    просадку там, где по инструменту как раз нет данных.
    """
    rowsa = [t for t in trades
             if t["arm"] == arm and t.get("opened_at") is not None]
    if not rowsa:
        return []
    alive = {}                                  # час → живые сделки
    closed_at = {}                              # час → закрытые в нём
    for t in rowsa:
        for h in live_hours(t, hold_h, now):
            alive.setdefault(h, []).append(t)
        if t["state"] == "закрыта" \
                and (t.get("closes_at") or t.get("review_at")):
            closed_at.setdefault(
                _hour_of(t["closes_at"] - 1), []).append(t)
    out, bal = [], start
    for h in sorted(set(alive) | set(closed_at)):
        for t in closed_at.get(h, []):
            bal += t.get("pnl") or 0.0
        mark_sum, full = 0.0, True
        for t in alive.get(h, []):
            if t in closed_at.get(h, []):
                continue                        # уже в балансе
            r = rows.get((t["sym"], h))
            size = t.get("size") or 0.0
            if not r or not t.get("entry_px") or not size:
                if size:
                    full = False
                continue
            move = (r["c"] / t["entry_px"] - 1.0) * 1e4
            adv = move if t["side"] == "long" else -move
            mark_sum += size * (adv - cost_bp) / 1e4
        out.append({"hour": h, "eq": round(bal + mark_sum, 2),
                    "cash": round(bal, 2), "open": len(alive.get(h, [])),
                    # Переоценка ВСЕЙ живой книги на этот час. Из неё
                    # берётся «сколько мы держали в минусе одновременно»,
                    # и считать её отдельным проходом было бы вторым
                    # определением одной величины.
                    "op": round(mark_sum, 2),
                    "full": full})
    return out


def worst_open(curve, deposit=START_BALANCE):
    """Худший момент по КНИГЕ: все открытые позиции разом.

    Просьба владельца, и разница с худшей сделкой настоящая. Одна
    сделка на −2 % депозита — это одна сделка; двадцать четыре позиции,
    одновременно стоящие −8 %, — это состояние счёта, и переживать
    приходится именно его. Совпадать эти числа не обязаны: худшая сделка
    может случиться в час, когда остальные в плюсе и книга в целом
    спокойна.

    Позиции складываются СО ЗНАКОМ: прибыльные гасят убыточные, потому
    что в этот момент на счёте лежит именно сальдо. Сумма одних лишь
    убыточных была бы не просадкой, а валовым убытком — величиной,
    которой счёт никогда не видел.
    """
    if not curve:
        return None
    w = min(curve, key=lambda p: p.get("op", 0.0))
    op = w.get("op", 0.0)
    out = {"usd": round(op, 2), "hour": w["hour"], "open": w.get("open"),
           "full": w.get("full", True)}
    if deposit:
        out["cap_bp"] = round(op / deposit * 1e4, 1)
    return out


def thin(curve, cap=600):
    """Кривая для показа: не длиннее `cap` точек, без потери провалов.

    Прореживать «каждую k-ю точку» нельзя: просадка живёт между
    выборками и пропадает целиком, а именно её и смотрят. Поэтому в
    каждой корзине сохраняются ТРИ величины — значение на конце, а
    также минимум и максимум внутри. Тогда линия остаётся линией, а
    провал виден полосой, и картинка не врёт о пережитом.

    Возвращает `[[метка времени, эквити, минимум, максимум], …]`.
    """
    if not curve:
        return []
    step = max(1, (len(curve) + cap - 1) // cap)
    out = []
    for i in range(0, len(curve), step):
        part = curve[i:i + step]
        eqs = [p["eq"] for p in part]
        ts = _ts(part[-1]["hour"])
        if ts is None:
            continue
        out.append([int(ts), round(part[-1]["eq"], 2),
                    round(min(eqs), 2), round(max(eqs), 2)])
    return out


def merge(curves):
    """Общая кривая нескольких счетов: сумма по часам.

    Час, в котором у одной руки записи нет, берётся её последним
    известным значением, а не нулём: рука со счётом в тысячу не
    перестаёт стоить тысячу оттого, что в этот час у неё не было сделок.
    """
    curves = [c for c in curves if c]
    if not curves:
        return []
    hours = sorted({p["hour"] for c in curves for p in c})
    idx = [{p["hour"]: p for p in c} for c in curves]
    last = [None] * len(curves)
    out = []
    for h in hours:
        tot, op, opn, full, known = 0.0, 0, 0.0, True, False
        for i, m in enumerate(idx):
            p = m.get(h) or last[i]
            if p is None:
                continue          # рука ещё не начинала — её тут нет
            known = True
            if h in m:
                last[i] = m[h]
            tot += p["eq"]
            # Баланс переносится, переоценка — НЕТ. Часа нет в кривой
            # руки ровно тогда, когда у неё в этот час не было живых
            # позиций, то есть открытая переоценка равна нулю, а не
            # прошлой величине. Перенести её значило бы держать призрак
            # закрытой позиции в просадке книги.
            if h in m:
                op += p["open"]
                opn += p.get("op", 0.0)
            full = full and p.get("full", True)
        if known:
            out.append({"hour": h, "eq": round(tot, 2), "open": op,
                        "op": round(opn, 2), "full": full})
    return out


def max_dd(curve):
    """Максимальная просадка кривой: доля от достигнутого максимума.

    `from` — вершина, ОТ которой считается записанная просадка, а не
    последняя вершина кривой. Разница появляется ровно тогда, когда счёт
    после провала обновил максимум: тогда бегущая вершина уезжает вперёд
    и пара «от / до» читается задом наперёд (у боевой руки так и вышло —
    `from` 08-05-01 при `at` 08-04-17). Глубина при этом всегда была
    верна, врало только место.
    """
    if not curve:
        return None
    peak, depth, at, top, top_now = None, 0.0, None, None, None
    for p in curve:
        eq = p["eq"]
        if peak is None or eq > peak:
            peak, top_now = eq, p["hour"]
        if peak and eq < peak:
            d = eq / peak - 1.0
            if d < depth:
                depth, at, top = d, p["hour"], top_now
    if at is None:
        return {"pct": 0.0, "at": None, "from": top_now, "hours": len(curve)}
    return {"pct": round(depth * 100.0, 2), "at": at, "from": top,
            # Длина кривой, а не длительность просадки: часов под водой
            # это число не считает и называться ими не должно.
            "hours": len(curve),
            # Час, где хоть одну живую ногу переоценить было нечем,
            # делает просадку заниженной — и молчать об этом нельзя.
            "gaps": sum(1 for p in curve if not p.get("full"))}


def mark(trades, prices, cost_bp=ROUND_COST_BP):
    """Проставить открытым сделкам нереализованный результат.

    `prices` — текущая цена по символу (середина стакана). Считается
    здесь, а не на странице: формула одна на весь проект, и вторая её
    запись в JavaScript однажды разошлась бы с той, по которой ведётся
    счёт.

    Величина в базисных пунктах, как и всё остальное внутри; в проценты
    её переводит показ. Нетто — за вычетом круга издержек: открытая
    сделка, показанная брутто, выглядит лучше, чем закроется, а разница
    как раз в размере типичного движения за четыре часа.
    """
    n = 0
    for t in trades:
        if t.get("state") != "открыта":
            continue
        px0, px1 = t.get("entry_px"), prices.get(t.get("sym"))
        if not px0 or not px1:
            continue
        raw = (px1 / px0 - 1.0) * 1e4
        t["cur_px"] = px1
        t["unreal_bp"] = round(raw if t["side"] == "long" else -raw, 1)
        t["unreal_net_bp"] = round(t["unreal_bp"] - cost_bp, 1)
        n += 1
    return n


def by_symbol(trades, sym):
    """Сделки одной монеты — для меток на её графике."""
    return [t for t in trades if t.get("sym") == sym]
