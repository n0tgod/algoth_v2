#!/usr/bin/env python3
"""
R4 — издержки на фактическом обороте книги. Ядро расчёта.

Спека 03, раздел 6. Здесь только арифметика: веса книги, оборот при
ребалансе, комиссия, funding. Ни диска, ни базы.

Единица измерения — и почему это первое, что здесь написано
-----------------------------------------------------------

**Всё выражается в долях ГРОСС-нотионала книги**, то есть суммы модулей
позиций по всем ногам, нормированной на единицу.

    Σ|w_i| = 1

При дециле из 300 активов это 30 лонгов по +1/60 и 30 шортов по −1/60.

Из этого следует:

    прибыль за период  = Σ w_i · форвард_i  =  ½ · спред дециля
    комиссия за период = Σ |Δw_i| · тейкер_i
    полная замена книги: Σ|Δw_i| = 2, то есть 11 б.п. при тейкере 5.5

Множитель ½ в первой строке — не описка. Спред дециля есть разность
средних по ногам, то есть величина «на ногу»; книга же держит две ноги
одновременно, и капитал делится между ними. В отчёте R2 §8.2 спред
сравнивался с «циклом издержек 26 б.п.» — две величины в разных
единицах, спред на ногу против цикла на пару ног. Вердикт от этого не
менялся (в общей единице выходило около шести крат вместо 5.6), но
число было нестрогим, и здесь оно пересчитывается честно.

Что входит в издержки и чего в них нет
--------------------------------------

**Комиссия — посимвольная.** A1 намерила разброс вчетверо: тейкер
5.5 б.п. у 396 символов, 2.75 у 137, 11.0 у 115. Средняя ставка по
универсуму подставляться не должна.

**Ставка делистнутой ноге назначается правилом, а не берётся из
данных.** Площадка прошлых тарифных сеток не отдаёт вовсе; ставки нет у
36.7 % крипто-активов универсума. Правило и его обоснование — раздел 6
спеки; здесь реализация.

**Исполнение считается тейкерным.** Допущение «коснулись — значит
исполнились» запрещено прямо: это была ошибка движка v1. Пассивное
исполнение дало бы лучшие числа, но требует калибровки вероятности
исполнения по тикам, а она отложена в `IDEAS.md` и делается только по
выжившим конструкциям.

**Проскальзывания сверх тейкера в базовом прогоне нет.** Оно не
выдумывается: §5.4 спеки 02 запрещает тиковый расчёт по всему
универсуму. Его роль играет обязательный прогон с издержками ×1.5
(критерий §8.3 п. 9) — там же сидит неблагоприятный отбор и всплески в
стрессе.
"""

import numpy as np


def weights(score, fwd, width):
    """Веса книги на одну дату. Сумма модулей равна единице.

    Ноги равны по деньгам — это и есть нейтральность по построению
    (§4 спеки): направление рынка убирается арифметикой, а не оценкой.

    Активы без сигнала либо без форварда веса не получают: торговать
    то, чего не наблюдали, нельзя.
    """
    w = np.zeros(len(score))
    m = ~(np.isnan(score) | np.isnan(fwd))
    n = int(m.sum())
    k = int(n * width)
    if k < 1:
        return w, 0
    orig = np.flatnonzero(m)
    idx = np.argsort(score[m], kind="mergesort")
    w[orig[idx[-k:]]] = +0.5 / k          # лонг: половина гросса на k имён
    w[orig[idx[:k]]] = -0.5 / k           # шорт: вторая половина
    return w, k


def align(names_a, w_a, names_b, w_b):
    """Два вектора весов на общем множестве имён, в одном порядке."""
    order = sorted(set(names_a) | set(names_b))
    pos = {s: i for i, s in enumerate(order)}
    a = np.zeros(len(order))
    b = np.zeros(len(order))
    for s, x in zip(names_a, w_a):
        a[pos[s]] = x
    for s, x in zip(names_b, w_b):
        b[pos[s]] = x
    return order, a, b


def turnover(names_prev, w_prev, names_now, w_now):
    """Оборот ребаланса: `(имена, |Δw| по именам, сумма)`.

    Считается по разности весов, а не как «книга обновилась целиком».
    Имя, оставшееся в той же ноге, не торгуется вовсе, а перевернувшееся
    из лонга в шорт торгуется двойным объёмом. Допущение «шестьдесят ног
    на каждый ребаланс» завышало бы издержки тем сильнее, чем длиннее
    окно сигнала: при k = 14 сигнал за сутки почти не меняется.
    """
    order, a, b = align(names_prev, w_prev, names_now, w_now)
    d = np.abs(b - a)
    return order, d, float(d.sum())


def commission(names, delta, rate_of):
    """Комиссия за ребаланс, доля гросс-нотионала.

    `rate_of(symbol)` возвращает тейкерную ставку в долях (0.000055 при
    5.5 б.п.). Ставка посимвольная: подставлять среднюю по универсуму
    нельзя, разброс вчетверо.
    """
    c = 0.0
    for s, d in zip(names, delta):
        if d > 0:
            c += d * rate_of(s)
    return c


def funding_cost(names, w, accrued_of):
    """Funding за период удержания, доля гросс-нотионала.

    `accrued_of(symbol)` — сумма начисленных ставок за период
    удержания. Положительная ставка означает, что платит лонг, поэтому
    в издержки идёт `+w·ставка` для лонга и `−|w|·ставка` для шорта, то
    есть `Σ w_i · ставка_i` со знаком «расход».

    Шорт при положительной ставке funding ПОЛУЧАЕТ. У книги, равной по
    деньгам с обеих сторон, общий funding равен дифференциалу ног, а не
    сумме — и знак его заранее неизвестен. Это измеряется, а не
    предполагается.
    """
    tot = 0.0
    for s, x in zip(names, w):
        if x == 0.0:
            continue
        a = accrued_of(s)
        if a is None:
            continue
        tot += x * a
    return tot


def quintile_expected_rate(turnovers, table, cheap, expensive, fallback):
    """Ожидаемая ставка по квинтилю оборота — правило раздела 6.

    Черновик спеки предлагал плоскую дорогую ставку как консервативную;
    замер это опроверг. Дорогой тариф действительно признак тонкого
    инструмента (его доля падает по квинтилям оборота 43 → 5 %), но сами
    активы без ставки распределены по квинтилям почти ровно. Плоская
    дорогая ставка назначила бы дорогой тариф и половине ликвидных имён,
    то есть систематически завышала бы издержки.

    Возвращает список ставок по позициям `turnovers`. Актив без
    измеримого оборота получает `fallback`: отсутствие оборота само по
    себе есть признак тонкости.
    """
    known = [(t, i) for i, t in enumerate(turnovers) if t is not None and t > 0]
    out = [fallback] * len(turnovers)
    if not known:
        return out
    known.sort()
    n = len(known)
    for rank, (_, i) in enumerate(known):
        q = min(4, rank * 5 // n)
        p = table[q]
        out[i] = p * expensive + (1.0 - p) * cheap
    return out


def net_spread(gross_spread, cost):
    """Прибыль за период нетто, доля гросс-нотионала.

    Множитель ½ переводит спред дециля («на ногу») в доход книги,
    которая держит обе ноги одновременно.
    """
    return 0.5 * gross_spread - cost
