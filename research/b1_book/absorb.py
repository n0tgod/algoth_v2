#!/usr/bin/env python3
"""
Поглощение в стакане: крупный стоит, его выедают, он подставляет снова.

Чем это отличается от всего, что стенд мерил раньше
---------------------------------------------------

Четыре замера направления ленты (T1–T4) считались по **принтам** — по
состоявшимся сделкам. По ним «крупного выкупают» и «продавцы кончились
сами» выглядят одинаково: в обоих случаях виден объём и стоящая цена.
Различает их только очередь заявок, а её в архивах нет ни у Bybit, ни у
Binance. Поэтому стакан пишется живьём, и поэтому здесь появляется
условие, которое на ленте не выражается в принципе.

Ключевая величина — **выедено против показанного**. Если через уровень
прошло агрессии больше, чем он когда-либо показывал размером, значит
его подставляли заново. Лента даёт числитель и не даёт знаменателя.

Правило входа, пять условий сразу
---------------------------------

Каждую секунду по каждому символу берётся самый крупный по нотионалу
уровень своей стороны в пределах хода, который цена реально прошла
за последние `HOLD` секунд. Дальше — недосягаемо, а недосягаемый
уровень поглощаться не может.

1. **Крупный** — его нотионал не меньше `BIG` от того, каким этот
   уровень обычно бывает **у этого же инструмента**: берётся медиана
   такого же замера за последние `CAL` секунд.

   Первая версия сравнивала с медианой соседних уровней, и живой прогон
   это убил за минуту: у BTCUSDT вышло 186×, у ETHUSDT 37×, а у всех
   шести альтов 1.1–2.7×, то есть порога 5 они не достигали никогда.
   Дело не в рынке, а в дробности котирования — двести уровней BTC
   стоят в четырёх базисных пунктах и почти все они пыль, а полсотни
   уровней альта размазаны на 63 б.п. и каждый весом. Мера, относительная
   к соседям, оказалась НЕ инвариантна к тому, как мелко нарезан стакан;
   мера, относительная к собственному прошлому, инвариантна. Тот же
   приём, которым T1 чинил порог объёма.

   Подозрение, что новая мера сглаживает всплеск (максимум делится на
   медиану того же максимума), замером НЕ подтвердилось: разброс обеих
   мер внутри каждого символа совпадает до второго знака (ARBUSDT 0.11
   против 0.12, ETHUSDT 0.32 против 0.32, BTCUSDT 0.65 против 0.68) —
   деление ряда на его же медиану не меняет форму ряда. Значит узкое
   распределение есть свойство рынка, а не прибора.

   **Множитель тоже пришлось убрать, и убил его тот же довод, что и
   первую версию — только на два шага глубже.** Замер по всем 25
   символам (1250 наблюдений за десять минут живого сбора) дал в
   агрегате медиану 1.02, 90-й процентиль 1.47, 99-й 5.08 — то есть
   порог 2.0 берут 4.4 % моментов, ровно как задумано. Но в разрезе по
   символам оказалось, что эти 4.4 % дают **шесть инструментов из
   двадцати пяти**: у BTC, ETH, HYPE, TAO, H и BEAT максимум 2.1–9.0, а
   у остальных девятнадцати (SOL, ADA, BNB, DOGE, LINK, 1000PEPE, SUI,
   WLD…) максимум за те же десять минут — 1.1–1.9, то есть гейт для них
   закрыт наглухо.

   Причина не в масштабе, а в РАЗБРОСЕ: у инструмента с ровной глубокой
   книгой самый крупный уровень всегда примерно одинаков, и отношение к
   собственной медиане не отходит от единицы; у инструмента с рваной
   книгой изредка встаёт кит и даёт 9×. Множитель инвариантен к
   масштабу и НЕ инвариантен к разбросу.

   Поэтому гейт задан **квантилью собственного прошлого**: крупным
   считается уровень, который крупнее `QBIG` доли того, что этот
   инструмент показывал за `CAL` секунд. Тогда частота срабатывания
   одинакова у всех по построению, а это то, что нужно кросс-секции:
   T1 уже намерил, что на нескольких символах контроль не строится
   вовсе.

   Возражение против квантили честное и записано здесь же: она
   срабатывает с объявленной частотой ВСЕГДА, даже когда ничего
   особенного не происходит. Ответ в том, что это гейт, а не сито —
   отсеивать должны «стоит», «выедают» и «восполнен». Множитель
   остаётся в диагностике (`big_x`), потому что читать его глазом
   удобнее, чем ранг.
2. **Стоит** — та же цена держится крупной `HOLD` секунд подряд.
   Сменилась цена или уровень измельчал — отсчёт с нуля.
3. **Выедают** — накопленная агрессия противоположной стороны с момента
   появления уровня не меньше `EAT` его размера.
4. **Не пробит** — сделок ниже уровня (для бида) не проходило.
   Пробой виден по ленте, а не по книге: у бида лучшая цена по
   построению не бывает ниже уровня, лежащего в этом же биде.
5. **Восполнен** — текущий размер не меньше `REFILL` от максимума,
   который уровень показывал.

Все пять — поглощение на стороне бида даёт лонг, на стороне аска шорт.

Чем это НЕ является
-------------------

Это наблюдение, а не гипотеза: порогов, объявленных заранее и
неизменных, здесь нет, и вердикта по этим сделкам не выносится. Пороги
подбираются глядя на диагностику — законно ровно потому, что никакого
вывода на них не строится. Вывод потребует спеки с объявленной сеткой,
нулевой моделью и замером на накопленных файлах, а не на памяти
процесса.

Оговорка, которую нельзя терять: агрессия считается **посекундно**, а
не по каждому принту, и приписывается уровню, когда цена секунды до
него дотянулась. На снимке раз в секунду точнее нельзя. Значит `EAT`
считается с точностью до секунды, и очень быстрые серии «удар —
восполнение» внутри секунды видны только в сыром потоке.

Только стандартная библиотека.
"""

import math
from collections import deque
from statistics import median

QBIG = 0.98                       # крупный = выше этой доли своего прошлого
BIG = 2.0                         # множитель, оставлен диагностикой
HOLD = 10                         # столько секунд подряд держится крупным
EAT = 1.0                         # выедено не меньше стольких его размеров
REFILL = 0.5                      # текущий размер к максимальному
MIN_LEVELS = 5                    # меньше уровней — медиана бессмысленна
CAL = 900                         # окно калибровки «обычного», секунд
# Квантиль требует больше выборки, чем медиана: при 120 наблюдениях
# 98-я процентиль есть третье по величине значение, то есть шум. При 300
# выше порога стоит уже шесть — оценка грубая, но не выдуманная.
MIN_CAL = 300


def quantile(vals, q):
    """Значение, которого не превышает доля `q` выборки.

    Своя реализация ради того, чтобы правило округления было видно:
    берётся элемент по индексу `ceil(q·n) − 1`, то есть порог сам
    принадлежит выборке. Никакой интерполяции — она создала бы
    значение, которого рынок не показывал.
    """
    s = sorted(vals)
    if not s:
        return None
    return s[max(0, min(len(s) - 1, math.ceil(q * len(s)) - 1))]


class Side:
    """Отслеживание одного кандидата на одной стороне."""

    def __init__(self):
        self.price = None
        self.since = 0.0
        self.peak = 0.0
        self.eaten = 0.0
        self.size = 0.0
        self.held = 0
        self.pierced = False

    def reset(self, price, size, now):
        self.price, self.since = price, now
        self.peak = self.size = size
        self.eaten = 0.0
        self.held = 0
        self.pierced = False

    def state(self):
        return {"price": self.price, "held": self.held,
                "size": round(self.size, 2), "peak": round(self.peak, 2),
                "eaten": round(self.eaten, 2),
                "eaten_x": (round(self.eaten / self.peak, 2)
                            if self.peak > 0 else None),
                "refill": (round(self.size / self.peak, 2)
                           if self.peak > 0 else None)}


def biggest(levels, best, reach, long):
    """Самый крупный по нотионалу уровень В ДОСЯГАЕМОСТИ цены.

    `reach` — граница, до которой цена реально доходила за последние
    `HOLD` секунд (для бида это минимум, для аска максимум). Уровень
    дальше неё поглощаться не может: до него просто не дотягиваются.

    **Это исправление дефекта, найденного живым замером, а не выбор.**
    Прежняя версия брала полосу `±2 шума` от лучшей цены, где шум —
    медианный ход МИНУТНОЙ свечи. Правило же работает на секундах, и
    величины разошлись на порядок: выбранный уровень стоял в 5.2–18.4
    б.п. от лучшей цены, а типичный глубокий спуск за десять секунд
    удержания — 1.9–7.3 б.п. Ни на одном из десяти проверенных
    символов цена до уровня не доходила, поэтому «выедено» выходило
    ТОЖДЕСТВЕННО нулём (51 замер на 13 символах, медиана 0.0, максимум
    0.0) и правило не могло сработать никогда.

    Ноль, полученный из недостижимости, выглядит ровно как ноль,
    полученный из отсутствия эффекта, — и это тот же класс дефекта, что
    зашитый шаг в загрузчике цен и горизонт короче шага хранилища:
    пустота выдавала себя за измерение.

    Возвращает `(цена, нотионал, медиана нотионала, сколько уровней)`.
    Медиана считается по всем видимым уровням стороны, а не по окну:
    окно узкое, и медиана по нему мерила бы сама себя.
    """
    if not levels or reach is None or reach <= 0:
        return None
    vals = [(p, p * q) for p, q in levels.items() if q > 0]
    if len(vals) < MIN_LEVELS:
        return None
    med = median([v for _, v in vals])
    # Для бида досягаемое — от минимума хода до лучшей цены; для аска
    # зеркально. Полоса строится из РЕАЛИЗОВАННОГО хода на масштабе
    # самого правила, а не из ширины минутной свечи.
    lo, hi = (reach, best) if long else (best, reach)
    near = [(p, v) for p, v in vals if lo <= p <= hi]
    if not near:
        return None
    p, v = max(near, key=lambda x: x[1])
    return p, v, med, len(vals)


class Tracker:
    """Поглощение по обеим сторонам одного инструмента."""

    def __init__(self, symbol):
        self.symbol = symbol
        self.by = {True: Side(), False: Side()}   # True — бид (лонг)
        self.diag = {True: {}, False: {}}
        # «Обычный» крупнейший уровень у этого инструмента: тот же замер,
        # накопленный по времени. Сравнение с собственным прошлым не
        # зависит от дробности котирования, сравнение с соседями зависит.
        self.hist = {True: deque(maxlen=CAL), False: deque(maxlen=CAL)}
        # Докуда доходит цепочка условий и что показывает выедание.
        # Диагностика, а не сигнал: «правило молчит» и «правило молчит
        # ВОТ НА ЭТОМ условии» — разные сообщения, и второе чинится.
        self.reached = {}
        self.eat_seen = deque(maxlen=500)
        # Реализованный ход за окно удержания. Полоса поиска уровня
        # строится из него, а не из ширины минутной свечи: правило
        # работает на секундах, и величины расходятся на порядок.
        self.span = deque(maxlen=HOLD)
        self.last_sec = None

    def reach(self, long):
        """Докуда цена доходила за окно удержания, или `None`."""
        if not self.span:
            return None
        return min(l for _h, l in self.span) if long \
            else max(h for h, _l in self.span)

    def chain(self):
        """Сводка «докуда дошли» для страницы наблюдения."""
        e = sorted(self.eat_seen)
        return {"stage": max(self.reached.values()) if self.reached else 0,
                "eat_n": len(e),
                "eat_med": e[len(e) // 2] if e else None,
                "eat_max": e[-1] if e else None}

    def step(self, bids, asks, sec, now):
        """Шаг на новом снимке книги.

        `sec` — только что закрытая секунда ленты
        `(t, buy_qv, sell_qv, high, low, close)`; из неё берётся
        агрессия, которую уровень принял на себя. Без неё условие
        «выедают» посчитать нечем, и шаг проходит вхолостую.
        """
        if not bids or not asks:
            return
        # Ход ленты за секунду копится ТОЛЬКО когда секунда новая: снимок
        # книги приходит чаще, и складывать одну и ту же секунду значит
        # мерить частоту опроса, а не рынок.
        if sec is not None and (not self.span or sec[0] != self.last_sec):
            self.last_sec = sec[0]
            self.span.append((sec[3], sec[4]))
        best_b, best_a = max(bids), min(asks)
        for long in (True, False):
            side = self.by[long]
            found = biggest(bids if long else asks,
                            best_b if long else best_a,
                            self.reach(long), long)
            if found is None:
                side.reset(None, 0.0, now)
                self.diag[long] = {"why": "цена не доходила до уровней"}
                continue
            price, notional, med, n = found
            h = self.hist[long]
            # Порог берётся по прошлому ДО добавления текущего замера:
            # иначе уровень входит в выборку, по которой его судят, и
            # при узком распределении сам себя приподнимает.
            ready = len(h) >= MIN_CAL
            gate = quantile(h, QBIG) if ready else None
            usual = median(h) if ready else None
            h.append(notional)
            big = gate is not None and gate > 0 and notional >= gate
            if not big or side.price != price:
                if big:
                    side.reset(price, notional, now)
                else:
                    side.reset(None, 0.0, now)
            else:
                side.held += 1
                side.size = notional
                side.peak = max(side.peak, notional)
                if sec is not None:
                    # Агрессия приписывается уровню, когда цена секунды
                    # до него дотянулась: иначе засчитывались бы сделки,
                    # прошедшие в другом конце стакана.
                    reach = (sec[4] <= price) if long else (sec[3] >= price)
                    if reach:
                        side.eaten += sec[2] if long else sec[1]
                    # Пробой виден по ленте, а не по книге: у бида лучшая
                    # цена по построению не бывает ниже уровня, который в
                    # этом биде и лежит, — проверка по книге была бы
                    # недостижимой. Сделка НИЖЕ уровня означает, что его
                    # выели, а не выдержали.
                    if (sec[4] < price) if long else (sec[3] > price):
                        side.pierced = True
            self.diag[long] = self._verdict(long, price, notional,
                                            med, n, usual, gate, len(h))

    def _verdict(self, long, price, notional, med, n, usual, gate, seen):
        s = self.by[long]
        d = {"price": price,
             # Условие — `gate_x`: во сколько раз уровень крупнее порога
             # своей же квантили. `big_x` (к медиане) и `vs_levels` (к
             # соседям) оставлены диагностикой: первый читается глазом,
             # второй помнит, почему сравнение с соседями не годится.
             "gate_x": (round(notional / gate, 2)
                        if gate and gate > 0 else None),
             "big_x": (round(notional / usual, 2)
                       if usual and usual > 0 else None),
             "vs_levels": round(notional / med, 2) if med else None,
             "levels": n, "calib_s": seen, "held": s.held,
             "eaten_x": (round(s.eaten / s.peak, 2) if s.peak > 0 else None),
             "refill": (round(s.size / s.peak, 2) if s.peak > 0 else None),
             "ok": False, "why": ""}
        if s.price is None:
            d["why"] = (f"калибровка {seen}/{MIN_CAL} с"
                        if seen < MIN_CAL
                        else f"не крупный ({d['gate_x']}× порога, "
                             f"{d['big_x']}× медианы)")
            return d
        self.reached[long] = max(self.reached.get(long, 0), 1)
        if s.held < HOLD:
            d["why"] = f"стоит {s.held} с при нужных {HOLD}"
            return d
        self.reached[long] = max(self.reached.get(long, 0), 2)
        # Куда дотягивает выедание у уровней, ДОЖИВШИХ до этой проверки.
        # Без этого «не срабатывает» неотличимо от «срабатывает редко»:
        # опрос живого сборщика поймал максимум 0.27× при нужных 1.0, но
        # выборка была случайной, а не полной. Порог назначать по этому
        # ряду, а не по интуиции.
        if s.peak > 0:
            self.eat_seen.append(round(s.eaten / s.peak, 3))
        if s.peak <= 0 or s.eaten < EAT * s.peak:
            d["why"] = (f"выедено {d['eaten_x']}× при нужных {EAT}")
            return d
        self.reached[long] = max(self.reached.get(long, 0), 3)
        if s.pierced:
            d["why"] = "цена прошла сквозь уровень"
            return d
        if s.size < REFILL * s.peak:
            d["why"] = f"не восполнен ({d['refill']} при нужных {REFILL})"
            return d
        d["ok"] = True
        d["why"] = "поглощение"
        return d

    def signal(self):
        """Сторона, на которой поглощение подтверждено, или `None`."""
        for long in (True, False):
            d = self.diag.get(long) or {}
            if d.get("ok"):
                return long, d["price"], d
        return None
