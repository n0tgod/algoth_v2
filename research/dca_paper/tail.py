#!/usr/bin/env python3
"""Хвост ленты, продолженный серединой стакана: ПРАВИЛО книги.

Зачем
-----

Бары исходов читаются из ЛЕНТЫ (`sweep.read_bars` по `out/trades/<sym>`),
и минута без единой сделки бара не даёт вовсе. Значит у тонкого имени
хвост окна пуст не потому, что цены не было, а потому, что по ней не
торговали: сборщик снимает СТАКАН раз в секунду по каждому записываемому
имени, и середина в те же минуты записана.

Отсюда правило: лента в хвосте продолжается серединой стакана. Позиция,
чьё окно не дошло до планового конца только из-за отсутствия принтов,
получает честный исход по НАБЛЮДЁННЫМ ценам, а не остаётся навсегда
«оборванной записью».

Три правила, каждое объявлено до внедрения
------------------------------------------

1. **Дописывается ТОЛЬКО хвост** — минуты ПОСЛЕ последнего бара ленты в
   запрошенном окне. Внутренние дыры (минуты без сделок внутри окна) не
   заполняются намеренно: по тем же барам считаются вход, структурные
   уровни и цены рунгов, и залив их серединой, мы получили бы не «ту же
   позицию с дописанным концом», а другую позицию.
2. **Середина есть наблюдение, а не оценка.** Минутный бар хвоста
   строится из секундных снимков стакана: открытие — первая середина
   минуты, максимум и минимум — крайние, закрытие — последняя. Момент
   наблюдения снимка — `max(t, ts)` тем же правилом, что у Z2 (метка
   сборщика ставится один раз на проход по именам и у поздних символов
   отстаёт от факта).
3. **Нет книги в хвосте — позиция остаётся оборванной.** Пустой хвост не
   превращается в «срок»: отсутствие свидетельства не есть свидетельство
   отсутствия. Число таких печатается отдельной строкой.

Чего хвост НЕ делает (обе границы держит вызывающий код)
--------------------------------------------------------

- **Вход из хвоста не открывает позицию.** Решение, чей вход пришёлся бы
  на минуту без единого принта, книга пропускает, как пропускала до
  правила: хвост продолжает начатое, а не заводит новых сделок
  (`last_tape` — граница, по которой это решается).
- **Лимитка на баре без принтов не исполняется.** Рунг и тейк исполняет
  чужой принт, и минута без сделок правом на заполнение не является
  (`ladder.simulate_dca`: заполнение требует объёма бара). Пол
  капитуляции, ликвидация и срок — наши собственные рыночные выходы
  против котировки, и они на середине считаются.

Второй копии решения нет: исход считает то же ядро (`run_d6.collect_recs`
через `src=`), меняется только то, ЧЕМ оно накормлено в хвосте.
"""

