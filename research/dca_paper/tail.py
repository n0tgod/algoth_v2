ROOT_B1 = D6.ROOT_B1
HOUR = 3600.0
MINUTE = 60.0


def book_minute_bars(root, sym, t0, t1, log=None):
    """Минутные бары по СЕРЕДИНЕ стакана в окне `[t0, t1]`.

    Формат тот же, что у ленты (`[t, open, high, low, close, объём]`),
    объём ноль: сделок в этой минуте не было, и придумывать их нечем.
    Ноль здесь несёт смысл — по нему ядро отличает котировку от принта и
    не исполняет на ней лимитку. Минута без снимков отсутствует, а не
    выходит нулевой (урок A2).
    """
    by = {}
    h = int(t0 // HOUR) * HOUR
    while h <= t1:
        hh = datetime.fromtimestamp(h, timezone.utc).strftime("%Y-%m-%d-%H")
        rows = read_hour(os.path.join(root, "book", sym), hh, log=log,
                         parse=BF.snap_line)
        for r in rows:
            known, mid = float(r[0]), float(r[1])
            if known < t0 or known > t1 or mid <= 0:
                continue
            m = int(known // MINUTE) * MINUTE
            c = by.get(m)
            if c is None:
                by[m] = [m, mid, mid, mid, mid, 0.0]
            else:
                c[2] = max(c[2], mid)
                c[3] = min(c[3], mid)
                c[4] = mid
        h += HOUR
    return [by[k] for k in sorted(by)]


class TailBars:
    """Бары ленты, продолженные серединой стакана ПОСЛЕ последнего принта.

    Источник передаётся `collect_recs(src=…)` — тем же входом, которым
    туда подаётся любой другой поставщик баров.

    Считает по дороге то, без чего правило нечем проверить: сколько минут
    дописано и каким именам, у кого хвоста нет и в книге, докуда доходит
    ЛЕНТА у каждого имени (`last_tape` — та самая граница, по которой
    вызывающий отличает продолжение позиции от входа из котировки), и
    сколько баров ЛЕНТЫ пришло с нулевым объёмом (их не должно быть
    вовсе: бар ленты рождается из принтов, и ноль там означал бы, что
    признак «принт был» перестал различать).
    """

    def __init__(self, root=ROOT_B1, log=None):
        self.root = root
        self.log = log
        self.added = {}        # символ → число дописанных минут
        self.dry = []          # символы, у которых хвоста нет и в книге
        self.span_h = {}       # символ → длина дописанного хвоста, часов
        self.last_tape = {}    # символ → время последнего бара ЛЕНТЫ
        self.last_book = {}    # символ → последняя ДОПИСАННАЯ минута книги
        self.zero_vol = 0      # баров ленты с нулевым объёмом

    def bars(self, sym, t0, t1):
        tape = SW.read_bars(self.root, sym, t0, t1)
        if not tape:
            # Ленты нет вовсе — значит нет ни входа, ни уровней. Такую
            # позицию досчитывать не из чего, и подменять её книгой
            # значило бы построить другую сделку, а не дописать эту.
            return tape
        self.zero_vol += sum(1 for b in tape if float(b[5]) <= 0)
        last = float(tape[-1][0])
        self.last_tape[sym] = last
        # Хвост начинается со СЛЕДУЮЩЕЙ минуты: бар ленты минутно
        # выровнен, и минута самого последнего принта остаётся за
        # лентой целиком. Взяв `last`, мы получили бы ту же минуту
        # дважды — раз принтами, раз котировкой, — и это был бы не
        # дописанный хвост, а подмена последнего бара. Границей служит
        # ровно это число: отдельной проверки «бар позже последнего»
        # здесь нет, потому что она была бы мёртвым кодом (тот же класс,
        # что декоративная привязка сделки к интервалу в Z3).
        add = book_minute_bars(self.root, sym, last + MINUTE, t1,
                               log=self.log)
        if add:
            self.added[sym] = self.added.get(sym, 0) + len(add)
            self.span_h[sym] = round((t1 - last) / HOUR, 2)
            # докуда дотянулась КНИГА: по этому числу позиция, оставшаяся
            # оборванной, называет свою причину, а не молчит
            self.last_book[sym] = max(self.last_book.get(sym, 0.0),
                                      float(add[-1][0]))
        else:
            self.dry.append(sym)
        return tape + add

    def stats(self):
        """Числа правила: их печатает отчёт, а не пересказ прогона."""
        sp = sorted(self.span_h.values())
        return {"syms": len(self.added),
                "minutes": sum(self.added.values()),
                "dry": len(self.dry),
                "span_med_h": (sp[len(sp) // 2] if sp else None),
                "zero_vol_tape": self.zero_vol}


def apply(recs, last_tape, last_book=None):
    """Разметить исходы хвостом и не пустить ВХОД из котировки.

    `recs` — словарь «пара линейки → список записей», то, что отдаёт
    `run_d6.collect_recs`. Здесь держатся обе границы правила:

    - **вход.** Решение, чей вход пришёлся бы на минуту без единого
      принта (`at` позже последнего бара ленты), выбрасывается ЦЕЛИКОМ и
      по всем линейкам разом. Иначе хвост не продолжал бы начатое, а
      заводил бы сделки, которых у книги на ленте не было, — то есть
      менял бы СОСТАВ книги, а не досчитывал исходы. Выброшенные
      считаются числом: молча потерять решение нельзя.
    - **исход.** Записи, чей выход случился позже последнего бара ленты,
      помечаются `tail = 1`. Пометка едет в журнал и дальше: по ней
      видно, какие деньги книги посчитаны по котировке, а не по принтам.

    Здесь же каждая позиция, оставшаяся ОБОРВАННОЙ, получает причину
    (`cut_why`). Правило хвоста снимает не всякий обрыв: если запись
    книги кончается там же, где лента (символ перестали писать вовсе,
    провал сбора), дописывать нечем — и «оборванных 46» без причины
    читается как «правило не работает». Причина обязана стоять рядом с
    числом, как прочерк обязан называть себя.

    Возвращает числа для отчёта. Записи правятся на месте — они же лягут
    в кэш реплея, и пометка обязана пережить его.
    """
    drop = set()
    for lst in recs.values():
        for r in lst:
            lt = last_tape.get(r["sym"])
            if lt is not None and float(r["at"]) > float(lt):
                drop.add((r["sym"], round(float(r["at"]), 3)))
    marked, why_n = 0, {}
    last_book = last_book or {}
    for k in list(recs):
        keep = []
        for r in recs[k]:
            if (r["sym"], round(float(r["at"]), 3)) in drop:
                continue
            lt = last_tape.get(r["sym"])
            if lt is not None and float(r.get("exit_ts") or 0.0) > float(lt):
                r["tail"] = 1
                marked += 1
            if r.get("state") == "cut":
                w = cut_reason(r, last_tape, last_book)
                r["cut_why"] = w
                bk = last_book.get(r["sym"])
                if bk is not None:
                    r["book_end"] = float(bk)
                why_n[w] = why_n.get(w, 0) + 1
            keep.append(r)
        recs[k] = keep
    return {"entry_dropped": len(drop), "marked": marked, "cut_why": why_n}


# Причины, по которым позиция остаётся оборванной ПОСЛЕ правила хвоста.
# Объявлены строками один раз: два дословных текста разошлись бы, и
# гистограмма отчёта перестала бы сходиться с подписью на странице.
CUT_NO_BOOK = "книги в хвосте нет вовсе"
CUT_BOOK_SHORT = "книга кончилась раньше планового конца"
CUT_BOOK_HOLE = "книга есть, но не в окне этой позиции"
CUT_UNKNOWN = "причина не измерена"


def cut_reason(r, last_tape, last_book):
    """Почему эта позиция осталась оборванной, когда хвост уже применён.

    Причина считается ПО ЭТОЙ позиции, а не по имени вообще:
    `last_book` держит САМУЮ ПОЗДНЮЮ дописанную минуту символа по всему
    прогону, и у окна, кончившегося раньше, она бывает много позже. Взяв
    её за ответ, мы объявили бы книгу «кончившейся раньше планового
    конца» там, где она вовсе не покрывает окно позиции, — то есть
    назвали бы причину, которой не было.

    Символа нет в границах прогона — значит его баров этот прогон не
    читал вовсе (запись из кэша), и причина НЕ ИЗМЕРЕНА: выдумывать её
    хуже, чем назвать пропуском.
    """
    sym = r["sym"]
    if sym not in last_tape:
        return CUT_UNKNOWN
    bk = last_book.get(sym)
    if bk is None:
        return CUT_NO_BOOK
    if float(bk) <= float(r.get("end_ts") or 0.0):
        return CUT_BOOK_SHORT
    return CUT_BOOK_HOLE
