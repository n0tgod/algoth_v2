# --- тейк позиции (решение владельца 2026-09-05, замер D8) --------------
# Было: `вход · (1 + mfe)` — НЕПОДВИЖНАЯ цена у базы, тогда как ТВХ едет
# вниз с каждым доливом. Стало: цель от ПЛАВАЮЩЕЙ ТВХ и вдвое дальше.
#
# Оба множителя выведены замером `research/dca_ladder/out/D8-take-1m.md`
