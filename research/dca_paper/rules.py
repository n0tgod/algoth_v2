def pair_share_mult(pair_key, book_key):
    """Во сколько раз билет СТОРОНЫ меньше её собственного в общем счёте.

    Длинная сторона входит своим билетом всегда; уменьшается только
    короткая, и только там, где это объявлено.
    """
    if side_of(book_key) != "short":
        return 1.0
    return float(SHORT_SHARE.get(pair_key, 1.0))


def ticket_in(pair_key, book_key, deposit):
    """Билет стороны в общем счёте: свой билет × доля, но НЕ НИЖЕ пола.

    Пол — биржевой минимум ордера, переведённый в маржу. Опустив билет
    под него, правило не уменьшило бы риск, а вычеркнуло бы сделки
    молча: касса отказала бы им «мельче минимума». На депозите $1k
    билеты и так стоят на полу, и доля там не кусается — это видно
    числом в отчёте, а не подразумевается.
    """
    t = ticket(deposit, book_key) * pair_share_mult(pair_key, book_key)
    return float(max(floor_of(book_key), t))


def share_in(pair_key, book_key, deposit):
    """Доля счёта на позицию стороны в общем счёте."""
    return ticket_in(pair_key, book_key, deposit) / float(deposit)


