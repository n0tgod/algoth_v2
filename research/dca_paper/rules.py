def notional_of(row):
    """Нотионал позиции = маржа × плечо; None, если чего-то из двух нет.

    Одна реализация на всех читателей записи (страница книги, график,
    отчёт): контракты выводятся из нотионала и цены рунга, и две копии
    этого умножения однажды разошлись бы — позиция показывала бы разное
    число монет в списке и на графике. Запись без маржи или без плеча
    контрактов не получает вовсе: неизмеримое не есть ноль.
    """
    try:
        m, lv = float(row.get("margin")), float(row.get("lev"))
    except (TypeError, ValueError, AttributeError):
        return None
    return m * lv if (m > 0 and lv > 0) else None


