def min_lev_of(key):
    """Порог входа по плечу у режима; НЕТ поля — гейта нет вовсе.

    Отсутствие и ноль здесь не одно и то же: ноль был бы гейтом,
    пропускающим всё, а отсутствие означает, что режим гейта не несёт и
    запись о нём в манифест не пойдёт. Правило, исчезающее при забытом
    поле, есть отказ, неотличимый от тишины, — поэтому читается оно в
    одном месте.
    """
    v = (RULERS.get(key) or {}).get("min_lev")
    return None if v is None else float(v)


