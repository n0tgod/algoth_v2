    try:
        st = os.stat(__file__)
        code = f"{st.st_mtime_ns}.{st.st_size}"
    except OSError:
        code = "nocode"
    fam = "-".join(f"{k}{v}" for k, v in sorted(FAMILY_RULES.items()))
    return f"cur{RULES}-{fam}-{code}"

