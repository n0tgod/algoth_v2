def notional_of(row):
    """Нотионал позиции = маржа × плечо; None, если чего-то из двух нет.

    Одна реализация на всех читателей записи (страница книги, график,
    отчёт): контракты выводятся из нотионала и цены рунга, и две копии
    этого умножения однажды разошлись бы — позиция показывала бы разное
    число монет в списке и на графике. Запись без маржи или без плеча
    контрактов не получает вовсе: неизмеримое не есть ноль.
    """
    try:
        m, lv = float(row.get("margin")), float(row.get("lev"))
    except (TypeError, ValueError, AttributeError):
        return None
    return m * lv if (m > 0 and lv > 0) else None


def avg_walk(fills, entry=None, notional=None, take_frac=None,
             side="long"):
    """Плавающая ТВХ: средняя цена входа ПОСЛЕ каждого рунга.

    Одна реализация на всех — её зовут и страница книги (разворот
    позиции), и график (ступенчатая линия ТВХ). Вторая копия этой
    арифметики разошлась бы с симуляцией, и позиция на графике стояла
    бы не там, где её посчитала книга; равенство последнего шага полю
    `avg` симуляции закреплено тестом.

    Живёт здесь, а не в `run_paper`, по той же причине, по которой
    `families.py` живёт в стандартной библиотеке: сборщик страниц не
    вправе тянуть numpy ради одной суммы.

    `notional` (маржа × плечо) добавляет КОНТРАКТЫ: `dq` — сколько
    куплено этим рунгом, `qty` — сколько стоит в позиции ПОСЛЕ него.
    Доля нотионала и цена рунга уже лежат в записи, поэтому контракты
    выводятся из неё же — второй записи заводить незачем, а `qty`
    симуляции есть ровно эта сумма (тождество под тестом). Без
    `notional` (у записи нет маржи или плеча) полей не будет вовсе:
    неизмеримое не есть ноль.

    Контракты к ШАГУ ЛОТА площадки не округляются намеренно: книга
    считает деньги нотионалом без округления, и округлённое количество
    рядом с неокруглёнными деньгами описывало бы две разные позиции.

    `take_frac` добавляет `take` — уровень ТЕЙКА после каждого рунга.
    Он тоже ступенчатый, потому что якорь цели — ПЛАВАЮЩАЯ ТВХ
    (`TAKE_ANCHOR`): долив опускает среднюю, и цель едет вместе с ней.
    Считается ЗДЕСЬ, рядом со ступенями ТВХ, ровно затем, чтобы две
    линии на графике не могли разойтись: вторая арифметика однажды
    нарисовала бы цель не от той средней. Без `take_frac` (правило
    сделки в записи не сохранено) поля не будет вовсе — рисовать
    уровень, которого мы не знаем, значит утверждать чужое число.

    `side` задаёт НАПРАВЛЕНИЕ цели — то же соглашение, что у ядра
    (`ladder.simulate_dca`): доля цены всегда положительна, а знак даёт
    сторона. У лонга цель стоит ВЫШЕ средней (`avg · (1 + доля)`), у
    шорта — НИЖЕ (`avg · (1 − доля)`): шорт откупается дешевле, чем
    продал. Пока стороны здесь не было, цель короткой книги рисовалась
    длинной геометрией — над средней, куда шорт не выходит никогда.
    Умолчание — лонг: записи до 2026-09-05 стороны не несут и все
    длинные, числа их не сдвигаются ни на бит.
    """
    # ДЕНЬГИ на монеты, а не среднее цен: рунг покупает свою ДОЛЮ
    # нотионала, поэтому средняя цена входа равна «потрачено / куплено»
    # (тождество с `avg` симуляции, закреплено тестом). Среднее
    # арифметическое цен дало бы близкое, но другое число — и позиция
    # на графике стояла бы не там, где её посчитала книга.
    nt = None
    try:
        nt = float(notional) if notional is not None else None
    except (TypeError, ValueError):
        nt = None
    if nt is not None and not (nt > 0):
        nt = None

    tf = None
    try:
        tf = float(take_frac) if take_frac is not None else None
    except (TypeError, ValueError):
        tf = None
    if tf is not None and not (tf > 0):
        tf = None
    # Знак цели даёт сторона, а не доля: у шорта цель ниже средней.
    d = 1.0 if side != "short" else -1.0

    def _row(at, px, w, avg, coins):
        r = {"at": at, "px": px, "w": w, "avg": avg}
        if nt is not None:
            r["dq"] = w * nt / px          # куплено этим рунгом
            r["qty"] = coins * nt          # стоит в позиции после него
        if tf is not None:
            r["take"] = avg * (1.0 + d * tf)   # цель ОТ ЭТОЙ средней
        return r

    out, cash, qty = [], 0.0, 0.0
    for f in (fills or []):
        try:
            at, px, w = float(f[0]), float(f[1]), float(f[2])
        except (TypeError, ValueError, IndexError):
            continue
        if not (px > 0 and w > 0):
            continue
        cash += w
        qty += w / px
        out.append(_row(at, px, w, cash / qty, qty))
    if not out and entry:
        # Запись прежнего образца входов не несёт: ТВХ равна цене
        # входа, и это НЕ выдумка — лестница там просто не разложена.
        out.append(_row(None, float(entry), 1.0, float(entry),
                        1.0 / float(entry)))
    return out


def open_stats(positions):
    """ХУДШАЯ из открытых позиций — та, что просела глубже всех СЕЙЧАС.

    Считает СЕРВЕР, а не страница: страница печатает это число и в
    плитке, и в подписи под ней, и вторая реализация однажды разошлась
    бы с первой — тем же путём, каким расходились списки книг.

    Возвращает РОВНО то, чего в артефакте нет. Числа «сколько открытых»,
    «отметка» и «переоценено» считает сам прогон и кладёт в артефакт —
    пересчитать их здесь значило бы завести второй счёт тем же величинам.

    Отметка открытой позиции не есть исход: до выхода она станет любой.
    Поэтому «худшая» здесь значит «глубже всех просевшая сейчас», а не
    «худшая сделка книги», и с закрытым счётом это не складывается.

    Позиция без отметки в сравнение не идёт: неизмеренное не есть ноль.
    """
    ps = [p for p in (positions or []) if p.get("mark_frac") is not None]
    if not ps:
        return {"worst_frac": None, "worst_sym": None, "worst_usd": None}
    w = min(ps, key=lambda p: float(p["mark_frac"]))
    return {"worst_frac": round(float(w["mark_frac"]), 6),
            "worst_sym": w.get("sym"),
            "worst_usd": (round(float(w["mark_usd"]), 2)
                          if w.get("mark_usd") is not None else None)}


def ruler_title(key):
    return (RULERS.get(key) or {}).get("title") or str(key)


def side_of(key):
    """Сторона книги. Ключ без поля — длинная: до 2026-09-05 других нет.

    Читается в ОДНОМ месте, потому что читателей стало трое (отбор ног,
    геометрия позиции, показ), и три копии умолчания однажды разошлись
    бы — короткая книга считалась бы длинным правилом, ничем себя не
    выдав.
    """
    return (RULERS.get(key) or {}).get("side") or "long"


def row_side(row, ruler=None):
    """Сторона ЗАПИСИ позиции — одно правило на всех читателей.

    Поле `side` строки — запись факта (его пишет прогон книги с 2026-09-05
    из самой симуляции); строка без поля — прежнего образца, и её сторона
    выводится из ЛИНЕЙКИ: короткая книга есть свойство ключа (`side_of`),
    а до появления коротких книг все записи были длинными.

    `ruler` нужен записям, у которых линейки в самой строке нет —
    открытым и оборванным позициям артефакта: они лежат ПОД ключом книги,
    а не несут его. Без него такая запись короткой книги читалась бы
    длинной по умолчанию `ruler_of`, то есть ровно тот дефект, ради
    которого функция и заведена (страница показывала шорт-книге лонги).
    """
    s = (row or {}).get("side")
    if s in ("long", "short"):
        return s
    return side_of(ruler if ruler is not None else ruler_of(row or {}))


def min_lev_of(key):
    """Порог входа по плечу у режима; НЕТ поля — гейта нет вовсе.

    Отсутствие и ноль здесь не одно и то же: ноль был бы гейтом,
    пропускающим всё, а отсутствие означает, что режим гейта не несёт и
    запись о нём в манифест не пойдёт. Правило, исчезающее при забытом
    поле, есть отказ, неотличимый от тишины, — поэтому читается оно в
    одном месте.
    """
    v = (RULERS.get(key) or {}).get("min_lev")
    return None if v is None else float(v)


