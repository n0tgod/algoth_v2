def mode_of(key):
    """Режим по ключу книги: без приставки общего счёта, хвоста короткой
    и суффикса ветви правил (`_g<порог>` или `_g<порог>i<обратный>`,
    спека 18; `_c<потолок>` — потолок плеча, `_cr<порог>` — гейт толпы,
    25.10; `_ai` — ветвь судьи спеки 19)."""
    k = re.sub(r"(?:_g\d+(?:i\d+)?|_c\d+|_cr\d+|_ai|_m\d+)$", "", str(key))
    if k.startswith("pair_"):
        k = k[5:]
    for suf in ("_h", "_s"):
        if k.endswith(suf):
            k = k[:-len(suf)]
    return k


def title_en(key):
    """Английское имя режима книги; неизвестный ключ — как есть. У ветви
    судьи спеки 19 — имя её корня в дереве («AI judge»), не режима плеча."""
    if str(key).endswith("_ai"):
        return "AI judge"
    if re.search(r"_m\d+$", str(key)):
        return "AI lab"
    return MODE_EN.get(mode_of(key), str(key))


