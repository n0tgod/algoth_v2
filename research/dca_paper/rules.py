#!/usr/bin/env python3
"""Правила бумажных DCA-книг: три депозита, одни правила.

Зачем отдельный модуль на стандартной библиотеке. Правила читают ДВОЕ:
сам прогон (`run_paper.py`, тянет numpy, duckdb и половину D-серии) и
веб-сервер страницы наблюдения (`b1_book/collect.py`, живёт на стандартной
библиотеке рядом со сбором стакана). Тянуть numpy в сборщик ради строки
«записано ли решение вперёд» нельзя, а завести второе такое правило —
тем более: два места, решающих одно, однажды разойдутся, и страница
станет называть настоящим наблюдением то, что прогон считает бэктестом.
Тот же приём, что `s8_loop/families.py` и `paper_monthly/paper_journal.py`.

Здесь живут: депозиты, размер билета с его выводом, гейты входа,
параметры ограды и выхода, правило `ahead` и чтение журнала. Всё, что
требует numpy (уровни, забор, исход), остаётся в `run_paper.py`.
"""

import json
import os

RULES = 1                        # версия правил книг; смена — новая запись

# --- депозиты (решение владельца) ---------------------------------------
DEPOSITS = [1000.0, 10000.0, 100000.0]

# --- размер билета ВЫВЕДЕН из пола биржи, а не назначен ------------------
# Минимальный ордер площадки ровно $5 у 1540 контрактов из 1540, а самый
# мелкий рунг лестницы есть 25 % нотионала позиции. Значит нотионал не
# бывает меньше $20, а маржа — меньше $20/плечо. Забор выдаёт от 1×, то
# есть худший случай требует ровно $20 маржи. Билет $25 — это пол плюс
# четверть запаса: маржа считается от ТЕКУЩЕГО счёта, и в просадке она
# проседает вместе с ним (у D-серии просадка 8–19 %).
MIN_NOTIONAL = 5.0
RUNG_SHARE = 0.25
TICKET = 25.0

# --- гейты входа: те же, которыми входит живая ситуационная книга -------
MIN_EDGE_BP = 33.0               # 3× круга издержек на ногу
MIN_RR = 2.0
SIDE = "long"                    # шорт-книга закрыта замером D2 (в)

# --- ограда и выход: база D3/D4 (забор 2.0, пол капитуляции 0.10) -------
SURVIVE_MULT = 2.0
FLOOR_FRAC = 0.10
N_RUNGS = 4
HOLD_H = 72                      # предел жизни позиции, часов

# --- две линейки плеча (решение владельца 2026-09-04) --------------------
# Плечо не настройка агрессивности: оно ВЫВОДИТСЯ из неравенства
# безопасности §5 спеки 14. Линеек ровно две, и различаются они тем, от
# чего считается запас до ликвидации:
#   depth  — от глубины самой лестницы (запас = 2 · d_max). D3 намерил у
#            неё антиселективность: волатильному имени лестница глубже,
#            значит и плеча выдаётся больше (медиана хвоста 7.34× против
#            3.02× по книге);
#   sigma  — от собственной σ имени (запас = 6 суточных σ, но не меньше
#            глубины лестницы). Волатильному имени плеча достаётся МЕНЬШЕ.
# Имена «безопасная» и «оптимальная» — ярлыки владельца, а не вердикт:
# какая лучше, покажет форвард, и обе книги ведутся параллельно ровно
# затем, чтобы этот вопрос решали числа, а не выбор задним числом.
SIGMA_MULT = 6.0
RULERS = {
    "safe": {
        "rule": "sigma", "param": SIGMA_MULT, "title": "безопасная",
        "plain": "плечо от собственной σ имени: запас 6 суточных σ до "
                 "ликвидации. Волатильному имени плеча достаётся меньше, "
                 "и в замере D3 такая книга не ликвидировала ни одной "
                 "позиции ценой примерно половины дохода."},
    "optimal": {
        "rule": "depth", "param": SURVIVE_MULT, "title": "оптимальная",
        "plain": "плечо от глубины лестницы: запас 2 · d_max до "
                 "ликвидации. Доход выше, хвост тяжелее (в замере D3 "
                 "ликвидировано 0.06 % позиций), и щедрее всего линейка "
                 "ровно к волатильным именам."},
}
RULER_ORDER = ["safe", "optimal"]
# Запись БЕЗ поля `ruler` писана этой линейкой: до 2026-09-04 книга была
# одна и считалась глубиной. Умолчание доказуемо, а не удобно.
DEFAULT_RULER = "optimal"


def ruler_of(row):
    """Линейка строки журнала; у строк прежнего образца поля нет."""
    r = row.get("ruler") or DEFAULT_RULER
    return r if r in RULERS else DEFAULT_RULER


def ruler_title(key):
    return (RULERS.get(key) or {}).get("title") or str(key)


# --- биржевое правило, которое реплей D-серии НЕ соблюдал ---------------
# На одном счёте в одностороннем режиме у имени позиция ОДНА: второй
# выбор по той же монете есть долив, а не вторая позиция. Книги обязаны
# это соблюдать с первого дня — иначе их числа неисполнимы (замечание
# владельца 2026-09-04). Повтор по уже открытому имени пропускается.
ONE_PER_NAME = True

# --- «записано вперёд» ---------------------------------------------------
# Решение считается записанным ВПЕРЁД, если попало в журнал не позже чем
# через `AHEAD_H` часов после самого решения. Число выведено, а не взято:
# исход позиции неизвестен до её закрытия, а жить она может `HOLD_H` = 72
# часа; плюс двое суток на суточный прогон и публикацию архива. Всё, что
# записано позже, есть ПЕРЕСЧЁТ по прошлому и в одну сумму с наблюдением
# не идёт никогда.
AHEAD_H = HOLD_H + 48

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
JOURNAL = os.path.join(OUT, "journal.jsonl")
ARTIFACT = os.path.join(OUT, "DCA-paper.json")


def slots(deposit, ticket=TICKET):
    """Сколько мест помещается в депозит при объявленном билете."""
    return int(deposit // ticket)


def share(deposit, ticket=TICKET):
    """Доля счёта на позицию — ровно билет, выраженный долей."""
    return ticket / float(deposit)


def ahead(decided_at, written_at, hours=AHEAD_H):
    """Записано ли решение вперёд, а не восстановлено пересчётом."""
    if decided_at is None or written_at is None:
        return None
    return (float(written_at) - float(decided_at)) <= hours * 3600.0


def read_journal(path=JOURNAL):
    """Строки журнала как есть. Битая строка пропускается со счётом —
    журнал write-ahead, и оборванная запись не вправе ронять чтение."""
    rows, bad = [], 0
    if not os.path.exists(path):
        return rows, bad
    with open(path, encoding="utf-8") as f:
        for ln in f:
            ln = ln.strip()
            if not ln:
                continue
            try:
                rows.append(json.loads(ln))
            except Exception:
                bad += 1
    return rows, bad


def split_rows(rows, hours=AHEAD_H):
    """Наблюдение и пересчёт — ДВА списка, и складывать их нельзя."""
    fwd, back = [], []
    for r in rows:
        a = ahead(r.get("at"), r.get("written_at"), hours)
        (fwd if a else back).append(r)
    return fwd, back
