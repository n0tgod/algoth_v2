def floor_of(ruler):
    """Пол билета РЕЖИМА: биржевой минимум, переведённый в маржу.

    Мельчайший рунг есть `RUNG_SHARE` нотионала, нотионал = маржа ×
    плечо, значит маржа не бывает меньше `MIN_NOTIONAL / RUNG_SHARE /
    плечо`. Худшее плечо режима — его собственный гейт: без гейта это
    1× (забор выдаёт от единицы), с гейтом — сам порог.
    """
    lv = min_lev_of(ruler)
    return MIN_NOTIONAL / RUNG_SHARE / float(lv or 1.0) * HEADROOM


def peak_of(ruler):
    """Пик РЕЖИМА, измеренный по журналу. Неизвестный режим — пик пула.

    Умолчание намеренно КОНСЕРВАТИВНО: пул шире любого режима, поэтому
    неизвестный ключ получает билет мельче нужного, а не крупнее — он
    оставит деньги простаивать, но не начнёт отказывать по кассе молча.
    """
    return int(PEAKS.get(ruler, PEAK_SEEN))


def ticket(deposit, ruler):
    """Билет книги: не меньше пола режима и не больше доли на все места.

    Режим обязателен, а не имеет умолчания: пол и пик у режимов разные,
    и забытый параметр отдал бы книге чужой билет молча — отказ,
    неотличимый от тишины. Величина НОМИНАЛЬНА (доля стартового счёта);
    настоящая маржа считается от текущего счёта и проседает вместе с
    ним, поэтому «мест» есть round-число, а не жёсткий предел.
    """
    room = float(deposit) / (peak_of(ruler) * PEAK_MARGIN)
    return float(max(floor_of(ruler), float(int(room))))


def slots(deposit, ruler):
    """Сколько мест помещается в депозит при билете этой книги."""
    return int(float(deposit) // ticket(deposit, ruler))


def share(deposit, ruler):
    """Доля счёта на позицию — ровно билет, выраженный долей."""
    return ticket(deposit, ruler) / float(deposit)


def ahead(decided_at, written_at, hours=AHEAD_H, since=None):
    """Записано ли решение вперёд, а не восстановлено пересчётом.

    Два условия, и второе появилось вместе со сменой правила тейка:
    решение, принятое ДО того, как нынешняя версия правил вступила в
    силу, есть бэктест по построению — правило выбрано после того, как
    эти часы стали видны, и никакая задержка записи этого не меняет.
    Без границы каждая смена правил молча перекрашивала бы последние
    `AHEAD_H` часов пересчёта в «вперёд».
    """
    if decided_at is None or written_at is None:
        return None
    lim = RULES_SINCE if since is None else float(since)
    if lim and float(decided_at) < lim:
        return False
    return (float(written_at) - float(decided_at)) <= hours * 3600.0


def shard_of(path, at=None):
    """Файл журнала, в который идёт решение: СУТКИ по метке решения.

    Ротация нужна не для порядка, а потому что растущий одним файлом
    журнал однажды упирается в защиту от опасного коммита (5 МБ) и
    молча замораживает ВЕСЬ канал публикации: 4 сентября он вырос до
    11 МБ, и с 12:10 в git не доехало ни одного лога задания, ни
    ночного отчёта. Сутки выбраны замером: около 320 решений в день,
    это доли мегабайта на файл.

    Дата берётся из МЕТКИ РЕШЕНИЯ, а не из «сегодня»: пересчёт по
    прошлому пишется вместе с наблюдением, и класть его в сегодняшний
    файл значило бы датировать запись моментом счёта.
    """
    base, ext = os.path.splitext(path)
    return f"{base}-{shard_day(at)}{ext}"


def shard_day(at=None):
    """Дата суток решения строкой — ключ ротации, один на всех."""
    d = (dt.datetime.fromtimestamp(float(at), dt.timezone.utc).date()
         if at is not None else dt.datetime.now(dt.timezone.utc).date())
    return d.isoformat()


# Порог ЧАСТИ суточного файла. Сутки оказались единицей недостаточной:
# одно решение живёт во всех книгах разом (девять на 2026-09-05,
# восемнадцать с зеркальными короткими), и куски 20–21 августа доросли
# до 4.2–4.35 МБ при защите коммита в 5 МиБ. Следующий пересчёт истории
# перешагнул бы порог и заморозил ВЕСЬ канал публикации — ровно то, что
# уже стоило шестнадцати часов тишины 4 сентября. Запас до защиты почти
# мегабайт: одна строка журнала весит сотни байт, и переступить порог
# между проверкой и записью нечем.
SHARD_CAP = 4 * 1024 * 1024


def shard_parts(path, at=None, day=None):
    """Части суток по порядку: `journal-<дата>.jsonl`, затем `.01`, `.02`…

    Первая часть без номера намеренно: имя суточного файла не меняется
    от того, что у суток появилось продолжение, и уже записанные части
    не переименовываются — журнал write-ahead.
    """
    base, ext = os.path.splitext(path)
    d = day or shard_day(at)
    first = f"{base}-{d}{ext}"
    rest = sorted(glob.glob(f"{base}-{d}.[0-9][0-9]{ext}"))
    return [first] + rest


def shard_place(path, day, lines, cap=SHARD_CAP):
    """Разложить строки суток по частям, не переступая порог.

    Возвращает {файл: [строки]}. Часть, в которую уже не влезает, не
    дописывается вовсе — заводится следующая; строка длиннее самого
    порога кладётся в свою часть одна (потерять решение хуже, чем
    перешагнуть запас).
    """
    base, ext = os.path.splitext(path)
    parts = shard_parts(path, day=day)
    cur = parts[-1]
    n = len(parts) - 1                       # номер последней части
    sz = os.path.getsize(cur) if os.path.exists(cur) else 0
    out = {}
    for ln in lines:
        add = len(ln.encode("utf-8"))
        if sz and sz + add > cap:
            n += 1
            cur = f"{base}-{day}.{n:02d}{ext}"
            sz = os.path.getsize(cur) if os.path.exists(cur) else 0
        out.setdefault(cur, []).append(ln)
        sz += add
    return out


def journal_parts(path=JOURNAL):
    """Все куски журнала: старый цельный файл и суточные, по порядку.

    Старый файл читается первым и навсегда: он ЗАПИСЬ, и перевод на
    ротацию не вправе сделать вид, что прежних решений не было.
    """
    base, ext = os.path.splitext(path)
    parts = [path] if os.path.exists(path) else []
    parts += sorted(glob.glob(f"{base}-*{ext}"))
    return parts


def journal_key(r):
    """Ключ решения: тем же составом, каким дедуплицирует запись.

    Версия правил и линейка входят в ключ по той же причине, что и при
    записи: строка, писанная другим билетом или другой линейкой, тем же
    решением не является.
    """
    return (int(r.get("rules", 0)), ruler_of(r), r.get("dep"),
            int(float(r.get("at") or 0)), r.get("sym"))


def read_journal(path=JOURNAL, stats=None):
    """Строки журнала как есть — из ВСЕХ его кусков, БЕЗ повторов.

    Битая строка пропускается со счётом: журнал write-ahead, и
    оборванная запись не вправе ронять чтение.

    Дедуп на чтении нужен ровно из-за ротации: старый цельный файл и
    суточные куски перекрываются по построению (разрезка не удаляет
    оригинал — удаление записи есть осознанное действие, а не побочный
    эффект правки). Считать одно решение дважды означало бы удвоить
    сделку в счёте, поэтому побеждает ПЕРВОЕ вхождение — старый файл.
    Число снятых повторов кладётся в `stats`, а не молчит.
    """
    rows, bad, seen, dups = [], 0, set(), 0
    for part in journal_parts(path):
        with open(part, encoding="utf-8") as f:
            for ln in f:
                ln = ln.strip()
                if not ln:
                    continue
                try:
                    r = json.loads(ln)
                except Exception:
                    bad += 1
                    continue
                k = journal_key(r)
                if k in seen:
                    dups += 1
                    continue
                seen.add(k)
                rows.append(r)
    if stats is not None:
        stats["dups"] = dups
        stats["parts"] = len(journal_parts(path))
    return rows, bad


def split_rows(rows, hours=AHEAD_H):
    """Наблюдение и пересчёт — ДВА списка, и складывать их нельзя."""
    fwd, back = [], []
    for r in rows:
        a = ahead(r.get("at"), r.get("written_at"), hours)
        (fwd if a else back).append(r)
    return fwd, back
