RISK_LIMITS = os.path.join(os.path.dirname(HERE), "a1_universe", "out",
                           "risk_limits.json")
_TIERS = {"at": None, "data": {}}


def risk_tiers(path=None):
    """Тиры площадки: символ → ступени. Перечитывается по времени файла."""
    path = path or RISK_LIMITS
    try:
        at = os.path.getmtime(path)
    except OSError:
        return {}
    if _TIERS["at"] != (path, at):
        try:
            with open(path, encoding="utf-8") as f:
                _TIERS["data"] = json.load(f)
        except (OSError, ValueError):
            _TIERS["data"] = {}
        _TIERS["at"] = (path, at)
    return _TIERS["data"]


def _ladder():
    """Ядро лестницы. Импорт ленивый: страница не тянет его без нужды."""
    import sys
    p = os.path.join(os.path.dirname(HERE), "dca_ladder")
    if p not in sys.path:
        sys.path.insert(0, p)
    import ladder as L
    return L


def levels_of(row, key=None, look=None):
    """Уровни позиции для исполнителя (спека 15 §9, Y1): цель, ликвидация,
    пол капитуляции, средняя — ТЕМИ ЖЕ функциями, что рисует страница
    (`avg_walk`, `liq_walk`, `take_rule`), и срок. Исполнителю не считать
    ничего самому — он читает числа строки.

    Чего нет — того нет (не ноль): без обещания модели цели нет, без
    маржи и плеча — ликвидации и пола. `look` — ставка поддержки по
    нотионалу (`mmr_look(sym)`); вызывающий, идущий по многим строкам
    одного имени, передаёт её сам, чтобы не читать тиры на каждую.
    """
    fills = row.get("fills") or []
    if not fills:
        return None
    side = row_side(row, key)
    tr = take_rule(row.get("fav_bp"), side)
    tf = abs(float(tr["frac"])) if tr else None
    notl = notional_of(row)
    walk = avg_walk(fills, row.get("entry_px"), notl, take_frac=tf, side=side)
    if not walk:
        return None
    margin = row.get("margin")
    if margin is not None and (look is not None or row.get("sym")):
        liq_walk(walk, margin, side, look=look if look is not None else mmr_look(row.get("sym")))
    last = walk[-1]
    avg = last.get("avg")
    liq = last.get("liq")
    out = {"avg": avg, "take_px": last.get("take"), "liq_px": liq, "floor_px": None,
           "term_ts": row.get("sched_end"), "depth": len(fills), "side": side}
    if liq is not None and avg is not None:
        ff = floor_frac_of(key or ruler_of(row), FLOOR_FRAC)
        # пол — на доле пути от ликвидации к средней, зеркально у шорта
        out["floor_px"] = liq + ff * (avg - liq)
        out["floor_frac"] = ff
    return out


def mmr_look(sym, path=None):
    """Функция «нотионал → ставка поддерживающей маржи» для имени.

    Тиров у имени нет — плоская ставка ядра (`ladder.FLAT_MMR`), и это
    названо здесь одним местом: справочник тиров отстаёт от волны
    листингов, и молчаливый ноль на его месте нарисовал бы ликвидацию
    там, где её нет.
    """
    L = _ladder()
    tiers = (risk_tiers(path) or {}).get(str(sym or "").upper()) or []
    return lambda notl, _t=tiers: L.mmr_for_notional(_t, notl,
                                                     flat=L.FLAT_MMR)


def liq_walk(steps, margin, side="long", look=None, mmr=None):
    """Цена ликвидации ПОСЛЕ каждого рунга — ядром лестницы, не копией.

    Ступени те же, что у ТВХ и у цели: долив двигает среднюю, а с ней и
    ликвидацию. Капитал позиции на каждой ступени — ВСЯ её маржа
    (`margin`), ровно как в симуляции (`ladder.simulate_dca`: касса
    резервирует маржу целиком при первом рунге, `liq_price(avg, qty,
    capital, …)` считается с ней). Ставка — из тиров площадки по
    заполненному нотионалу ступени.

    Дефект, найденный владельцем по графику (PHAUSDT, шорт 2026-09-21
    13:00, «цена пробила уровень ликвидации, а позиции нет»): капитал
    ступени брался как «нотионал ступени / плечо» — маржа одних
    заполненных рунгов. При глубине 1 (86 % позиций, замер D8) это
    четверть маржи, и линия стояла в 20× там, где книга держит позицию
    на 5× действующих: 0.0592 на графике против 0.0677 у самой книги;
    цена дошла до 0.0598 и по правилу книги до ликвидации не дотянула.
    График утверждал ликвидацию, которой у книги не было. Сойдутся обе
    картины только у полностью заполненной лестницы.

    Нет маржи или количества контрактов — поля не будет вовсе:
    рисовать ликвидацию, которой мы не знаем, значит утверждать чужое
    число (маржа одного рунга — тоже чужое).
    """
    try:
        cap = float(margin)
    except (TypeError, ValueError):
        return steps
    if not cap > 0 or (look is None and mmr is None):
        return steps
    L = _ladder()
    for st in (steps or []):
        q, a = st.get("qty"), st.get("avg")
        if q is None or not a:
            continue
        notl = float(q) * float(a)
        m = float(look(notl)) if look is not None else float(mmr)
        st["liq"] = L.liq_price(float(a), float(q), cap, m, side)
    return steps


def journal_of(key, sizing=DEFAULT_SIZING):
    """Журнал СЕМЕЙСТВА книги. Одно место на всех читателей.

    Журналов три, и выбирать между ними по памяти — способ однажды
    показать пустую книгу: страница графика читала журнал длинных книг
    для ЛЮБОЙ книги, и позиции коротких и общих на графике не
    рисовались вовсе (владелец 2026-09-10: «пустой график»).

    У фиксированного билета журнал СВОЙ рядом (`fixed_twin`).
    """
    fam = family_of(key)
    if fam == "h24":
        p = H24_JOURNAL
    elif fam == "pair":
        p = PAIR_JOURNAL
    else:
        p = JOURNAL
    return p if sizing == DEFAULT_SIZING else fixed_twin(p)


def artifact_of(key):
    """Артефакт СЕМЕЙСТВА книги: открытые позиции живут в нём, не в журнале."""
    fam = family_of(key)
    if fam == "h24":
        return H24_ARTIFACT
    if fam == "pair":
        return PAIR_ARTIFACT
    return ARTIFACT


def floor_of(ruler):
    """Пол билета РЕЖИМА: биржевой минимум, переведённый в маржу.

    Мельчайший рунг есть `RUNG_SHARE` нотионала, нотионал = маржа ×
    плечо, значит маржа не бывает меньше `MIN_NOTIONAL / RUNG_SHARE /
    плечо`. Худшее плечо режима — его собственный гейт: без гейта это
    1× (забор выдаёт от единицы), с гейтом — сам порог.
    """
    lv = min_lev_of(ruler)
    return MIN_NOTIONAL / RUNG_SHARE / float(lv or 1.0) * HEADROOM


def peak_of(ruler):
    """Пик РЕЖИМА, измеренный по журналу. Неизвестный режим — пик пула.

    Умолчание намеренно КОНСЕРВАТИВНО: пул шире любого режима, поэтому
    неизвестный ключ получает билет мельче нужного, а не крупнее — он
    оставит деньги простаивать, но не начнёт отказывать по кассе молча.
    """
    return int(PEAKS.get(ruler, PEAK_SEEN))


def ticket(deposit, ruler):
    """Билет книги: не меньше пола режима и не больше доли на все места.

    Режим обязателен, а не имеет умолчания: пол и пик у режимов разные,
    и забытый параметр отдал бы книге чужой билет молча — отказ,
    неотличимый от тишины. Величина НОМИНАЛЬНА (доля стартового счёта);
    настоящая маржа считается от текущего счёта и проседает вместе с
    ним, поэтому «мест» есть round-число, а не жёсткий предел.
    """
    room = float(deposit) / (peak_of(ruler) * PEAK_MARGIN)
    return float(max(floor_of(ruler), float(int(room))))


def slots(deposit, ruler):
    """Сколько мест помещается в депозит при билете этой книги."""
    return int(float(deposit) // ticket(deposit, ruler))


def share(deposit, ruler):
    """Доля счёта на позицию — ровно билет, выраженный долей."""
    return ticket(deposit, ruler) / float(deposit)


def ahead(decided_at, written_at, hours=AHEAD_H, since=None):
    """Записано ли решение вперёд, а не восстановлено пересчётом.

    Два условия, и второе появилось вместе со сменой правила тейка:
    решение, принятое ДО того, как нынешняя версия правил вступила в
    силу, есть бэктест по построению — правило выбрано после того, как
    эти часы стали видны, и никакая задержка записи этого не меняет.
    Без границы каждая смена правил молча перекрашивала бы последние
    `AHEAD_H` часов пересчёта в «вперёд».
    """
    if decided_at is None or written_at is None:
        return None
    lim = RULES_SINCE if since is None else float(since)
    if lim and float(decided_at) < lim:
        return False
    return (float(written_at) - float(decided_at)) <= hours * 3600.0


def shard_of(path, at=None):
    """Файл журнала, в который идёт решение: СУТКИ по метке решения.

    Ротация нужна не для порядка, а потому что растущий одним файлом
    журнал однажды упирается в защиту от опасного коммита (5 МБ) и
    молча замораживает ВЕСЬ канал публикации: 4 сентября он вырос до
    11 МБ, и с 12:10 в git не доехало ни одного лога задания, ни
    ночного отчёта. Сутки выбраны замером: около 320 решений в день,
    это доли мегабайта на файл.

    Дата берётся из МЕТКИ РЕШЕНИЯ, а не из «сегодня»: пересчёт по
    прошлому пишется вместе с наблюдением, и класть его в сегодняшний
    файл значило бы датировать запись моментом счёта.
    """
    base, ext = os.path.splitext(path)
    return f"{base}-{shard_day(at)}{ext}"


def shard_day(at=None):
    """Дата суток решения строкой — ключ ротации, один на всех."""
    d = (dt.datetime.fromtimestamp(float(at), dt.timezone.utc).date()
         if at is not None else dt.datetime.now(dt.timezone.utc).date())
    return d.isoformat()


# Порог ЧАСТИ суточного файла. Сутки оказались единицей недостаточной:
# одно решение живёт во всех книгах разом (девять на 2026-09-05,
# восемнадцать с зеркальными короткими), и куски 20–21 августа доросли
# до 4.2–4.35 МБ при защите коммита в 5 МиБ. Следующий пересчёт истории
# перешагнул бы порог и заморозил ВЕСЬ канал публикации — ровно то, что
# уже стоило шестнадцати часов тишины 4 сентября. Запас до защиты почти
# мегабайт: одна строка журнала весит сотни байт, и переступить порог
# между проверкой и записью нечем.
SHARD_CAP = 4 * 1024 * 1024


def shard_parts(path, at=None, day=None):
    """Части суток по порядку: `journal-<дата>.jsonl`, затем `.01`, `.02`…

    Первая часть без номера намеренно: имя суточного файла не меняется
    от того, что у суток появилось продолжение, и уже записанные части
    не переименовываются — журнал write-ahead.
    """
    base, ext = os.path.splitext(path)
    d = day or shard_day(at)
    first = f"{base}-{d}{ext}"
    rest = sorted(glob.glob(f"{base}-{d}.[0-9][0-9]{ext}"))
    return [first] + rest


def shard_place(path, day, lines, cap=SHARD_CAP):
    """Разложить строки суток по частям, не переступая порог.

    Возвращает {файл: [строки]}. Часть, в которую уже не влезает, не
    дописывается вовсе — заводится следующая; строка длиннее самого
    порога кладётся в свою часть одна (потерять решение хуже, чем
    перешагнуть запас).
    """
    base, ext = os.path.splitext(path)
    parts = shard_parts(path, day=day)
    cur = parts[-1]
    n = len(parts) - 1                       # номер последней части
    sz = os.path.getsize(cur) if os.path.exists(cur) else 0
    out = {}
    for ln in lines:
        add = len(ln.encode("utf-8"))
        if sz and sz + add > cap:
            n += 1
            cur = f"{base}-{day}.{n:02d}{ext}"
            sz = os.path.getsize(cur) if os.path.exists(cur) else 0
        out.setdefault(cur, []).append(ln)
        sz += add
    return out


def journal_parts(path=JOURNAL):
    """Все куски журнала: старый цельный файл и суточные, по порядку.

    Старый файл читается первым и навсегда: он ЗАПИСЬ, и перевод на
    ротацию не вправе сделать вид, что прежних решений не было.
    """
    base, ext = os.path.splitext(path)
    parts = [path] if os.path.exists(path) else []
    parts += sorted(glob.glob(f"{base}-*{ext}"))
    return parts


def journal_key(r):
    """Ключ решения: тем же составом, каким дедуплицирует запись.

    Версия правил и линейка входят в ключ по той же причине, что и при
    записи: строка, писанная другим билетом или другой линейкой, тем же
    решением не является.
    """
    return (int(r.get("rules", 0)), int(r.get("book_rules") or 0),
            ruler_of(r), r.get("dep"), sizing_of(r),
            int(float(r.get("at") or 0)), r.get("sym"))


def _parse_part(part, keep=None):
    """Один кусок журнала: строки, их ключи дедупа, число битых и
    разобранных.

    Ключ считается ЗДЕСЬ, один раз на строку, и едет рядом с ней: дедуп
    по кускам и чтение из кеша берут его готовым, а не считают заново.

    `keep` — отбор строк при разборе (у сборщика это `is_current`):
    строки вне отбора не возвращаются вовсе и в кеше не лежат — так
    сборщик держит в памяти 34 тысячи строк текущих правил, а не все
    178 тысяч (90 МБ против 490). Отбирать ДО дедупа законно только
    потому, что всё, от чего зависит `is_current`, — версия правил,
    версия семейства, линейка — входит в сам ключ: у двух строк с одним
    ключом отбор даёт один ответ, и «первое вхождение» среди отобранных
    есть первое вхождение вообще. Предикат, смотрящий на поле вне
    ключа, менял бы, какое вхождение побеждает, — сюда его не подавать.
    """
    rows, keys, bad, n = [], [], 0, 0
    with open(part, encoding="utf-8") as f:
        for ln in f:
            ln = ln.strip()
            if not ln:
                continue
            n += 1
            try:
                r = json.loads(ln)
            except Exception:
                bad += 1
                continue
            if keep is not None and not keep(r):
                continue
            rows.append(r)
            keys.append(journal_key(r))
    return rows, keys, bad, n


def read_journal(path=JOURNAL, stats=None, keep=None, cache=None,
                 disk=None, keep_sig=None):
    """Строки журнала как есть — из ВСЕХ его кусков, БЕЗ повторов.

    Битая строка пропускается со счётом: журнал write-ahead, и
    оборванная запись не вправе ронять чтение.

    Дедуп на чтении нужен ровно из-за ротации: старый цельный файл и
    суточные куски перекрываются по построению (разрезка не удаляет
    оригинал — удаление записи есть осознанное действие, а не побочный
    эффект правки). Считать одно решение дважды означало бы удвоить
    сделку в счёте, поэтому побеждает ПЕРВОЕ вхождение — старый файл.
    Число снятых повторов кладётся в `stats`, а не молчит.

    `cache` — словарь ВЫЗЫВАЮЩЕГО: {кусок: (подпись, строки, ключи,
    битых)}. Кусок с той же подписью (mtime_ns, размер) не разбирается
    заново: журнал write-ahead, старые куски меняются только
    переразрезкой, а она меняет и подпись. Подпись снимается ДО чтения:
    дописанное между чтением и подписью тогда разберётся лишний раз, а
    не потеряется до следующей дописи. Кому держать память, решает
    вызывающий: сборщик отвечает страницам каждые две минуты и держит,
    прогон книги читает раз и уходит. Без кеша каждый промах
    двухминутного кеша страницы DCA заново разбирал 200 653 строки трёх
    журналов (70 МБ) — 3.9 с из 5.9 у холодного ответа (владелец,
    2026-09-22: «жду по 5–10 секунд»). Строки из кеша ОБЩИЕ между
    вызовами — читать, не править; один словарь — один `keep`.

    `disk` — каталог кеша НА ДИСКЕ для процесса, который читает раз и
    уходит (прогон книги, 15.10): pickle на кусок, подпись та же
    (mtime_ns, размер) плюс `keep_sig` — подпись отбора `keep`
    (`current_sig()` для `is_current`; без `keep` — «all»). Отбор без
    подписи с диском не сочетается: кеш отдал бы строки чужого отбора,
    поэтому это ошибка, а не молчаливое «без кеша». Кусок, которого
    больше нет, уносит с собой и свой pickle. Запись атомарная.

    `stats`: `dups`, `parts`, `parsed` (строк разобрано ЭТИМ вызовом),
    `cached` (кусков взято из кеша памяти), `disk` (кусков с диска).
    """
    rows, bad, seen, dups, parsed, hits, dhits = [], 0, set(), 0, 0, 0, 0
    parts = journal_parts(path)
    if disk is not None:
        if keep is not None and not keep_sig:
            raise ValueError("read_journal: отбор `keep` с кешем на диске требует keep_sig")
        keep_sig = keep_sig or "all"
        os.makedirs(disk, exist_ok=True)
        _disk_sweep(disk, path, parts, keep_sig)
    if cache is not None:
        # Кусок, которого больше нет (переразрезка переименовала), из
        # кеша уходит — но только СВОЕГО журнала: словарь у сборщика
        # один на три семейства.
        base = os.path.splitext(path)[0] + "-"
        for k in [k for k in cache
                  if (k == path or k.startswith(base)) and k not in parts]:
            del cache[k]
    for part in parts:
        hit = None
        if cache is not None:
            st = os.stat(part)
            sig = (st.st_mtime_ns, st.st_size)
            hit = cache.get(part)
            if hit is not None and hit[0] != sig:
                hit = None
        if hit is None and disk is not None:
            st = os.stat(part)
            sig = (st.st_mtime_ns, st.st_size)
            got = _disk_get(_disk_path(disk, part, keep_sig), sig)
            if got is not None:
                prow, pkeys, pbad = got
                dhits += 1
                hit = (sig, prow, pkeys, pbad)
                if cache is not None:
                    cache[part] = hit
        if hit is None:
            prow, pkeys, pbad, n = _parse_part(part, keep)
            parsed += n
            if cache is not None:
                cache[part] = (sig, prow, pkeys, pbad)
            if disk is not None:
                _disk_put(_disk_path(disk, part, keep_sig), sig, prow, pkeys, pbad)
        else:
            _, prow, pkeys, pbad = hit
            hits += 1
        bad += pbad
        for r, k in zip(prow, pkeys):
            if k in seen:
                dups += 1
                continue
            seen.add(k)
            rows.append(r)
    if stats is not None:
        stats["dups"] = dups
        stats["parts"] = len(parts)
        stats["parsed"] = parsed
        stats["cached"] = hits
        stats["disk"] = dhits
    return rows, bad


def _disk_path(disk, part, keep_sig):
    return os.path.join(disk, f"{os.path.basename(part)}.{keep_sig}.pkl")


def _disk_get(cpath, sig):
    """Разобранный кусок с диска, если подпись та же; иначе None. Любой
    отказ чтения есть промах: кеш пересоздаётся, журнал не страдает."""
    import pickle
    try:
        with open(cpath, "rb") as f:
            d = pickle.load(f)
        if d.get("sig") == sig:
            return d["rows"], d["keys"], d["bad"]
    except (OSError, EOFError, ValueError, TypeError, AttributeError,
            KeyError, pickle.UnpicklingError):
        pass
    return None


def _disk_put(cpath, sig, rows, keys, bad):
    import pickle
    try:
        tmp = cpath + ".tmp"
        with open(tmp, "wb") as f:
            pickle.dump({"sig": sig, "rows": rows, "keys": keys, "bad": bad}, f,
                        protocol=pickle.HIGHEST_PROTOCOL)
        os.replace(tmp, cpath)
    except OSError:
        pass


def _disk_sweep(disk, path, parts, keep_sig):
    """Pickle кусков ЭТОГО журнала, которых больше нет (переразрезка), или
    чужой подписи отбора — удаляются: иначе каталог рос бы молча."""
    base = os.path.basename(os.path.splitext(path)[0])
    want = {os.path.basename(_disk_path(disk, p, keep_sig)) for p in parts}
    try:
        names = os.listdir(disk)
    except OSError:
        return
    for nm in names:
        if not nm.endswith(".pkl") or nm in want:
            continue
        stem = nm.split(".jsonl.")[0] if ".jsonl." in nm else None
        if stem is None or not (stem == base or stem.startswith(base + "-")):
            continue
        try:
            os.unlink(os.path.join(disk, nm))
        except OSError:
            pass


_SINCE_TS = {}


def ruler_since_ts(key):
    """Начало суток СВОЕГО дня книги (`RULER_SINCE`, есть у ветвей) в
    секундах UTC; у книги без своего дня — None."""
    if key not in _SINCE_TS:
        d = RULER_SINCE.get(key)
        _SINCE_TS[key] = (None if not d else
                          dt.datetime.strptime(d, "%Y-%m-%d")
                          .replace(tzinfo=dt.timezone.utc).timestamp())
    return _SINCE_TS[key]


def row_ahead(r, hours=AHEAD_H):
    """`ahead` строки журнала с границей её книги. Новая ветвь пишет в
    первом прогоне ВСЮ историю, и окно `AHEAD_H` (120 ч) перекрасило бы
    последние пять суток пересчёта в «вперёд» (ветвь «4+2», 16.10: 104
    позиции «вперёд» до своего дня). Решение раньше дня ветви — пересчёт."""
    lim = ruler_since_ts(ruler_of(r))
    if lim is not None:
        lim = max(lim, float(RULES_SINCE or 0))
    return ahead(r.get("at"), r.get("written_at"), hours, since=lim)


# Лучшие сделки для главной сайта (владелец 16.10: «блок с топ-100
# лучшими сделками»). Отбор — в прогоне книги, где деньги уже НЕТТО
# (`costs.apply_to_rows`), а не в сборщике по журналу (там брутто).
# Мера — доллары нетто на депозите ячейки, формат размера — сложный
# процент, правила — нынешние. Одна позиция (имя, сторона, момент
# решения) — одна строка: её держат и сестры-ветви, и общий счёт, и сто
# копий одного входа вытеснили бы остальные; остаётся лучшая копия.
# Рядом всегда объём выборки и доля убыточных: топ без знаменателя —
# отбор лучшего, выдаваемый за типичное.
BEST_N = 100
BEST_KEEP = 200            # с запасом на пересечение семейств при сведении


def _best_key(r):
    return (r.get("sym"), r.get("side"), int(round(float(r.get("at") or 0))))


def best_trades(rows, keys=None, keep=BEST_KEEP):
    """Лучшие закрытые сделки семейства по депозитам: {депозит: {n,
    n_loss, top}}. `rows` — строки журнала с деньгами нетто; берутся
    нынешние правила, сложный процент и книги из `keys`."""
    want = set(keys) if keys is not None else None
    by_dep = {}
    for r in rows:
        if r.get("exit_ts") is None or r.get("usd") is None or not is_current(r):
            continue
        if sizing_of(r) != SIZING_COMPOUND:
            continue
        rk = ruler_of(r)
        if want is not None and rk not in want:
            continue
        d = by_dep.setdefault(str(int(r.get("dep") or 0)), {"n": 0, "n_loss": 0, "pos": {}})
        usd = float(r["usd"])
        d["n"] += 1
        d["n_loss"] += usd < 0
        side = row_side(r, rk)
        try:
            margin = float(r.get("margin"))
        except (TypeError, ValueError):
            margin = None
        x = {"book": rk, "sym": r.get("sym"), "side": side,
             "at": float(r["at"]), "exit_ts": float(r["exit_ts"]),
             "lev": r.get("lev"), "margin": r.get("margin"),
             "usd": round(usd, 2),
             "usd_gross": (None if r.get("usd_gross") is None else round(float(r["usd_gross"]), 2)),
             "ret": (round(usd / margin, 4) if margin else None),
             "exit": r.get("exit"), "bt": row_ahead(r) is not True,
             "tail": bool(r.get("tail"))}
        k = _best_key(x)
        cur = d["pos"].get(k)
        if cur is None or x["usd"] > cur["usd"]:
            d["pos"][k] = x
    out = {}
    for dep, d in by_dep.items():
        top = sorted(d["pos"].values(), key=lambda x: -x["usd"])[:keep]
        out[dep] = {"n": d["n"], "n_loss": d["n_loss"], "top": top}
    return out


def merge_best(parts, n=BEST_N):
    """Свести лучшие сделки семейств: объём и убыточные — суммой,
    позиция — один раз (лучшая копия), первые `n`."""
    out = {}
    for part in parts:
        for dep, d in (part or {}).items():
            o = out.setdefault(str(dep), {"n": 0, "n_loss": 0, "pos": {}})
            o["n"] += int(d.get("n") or 0)
            o["n_loss"] += int(d.get("n_loss") or 0)
            for x in d.get("top") or []:
                k = _best_key(x)
                cur = o["pos"].get(k)
                if cur is None or float(x["usd"]) > float(cur["usd"]):
                    o["pos"][k] = x
    return {dep: {"n": o["n"], "n_loss": o["n_loss"],
                  "top": sorted(o["pos"].values(), key=lambda x: -float(x["usd"]))[:n]}
            for dep, o in out.items()}


def split_rows(rows, hours=AHEAD_H):
    """Наблюдение и пересчёт — ДВА списка, и складывать их нельзя."""
    fwd, back = [], []
    for r in rows:
        a = row_ahead(r, hours)
        (fwd if a else back).append(r)
    return fwd, back
