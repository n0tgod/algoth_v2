#
#   якорь — сам по себе почти ничего не двигает (итог +12.83 % против
#   +12.72), и это следствие того, что у 86 % позиций глубина 1, а без
#   долива якоря совпадают по построению. Берётся он не за деньги, а за
#   согласованность: тейк по ТВХ платит тождественно «заполненный
#   нотионал × доля», и после долива цель не висит у старого входа;
#
#   расстояние — то, что двигает всё. Медианное обещание `mfe` равно
#   2.56 % при суточной σ имени 5.55 %, то есть цель стояла ниже
#   половины дневного размаха монеты. Обещание ×2 лучше прежнего правила
#   по КАЖДОЙ мере и во всех трёх книгах (оптимальная, $10 тыс.: итог
#   +12.72 → +17.95 %, $1.02 → $2.03 на тейк, зелёных дней 44 → 59 %,
#   медиана дня −0.002 → +0.007 %, «без 3 лучших дней» −16 → +199 $,
#   просадка −0.55 → −0.54 %, ликвидаций 0.20 → 0.26 %), и порядок
#   держится в обеих половинах окна и на всех трёх депозитах.
#
# Ось НЕ монотонна — ×3 хуже ×2 (+16.34 против +17.95), — то есть у сетки
# внутренний максимум, а не «чем дальше, тем лучше». Оговорки в силе:
# окно одно, веса модели видели эти часы, семнадцать ячеек просмотрены;
# ×2 назван по совокупности мер, а не по максимуму итога (ошибка R5).
TAKE_ANCHOR = "avg"              # цель едет вниз вместе с ТВХ
TAKE_MULT = 2.0                  # доля цены = обещание mfe × TAKE_MULT


def take_rule(fav_bp, side="long"):
    """Правило тейка позиции: якорь и доля цены. None — цели нет.

    Доля считается ЗДЕСЬ, а не у каждого читателя: два места, решающих
    «во сколько раз дальше обещания», однажды разойдутся, и книга стала
    бы торговать не тем правилом, которым её судят.

    Обещание, не строго положительное, цели не даёт вовсе. Это не мелочь:
    прежнее правило требовало `take_px > вход`, то есть ровно `fav > 0`,
    и состав позиций обязан остаться тем же — иначе правка меняла бы не
    только тейк.

    У ШОРТА обещание в пользу есть ход цены ВНИЗ, то есть `fav_bp < 0`
    (поля записи уже размечены сторонами — `trades.path_fields`, и
    применять разметку повторно нельзя). Поэтому условие годности —
    «обещание смотрит в сторону позиции», а доля цены всегда берётся
    модулем: направление уровня задаёт сама симуляция знаком стороны.
    Лонг при этом считается прежним числом бит в бит.
    """
    try:
        f = float(fav_bp) / 1e4
    except (TypeError, ValueError):
        return None
    f *= float(TAKE_MULT)
    d = 1.0 if side == "long" else -1.0
    if not d * f > 0:
        return None
    return {"anchor": TAKE_ANCHOR, "frac": f if side == "long" else -f}


