#!/usr/bin/env python3
"""
F1 — carry на funding. Ядро расчёта.

Спека 04, разделы 3 и 8.1. Здесь только арифметика книги: веса из
оценки, разложение PnL на начисления и цену, отдельно по ногам. Ни
диска, ни базы — чтобы проверялось тестами с известным ответом.

Что именно раскладывается и зачем
---------------------------------

Гипотеза утверждает не «ставки персистентны» (это A1 доказала), а
«начисления перекрывают ход цены против книги». Значит единственная
величина, ради которой этап существует, — **разность двух чисел**:

    доход книги = начисления + ход цены

и её надо видеть слагаемыми, а не суммой. Больше того — **по ногам
отдельно**. Замер к спеке 04 показал, что толстый хвост ставок
отрицательный (5-й процентиль −24.7 б.п. в сутки против +6.9 на 95-м),
то есть длинная нога набирается из активов, которые толпа шортит. Если
гипотеза умрёт, она умрёт именно там, и агрегат по книге это скроет:
короткая нога может тянуть вверх ровно столько же, сколько длинная
теряет.

Знаки
-----

Положительная ставка означает, что лонги платят шортам.

    начисления ноги = − вес · сумма_ставок

Лонг (вес > 0) при положительной ставке платит, то есть получает
отрицательный вклад; шорт при той же ставке получает. Это ровно та же
формула, что `costs.funding_cost`, взятая с обратным знаком, потому что
там она издержка, а здесь — доход.
"""

import numpy as np


def weights(score, width):
    """Веса книги: верхняя доля `width` в лонг, нижняя в шорт.

    Сумма модулей равна единице, ноги равны **по деньгам**. Равенство
    по деньгам не есть равенство по риску — ловушка §5.2 спеки — и
    поэтому бета книги меряется отдельно, а не предполагается нулевой.

    Отличается от `costs.weights` одним: там отбор дополнительно
    требовал наличия форварда, потому что вес без форварда бесполезен
    для оценки. Здесь форвардов два (цена и начисления), и требование
    к ним ставится снаружи — иначе актив, у которого нет одного из
    двух, молча выпадал бы из книги, а разложение перестало бы
    складываться в сумму.
    """
    w = np.zeros(len(score))
    m = ~np.isnan(score)
    n = int(m.sum())
    k = int(n * width)
    if k < 1:
        return w, 0
    orig = np.flatnonzero(m)
    idx = np.argsort(score[m], kind="mergesort")
    w[orig[idx[-k:]]] = +0.5 / k
    w[orig[idx[:k]]] = -0.5 / k
    return w, k


def decompose(w, price_fwd, funding_fwd):
    """PnL книги слагаемыми и по ногам.

    `price_fwd` — доходность актива за окно удержания, `funding_fwd` —
    сумма начисленных ему за то же окно ставок. Оба вектора в тех же
    единицах, что и веса: доли нотионала.

    Актив без цены либо без начислений в разложение не входит **ни
    одним слагаемым**. Подставить ноль было бы удобно и неверно: ноль
    означает «цена не двигалась» либо «начислений не было», то есть
    наблюдение, которого не существует. Возвращается `dropped` —
    сколько веса ушло из книги по этой причине; если величина не мала,
    разложение описывает не ту книгу, которую мы построили.
    """
    ok = np.isfinite(price_fwd) & np.isfinite(funding_fwd)
    ww = np.where(ok, w, 0.0)
    dropped = float(np.abs(w[~ok]).sum())

    price = ww * np.where(ok, price_fwd, 0.0)
    fund = -ww * np.where(ok, funding_fwd, 0.0)

    lo, sh = ww > 0, ww < 0
    out = {
        "price": float(price.sum()),
        "funding": float(fund.sum()),
        "gross": float(price.sum() + fund.sum()),
        "dropped_weight": dropped,
        "long": {"price": float(price[lo].sum()),
                 "funding": float(fund[lo].sum()),
                 "gross": float(price[lo].sum() + fund[lo].sum()),
                 "names": int(lo.sum())},
        "short": {"price": float(price[sh].sum()),
                  "funding": float(fund[sh].sum()),
                  "gross": float(price[sh].sum() + fund[sh].sum()),
                  "names": int(sh.sum())},
    }
    return out


def robust(v, how="median"):
    v = [float(x) for x in v if x is not None and x == x]
    if not v:
        return None
    if how == "median":
        return float(np.median(v))
    if how == "mean":
        return float(np.mean(v))
    raise ValueError(how)


def share_positive(v):
    v = [x for x in v if x is not None and x == x]
    return (sum(1 for x in v if x > 0) / len(v)) if v else None


def tail_ratio(v):
    """Отношение худшего периода к медианному по модулю. Критерий §8.3 п. 8.

    Мера того, чего Sharpe не видит вовсе: насколько один плохой период
    больше обычного. Carry даёт ровную мелкую прибыль и редкий крупный
    убыток, и отношение 40 означает, что год работы отдаётся за неделю,
    каким бы ни был Sharpe.

    Знаменателем берётся медиана **модулей**, а не модуль медианы: у
    книги с медианой около нуля второе взорвалось бы в бесконечность,
    сообщив о хвосте то, чего в нём нет.
    """
    v = np.asarray([x for x in v if x is not None and x == x],
                   dtype=np.float64)
    if len(v) < 10:
        return None
    typical = float(np.median(np.abs(v)))
    if typical <= 0:
        return None
    return float(abs(v.min()) / typical)
