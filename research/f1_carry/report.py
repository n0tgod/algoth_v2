#!/usr/bin/env python3
"""
F1 — отчёт по артефакту прогона.

Зависимостей не имеет намеренно: собирается из готового JSON одним
`json`, без numpy. Дефект R1, где отчёт нельзя было собрать, потому что
он импортировал модуль с numpy, повторять незачем.

    python3 report.py --interval 1m > out/F1-report-1m.md
"""

import argparse
import json
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")


def bp(x, d=1):
    return "—" if x is None else f"{x * 10000:.{d}f}"


def f(x, d=2):
    return "—" if x is None else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--interval", default="1m")
    ap.add_argument("--funding-venue", default="bybit")
    a = ap.parse_args()
    path = os.path.join(OUT, f"f1_{a.interval}_{a.funding_venue}.json")
    if not os.path.exists(path):
        raise SystemExit(f"нет {path} — сначала run.py")
    with open(path, encoding="utf-8") as fh:
        d = json.load(fh)
    cfg, grid, cells, prem = d["config"], d["grid"], d["cells"], d["premises"]
    p = print

    p("# F1 — книга carry и разложение её PnL\n")
    p("**Спека:** 04, этап F1, посылки §8.1  ")
    p(f"**Разрешение хранилища:** {cfg['interval']}  ")
    p(f"**Ставки:** {cfg['funding_venue']}, ряды у "
      f"{cfg['funding_symbols']} активов  ")
    p(f"**Период:** {cfg['start']} … {cfg['end']}, сечений "
      f"{grid['sections']}, активов в сечении {f(grid['assets_median'], 0)}  ")
    p(f"**Объявленных испытаний:** {cfg['declared_trials']}\n")

    if cfg["funding_venue"] != "bybit":
        p("> **Ставки взяты НЕ с площадки исполнения.** Результат непригоден "
          "для вердикта: спека 02 §2.0 запрещает подменять площадку, а A1 "
          "измерила, что знак расхождения площадок неустойчив. Этот прогон "
          "проверяет конвейер, а не гипотезу.\n")

    p("## Что здесь измеряется\n")
    p("Гипотеза утверждает не «ставки персистентны» — это A1 доказала, — а "
      "**«начисления перекрывают ход цены против книги»**. Поэтому главная "
      "величина отчёта не доход, а его разложение:\n")
    p("```\nбрутто книги = начисления + ход цены\n```\n")
    p("И раскладывается оно **по ногам отдельно**. Замер к спеке показал, "
      "что толстый хвост ставок отрицательный, то есть длинная нога "
      "набирается из активов, которые толпа шортит. Если гипотеза умрёт, "
      "она умрёт именно там, а агрегат по книге это скроет: короткая нога "
      "может тянуть вверх ровно столько, сколько длинная теряет.\n")
    p("Издержек здесь нет вовсе — они предмет F4. Всё, что ниже, брутто.\n")

    p("## Сетка\n")
    p("| Ячейка | Периодов | Начисления, б.п. | Цена, б.п. | Брутто, б.п. "
      "| Доля + | Хвост | Потерян вес |")
    p("|---|---|---|---|---|---|---|---|")
    for n in sorted(cells):
        c = cells[n]
        p(f"| {n} | {c['periods']} | {bp(c['funding'])} | {bp(c['price'])} "
          f"| **{bp(c['gross'])}** | {f(c['positive_share'])} "
          f"| {f(c['tail_ratio'], 1)} | {f(c['dropped_weight'], 3)} |")
    p("")
    p("«Хвост» — отношение худшего периода к медианному по модулю, "
      "критерий §8.3 п. 8. «Потерян вес» — доля гросса, выпавшая из-за "
      "отсутствия цены или начислений; выше 0.05 означает, что разложение "
      "описывает не ту книгу, которую мы построили.\n")

    p("## Разложение по ногам\n")
    p("| Ячейка | Лонг: начисл. | Лонг: цена | Лонг: брутто "
      "| Шорт: начисл. | Шорт: цена | Шорт: брутто |")
    p("|---|---|---|---|---|---|---|")
    for n in sorted(cells):
        c = cells[n]
        L, S = c["long"], c["short"]
        p(f"| {n} | {bp(L['funding'])} | {bp(L['price'])} "
          f"| **{bp(L['gross'])}** | {bp(S['funding'])} | {bp(S['price'])} "
          f"| **{bp(S['gross'])}** |")
    p("")

    p("## Посылки §8.1\n")
    p("| # | Посылка | Порог | Получено | |")
    p("|---|---|---|---|---|")
    p(f"| П1 | Медиана начислений книги за период | ≥ 30 б.п. "
      f"| {bp(grid['funding_median'])} "
      f"| {'✓' if prem['P1_funding_ge_30bp'] else '✗'} |")
    p(f"| П2 | Медиана полного брутто (начисления + цена) | > 0 "
      f"| {bp(grid['gross_median'])} "
      f"| {'✓' if prem['P2_gross_positive'] else '✗'} |")
    p("")
    p(f"Ячеек, где цена съедает начисления: "
      f"**{grid['cells_price_eats_carry']} из {grid['n_cells']}** "
      f"(критерий остановки §8.2 — пять и более).\n")

    p("## Диагностика прочтения «средней ставки»\n")
    p("Отбор идёт по средней **суточной** ставке. Вторая законная "
      "прочитка — средняя на начисление — приводится, чтобы разница была "
      "видна числом, а не предполагалась малой: у актива на часовых "
      "начислениях та же ставка стоит вчетверо дороже.\n")
    p("| k, дней | Ранговое согласие прочиток |")
    p("|---|---|")
    for k, v in sorted(d.get("reading_agreement", {}).items()):
        p(f"| {k} | {f(v, 4)} |")
    p("")

    p("## Вердикт\n")
    ok = prem["P1_funding_ge_30bp"] and prem["P2_gross_positive"]
    stop = grid["cells_price_eats_carry"] >= 5
    if ok and not stop:
        p("Обе посылки выполнены, критерий остановки не сработал. "
          "Переход к **F2** — ловушки §5: бета книги, вклад делистингов, "
          "ликвидность и ёмкость дециля, смена режима начисления.\n")
    else:
        p("**Посылки §8.1 не выполнены.** Гипотеза закрывается на первом "
          "этапе, до издержек и бэктеста — ровно так, как спека и "
          "проектировалась: самый дешёвый прогон отвечает на самый "
          "опасный вопрос.\n")
        p("Что именно провалилось, читать по разложению ног: если "
          "начисления есть, а брутто отрицательно, сработала ловушка "
          "§5.1 — нам платят за покупку падающего.\n")


if __name__ == "__main__":
    main()
